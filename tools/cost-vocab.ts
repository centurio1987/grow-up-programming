/**
 * 계수 이름 하나를 잰다. 위반이면 옮길 곳을, 아니면 `null` 을 낸다.
 * 밑줄은 이름을 가리지 않고 위반이다 — bench 키도 본문에 실리는 이름이다.
 */
export function retiredCostName(
  metric: string,
): { name: string; target: string } | null {
  if (metric.includes("_"))
    return {
      name: metric,
      target: "밑줄 대신 띄어쓰기(`합치기_비교` → `합치기 비교`)",
    };
  const m = metric.trim();
  // 머리 명사 없이 「칸」 하나만 쓴 이름은 공간 셋 중 무엇인지 말하지 않는다. `endsWith` 로 걸면
  // 맞는 이름(「추가 칸」)까지 걸리므로 통째로 같을 때만 본다.
  if (m === "칸") return { name: "칸", target: SPACE_TARGET };
  for (const [name, target] of RETIRED_COST_NAMES) {
    if (m === name || m.endsWith(` ${name}`)) return { name, target };
  }
  return null;
}

