test("입력 edges 배열을 정렬해 놓지 않는다", () => {
  const edges: Edge[] = [
    [3, 4, 6],
    [0, 1, 1],
    [0, 3, 4],
    [4, 5, 5],
    [2, 3, 2],
    [0, 5, 7],
    [1, 2, 3],
  ];
  const snapshot = JSON.stringify(edges);
  kruskalMst(6, edges);
  expect(JSON.stringify(edges)).toBe(snapshot);
});

test("제약 상한 규모의 입력에서 답이 나온다", () => {
  // 원본의 벽시계 케이스와 같은 생성식이다. 재는 것은 시간이 아니라 반환값이다.
  const v = 100_000;
  const edges: Edge[] = [];
  for (let i = 0; i < v - 1; i++)
    edges.push([i, i + 1, ((i * 1009) % 1000) + 1]);
  let seed = 12_345;
  for (let i = 0; i < 100_000; i++) {
    seed = (seed * 1_103_515_245 + 12_345) & 0x7fff_ffff;
    const u = seed % v;
    seed = (seed * 1_103_515_245 + 12_345) & 0x7fff_ffff;
    const w = seed % v;
    if (u !== w) edges.push([u, w, ((i * 31) % 1000) + 1]);
  }
  const got = kruskalMst(v, edges);
  // 한 줄로 이은 간선만으로도 연결이 보장되므로 답이 -1 은 아니고, 고른 간선이 99,999 개라
  // 각 가중치가 1 이상 1,000 이하이므로 합계가 그 구간 안에 있다.
  expect(got).toBeGreaterThanOrEqual(v - 1);
  expect(got).toBeLessThanOrEqual((v - 1) * 1_000);
});

test("한 줄로 이은 정점 100,000 개에서 합계가 닫힌 값과 같다", () => {
  // 가중치를 자리 번호 + 1 로 두면 합계가 1 + 2 + … + (V-1) 이다.
  const v = 100_000;
  const edges: Edge[] = [];
  for (let i = 0; i + 1 < v; i++) edges.push([i, i + 1, i + 1]);
  expect(kruskalMst(v, edges)).toBe(((v - 1) * v) / 2);
});

test("덩어리가 둘이면 간선이 아무리 많아도 -1 이다", () => {
  const edges: Edge[] = [];
  for (let i = 0; i + 1 < 500; i++) edges.push([i, i + 1, i + 1]);
  for (let i = 500; i + 1 < 1_000; i++) edges.push([i, i + 1, i + 1]);
  expect(kruskalMst(1_000, edges)).toBe(-1);
});
