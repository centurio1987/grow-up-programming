test("입력 edges 배열을 건드리지 않는다", () => {
  const edges: Edge[] = [
    [0, 1, 1],
    [0, 3, 4],
    [0, 5, 7],
    [1, 2, 3],
    [2, 3, 2],
    [3, 4, 6],
    [4, 5, 5],
  ];
  const snapshot = JSON.stringify(edges);
  primMst(6, edges);
  expect(JSON.stringify(edges)).toBe(snapshot);
});

test("정점 번호를 돌려 붙여도 합계가 같다", () => {
  // 시작 정점은 0 으로 못 박혀 있다. 정점 번호를 `k` 만큼 밀어 붙이면 시작 정점이 원래
  // 그래프의 `n-k` 번 정점이 된 것과 같으므로, 여섯 판의 합계가 모두 같아야 한다.
  const base: Edge[] = [
    [0, 1, 1],
    [0, 3, 4],
    [0, 5, 7],
    [1, 2, 3],
    [2, 3, 2],
    [3, 4, 6],
    [4, 5, 5],
  ];
  for (let k = 0; k < 6; k++) {
    const shifted: Edge[] = base.map(([u, v, w]) => [
      (u + k) % 6,
      (v + k) % 6,
      w,
    ]);
    expect(primMst(6, shifted)).toBe(17);
  }
});

test("한 줄로 이은 정점 10,000 개에서 합계가 닫힌 값과 같다", () => {
  // 가중치를 자리 번호 + 1 로 두면 합계가 1 + 2 + … + (V-1) 이다.
  const v = 10_000;
  const edges: Edge[] = [];
  for (let i = 0; i + 1 < v; i++) edges.push([i, i + 1, i + 1]);
  expect(primMst(v, edges)).toBe(((v - 1) * v) / 2);
});

test("제약 상한 규모의 밀집 그래프에서 답이 나온다", () => {
  // 원본의 벽시계 케이스와 같은 생성식이다. 재는 것은 시간이 아니라 반환값이다.
  const v = 300;
  const edges: Edge[] = [];
  for (let i = 0; i < v; i++) {
    for (let j = i + 1; j < v; j++) {
      edges.push([i, j, ((i * 7919 + j * 1009) % 1000) + 1]);
    }
  }
  const got = primMst(v, edges);
  // 고른 간선이 299 개이고 각 가중치가 1 이상 1,000 이하이므로 합계가 그 구간 안에 있다.
  expect(got).toBeGreaterThanOrEqual(v - 1);
  expect(got).toBeLessThanOrEqual((v - 1) * 1_000);
});

test("덩어리가 둘이면 간선이 아무리 많아도 -1 이다", () => {
  const edges: Edge[] = [];
  for (let i = 0; i + 1 < 500; i++) edges.push([i, i + 1, i + 1]);
  for (let i = 500; i + 1 < 1_000; i++) edges.push([i, i + 1, i + 1]);
  expect(primMst(1_000, edges)).toBe(-1);
});
