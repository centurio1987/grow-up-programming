/**
 * L9 — 가이드가 싣는 코드가 **기존 테스트의 입출력 케이스**를 통과하는가.
 *
 * 원본 `src/algorithms/tree/treeDiameter/treeDiameter.test.ts` 는 학습자 스텁을 가져오므로
 * 그대로 재사용할 수 없다. **케이스만** 옮겨 정본에 다시 건다.
 *
 * 벽시계를 재는 케이스 둘(한 줄로 이은 정점 100,000 개와 별 모양 100,000 개를 100ms 안에)은
 * 그대로 옮기지 않았다 — 실행마다 값이 달라 판정이 안 된다. 그 케이스들이 실제로 지키던 것은
 * **제약 상한 규모에서 호출 깊이에 걸리지 않고 답이 나온다**는 것이라, 아래에서 같은 두 모양의
 * 반환값으로 다시 건다. 같은 규모의 비용은 「최악을 만드는 입력」이 배열 칸 접근 수로 진다.
 *
 * **원본에 없던 케이스 셋을 더 걸었다.** ① 입력 배열을 변형하지 않는가 ② 시작 정점을 무엇으로
 * 두어도 같은 답이 나오는가(본문 「아이디어 상세」가 값으로 보인 성질) ③ 지름 경로가 뿌리를
 * 지나지 않는 트리.
 */
import { expect, test } from "bun:test";
import { treeDiameter } from "./treeDiameter-guide.ref.ts";

type Edge = [number, number, number];

const CASES: [string, number, Edge[], number][] = [
  ["정점 하나 — 간선이 없다", 1, [], 0],
  ["정점 둘 · 가중치 5", 2, [[0, 1, 5]], 5],
  [
    "작은 트리에서 가장 긴 경로",
    4,
    [
      [0, 1, 1],
      [1, 2, 2],
      [1, 3, 3],
    ],
    5,
  ],
  [
    "Y 자 모양 트리",
    5,
    [
      [0, 1, 2],
      [1, 2, 3],
      [1, 3, 4],
      [3, 4, 1],
    ],
    8,
  ],
  [
    "한 줄로 이은 다섯 정점",
    5,
    [
      [0, 1, 2],
      [1, 2, 2],
      [2, 3, 2],
      [3, 4, 2],
    ],
    8,
  ],
  [
    "별 모양 — 가장 무거운 두 간선의 합",
    5,
    [
      [0, 1, 1],
      [0, 2, 2],
      [0, 3, 3],
      [0, 4, 4],
    ],
    7,
  ],
  [
    "가중치가 전부 0",
    3,
    [
      [0, 1, 0],
      [1, 2, 0],
    ],
    0,
  ],
  [
    "균형 잡힌 이진 트리",
    7,
    [
      [0, 1, 1],
      [0, 2, 1],
      [1, 3, 1],
      [1, 4, 1],
      [2, 5, 1],
      [2, 6, 1],
    ],
    4,
  ],
  ["정점 둘 · 큰 가중치", 2, [[0, 1, 1_000]], 1_000],
  [
    "가중치 백만짜리 간선 둘",
    3,
    [
      [0, 1, 1_000_000],
      [1, 2, 1_000_000],
    ],
    2_000_000,
  ],
  [
    "본문 전개가 쓰는 고정 입력",
    7,
    [
      [0, 1, 2],
      [0, 2, 3],
      [1, 3, 4],
      [1, 4, 1],
      [2, 5, 5],
      [5, 6, 2],
    ],
    16,
  ],
  [
    "지름 경로가 정점 0 을 안 지난다",
    6,
    [
      [0, 1, 1],
      [1, 2, 10],
      [1, 3, 10],
      [0, 4, 1],
      [4, 5, 1],
    ],
    20,
  ],
];

for (const [name, n, edges, want] of CASES) {
  test(`정본 — ${name}`, () => {
    expect(treeDiameter(n, edges)).toBe(want);
  });
}

test("입력 edges 배열을 변형하지 않는다", () => {
  const edges: Edge[] = [
    [0, 1, 2],
    [0, 2, 3],
    [1, 3, 4],
    [1, 4, 1],
    [2, 5, 5],
    [5, 6, 2],
  ];
  const snapshot = JSON.stringify(edges);
  treeDiameter(7, edges);
  expect(JSON.stringify(edges)).toBe(snapshot);
});

test("정점 번호를 바꿔 달아도 답이 같다", () => {
  // 본문이 「시작 정점을 무엇으로 두어도 같은 답이 나온다」를 값으로 보인다. 코드는 언제나
  // 0 에서 시작하므로, 그 성질을 걸려면 어느 정점이 0 이 되는지를 바꿔 본다.
  const base: Edge[] = [
    [0, 1, 2],
    [0, 2, 3],
    [1, 3, 4],
    [1, 4, 1],
    [2, 5, 5],
    [5, 6, 2],
  ];
  for (let shift = 0; shift < 7; shift++) {
    const renamed: Edge[] = base.map(([u, v, w]) => [
      (u + shift) % 7,
      (v + shift) % 7,
      w,
    ]);
    expect(treeDiameter(7, renamed)).toBe(16);
  }
});

test("한 줄로 이은 정점 100,000 개에서 답이 나온다", () => {
  // 원본의 벽시계 케이스가 지키던 것 — 호출 깊이가 아니라 배열 길이로 깊이를 잡는다.
  const n = 100_000;
  const edges: Edge[] = [];
  for (let i = 0; i + 1 < n; i++) edges.push([i, i + 1, 1]);
  expect(treeDiameter(n, edges)).toBe(n - 1);
});

test("별 모양 정점 100,000 개에서 답이 나온다", () => {
  const n = 100_000;
  const edges: Edge[] = [];
  for (let i = 1; i < n; i++) edges.push([0, i, 1]);
  expect(treeDiameter(n, edges)).toBe(2);
});
