/**
 * `deep.walk.final`(전체 코드) 이 싣는 코드의 정본.
 *
 * 원본 `src/algorithms/number-theory/isPrimeTrial/isPrimeTrial.ts` 는 학습자가 채우는
 * 자리라 가이드가 그대로 인용할 수 없다. 본문의 전체 코드는 이 파일에서 옮기고, 증명
 * 사이드카(`*.proof.ts`)와 재실행 시험(`*.test.ts`)도 이 파일을 부른다.
 *
 * **`number` 로 받는다.** 계약이 그렇고, 이 절차가 만드는 가장 큰 중간값은 `d * d` 인데
 * 루프가 `d * d <= n` 에서 멈추므로 그 값이 `n` 근처를 넘지 않는다. 권장 상한 `10^12` 는
 * 배정밀도 부동소수점이 정수를 오차 없이 담는 한계 `2^53 - 1`(약 `9 × 10^15`) 아래다.
 *
 * **변이는 이 파일 원문에서 기계로 만든다**(`tools/check-proof.ts` 의 `loadMutant`) —
 * 아래 세 자리가 각각 정확히 한 줄이다.
 *
 * - 루프 조건의 등호를 빼면 소수의 제곱에서 후보 하나를 안 시도한다.
 * - 2 와 3 의 배수를 거르는 줄을 지우면 4·6·9 처럼 작은 합성수가 소수로 나온다.
 * - 걸음 폭을 2 로 고정하면 답은 같고 나눗셈 횟수만 는다.
 */

/**
 * 정수 `n` 이 소수이면 `true`, 아니면 `false` 를 돌려준다.
 *
 * `n` 이 2 보다 작으면(음수 · 0 · 1) 소수가 아니다. 권장 입력 범위는 `n <= 10^12` 다.
 */
export function isPrimeTrial(n: number): boolean {
  // ① 2 보다 작은 수는 소수가 아니다. 음수와 0 과 1 이 여기서 걸린다.
  if (n < 2) return false;

  // ② 2 와 3 은 소수다. 아래 ③ 이 이 둘을 합성수로 판정하므로 먼저 답한다.
  if (n === 2 || n === 3) return true;

  // ③ 2 의 배수와 3 의 배수를 거른다. 여기를 지나면 n 자신이 6k±1 이다.
  if (n % 2 === 0 || n % 3 === 0) return false;

  // ④ 후보를 5 부터 6k±1 로만 만든다. step 이 2 와 4 를 번갈아 내놓는다.
  let d = 5;
  let step = 2;
  while (d * d <= n) {
    // ⑤ 약수를 하나라도 찾으면 합성수다.
    if (n % d === 0) return false;
    d += step;
    step = 6 - step;
  }
  return true;
}
