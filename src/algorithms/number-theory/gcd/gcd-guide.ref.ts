/**
 * `deep.walk.final`(전체 코드) 이 싣는 코드의 정본.
 *
 * 원본 `src/algorithms/number-theory/gcd/gcd.ts` 는 학습자 스텁이라 본문에 실을 수 없다.
 * 여기 있는 것이 가이드 본문의 전체 코드와 **글자 그대로** 같은 절차다 — 두 수를 절댓값으로
 * 바꾼 뒤, 나머지가 0 이 될 때까지 `(y, x mod y)` 로 옮긴다.
 *
 * **`bigint` 로 받는다.** 계약이 그렇고, 그래서 나눗셈 한 번의 비용이 자릿수에 달린다 —
 * 본문의 경쟁 설계 대조가 그 자리를 겨눈다.
 *
 * 변이는 이 파일 원문에서 기계로 만든다(`tools/check-proof.ts` 의 `loadMutant`) — 아래 두
 * 자리가 각각 정확히 한 줄이라 「한 곳만 바꿨다」가 검사된다.
 *
 * - 둘째 인자의 절댓값 처리를 지우면 음수가 들어왔을 때 음수 답이 나온다.
 * - 다음 걸음의 첫 값을 나머지로 바꾸면 두 값이 같아져 첫 나머지가 그대로 답이 된다.
 */

/**
 * 두 정수의 최대공약수를 돌려준다. 부호와 무관하게 언제나 0 이상이고, 둘 다 0 이면 0 이다.
 */
export function gcd(a: bigint, b: bigint): bigint {
  // ① 부호를 떼어 낸다. 공약수는 부호와 무관하다.
  let x = a < 0n ? -a : a;
  let y = b < 0n ? -b : b;

  // ② 나머지가 0 이 될 때까지 두 값을 (y, x mod y) 로 옮긴다.
  while (y !== 0n) {
    const r = x % y;
    x = y;
    y = r;
  }

  // ③ 나머지가 0 이 된 순간의 x 가 답이다. 둘 다 0 이면 반복이 한 번도 실행되지 않는다.
  return x;
}
