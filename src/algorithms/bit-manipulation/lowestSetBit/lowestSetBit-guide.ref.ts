/**
 * 32 비트 정수에서 가장 낮은 자리의 1 비트만 남긴 값을 돌려준다.
 *
 * 32 비트 2 의 보수에서 부호를 뒤집은 값은 모든 자리를 뒤집고 1 을 더한 것이다. 그 덧셈의
 * 자리올림이 최하위 1 비트에서 멈추므로, 두 값이 함께 1 인 자리가 그 자리 하나뿐이다.
 * 1 비트가 하나도 없으면(입력이 0) 두 값이 다 0 이라 결과도 0 이다.
 *
 * JavaScript 의 `&` 는 피연산자를 32 비트 부호 있는 정수로 자른다. 이 문제의 제약이
 * `-2^31 ≤ x ≤ 2^31 - 1` 이라 그 안에 있다.
 */
export function lowestSetBit(x: number): number {
  // ① 모든 자리를 뒤집는다 — 자리 p 아래가 전부 1 이 되고 자리 p 자신은 0 이 된다.
  // ② 거기에 1 을 더한다 — 자리올림이 자리 p 에서 멈추고, 그 값이 32 비트 2 의 보수다.
  // ③ 두 값이 함께 1 인 자리만 남긴다. 입력이 0 이면 부호를 뒤집어도 0 이라 결과가 0 이다.
  return x & -x;
}
