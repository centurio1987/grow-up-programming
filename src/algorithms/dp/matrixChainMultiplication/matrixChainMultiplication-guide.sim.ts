/**
 * `deep.walk`(수행으로 알아보는 알고리즘) 절과 **같은 입력**을 쓴다 — `dims = [10, 30, 5, 60, 10]`.
 * `len2` 는 대각선을 까는 T1 과 구간 길이 2 의 T2~T4, `len3` 은 길이 3 의 T5~T8, `len4` 는 길이 4 의
 * T9~T11 과 답을 읽는 T12 다. 한 벌에 모으면 정적 필름이 열두 장이라 구간 길이마다 가른다 — 이 편이
 * DP 테이블을 채우는 차례가 곧 구간 길이 차례다. `result` 는 앞의 둘이 그 벌에서 정한 칸의 값, `len4`
 * 가 반환값이다.
 *
 * `player: "stage"` 가 걸음 재생 패널(`src/_viz/player/StepPlayer.tsx`)을 고르고, `stage: "table"` 이
 * 2 차원 표 무대(`tableStage.ts`)를 고른다. 무대는 줄 `i = 1 … n` · 열 `j = 1 … n` 이고 아래쪽 삼각형은
 * 구간이 아니라 `out`(이번 걸음 밖)이다. 걸음 하나가 후보 하나다 — `read` 는 그 후보가 읽은 두 칸,
 * 칸의 마지막 후보면 `write` 가, 아니면 `target`(열 머리만 반전)이 정하는 중인 칸을 가리킨다. 표 아래
 * 행렬 줄(`strip`)에 걸린 `pieces` 가 곱의 구간과 그 구간을 가른 두 조각이다.
 *
 * `steps` 는 **인라인 배열 리터럴**이어야 한다(spread·변수 참조·함수 호출 금지).
 * 정적 계수가 실제보다 적게 세면 얇은 전개가 P3 을 그냥 지나간다. 리터럴은 그림 사이드카의
 * `simStepsFromRef()`(정본 실행에서 만든 걸음)를 글자 그대로 옮긴 것이고, 둘이 같은지는
 * `matrixChainMultiplication-guide.test.ts` 가 잰다.
 */

