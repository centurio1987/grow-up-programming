/**
 * SuffixTree — 고정된 문자열의 부분 문자열 색인. 질의 비용이 색인 크기에 기대지 않는다.
 *
 * **목적.** 문자열 하나를 받아 그 부분 문자열에 대한 질의에 답하되, **질의 비용이 색인한
 * 문자열의 길이에 기대지 않게** 하는 것. 패턴을 물으면 비용이 패턴 길이(와 답의 개수)로만
 * 결정된다 — 3천 자를 색인하든 30억 자를 색인하든 같은 패턴에 드는 비용이 같다.
 *
 * 문자열은 **생성 시점에 정해지고 그 뒤로 바뀌지 않는다.** 이 계약에는 상태를 바꾸는 연산이
 * 하나도 없다.
 *
 * **접미사의 사전순 순서는 이 계약에 없다.** 순서를 관측할 수 있게 하려면 그 순서를 실제로
 * 들고 있어야 하는데, 이 계약이 요구하는 것은 순서가 아니라 **공통 접두사에 따른 묶음**이다.
 * 순서를 함께 요구하면 그것은 다른 계약이다 — `trie/suffixArray` 가 그 계약이고, 둘은
 * 연산이 겹치지만 같은 구조가 아니다(§규약1 「같은 구조인가」).
 *
 * **문자열은 코드 단위의 수열로 본다.** 길이도 비교도 언어가 문자열에 정해 둔 코드 단위
 * 기준이다.
 *
 * **불변식.** 없다.
 *
 * **상태를 바꾸는 연산이 없다는 것만으로 비는 것이 아니다.** 판별 절차(§규약1 「불변식 판별
 * 절차」)를 돌린 결과다. 관측 경로가 둘인 성질은 있다 — `count(p)` 와 `findAll(p).length` 가
 * 같은 수를 말하고 `contains(p)` 는 그 수가 0인지를 말한다. 그러나 그 정합은 **각 연산의
 * 의미에 이미 적혀 있다** — 셋 다 "패턴이 시작하는 자리"를 각각 다른 형태로 돌려준다고 위
 * 표가 적고 있으므로, 대조는 축1이 참조 모델과 하는 일이다.
 *
 * 내부 표현의 성질(서브트리 개수가 자식의 합과 같다, 자식 간선의 첫 문자가 서로 다르다,
 * 깊이가 내려가며 는다)은 불변식 후보가 아니다. 계약에 적어야 검사할 수 있는데 **적는 순간
 * 그것이 트리라는 표현을 처방한다**(§규약2 「균형·높이 같은 내부 표현의 성질을 검사하지
 * 않는다」). 이 계약은 트리를 요구하지 않는다 — 요구하는 것은 상한뿐이다.
 *
 * 여기에 하나가 더 붙는다. 상태를 바꾸는 연산이 없으므로 축2가 볼 수 있는 상태가 생성 직후
 * 하나뿐이고, 그 하나에서 관측값들이 서로 맞는지는 축1이 이미 매 연산 대조한다. **불변 구조
 * 에서는 판별 결과와 무관하게 축2가 축1보다 더 잡는 것이 없다.**
 *
 * **연산 계약.** n 은 색인한 문자열의 길이, m 은 패턴의 길이, k 는 답의 개수다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(s)` | 길이 n 의 문자열 `s` 를 색인한다. 돌아온 뒤의 질의는 아래 상한을 지킨다 | O(n log n) | worst |
 * | `length()` | 색인한 문자열의 길이 n | O(1) | worst |
 * | `contains(pattern)` | `pattern` 이 `s` 의 부분 문자열인가. `count(pattern) > 0` 과 같다 | O(m) | worst |
 * | `count(pattern)` | `pattern` 이 시작하는 자리의 수 — `0 <= i <= n - m` 중 `s` 의 `i` 부터가 `pattern` 과 같은 것. 겹쳐서 나타나는 것도 따로 센다 | O(m) | worst |
 * | `findAll(pattern)` | 위 조건을 만족하는 모든 `i`. **순서를 정하지 않는다** | O(m + k) | worst |
 * | `longestRepeatedSubstring()` | 두 번 이상 나타나는 가장 긴 부분 문자열. 같은 길이가 여럿이면 어느 것이든. 없으면 `""` | 구성과 합쳐 O(n log n) | worst |
 *
 * **빈 패턴의 답은 자리 `n` 을 포함한다.** 위 조건에 `m = 0` 을 넣으면 `0 <= i <= n` 이므로
 * `count("")` 는 `n + 1` 이고 `findAll("")` 은 `0..n` 이다. 원문에 없는 자리를 답에 넣는 것이
 * 아니라 **빈 문자열이 끝자리에서도 시작한다**는 사실이다. 이 자리를 빼면 `contains` 가
 * 빈 문자열에 대해 빈 원문에서만 `false` 가 되어 `count(p) > 0` 과 갈린다.
 *
 * **`findAll` 의 순서를 정하지 않는 것이 계약이다.** 정하면 그 순서를 만드는 방법까지 계약이
 * 정하게 된다 — 위치 오름차순을 요구하면 답을 모은 뒤 정렬하거나(비용이 $k \log k$ 로 는다)
 * 자식을 위치 순으로 들고 다녀야 하고, 둘 다 이 계약의 목적과 무관한 처방이다. 접미사 배열
 * 쪽은 반대다. 거기서는 순서가 관측값 자체이므로 정하는 것이 계약이다.
 *
 * **구성 시점을 계약이 정한다.** 위 표의 질의 상한은 `constructor` 가 돌아온 **뒤**에 대한
 * 것이다. 언제 짓느냐가 자유이면 아무것도 안 하는 생성자와 첫 질의에서 다 짓는 구현이 두
 * 상한을 모두 만족해 버리고, 그러면 구성 상한도 질의 상한도 아무 구현을 배제하지 못한다.
 *
 * **검사 공백 — 한정자 근거 문단이 없고, 구성을 첫 질의로 미루는 계열을 재지 않았다**(`KAN-044`
 * `S2`·`S4` 가 열었다 · 받는 카드 `KAN-050-0B1N1Z`). 위 표는 여섯 행을 전부 `worst` 로 적지만
 * **그 한정자가 무엇을 배제하는지는 이 헤더에 적혀 있지 않다.** §「`worst` 만 있는 계약의 한정자
 * 근거는 「배제될 계열이 없다」로 적는다」(T1-06)의 셋째 계열 — 생성자가 문자열을 베끼기만 하고
 * 첫 질의가 색인을 통째로 짓는 구현 — 이 이 계약에도 선다. 스위트는 그 계열을 잡을 **모양이다**
 * (질의 시나리오가 `reindex` 를 걸음 밖에서 부르고 그 뒤 n 번을 잰다). **다만 실물을 지어 재지는
 * 않았으므로 「걸린다」가 아니라 공백으로 적는다** — 닫는 일은 지연 구성 fixture 를 지어 재고 그
 * 수치로 근거 문단을 새로 쓰는 것이다.
 *
 * **한 번 정해지고 마는 값은 구성과 묶어 적는다.** `longestRepeatedSubstring()` 은 인자가
 * 없고 색인이 바뀌지 않으므로 그 값은 색인 시점에 이미 정해져 있다. 구성 때 계산해 두면
 * 호출이 O(1) 이고 호출 때 계산하면 O(n) 인데 **둘 다 이 계약의 목적을 해치지 않으므로**,
 * 나누어 적으면 그중 하나를 처방하게 된다.
 *
 * **여러 번 부르면 어떻게 되는가.** 이 값은 색인이 사는 동안 바뀌지 않으므로, 여러 번
 * 필요하면 **호출자가 들고 있으면 된다.** 계약이 적는 것은 한 번 얻는 비용이다. 호출 때
 * 계산하는 구현을 $q$ 번 부르면 $O(n \log n + qn)$ 이고 미리 계산해 둔 구현은
 * $O(n \log n + q)$ 인데, 그 차이가 계약의 문장이 되면 다시 그중 하나를 처방하게 된다.
 *
 * **질의 상한을 `O(m)` 으로 적은 것이 이 계약의 중심이다.** `O(m \log n)` 으로 적으면 정렬된
 * 접미사 순서에 이분 탐색을 붙인 구현이 이 계약을 만족하고, 그러면 이 계약은
 * `trie/suffixArray` 의 계약에 담긴다 — 연산 이름만 다른 같은 약속이 된다. 색인 크기가
 * 질의에 들어오지 않는다는 것이 이 구조가 따로 있는 이유이고, 그것을 계약에서 빼면 이유가
 * 사라진다.
 *
 * **구성 상한 `O(n log n)` 은 고른 값이다.** 목적이 요구하는 것은 **이차보다 빠를 것**
 * 하나뿐이고, 그 아래에는 후보가 여럿 있는데 어느 것도 하한이 아니다(§규약1 「약한 쪽
 * 규칙은 상한으로 확장되지 않는다」).
 *
 * - **이차 이상은 계약이 뜻을 잃는다.** 접미사를 하나씩 뿌리부터 내려가며 넣으면 그 상한이
 *   나오고, 그것이 상한이면 이 구조를 따로 둘 이유를 계약이 말하지 못한다.
 * - **`O(n)` 을 적으면 정본이 한 계열로 좁혀진다.** 선형 구성은 접미사 링크를 들고 다니며
 *   한 번의 훑기로 짓는 계열에서만 나온다. 접미사 순서를 먼저 짓고 그 위에 트리를 얹는
 *   구현은 $\Theta(n\log n)$ 이고, 그 구현을 배제할 이유가 이 계약의 목적에는 없다.
 *
 * 남는 것은 **정본이 서는 계급을 적는 일**이다(§규약2 「축3은 상한이 아니라 성장 계급을
 * 판정한다」가 그것을 요구한다).
 *
 * **주입 정책.** 없다. 입력이 문자열 하나뿐이고 문자의 동등성은 언어가 이미 정해 둔 코드
 * 단위 비교를 쓴다. 이 계약은 문자를 **비교**하지 않고 **같은지만** 본다 — 순서가 계약에
 * 없기 때문이다. 없는 패턴에 대해 `contains` 는 `false`, `count` 는 `0`, `findAll` 은 빈
 * 배열이고 예외를 던지지 않는다.
 *
 * **검증 등급.** `complexity`.
 * 구성 상한이 자명한 구현으로 달성되지 않는다. 반례를 적을 수 있다 — 접미사 n 개를 하나씩
 * 압축 트라이에 넣으면 넣는 자리를 찾는 데 이미 넣은 것과 겹치는 만큼 내려가야 하므로,
 * 같은 문자가 반복되는 입력에서 $\Theta(n^2)$ 이다. 질의 쪽도 자명하지 않다 — 배열 하나에
 * 원문을 담고 훑으면 $\Theta(n)$ 이다.
 *
 * **필요충분조건.**
 * - 의미: 부분 문자열들이 **공통 접두사에 따라 묶여** 있어야 한다. 어떤 패턴에 대해서든
 *   그 패턴으로 시작하는 자리 전부가 한 자리에 모여 있고, 그 자리를 패턴을 따라가는 것만으로
 *   찾을 수 있어야 한다. 묶여 있지 않으면 자리를 찾는 데 색인 전체를 봐야 하고, 그러면
 *   남는 것은 색인이 아니라 원문 그대로다.
 * - 비용: 질의가 색인 크기에 기대면 그건 원문을 훑는 것이거나 접미사 배열이고, 구성이
 *   문자열 길이의 제곱에 비례하면 접미사를 하나씩 뿌리부터 넣은 것이다. **둘 다 아닌 것**이
 *   이 구조이고, 어느 한쪽을 포기하면 트리를 따로 짓는 이유가 그 자리에서 사라진다.
 */
