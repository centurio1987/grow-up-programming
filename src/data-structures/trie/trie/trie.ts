/**
 * Trie — 문자열 집합. 접두사로 묶어 저장하고 접두사로 찾는다.
 *
 * **이 계약은 `trie/ternarySearchTree` 의 계약과 같다.** 아래 연산 계약 표의 여섯 행이 그 파일의
 * 여섯 행과 글자까지 같고, 스위트도 그 파일의 `ContractSpec` 을 그대로 돌린다
 * (`./trie.contract.ts`). 그 사실을 감추지 않고 여기 맨 앞에 적는다 — 이름이 다르다고 계약이
 * 다른 것이 아니다(불변 사실 43). B15 가 두 이름을 이미 한 계약으로 판정했고
 * (`docs/ORD-006-conventions.md:1769-1799`), A군 판정이 그것을 그대로 적용했다.
 *
 * **처분은 「존치 + 성격 전환」이다**(불변 사실 61). 두 이름이 갈리는 자리가 계약의 문장이 될 수
 * 없는 것뿐이고, 지우지 않는 이유는 판정이 *"계약이 담지 못한다"* 이지 *"쓸모가 없다"* 가 아니기
 * 때문이다. **계약을 적어 둔 자리는 `trie/ternarySearchTree` 이고 임시다** — 세 이름(`trie` ·
 * `ternarySearchTree` · `radixTree`)이 전부 담는 모양을 가리키는 구현 이름이라 정본 이름이 정해지지
 * 않는다(불변 사실 64). 계약 이름은 KAN-031 이 정한다.
 *
 * **갈라 보려 시도한 것 셋이 전부 계약의 문장이 되지 못했다.**
 *
 * - **자리마다 표로 찾는다 — 옆걸음이 없다.** 이 기법의 실제 차이이고 삼분 표현보다 센 사실이다.
 *   삼분 표현은 자리마다 그 자리에 쓰인 문자들 사이를 옆으로 움직이므로 코드 단위 가짓수
 *   $\sigma$ 를 상수로 접어야 `O(m)` 이 되고, 표로 찾으면 접지 않아도 걸음이 낱말 길이다. 그런데
 *   계약의 모형이 이미 $\sigma$ 를 언어가 정한 상수로 접었다(정본 헤더의 상한 항목). **$\sigma$ 가
 *   상한의 변수가 아니므로** 이 차이를 적을 자리가 표에 없고, 적더라도 축3이 잴 수 없다 —
 *   사다리가 키우는 것은 담긴 낱말 수이고 $\sigma$ 는 고정이다.
 * - **공간.** 자리마다 표를 드는 것이 삼분 표현보다 자리를 더 쓰거나 덜 쓰는 것은 공간이고
 *   **공간은 이 저장소의 어느 계약에도 없다**(§규약1 「공간은 어느 계약에도 없다」 — 미결). 그
 *   공간을 관측하는 연산도 이 계약에 없다(불변 사실 67).
 * - **지운 낱말의 가지를 떼어 내는가.** 물려받은 문서가 「다른 단어의 공유 경로는 유지한다」로
 *   적어 둔 자리다. 떼어 내는 구현과 남겨 두고 건너뛰는 구현이 **같은 호출에 같은 값을 돌려준다**
 *   — 계약이 말하는 상태는 담긴 낱말의 모음이지 담는 모양이 아니다(불변 사실 79).
 *
 * **갈리지 않는다는 것을 수치로 확인했다.** 같은 스위트 일곱 시나리오를 세 정본(삼분 · 자리마다
 * 표 · 접힌 에지)이 **전부 통과**한다. 한 호출 최대 비용(n = 1,024 → 4,096)은 이렇다.
 *
 * | 시나리오 | 삼분 | 자리마다 표 | 접힌 에지 |
 * |---|---|---|---|
 * | insert | 37 → 48 | 9 → 9 | 8 → 10 |
 * | search | 21 → 27 | 9 → 9 | 13 → 14 |
 * | startsWith · wordsWithPrefix | 40 → 52 | 17 → 17 | 23 → 25 |
 * | delete | 42 → 54 | 17 → 17 | 15 → 16 |
 * | size | 1 → 1 | 1 → 1 | 1 → 1 |
 * | 곁에 긴 낱말 insert · delete (KAN-026 S20) | 16 → 16 | 2 → 2 | 4 → 4 |
 *
 * 절대 비용이 최대 5.3 배 갈리는데 성장률은 셋 다 허용 구간 안이다. 삼분 쪽이 1.3 배 자라는 것은
 * 자리마다 쓰인 문자가 늘어나는 몫이고, 사다리를 한 칸 더 올리면 그 비율이 1.10 으로 준다
 * (4,096 → 16,384 에서 48 → 53) — $\sigma$ 를 접은 상수가 채워지는 모습이다. 상수 배수는 판정에
 * 안 들어온다(불변 사실 6 · 76).
 *
 * **연산 표면을 정본에 맞췄다.** 이름 여섯은 처음부터 같았다. 뺀 것은 표현 누출 셋이다 — 자식 표와
 * 끝 표시를 적은 마디 인터페이스, 뿌리와 낱말 수를 담는 private 필드, 그 둘을 채우라고 둔 생성자
 * (불변 사실 20). 물려받은 요구사항 중 두 문장도 뺐다. 「공유 경로는 유지한다」는 위 셋째 항목대로
 * 담는 모양의 이야기이고, `wordsWithPrefix` 에 달린 「사전순이면 더 좋음」은 정본 계약이 순서를 정하지
 * 않기로 한 자리다 — 자식을 정렬해 들고 다니면 어느 기법이든 그 순서를 내므로 요구해도 배제되는
 * 기법이 없고 목적과 무관한 좁힘만 남는다(정본 헤더).
 *
 * **목적.** 문자열의 집합을 담고, **어떤 접두사로 시작하는 것들을 함께** 찾는 것. 낱말 하나가
 * 있는지 묻는 일과 접두사로 시작하는 낱말 전부를 받는 일이 같은 구조에서 나온다. 비용은 **낱말
 * 길이**로 결정되고 담긴 낱말 수에 기대지 않는다. 값을 붙여 두는 일, 개수를 세는 일, 순위를 묻는
 * 일은 이 계약에 없다. 같은 낱말을 두 번 넣어도 하나다. 문자열은 코드 단위의 수열로 보고 빈 낱말도
 * 낱말이다. 상한과 순서를 그렇게 고른 근거는 정본 헤더에 있다
 * (`src/data-structures/trie/ternarySearchTree/ternarySearchTree.ts`).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도 없다」).
 *
 * **불변식.**
 * 1. `size()` 가 말하는 낱말 수와 `wordsWithPrefix("")` 가 내놓는 배열의 길이가 같다.
 * 2. `wordsWithPrefix(p)` 가 내놓는 모든 낱말에 대해 `search` 가 참이고, 그 낱말은 `p` 로
 *    시작한다.
 *
 * 정본과 같은 판별 절차를 돌린 결과이고 답도 같다 — 둘 다 관측 경로가 둘이고(세어 둔 수 대 늘어놓은
 * 수, 접두사로 받은 낱말 대 하나씩 물은 낱말) 어느 연산의 계약 줄도 그 정합을 적지 않는다. 자리마다
 * 표를 드는 구현에서도 **끝 표시와 낱말 수가 따로** 갱신되므로, 지우다가 한쪽만 고치면 각 연산이
 * 저마다 옳은 채로 둘이 갈린다.
 *
 * **연산 계약.** m 은 낱말·접두사의 길이, k 는 답으로 나가는 낱말들의 길이 합이다. n(담긴 낱말
 * 수)은 **어느 행에도 들어오지 않는다.** 표의 `worst` 는 $\sigma$ 를 상수로 접은 모형 위의 값이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `insert(word)` | `word` 를 담는다. 이미 있으면 아무것도 하지 않는다 | O(m) | worst |
 * | `search(word)` | `word` 가 담겨 있는가 | O(m) | worst |
 * | `startsWith(prefix)` | `prefix` 로 시작하는 낱말이 하나라도 있는가. 빈 접두사는 담긴 낱말이 하나라도 있으면 참 | O(m) | worst |
 * | `delete(word)` | `word` 를 지우고 지웠으면 `true`, 없었으면 `false`. 다른 낱말은 남는다 | O(m) | worst |
 * | `wordsWithPrefix(prefix)` | `prefix` 로 시작하는 낱말 전부. **순서를 정하지 않는다** | O(m + k) | worst |
 * | `size()` | 담긴 낱말 수 | O(1) | worst |
 *
 * **주입 정책.** 없다. 입력이 문자열이고 문자의 순서·동등성은 언어가 이미 정해 둔 코드 단위 기준을
 * 쓴다. 없는 낱말을 지우면 예외를 던지지 않고 `false` 를 돌려주고, 없는 접두사에 `wordsWithPrefix`
 * 는 빈 배열을 돌려준다.
 *
 * **검증 등급.** `invariant`.
 * 정본과 같은 판정이다 — **이 이름이 가리키는 기법이 정본 헤더가 든 자명한 구현 그 자체다.**
 * 자식을 표로 들고 있는 마디를 낱말 길이만큼 따라가면 여섯 행이 전부 상한 안이고, 재균형도 상각
 * 설계도 확률 논증도 들어오지 않는다(§규약1 「자명한 구현은 존재 조건이다」). 그러므로 `complexity`
 * 가 아니다. 불변식 절에 내용이 있으므로 `basic` 도 아니다.
 *
 * **필요충분조건.**
 * - 의미: 어떤 접두사에 대해서든 그것으로 시작하는 낱말 전부를 **담긴 낱말 수와 무관한 비용으로**
 *   찾을 수 있어야 한다. 이것을 「자리마다 표로 나뉘어 있어야 한다」로 쓰지 않는다 — 그것은 이
 *   조건을 얻는 한 가지 방법이고, 삼분 표현과 접힌 에지가 같은 관측을 낸다. 못 지키면
 *   `wordsWithPrefix` 가 담긴 낱말을 전부 봐야 하고, 남는 것은 문자열을 담은 배열이다.
 * - 비용: 어느 연산이든 담긴 낱말 수 n 에 기대면 이 구조가 아니다. 훑으면 배열이고 log 로 기대면
 *   정렬된 배열이다.
 */
