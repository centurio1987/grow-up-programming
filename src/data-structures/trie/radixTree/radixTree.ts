/**
 * RadixTree — 문자열 집합. 접두사로 묶어 저장하고 접두사로 찾는다.
 *
 * **이 계약은 `trie/ternarySearchTree` 의 계약과 같다.** `trie/trie` 의 계약과도 같다. 아래 연산
 * 계약 표의 여섯 행이 그 파일의 여섯 행과 글자까지 같고, 스위트도 그 파일의 `ContractSpec` 을
 * 그대로 돌린다(`./radixTree.contract.ts`). 그 사실을 감추지 않고 여기 맨 앞에 적는다 — 이름이
 * 다르다고 계약이 다른 것이 아니다(불변 사실 43). A군 판정이 이 이름을 B15 계약으로 접었다
 * (`docs/ORD-006-conventions.md` 「A군 17종 판정」 ②).
 *
 * **처분은 「존치 + 성격 전환」이다**(불변 사실 61). 갈리는 자리가 계약의 문장이 될 수 없는
 * 것뿐이고, 지우지 않는 이유는 판정이 *"계약이 담지 못한다"* 이지 *"쓸모가 없다"* 가 아니기
 * 때문이다. **계약을 적어 둔 자리는 `trie/ternarySearchTree` 이고 임시다** — 세 이름이 전부 담는
 * 모양을 가리키는 구현 이름이라 정본 이름이 정해지지 않는다(불변 사실 64). 계약 이름은 KAN-031
 * 이 정한다.
 *
 * **물려받은 문서가 이 이름의 차이로 든 셋이 전부 계약의 문장이 되지 못했다.**
 *
 * - **에지에 글자 하나가 아니라 문자열을 달고, 넣을 때 쪼개고 지울 때 합친다.** 이 기법의 실제
 *   차이인데 담는 모양의 이야기다(§규약1 「금지 — 내부 처방」 1번). 물려받은 요구사항이 「에지
 *   레이블을 적절히 분할/병합한다」 · 「불필요한 노드를 병합해 트리를 압축 유지한다」로 그것을
 *   처방하고 있었고 뺐다. 접힌 모양을 지키지 않는 구현도 같은 호출에 같은 값을 돌려준다 — 계약이
 *   말하는 상태는 담긴 낱말의 모음이다(불변 사실 79).
 * - **메모리 효율 — 마디 수가 전체 글자 수가 아니라 낱말 수를 따라간다.** 공간이고, **공간은 이
 *   저장소의 어느 계약에도 없다**(§규약1 「공간은 어느 계약에도 없다」 — 미결). 마디 수든 자리
 *   수든 그것을 관측하는 연산이 이 계약에 없다(불변 사실 67).
 * - **IP 라우팅 테이블 · 최장 접두사 매칭.** 활용 사례다(§규약1 「금지 — 내부 처방」 5번). 최장 접두사
 *   매칭을 연산으로 올려 볼 수는 있는데 **올릴 근거가 없다** — 자식을 표로 드는 트라이도 같은
 *   비용(질의 길이에 비례)에 답하므로 이 기법을 지목하지 못하고, 그 연산이 없어도 이 계약이 자기
 *   목적을 진술한다(불변 사실 47).
 *
 * **압축이 이 계약과 부딪히는 자리는 하나이고, 가르는 것은 계약이 아니라 구현이다.** 가운데서
 * 쪼갤 때 딸린 꼬리를 **새 문자열로 만들면** 그 꼬리 길이만큼 글자를 옮기고, 그 길이는 넣는 낱말의
 * 길이 m 과 무관하다. 긴 낱말 하나 곁에 그 첫 글자만 넣으면 m = 1 인데 긴 낱말의 길이만큼 든다.
 * 지워서 다시 합칠 때도 같다. **그 구현은 `insert` · `delete` 행을 어긴다.** 꼬리를 새로 만들지
 * 않고 쪼개고 합치는 구현은 여섯 행을 전부 지킨다(정본이 그렇게 한다 — `./_reference/radixTree.ts`).
 * 계약은 압축을 배제하지도 처방하지도 않는다. 배제하는 것은 **넣거나 지우는 낱말이 아닌 다른
 * 낱말의 길이에 비례하는 일**이고, 그것은 표의 상한에 이미 들어 있다.
 *
 * 실측했다(`src/data-structures/_contract/runContract.radixTree.test.ts`). 긴 낱말 여덟을 세워 두고 그
 * 첫 글자를 하나씩 넣었다 지우는 입력에서, 긴 낱말 길이 1,024 → 4,096 에 한 호출 최대 비용이
 * 정본은 4 → 4 이고 꼬리를 새로 만드는 구현은 1,027 → 4,099(성장률 3.99)다. **이 계약의 스위트는
 * 그 자리를 재지 않는다** — 스위트 시나리오의 낱말 길이가 8 로 고정이라 꼬리도 8 글자를 넘지 않고,
 * 꼬리를 새로 만드는 구현이 다섯 시나리오를 전부 통과한다. 그 사실을 자기시험이 이름으로 고정한다
 * (불변 사실 62).
 *
 * **갈리지 않는다는 것을 수치로 확인했다.** 같은 스위트 다섯 시나리오를 세 정본(삼분 · 자리마다
 * 표 · 접힌 에지)이 **전부 통과**한다. 한 호출 최대 비용(담긴 낱말 수 1,024 → 4,096)은 이렇다.
 *
 * | 시나리오 | 삼분 | 자리마다 표 | 접힌 에지 |
 * |---|---|---|---|
 * | insert | 37 → 48 | 9 → 9 | 8 → 10 |
 * | search | 21 → 27 | 9 → 9 | 13 → 14 |
 * | startsWith · wordsWithPrefix | 40 → 52 | 17 → 17 | 23 → 25 |
 * | delete | 42 → 54 | 17 → 17 | 15 → 16 |
 * | size | 1 → 1 | 1 → 1 | 1 → 1 |
 *
 * 절대 비용이 최대 5.3 배 갈리는데 성장률은 셋 다 허용 구간 안이다. 사다리를 한 칸 더 올려도
 * (4,096 → 16,384) 접힌 에지 쪽은 10 → 12 · 14 → 15 · 25 → 27 · 16 → 17 이고, 이것도 구간 안이다.
 * 상수 배수는 판정에 안 들어온다(불변 사실 6 · 76).
 *
 * **연산 표면을 정본에 맞췄다.** 이름 여섯은 처음부터 같았다. 뺀 것은 표현 누출 셋이다 — 자식 표 ·
 * 에지 문자열 · 끝 표시를 적은 마디 인터페이스, 뿌리와 낱말 수를 담는 private 필드, 그 둘을
 * 채우라고 둔 생성자(§규약1 「금지 — 내부 처방」 3번). 요구사항의 처방 문장 둘은 위 첫 항목대로 뺐다.
 *
 * **목적.** 문자열의 집합을 담고, **어떤 접두사로 시작하는 것들을 함께** 찾는 것. 낱말 하나가
 * 있는지 묻는 일과 접두사로 시작하는 낱말 전부를 받는 일이 같은 구조에서 나온다. 비용은 **낱말
 * 길이**로 결정되고 담긴 낱말 수에 기대지 않는다. 값을 붙여 두는 일, 개수를 세는 일, 순위를 묻는
 * 일은 이 계약에 없다. 같은 낱말을 두 번 넣어도 하나다. 문자열은 코드 단위의 수열로 보고 빈 낱말도
 * 낱말이다. 상한과 순서를 그렇게 고른 근거는 정본 헤더에 있다
 * (`src/data-structures/trie/ternarySearchTree/ternarySearchTree.ts`).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도 없다」).
 *
 * **불변식.**
 * 1. `size()` 가 말하는 낱말 수와 `wordsWithPrefix("")` 가 내놓는 배열의 길이가 같다.
 * 2. `wordsWithPrefix(p)` 가 내놓는 모든 낱말에 대해 `search` 가 참이고, 그 낱말은 `p` 로
 *    시작한다.
 *
 * 정본과 같은 판별 절차를 돌린 결과이고 답도 같다 — 둘 다 관측 경로가 둘이고(세어 둔 수 대 늘어놓은
 * 수, 접두사로 받은 낱말 대 하나씩 물은 낱말) 어느 연산의 계약 줄도 그 정합을 적지 않는다. 기법이
 * 달라도 절차의 답이 같은 것은 절차가 담는 모양이 아니라 상태의 성질만 보기 때문이다.
 *
 * **연산 계약.** m 은 낱말·접두사의 길이, k 는 답으로 나가는 낱말들의 길이 합이다. n(담긴 낱말
 * 수)은 **어느 행에도 들어오지 않는다.** 표의 `worst` 는 $\sigma$ 를 상수로 접은 모형 위의 값이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `insert(word)` | `word` 를 담는다. 이미 있으면 아무것도 하지 않는다 | O(m) | worst |
 * | `search(word)` | `word` 가 담겨 있는가 | O(m) | worst |
 * | `startsWith(prefix)` | `prefix` 로 시작하는 낱말이 하나라도 있는가. 빈 접두사는 담긴 낱말이 하나라도 있으면 참 | O(m) | worst |
 * | `delete(word)` | `word` 를 지우고 지웠으면 `true`, 없었으면 `false`. 다른 낱말은 남는다 | O(m) | worst |
 * | `wordsWithPrefix(prefix)` | `prefix` 로 시작하는 낱말 전부. **순서를 정하지 않는다** | O(m + k) | worst |
 * | `size()` | 담긴 낱말 수 | O(1) | worst |
 *
 * **주입 정책.** 없다. 입력이 문자열이고 문자의 순서·동등성은 언어가 이미 정해 둔 코드 단위 기준을
 * 쓴다. 없는 낱말을 지우면 예외를 던지지 않고 `false` 를 돌려주고, 없는 접두사에 `wordsWithPrefix`
 * 는 빈 배열을 돌려준다.
 *
 * **검증 등급.** `invariant`.
 * 정본과 같은 판정이다. 자식을 표로 들고 있는 마디를 낱말 길이만큼 따라가는 구현이 여섯 행을 전부
 * 상한 안에 하고 재균형도 상각 설계도 확률 논증도 들어오지 않는다 — 그러므로 `complexity` 가
 * 아니다. **에지를 접는 이 기법이 그 자명한 구현보다 손이 더 가는 것은 등급을 바꾸지 않는다** —
 * 등급은 달성하는 자명한 구현이 하나라도 있는가를 묻는다(불변 사실 55). 불변식 절에 내용이
 * 있으므로 `basic` 도 아니다.
 *
 * **필요충분조건.**
 * - 의미: 어떤 접두사에 대해서든 그것으로 시작하는 낱말 전부를 **담긴 낱말 수와 무관한 비용으로**
 *   찾을 수 있어야 한다. 이것을 「자식 하나뿐인 자리를 접어 두어야 한다」로 쓰지 않는다 — 그것은
 *   이 조건과 무관한 모양이고, 접지 않은 트라이와 삼분 표현이 같은 관측을 낸다. 못 지키면
 *   `wordsWithPrefix` 가 담긴 낱말을 전부 봐야 하고, 남는 것은 문자열을 담은 배열이다.
 * - 비용: 어느 연산이든 담긴 낱말 수 n 에 기대면 이 구조가 아니다. 그리고 **넣거나 지우는 일이 그
 *   낱말이 아닌 다른 낱말의 길이에 기대도** 이 구조가 아니다 — 꼬리를 새로 만들어 쪼개는 구현이
 *   거기서 나간다.
 */
