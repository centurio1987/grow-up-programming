/**
 * TernarySearchTree — 문자열 집합. 접두사로 묶어 저장하고 접두사로 찾는다.
 *
 * **이 계약은 `trie/trie` 의 계약과 같다.** 연산 여섯의 이름과 의미가 같고, 상한을 어디에
 * 두든 **삼분 표현이 지목되지 않는다**(아래 상한 항목). 그 사실을 감추지 않고 여기 맨 앞에
 * 적는다 — 이름이 다르다고 계약이 다른 것이 아니다(§규약1 「같은 구조인가」).
 *
 * 갈라 보려고 셋을 시도했고 셋 다 계약의 문장이 되지 못했다.
 *
 * - **상한.** 여기가 처음 쓴 것보다 복잡하다. 자식을 문자 순서로 견주어 내려가는 구현은
 *   자리마다 그 자리에 쓰인 문자들 사이를 옆으로 움직이고, 그 걸음 수는 **자식을 어떻게
 *   들고 있느냐**로 갈린다 — 균형을 잡으면 $O(\log \sigma)$, 안 잡으면 최악 $O(\sigma)$ 다.
 *   $\sigma$ 가 언어가 정한 코드 단위 가짓수로 유계이므로 **$\sigma$ 를 상수로 접으면**
 *   둘 다 $O(m)$ 이고 표로 찾는 구현과 같아진다. 접지 않으면 삼분 쪽이 **더 약하다.**
 *
 *   그런데 어느 쪽으로 적어도 이 표현이 지목되지 않는다. **강하게 적으면**($O(m)$, $\sigma$ 를
 *   접은 값) 자식을 표로 찾는 구현이 만족하고, **약하게 적으면**($O(m\sigma)$) 그 구현이
 *   **더더욱** 만족한다. 상한을 어디에 두든 배제되는 것이 없다는 것이 판정이다.
 *
 *   $\sigma$ 를 상수로 접는 것은 공짜가 아니다 — 코드 단위 가짓수가 $2^{16}$ 이므로 그
 *   "상수"가 65,536 까지 간다. 그래서 이 계약의 `worst O(m)` 은 **$\sigma$ 를 상수로 보는
 *   모형 위에서만** 성립하고, 그 사실을 감추지 않고 여기 적는다.
 * - **순서.** `wordsWithPrefix` 를 사전순으로 요구해도 자식을 정렬해 들고 다니는 구현이
 *   그것을 만족한다. 배제되는 구현이 없다.
 * - **공간.** 이 구조가 따로 이름을 가진 진짜 이유가 여기인데, **공간은 이 저장소의
 *   어느 계약에도 없다**(§규약1 「공간은 어느 계약에도 없다」). 게다가 "노드마다 알파벳
 *   크기만큼 자리를 잡는다"는 전제 자체가 이 저장소에서 성립하지 않는다 — `trie/trie` 는
 *   자식을 표로 들고 있어 실제로 쓰인 문자만큼만 자리를 쓴다.
 *
 * **그래서 이 구조는 계약이 아니라 표현으로 갈린다.** 계약이 구현을 처방하지 않기로 한
 * 이상 그 갈림은 계약에 들어올 수 없고, 자리는 가이드다(불변 사실 45).
 *
 * **목적.** 문자열의 집합을 담고, **어떤 접두사로 시작하는 것들을 함께** 찾는 것.
 * 낱말 하나가 있는지 묻는 일과 접두사로 시작하는 낱말 전부를 받는 일이 같은 구조에서
 * 나온다. 비용은 **낱말 길이**로 결정되고 담긴 낱말 수에 기대지 않는다.
 *
 * 값을 붙여 두는 일(사전), 개수를 세는 일(다중집합), 순위를 묻는 일은 이 계약에 없다.
 * 담는 것은 낱말이 있다·없다뿐이고 같은 낱말을 두 번 넣어도 하나다.
 *
 * **문자열은 코드 단위의 수열로 본다.** 길이도 비교도 언어가 문자열에 정해 둔 코드 단위
 * 기준이다. 빈 낱말도 낱말이다 — 넣으면 담기고 `search("")` 가 참이 된다.
 *
 * **불변식.**
 * 1. `size()` 가 말하는 낱말 수와 `wordsWithPrefix("")` 가 내놓는 배열의 길이가 같다.
 * 2. `wordsWithPrefix(p)` 가 내놓는 모든 낱말에 대해 `search` 가 참이고, 그 낱말은 `p` 로
 *    시작한다.
 *
 * 둘 다 관측 경로가 둘이고(세어 둔 수 대 늘어놓은 수, 접두사로 받은 낱말 대 하나씩 물은
 * 낱말) 어느 연산의 계약 줄도 그 정합을 적지 않는다. 낱말을 경로로 쪼개 담는 구현은
 * **낱말의 끝을 표시하는 자리와 낱말 수를 세는 자리가 따로**이므로, 지우다가 한쪽만
 * 갱신하면 각 연산이 저마다 옳은 채로 둘이 갈린다.
 *
 * **연산 계약.** m 은 낱말·접두사의 길이, k 는 답으로 나가는 낱말들의 길이 합이다.
 * n(담긴 낱말 수)은 **어느 행에도 들어오지 않는다** — 그것이 이 계약의 요지다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `insert(word)` | `word` 를 담는다. 이미 있으면 아무것도 하지 않는다 | O(m) | worst |
 * | `search(word)` | `word` 가 담겨 있는가 | O(m) | worst |
 * | `startsWith(prefix)` | `prefix` 로 시작하는 낱말이 하나라도 있는가. 빈 접두사는 담긴 낱말이 하나라도 있으면 참 | O(m) | worst |
 * | `delete(word)` | `word` 를 지우고 지웠으면 `true`, 없었으면 `false`. 다른 낱말은 남는다 | O(m) | worst |
 * | `wordsWithPrefix(prefix)` | `prefix` 로 시작하는 낱말 전부. **순서를 정하지 않는다** | O(m + k) | worst |
 * | `size()` | 담긴 낱말 수 | O(1) | worst |
 *
 * **`n` 이 상한에 없는 것이 이 계약의 전부다.** 낱말을 통째로 배열에 담고 훑으면
 * `search` 가 담긴 수에 비례하고, 정렬해 두고 이분 탐색을 하면 $O(m \log n)$ 이다.
 * 둘 다 이 계약을 어긴다.
 *
 * **위 표의 `m` 은 코드 단위 길이이고, `worst` 는 $\sigma$ 를 상수로 접은 모형 위의 값이다**
 * (맨 앞 상한 항목). 자리마다 옆으로 움직이는 몫이 그 상수 안에 접혀 있으므로, 표를 읽을
 * 때 그 사실을 함께 읽는다.
 *
 * **`wordsWithPrefix` 의 순서를 정하지 않는 이유**는 정하면 그 순서를 만드는 방법까지
 * 계약이 정하게 되기 때문이다. 사전순을 요구하면 자식을 순서로 들고 다니거나 답을 모아
 * 정렬해야 하고, 둘 다 이 계약의 목적과 무관한 좁힘이다.
 *
 * **`k` 를 낱말 길이의 합으로 잡은 이유**는 답을 문자열로 내놓기 때문이다. 낱말 개수로
 * 잡으면 어떤 구현도 그 상한을 지킬 수 없다 — 길이 $\ell$ 인 낱말을 만들어 내는 데
 * 최소 $\ell$ 이 든다.
 *
 * **주입 정책.** 없다. 입력이 문자열이고 문자의 순서·동등성은 언어가 이미 정해 둔 코드
 * 단위 기준을 쓴다. 없는 낱말을 지우면 예외를 던지지 않고 `false` 를 돌려주고, 없는
 * 접두사에 `wordsWithPrefix` 는 빈 배열을 돌려준다.
 *
 * **검증 등급.** `invariant`.
 * 상한이 자명한 구현으로 달성된다 — 자식을 표로 들고 있는 노드를 낱말 길이만큼 따라가면
 * 여섯 행이 전부 상한 안이고, 재균형도 상각 설계도 확률 논증도 들어오지 않는다(§규약1
 * 「자명한 구현은 존재 조건이다」). 그러므로 `complexity` 가 아니다. 불변식 절에 내용이
 * 있으므로 `basic` 도 아니다.
 *
 * **필요충분조건.**
 * - 의미: 어떤 접두사에 대해서든 그것으로 시작하는 낱말 전부를 **담긴 낱말 수와 무관한
 *   비용으로** 찾을 수 있어야 한다. 이 조건을 적을 때 「접두사에 따라 묶여 있어야 한다」로
 *   쓰지 않는다 — 그것은 이 조건을 **얻는 한 가지 방법**이고, 다른 표현(완전 해시·간결
 *   색인 등)이 같은 관측을 낼 수 있는지를 계약이 미리 닫을 이유가 없다. 못 지키면
 *   `wordsWithPrefix` 가 담긴 낱말을 전부 봐야 하고, 그러면 남는 것은 문자열을 담은 배열이다.
 * - 비용: 어느 연산이든 **담긴 낱말 수 n 에 기대면** 이 구조가 아니다. 훑으면 배열이고
 *   log 로 기대면 정렬된 배열이다. n 이 비용에서 빠지는 것이 이 구조이고, 그것을 포기하면
 *   접두사로 묶어 둘 이유가 그 자리에서 사라진다.
 */
