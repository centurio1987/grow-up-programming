/**
 * SuffixArray — 고정된 문자열의 접미사를 사전순으로 늘어놓은 색인.
 *
 * **목적.** 문자열 하나를 받아 그 **모든 접미사를 사전순으로 늘어놓은 전순서**를 주고, 그
 * 순서 위에서 부분 문자열 질의에 답하는 것. 접미사는 시작 위치로 가리키고, 순서는 순위로
 * 가리킨다 — 둘은 다른 좌표이며 계약은 둘 사이를 양방향으로 오갈 수 있게 한다.
 *
 * 문자열은 **생성 시점에 정해지고 그 뒤로 바뀌지 않는다.** 이 계약에는 상태를 바꾸는 연산이
 * 하나도 없다. 문자를 더하거나 지우는 일, 여러 문자열을 함께 색인하는 일은 이 계약에 없다.
 *
 * **문자열은 코드 단위의 수열로 본다.** 길이도 순서도 언어가 문자열에 정해 둔 코드 단위
 * 기준이고, 그래서 기본 다국어 평면 밖의 문자(서로게이트 쌍)에서는 이 사전순이 유니코드
 * 코드포인트 순서와 어긋난다. 계약이 이 사실을 감추지 않는 이유는 순서가 이 구조의 관측값
 * 자체이기 때문이다 — 어느 순서인지 적지 않으면 `at` 이 무엇을 돌려주는지가 정해지지 않는다.
 *
 * **불변식.** 없다.
 *
 * 이 계약에는 상태를 바꾸는 연산이 없다. 불변식은 연산 사이의 정합인데(§규약1 「불변식 판별
 * 절차」) 어느 연산도 상태를 바꾸지 않으므로 "연산 사이"라는 것이 생기지 않는다. 관측 경로가
 * 둘인 성질은 있다 — `at` 과 `rankOf` 는 같은 하나의 사전순 순서를 반대 방향에서 읽고,
 * `range` 가 돌려주는 구간의 원소는 `at` 으로도 짚힌다. 그러나 셋의 정합은 **각 연산의
 * 의미에 이미 적혀 있고**(셋 다 같은 하나의 순서를 참조한다) 그 의미를 대조하는 것은 축1이다.
 *
 * **연산 계약.** n 은 색인한 문자열의 길이, m 은 패턴의 길이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(s)` | 길이 n 의 문자열 `s` 를 색인한다. 돌아온 뒤의 질의는 아래 상한을 지킨다 | O(n log n) | worst |
 * | `length()` | 색인한 문자열의 길이 n | O(1) | worst |
 * | `at(rank)` | 사전순 `rank` 번째 접미사의 시작 위치. `0 <= rank < n` 밖이면 `null` | O(1) | worst |
 * | `rankOf(start)` | `start` 에서 시작하는 접미사의 사전순 순위. `0 <= start < n` 밖이면 `null` | O(1) | worst |
 * | `range(pattern)` | `pattern` 으로 시작하는 접미사들의 순위 구간 `[lo, hi)`. `lo` 는 패턴보다 작은 접미사의 수이므로 하나도 없으면 `lo === hi` 이고 그 값이 **패턴이 들어갈 자리**다. 빈 패턴은 `[0, n)` | O(m log n) | worst |
 * | `longestRepeatedSubstring()` | 두 번 이상 나타나는 가장 긴 부분 문자열. 같은 길이가 여럿이면 어느 것이든. 없으면 `""` | 구성과 합쳐 O(n log n) | worst |
 *
 * **구성 시점을 계약이 정한다.** 위 표의 질의 상한은 `constructor` 가 돌아온 **뒤**에 대한
 * 것이다. 색인이 하는 일은 짓는 비용과 묻는 비용을 나누는 것인데, 언제 짓느냐가 자유이면
 * 그 나눔이 계약에서 사라진다 — 아무것도 안 하는 생성자와 첫 질의에서 다 짓는 구현이 두
 * 상한을 모두 만족해 버리고, 그러면 구성 상한도 질의 상한도 아무 구현을 배제하지 못한다.
 *
 * **한 번 정해지고 마는 값은 구성과 묶어 적는다.** `longestRepeatedSubstring()` 은 인자가
 * 없고 색인이 바뀌지 않으므로 그 값은 색인 시점에 이미 정해져 있다. 구성 때 계산해 두면
 * 호출은 O(1) 이고, 호출 때 계산하면 O(n) 이다. **둘 다 이 계약의 목적을 해치지 않는데**
 * 상한을 따로 적으면 그중 하나를 처방하게 된다. 반복 호출되는 질의(`at`·`rankOf`·`range`)는
 * 사정이 다르다 — 호출 때마다 짓는 구현은 색인이라 부를 수 없으므로 계약이 그것을 배제한다.
 *
 * **구성 상한을 왜 하필 `O(n log n)` 로 적었는가.** 이 값은 목적에서 유일하게 따라 나오지
 * 않는다. 목적이 요구하는 것은 **이차보다 빠를 것** 하나뿐이고, 그 아래에는 후보가 여럿
 * 있는데 어느 것도 하한이 아니다(§규약1 「약한 쪽 규칙은 상한으로 확장되지 않는다」).
 * 그러므로 이것은 고른 값이고, 고른 이유를 여기 적는다.
 *
 * - **이차 이상은 계약이 뜻을 잃는다.** 접미사를 문자열로 잘라 언어 내장 정렬에 넘기면
 *   그 상한이 나온다. 그것이 상한이면 이 구조를 따로 둘 이유를 계약이 말하지 못한다.
 * - **`O(n)` 을 적으면 정본이 한 계열로 좁혀진다.** 선형 구성은 문자를 정수 구간으로 보고
 *   버킷을 만드는 유도 정렬 계열에서만 나온다. 순위 쌍을 반복해서 정렬해 올라가는 구현은
 *   $\Theta(n \log n)$ 이고, 그 구현을 배제할 이유가 이 계약의 목적에는 없다.
 * - 그 사이의 값($O(n \log \log n)$ 등)은 어느 구현 계열의 경계와도 맞지 않는다.
 *
 * 남는 것은 **정본이 서는 계급을 적는 일**이다(§규약2 「축3은 상한이 아니라 성장 계급을
 * 판정한다」가 그것을 요구한다). 순환이 아니다 — 목적이 후보를 이차 아래로 자르고, 그
 * 안에서 하나를 고르는 일만 정본이 한다.
 *
 * **질의 상한이 색인 크기에 기대는 것도 고른 것이다.** `range` 를 `O(m)` 으로 적으면
 * 정렬된 순서 위에서 구간을 좁혀 가는 구현 전부가 계약 위반이 된다 — 순서만 들고 있으면
 * 패턴을 어디서부터 찾을지 정하는 데 순서를 log 번 갈라야 하기 때문이다. `O(m)` 은 접미사
 * 트리·자동자 계열을 지목하는 처방이고, 그 계열은 **다른 계약**이다(§규약1 「같은 구조인가」).
 *
 * **주입 정책.** 없다. 입력이 문자열 하나뿐이고 문자의 순서는 언어가 이미 정해 둔 코드 단위
 * 순서를 쓴다. 비교자를 주입받지 않는 것은 편의가 아니라 계약의 일부다 — 주입을 열면 문자를
 * 정수로 다루는 구현이 전부 배제되고, 그것은 위에서 처방으로 판정한 바로 그 좁힘이다.
 * 범위 밖 접근은 예외를 던지지 않고 `null` 을 돌려준다.
 *
 * **검증 등급.** `complexity`.
 * 구성 상한이 자명한 구현으로 달성되지 않는다. 반례를 적을 수 있다 — 접미사 n 개를 문자열로
 * 잘라 언어 내장 정렬에 넘기면 비교 하나가 최악에 n 문자를 읽으므로 $\Theta(n^2 \log n)$ 이다.
 * 질의 쪽은 자명하다(정렬된 순서에 이분 탐색). 등급을 정하는 것은 구성 쪽이다.
 *
 * **필요충분조건.**
 * - 의미: 접미사들이 **사전순 전순서**로 놓이고, 어떤 패턴으로 시작하는 접미사들이 그
 *   순서에서 **연속 구간**을 이루어야 한다. 순서가 사전순이 아니면(예: 시작 위치 순)
 *   그 연속성이 깨져 `range` 가 구간을 돌려줄 수 없고, 그러면 남는 것은 색인이 아니라
 *   원문 그대로다.
 * - 비용: 구성이 문자열 길이의 제곱에 비례하면 접미사를 잘라 정렬한 것이고, 질의가 색인
 *   크기에 선형이면 색인을 지어 놓고도 원문을 훑는 것이다. **둘 다 아닌 것**이 이 구조이고,
 *   어느 한쪽을 포기하면 색인을 따로 짓는 이유가 그 자리에서 사라진다.
 */
