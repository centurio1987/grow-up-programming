/**
 * HashSet — 원소의 모임을 담고 소속을 담긴 수와 무관한 비용에 답하며, 두 모임을 견주어 새
 * 모임을 짓는다. **견주는 비용의 `n` 이 무엇인지가 이 계약의 고유한 자리다.**
 *
 * **목적.** 원소를 중복 없이 담고, 「담겨 있는가」를 담긴 수와 무관한 비용에 답하고, **두
 * 집합을 견주어 새 집합을 짓는** 일을 제공하는 것. 담긴 것 전부를 훑는 일이 담긴 수에
 * 비례하는 비용으로 붙는다. **어떤 원소가 어떤 원소보다 앞선다는 말은 이 계약에 없다** —
 * 순서를 약속하는 순간 정렬 집합이 되고 상한이 로그로 올라간다. **원소에 딸린 값도 없다** —
 * 값을 담으면 사전이고(`hash/hashMapChaining`) 두 계약은 서로 담지 않는다(불변 사실 54).
 * 담긴 원소의 수를 읽는 일도 이 계약에 없다.
 *
 * **뺀 행의 판정은 목적 항목 밖에 적는다.** `size()` 는 원칙 A 판정표 ③ 의 판정으로 뺐다 —
 * 판정 줄과 목적 인용은 `docs/ORD-006-conventions.md` 「판정표 ③ 의 103 행을 묶어 판정했다」
 * 절에, 행 단위 대장은 `tools/_baseline/principle-a-verdicts.tsv` 에 있다. 판정의 결론을 목적
 * 문단 안에 적으면 다음 판정이 자기 메아리를 근거로 읽는다(§원칙 A A5′-2).
 *
 * **「기대」가 무엇에 대한 기댓값인지는 `hash/hashMapChaining` 헤더가 정의한 것과 같다.**
 * 둘이다. ① **구현이 뽑는 무작위성에 대한 기댓값이지 입력에 대한 것이 아니다** — 「입력
 * 분포에 대한 기댓값」으로 읽으면 담을 자리를 고정된 함수로만 정하는 구현이 이 계약을
 * 만족하게 되고, 그러면 계약이 아무것도 배제하지 못한다. 그래서 **호출자가 어떤 원소를
 * 주든** 구현 자신이 만들어 내는 무작위성에 대해 기댓값이 상한 안이어야 한다. ② **호출
 * 하나가 아니라 호출 시퀀스에 대한 기댓값이다** — 같은 인스턴스에 n 번 부른 총비용의
 * 기댓값이 n × 상한 안이라는 뜻이고, 호출 하나가 담긴 수에 비례해 튀는 것은 계약을 어기지
 * 않는다.
 *
 * **이 문장이 한정자 셋 중 하나가 아니라는 사실과 그 처분은 여기서 다시 세우지 않는다.**
 * 규격이 쓸 수 있는 이름은 `worst`·`amortized`·`expected` 셋뿐이고 셋이 각각 배제하면 안
 * 되는 것을 배제한다 — 근거와 처분(뜻이 가장 가까운 `expected` 를 적고 헤더가 그 이름을
 * 정의한다)은 §규약1 「한정자 셋으로 못 적는 계약이 있다」에 있다. 축3이 재는 통계가 이
 * 문장과 정확히 같지 않다는 것도 같은 자리다 — `_contract/judge.ts` 의 `statistic` 은
 * `expected` 에 대해 반복 단위 열의 시퀀스 평균 열 중 **가운데 값**을 내고, 중앙값은 기댓값이
 * 아니다. 이 틈은 판정 규격의 한계이고 메우려면 69종 전체에 걸리는 결정이 필요하다.
 *
 * **불변식.** 하나다. **관측 경로가 둘**이라 성립한다 — 구현이 두 경로를 따로 유지할
 * 수 있고, 따로 유지하는 순간 갈린다. 어떤 연산 뒤에도 성립해야 한다.
 * 1. 임의의 원소 `x` 에 대해 `has(x)` 는 `values()` 안에 `x` 가 있는가와 같다. 담김 여부를
 *    읽는 길이 둘이다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 **한 행을 뺀 표면에 다시 돌린 결과다.** 둘 가운데
 * 「`values().length === size()`」가 사라졌다 — 담긴 수를 읽는 두 경로 가운데 세어 둔 쪽이
 * 표면에서 사라져 경로가 `values()` 하나로 줄었고 첫 번째 물음에서 걸린다. 열거가 담긴 원소
 * 전부를 내놓는지는 `values` 행의 의미라 축1이 참조 모델과 대조한다.
 *
 * 세 집합 연산은 불변식을 하나도 더하지 않는다. 후보 둘이 판별 절차에서 갈렸다. 포함·배제
 * 등식(`union` 의 크기 + `intersection` 의 크기 = 두 크기의 합)은 세 연산의 **의미의 논리적
 * 귀결**이므로 축1이 이미 매 연산 대조한다. 돌려준 집합이 피연산자와 독립이라는 것은 상태의
 * 성질이 아니라 **시간에 걸친 성질**이라 축2가 볼 수 있는 모양이 아니다 — 그 자리는 축1의
 * 경계 케이스다(불변 사실 35).
 *
 * 담는 모양의 성질(자리가 몇이고 한 자리에 몇이 매달렸는가, 적재율이 얼마인가)은 후보가
 * 아니다. 계약에 적어야 검사할 수 있는데 **적는 순간 그것이 표현을 처방한다**(불변 사실 36).
 *
 * **연산 계약.** `n` 은 **이 집합**에 담긴 원소의 수, `m` 은 인자로 받은 집합에 담긴 원소의
 * 수다. 두 값이 갈리는 자리가 아래 세 행이고, 그것이 이 계약이 정하는 것이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(spread)` | 원소를 정수로 펴는 함수를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `add(item)` | `item` 을 담는다. 이미 담겨 있으면 **상태가 바뀌지 않는다** | O(1) | expected |
 * | `has(item)` | 담겨 있으면 `true` | O(1) | expected |
 * | `delete(item)` | 지우고 `true`. 없으면 `false` 이고 상태가 바뀌지 않는다 | O(1) | expected |
 * | `values()` | 담긴 원소 전부의 배열. **순서는 계약이 정하지 않는다.** 사본이다 | O(n) | worst |
 * | `union(other)` | 둘 중 한쪽에라도 있는 원소를 담은 **새 집합** | O(n + m) | expected |
 * | `intersection(other)` | 둘 다에 있는 원소를 담은 새 집합 | O(n) | expected |
 * | `difference(other)` | 이 집합에 있고 `other` 에 없는 원소를 담은 새 집합 | O(n) | expected |
 *
 * **세 연산은 새 집합을 돌려주고 피연산자는 둘 다 바뀌지 않는다.** 그리고 돌려준 집합은 두
 * 피연산자와 **독립이다** — 뒤에 어느 쪽을 고쳐도 나머지가 바뀌지 않는다. 제자리 갱신으로
 * 적지 않은 이유는 유도의 방향이 한쪽이기 때문이다: 새 집합을 돌려주면 호출자가 그것을
 * 대입해 제자리 갱신을 만들 수 있지만, 제자리 갱신만 있으면 피연산자를 잃지 않고 결과를
 * 얻는 길이 사본을 뜨는 것뿐이고 그 사본이 `O(n)` 을 문다. 독립을 요구하는 이유는 관측
 * 때문이다 — 요구하지 않으면 결과를 들고 있는 동안 피연산자를 고쳤을 때 결과가 무엇인지를
 * 계약이 말하지 못하고, **말하지 못하는 약속은 계약이 아니다**(불변 사실 69 ③이 단일 스레드
 * 계약에서 같은 모양으로 걸린다).
 *
 * **세 행 중 둘은 하한이 값을 지목하고 하나는 아니다.** 셋을 갈라 적는다.
 *
 * - `union` — `n + m` 이고 하한이 그 값을 지목한다. 돌려주는 것이 **독립인** 집합이므로
 *   결과가 자기 저장을 가져야 하고, 어느 원소든 **읽지 않고는** 그 저장에 넣을 수 없다.
 *   그래서 양쪽 원소를 한 번씩 읽는 `n + m` 아래로 못 내려간다. **결과에 담기는 원소가
 *   `n + m` 개라는 말이 아니다** — 담기는 수는 `|A ∪ B|` 이고 두 집합이 같으면 `n` 이다.
 *   하한이 세는 것은 담긴 수가 아니라 **읽어야 하는 수**다. 독립 요구를 빼면 이 하한도
 *   사라진다.
 * - `difference` — `n` 이고 여기도 하한이 값을 지목한다. 답이 이 집합의 원소만 걸러 낸
 *   것이므로 **이 집합의 원소마다 「인자에 있는가」가 정해져야 하고**, 읽지 않은 원소에
 *   대해서는 그 값이 정해지지 않는다. 그러니 `n` 번은 읽어야 한다. `other` 에는 묻기만
 *   하고 묻는 값이 상수이므로 `m` 이 상한에 들어오지 않는다.
 * - `intersection` — **여기서는 같은 논증이 서지 않는다.** 답이 `A` 의 원소 중 일부이기는
 *   하지만 `B` 를 훑고 `A` 에 물어도 같은 답이 나오므로, 이 연산의 하한은 `n` 이 아니라
 *   `min(n, m)` 이다. **그래서 이 행의 `n` 은 따라 나온 값이 아니라 고른 값이다**(불변 사실
 *   48 — 상한은 규칙에서 따라 나오지 않는다). 고른 결과가 `difference` 와 같은 모양이고,
 *   따라 나오는 것이 하나 있다: **답은 대칭인데 상한은 대칭이 아니다** — `A.intersection(B)`
 *   와 `B.intersection(A)` 는 같은 집합을 돌려주면서 다른 상한을 진다.
 *
 * **고른 값이므로 근거를 두 물음으로 적는다**(§규약1 「상한이 목적에서 유일하게 따라 나오지
 * 않는 계약이 있다」). 물음이 실제로 무는 것은 `intersection` 행이고, `difference` 행은
 * 하한이 이미 값을 지목했으므로 아래 두 답이 그 선택을 **확인**할 뿐이다.
 *
 * - **더 약하게 `O(n + m)` 으로 적으면 무엇이 들어오는가.** 인자를 통째로 훑어 답을 짓는
 *   구현이 들어온다. 그 구현은 인자가 소속을 상수에 답한다는 사실을 하나도 쓰지 않으므로,
 *   작은 집합이 큰 집합을 인자로 받는 호출이 **인자의 크기에 비례한다.** 그러면 이 계약이
 *   소속 판정을 상수에 하기로 한 이유가 집합 연산에서 사라지고, 원소를 열거할 수 있는 아무
 *   모임(정렬 배열·목록)이 같은 비용에 세 연산을 한다 — 계약이 뜻을 잃는다.
 * - **더 강하게 `O(min(n, m))` 으로 적으면 무엇이 나가는가.** 수신자를 훑고 인자에 묻는
 *   구현이 통째로 나간다. 배제할 이유가 목적에 없다 — 작은 쪽을 고르는 것은 최적화이고,
 *   계약이 그것을 요구하면 두 크기를 견주는 일이 모든 구현의 의무가 된다. 그리고 판정
 *   규격에 그 상한을 적을 이름이 없다(§규약2 의 `Bound` 다섯).
 *
 * **두 물음의 답이 모두 실측으로 있다.** 인자를 훑는 구현은 인자를 키우는 교집합 시나리오
 * 에서 6,115.5 · 23,024.8 · 90,573.8 로 자라고($r$ = 3.76 · 3.93) 정본은 842.8 · 844.0 ·
 * 842.8 로 움직이지 않는다 — 앞쪽 물음이 말하는 「들어오는 것」이 그것이다. 뒤쪽 물음의
 * 답은 반대편에 있다: 작은 쪽을 골라 훑는 구현은 이 계약을 **지키면서** 수신자를 키우는
 * 교집합 시나리오에서 843.3 · 848.5 · 843.8 로 남아 걸린다($r$ = 1.01 · 0.99, 기대 4.00).
 * 계약을 어겨서가 아니라 계급이 아래라서다(불변 사실 49). 그리고 그것은 지어낸 설계가
 * 아니다 — **이 저장소가 도는 런타임의 `Set.prototype.intersection` 이 그렇게 한다**(실행해
 * 관측했다. 크기 3인 `Set` 에 크기 100만이라고 답하는 상대를 주면 상대의 `has` 를 세 번
 * 부르고, 반대로 주면 상대의 `has` 를 한 번도 안 부르고 `keys()` 를 훑는다). **표준 문서를
 * 확인하지는 않았으므로 「명세가 그렇게 정한다」로 적지 않는다** — 여기 서 있는 것은 한
 * 런타임에서의 관측이고, 그것으로 충분하다. 이 선택을 하는 구현이 **실재한다**는 것만
 * 보이면 되기 때문이다.
 *
 * **`difference` 의 `O(n)` 은 인자의 계약에 기대어 선다.** 인자가 소속을 상수에 답하지
 * 않으면 이 상한이 성립하지 않는다. 그래서 인자는 **같은 계약을 만족하는 집합**이어야 하고
 * 원소를 열거할 수만 있는 것(배열·이터러블)이면 안 된다 — 그때 이 행은 `n · m` 이 된다.
 * 상한 하나가 다른 계약 조항에 기대는 모양이고, 여기서는 기대는 대상이 같은 구조의 다른
 * 행이 아니라 **인자의 계약**이라는 점만 다르다.
 *
 * **`values` 가 `worst` 인 것은 세 한정자가 아무것도 다르게 배제하지 않기 때문이다.** 담긴
 * 것 n 개를 배열에 적는 일은 어느 구현에서도 호출 하나가 n 에 비례하므로 상각할 여지도
 * 무작위성이 개입할 자리도 없다. 그럴 때는 더 말이 되는 쪽을 적는다(§규약1 B9 단서). 이
 * 행이 실제로 배제하는 것은 하나다 — **담긴 수와 무관하게 커진 자리를 훑어야만 열거되는
 * 구현.** 담긴 것을 따로 이어 두면 자리를 얼마나 쓰든 이 행을 지키므로, 이것은 공간 제약이
 * 아니라 열거 비용에 대한 요구다.
 *
 *
 * **세 집합 연산이 `expected` 인 것은 두 쪽에서 온다.** 하나는 담기다 — 답을 짓는 일이
 * 결국 새 집합에 담기를 여러 번 부르는 일이고 그 담기가 구현이 뽑는 무작위성 위에 서 있다.
 * 다른 하나는 **인자에 묻기**다: `intersection`·`difference` 는 `n` 번 묻고 그 물음 하나가
 * 인자의 `has` 행, 곧 인자의 `expected` 약속에 기댄다. 둘 중 하나만 들어도 이 세 행이
 * `worst` 일 수 없다 — `worst` 로 적으면 무작위를 뽑는 구현이 나가는데 그것이 이 계약이
 * 요구하는 바로 그 일이다.
 *
 * **`constructor` 가 `worst` 인 것은 근거가 다르다.** 이 생성자가 하는 일이 함수 하나를
 * 붙들어 두는 것뿐이고, 축3이 이 행을 재지 않는다(§규약2 축3 면제 — n 에 대해 반복 호출되는
 * 연산이 아니다).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로 담긴 수보다 훨씬 많은 자리를
 * 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **`hash/hashMapChaining` 과는 서로 담지 않는다**(불변 사실 54). 그쪽은 `get(key): V` 로
 * 값을 돌려주므로 **값을 담을 자리가 없는 구현**이 만족하지 못하고, 이쪽은 세 집합 연산을
 * 요구하므로 **그 표면이 없는 사전 구현**이 만족하지 못한다. 반례가 양쪽에 하나씩 있으므로
 * 어느 쪽도 상대를 담지 않는다.
 *
 * **이름은 임시가 아니다.** 계약 이름인 「집합」이 구조 이름 안에 있다(불변 사실 66).
 * 앞머리의 `hash` 와 카테고리 `hash/` 가 구현 기법의 이름인 것은 별건이고 KAN-031 이 정한다.
 *
 * **주입 정책.**
 * - 주입받는 것은 **원소를 정수로 펴는 함수 하나**이고, 생성자가 고정한다. 선택이 아니라
 *   필수다 — 기본값을 두면 그 기본값이 고정 함수이므로 아래 조건을 계약이 스스로 어기게 된다.
 * - 주입자가 지켜야 할 것 셋. ① **순수해야 한다** — 같은 원소에 언제나 같은 정수.
 *   ② **원소의 동등성과 맞아야 한다** — `Object.is` 로 같은 두 원소는 같은 정수여야 한다.
 *   ③ **원소의 차이를 지우지 말아야 한다.**
 * - **③ 이 없으면 상한이 성립하지 않는다.** 모든 원소를 0 으로 보내는 함수는 ①·②를 지키는
 *   정당한 함수인데, 그것을 받은 구현에게는 담긴 원소를 가를 수단이 없다 — **어떤 구현도**
 *   그 조건에서 상한을 지킬 수 없다. 그래서 위 표에서 `values` 를 뺀 여섯 행은
 *   조건부다: 같은 정수로 가는 원소가 담긴 것 중 `c` 개면 그 원소들에 드는 비용이 `c` 에
 *   비례한다.
 * - **③ 은 「잘 섞어라」가 아니다.** 흩는 일은 구현의 몫이고, 주입자에게 요구하는 것은 정보를
 *   남기라는 것뿐이다. 둘을 합쳐 주입자에게 좋은 흩기를 요구하면 그 순간 계약이 무너진다 —
 *   주입자가 고른 것은 **고정 함수**이므로 그것을 역산한 원소 묶음이 존재하고, 「호출자가
 *   어떤 원소를 주든」이 다시 거짓이 된다.
 * - **두 피연산자가 서로 다른 펴기를 써도 된다.** 같은 펴기를 요구하지 않는다 — 요구해서
 *   얻는 것은 「두 표의 자리가 맞는다」뿐인데 그것은 표현에 대한 진술이라 계약이 쓸 수 없고,
 *   요구하지 않아서 잃는 것은 없다(펴기가 정하는 것은 자리이지 의미가 아니다). 돌려주는 새
 *   집합이 어느 펴기를 쓰는지도 같은 이유로 계약이 정하지 않는다. **수신자의 펴기를 인자
 *   쪽 원소에 써도 되는 것은 ①이 이미 답한다** — 펴기는 원소 타입 전체에 정의된 순수
 *   함수이고, 인자도 같은 타입의 집합이다.
 * - 돌려주는 정수는 32비트로 읽는다. **완전한 단사를 요구하지 않는다** — 원소 공간이
 *   무한이면 32비트로 단사가 불가능하다. 요구는 담긴 원소들 사이에서 지켜지면 되고, 안
 *   지켜지는 몫은 위 조건부 문장이 답한다.
 * - 원소의 동등성은 `Object.is` 다. 던지는 자리가 없다 — 담기지 않은 원소를 묻거나 지우는
 *   것은 오류가 아니라 답이 있는 물음이다.
 *
 * **검증 등급.** `complexity`.
 * 판정 절차의 2번에서 걸린다 — **상한이 자명한 구현으로 달성되지 않는다.** 자명한 구현은
 * 「배열·객체의 기본 연산만으로, 재균형·상각 설계·**확률 논증 없이** 상한이 나오는 구현」인데,
 * 이 계약의 상한은 확률 논증에서만 나온다. 자명한 길 셋을 실제로 지어 재 봤고 셋 다 막힌다.
 *
 * - **차례로 담고 훑기** — 담기·찾기·지우기가 선형이다(담기가 연산당 511.5 · 2,047.5 ·
 *   8,191.5, $r$ = 4.00). 인자를 키우는 교집합·차집합 시나리오도 함께 걸린다.
 * - **정렬해 두고 이분 탐색** — 담기·지우기가 선형이고(담기가 263.2 · 1,034.6 · 4,122.3,
 *   $r$ = 3.93 · 3.98), 찾기는 로그라 이 계약의 `O(1)` 을 **어기는데 축3이 그 위반을 못
 *   본다**(10 · 12 · 14, $r$ = 1.20 · 1.17. §규약2 「계약 위반을 축3이 놓치는 자리」).
 * - **펴기 값을 그대로 자리로 쓰기** — 무작위 원소에서는 세 행이 전부 통과하고(담기가 8.62 ·
 *   8.63 · 8.64), `i * 65536` 같은 원소 묶음에서 셋이 선형이 된다(담기가 519.97 · 2,055.99 ·
 *   8,200.00, $r$ = 3.95 · 3.99). 그 원소 묶음은 위 주입 정책이 요구하는 것을 전부 지킨다.
 *   **자리를 고정 함수로 정하면 그런 묶음이 반드시 있다** — 원소 공간이 32비트보다 넓으면
 *   비둘기집으로 같은 자리에 가는 원소가 무한히 많고, 그중 n 개를 고르면 된다. 계산까지
 *   쉬운지는 함수에 달렸고(나머지 계열은 쉽다) **계약이 요구하는 것은 존재뿐이다.**
 *
 * **집합 연산 쪽에도 막히는 길이 있고, 그것이 위 셋과 독립인 이유다.** 정렬해 두는 설계는
 * 세 집합 연산을 **병합 하나로** 내므로 셋 다 `n + m` 이다 — 담기·찾기의 상한을 잊고 보면
 * 그 설계가 집합 연산에서는 정본과 같은 계급에 선다. 갈리는 자리는 인자를 키울 때이고
 * (2,112 · 8,256 · 32,832, $r$ = 3.91 · 3.98 대 정본의 상수), 그 갈림이 곧 아래 비용
 * 조건이다.
 *
 * **언어가 내주는 `Set` 에 위임하는 길은 이 판정에서 자명한 구현으로 세지 않는다.** 그것은
 * 상한을 배열·객체의 기본 연산에서 **얻는** 것이 아니라 같은 계약을 이미 만족하는 다른
 * 구현을 부르는 것이고, 등급이 묻는 것은 그 상한이 어디서 나오는가다. **등급 규격이 이
 * 자리를 명시하지 않는다는 것을 함께 적어 둔다**(T3-01 이 `Map` 에서 같은 물음을 냈고
 * 미결로 남겼다). 다만 이 계약에서는 미결이 하나 좁혀진다 — 얇게 감싸 위임한 구현은 등급
 * 판정과 무관하게 **이 계약의 축3을 통과하지 못한다.** `Set.prototype.intersection` 이
 * 작은 쪽을 훑기 때문이고, 위에 적은 그대로다.
 *
 * **필요충분조건.**
 * - 의미: 원소의 모임을 담는 일 · 소속을 **원소로** 묻는 일 · 두 집합을 견주어 **새 집합을
 *   짓는** 일 셋 중 하나라도 버리면 이 구조가 아니다. 셋째를 버리면 값 없는 사전이고(사전
 *   계약의 구현이 그대로 만족한다), 둘째를 버리면 그냥 원소를 이어 둔 목록이며, 원소마다
 *   값을 딸리면 사전이다.
 * - 비용: **인자의 크기가 `union` 에만 상한으로 들어오는 것**이 이 계약의 비용 조건이다.
 *   교집합·차집합이 인자의 크기에 비례하면 소속 판정을 상수에 하기로 한 약속을 집합 연산이
 *   하나도 쓰지 않는 것이고, 그때 이 구조는 원소를 열거할 수 있는 아무 모임과 갈리지
 *   않는다 — 정렬 배열 둘을 병합해도 같은 비용이 나온다. 그리고 그 상한이 **호출자가 고른
 *   원소에 대해** 성립해야 한다. 자리를 고정 함수로 정하면 그것을 역산한 원소 묶음에서
 *   총비용이 담긴 수의 제곱이 되고, 그때 이것은 집합이 아니라 목록이다.
 */
