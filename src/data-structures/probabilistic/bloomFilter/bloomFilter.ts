/**
 * BloomFilter — 넣은 원소에는 늘 참으로 답하고, 넣지 않은 원소에는 정해 둔 몫 이하로만 참으로 잘못 답하는 소속 판정. 지우기가 없다.
 *
 * **목적.** 문자열을 넣고 「넣었는가」를 묻는 일을 **담긴 수와 무관한 비용**에 제공하되, 답이 한쪽으로만 틀리는 것을
 * 허용하는 것. 넣은 원소에 거짓으로 답하는 일(거짓 음성)은 없고, 넣지 않은 원소에 참으로 답하는 일(거짓 양성)은 생성
 * 때 받은 **용량 n** 과 **목표 거짓 양성률 ε** 이 정한 몫 이하다.
 *
 * **두 매개변수가 계약이고, 물려받은 두 매개변수는 표현이었다.** 물려받은 생성자는 `(size, hashCount)` — 비트 배열의 길이와
 * 해시 수 — 를 받았다. 그것은 한 표현의 눈금이라 오차를 그 둘로 적으면 그 표현을 처방한다(`docs/ORD-006-conventions.md`
 * 「A군 17종 판정」 ④ — `heap/daryHeap` 의 갈래 수와 같은 자리). 호출자가 고르는 것은 「몇 개를 넣을 것인가」와 「얼마나
 * 틀려도 되는가」다. 물려받은 문서의 「size = 1 이면 모든 질의가 참」 같은 문장은 그 표현에서만 참이라 옮기지 않았다(불변
 * 사실 38).
 *
 * 이 계약에 없는 것은 넷이다.
 *
 * - **공간.** 필터가 존재하는 이유 — 원소를 담지 않고 소속에 답해 자리를 아낀다 — 는 계약이 아니다(§규약1 「공간은 어느
 *   계약에도 없다」). 그래서 **넣은 원소를 빠짐없이 담는 정확한 집합도 이 계약을 지킨다** — 거짓 양성이 0 이라 ε 이하다.
 *   반대로 필터는 `hash/hashSet` 의 계약을 못 지킨다(넣지 않은 원소에 참으로 답한다). 이쪽이 **더 적게 약속하는 다른
 *   계약**이다(불변 사실 43).
 * - **지우기.** `probabilistic/cuckooFilter` 와 갈리는 자리다 — 칸을 함께 쓰는 표현은 지우면 다른 원소가 거짓 음성이 된다
 *   (판정 전문은 「A군 17종 판정」 ②).
 * - **넣기의 실패.** `add` 는 실패를 돌려주지 않는다. 용량을 넘겨 넣어도 넣은 원소는 참이다 — 넘긴 뒤에 서지 않는 것은
 *   확률 쪽 보장뿐이다. 뻐꾸기 필터 계약과의 반례 둘째가 이것이다(가득 차면 넣기를 거절하는 구현이 이 계약을 어긴다).
 * - **담긴 수 · 채워진 몫 · 필터끼리 합치기.** 물려받은 표면에 없고, 없으면 목적을 진술하지 못하는 연산이 아니다(불변
 *   사실 47). 채워진 몫은 표현을 읽는 값이다.
 *
 * **이름은 임시다.** 「블룸 필터」는 비트 배열에 해시 여럿을 거는 **기법의 이름**이다. 계약이 말하는 것은 「지우기 없는
 * 근사 소속 집합」이고 계약 이름은 KAN-031 이 정한다(불변 사실 198).
 *
 * **불변식.** 없다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 소속을 읽는 공개 연산이 `has` 하나라 첫 물음에서 걸린다. 「넣은
 * 원소는 참」은 `has` 행의 의미이고 축1이 본다. 「켜진 비트 수」 같은 조건은 표현의 성질이라 후보가 아니다(불변 사실 36).
 *
 * **연산 계약.** n 은 생성자가 받은 **용량**, L 은 인자 문자열의 길이(UTF-16 코드 단위 수), ε 은 목표 거짓 양성률이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(capacity, falsePositiveRate)` | 용량 n · 목표 ε 인 빈 필터를 연다 | O(n · log(1/ε)) | worst |
 * | `add(item)` | `item` 을 넣는다. 반환이 없고 실패하지 않는다. 이 뒤로 `has(item)` 은 늘 참이다 | O(L · log(1/ε)) | expected |
 * | `has(item)` | 넣은 원소면 **반드시 참**. 넣지 않은 원소면 참이거나 거짓이고, 참일 확률을 아래 「오차 보장」이 누른다 | O(L · log(1/ε)) | expected |
 *
 * **오차 보장.** 확률 문장 하나와 그것을 판정하는 문장 하나다.
 *
 * - **확률 문장.** 넣은 **서로 다른** 원소가 n 개 이하인 동안, 넣지 않은 원소 x 에 대해 `has(x)` 가 참일 확률이 ε
 *   이하다. 같은 원소를 거듭 넣는 것은 한 번으로 센다.
 * - **확률의 출처는 구현이 뽑는 무작위다 — 입력의 분포가 아니다.** 넣을 원소와 물을 원소가 **필터가 무작위를 뽑기
 *   전에** 정해져 있으면 어떤 묶음이든 이 문장이 선다. 필터의 답을 보고 다음에 물을 원소를 고르는 호출자는 덮지
 *   않는다. 이 출처를 고른 근거는 셋이다.
 *   1. 입력 분포로 읽으면 계약이 그 분포에 이름을 붙여야 하는데 문자열에는 그럴 분포가 없고(주소 · 차례 번호는 고르게
 *      흩어져 있지 않다), **고르게 뽑은 원소에서만 성립하는 고정 해시가 계약을 지키게 된다** — 줄지은 키에서 무너지는
 *      해시를 계약이 배제하지 못한다. `hash/hashSet` 헤더가 「기대」를 입력 분포로 읽지 않은 이유와 같다.
 *   2. 같은 저장소의 확률 문장이 출처를 하나로 가져야 나란히 읽힌다 — `hash/hashSet` · `hash/hashMapChaining` 의
 *      「기대」가 이미 구현의 무작위다.
 *   3. 스위트가 원소를 고정 seed 로 **줄지어** 정할 수 있다. 출처가 구현 쪽이므로 어떤 고정 묶음도 정당한 입력이다.
 *
 *   따라 나오는 것 하나 — **원소를 자리로 보내는 함수를 고정한 구현은 이 계약을 어긴다.** 그 함수에 대해 헷갈리는 원소가
 *   실재하고, 그 원소를 미리 고른 호출자에게 확률이 1 이다. 스위트는 구현을 읽지 않고는 그 원소를 짓지 못하므로(불변
 *   사실 44) **그 위반은 스위트를 통과한다** — 이름을 적어 둔다(불변 사실 62,
 *   `src/data-structures/_contract/_fixtures/fixedSeedBloomFilter.ts`).
 * - **판정 문장과 여유.** 스위트는 확률 문장을 축1 안에서 이렇게 판정한다(2026-09-15 유저 결정 — 축을 늘리지 않는다).
 *   고정 seed 로 서로 다른 원소 n 개를 넣고, 넣지 않은 서로 다른 원소 N 개(N · ε = 64)를 물어 **참의 수가 2 · ε · N
 *   이하인가**를 관측값으로 돌려준다. **여유는 2 다.** 넣지 않은 원소마다 따로 확률 ε 로 참을 내는 구현 — 확률 문장을
 *   경계에서 지키는 구현 — 이 한 판정에서 떨어질 확률이 체르노프 부등식으로 e^{−64/3}(약 5 × 10^−10) 이하이고, 여유를
 *   줄이면 그 상한이 빠르게 커진다(실측은 `./bloomFilter.contract.ts` 머리말).
 * - **판정 문장은 확률 문장과 같지 않다 — 틈 하나를 적어 둔다.** 확률 문장은 원소 하나씩에 대한 것이라, **답을 한데 몰아
 *   내는 구현** — 생성 때 동전을 한 번 던져 확률 ε 로 넣지 않은 원소 전부에 참을 내는 것 — 도 지킨다. 그 구현은 판정에서
 *   확률 ε 로 떨어진다. `hash/hashSet` 의 `expected` 판정이 기댓값이 아니라 중앙값을 재는 틈과 같은 모양이다(§규약2
 *   「`expected` 통계는 기댓값이 아니라 중앙값이다」).
 *
 * **`add` · `has` 가 `expected` 인 이유.** 「기대」의 뜻은 `hash/hashSet` 헤더가 정의한 것과 같다 — 구현이 뽑는 무작위에
 * 대한, 호출 **시퀀스** 총비용의 기댓값이다. 이 계약이 배제하려는 것은 담긴 수 · 용량에 비례하는 구현이고, 그것을 배제하는
 * 가장 약한 한정자가 이 뜻의 `expected` 다(불변 사실 21 · 59). 정본(비트 배열)은 호출마다 같은 비용이라 `worst` 로도
 * 지키지만, `worst` 를 적으면 **자리를 무작위 해시로 찾고 이웃을 훑는 정확한 집합**(`hash/hashSet` 의 정본이 그것이다)이
 * 나간다. 그 배제를 목적이 요구하지 않는다.
 *
 * **상한에 log(1/ε) 가 드는 이유 — 고른 값이다(불변 사실 48 · 51).**
 *
 * - **더 강하게 `O(L)` 로 적으면** ε 가 작을수록 원소 하나가 자리를 여럿 켜는 구현 — 이름이 가리키는 기법 — 이 나간다.
 *   남는 것은 자리 하나만 켜고 오차를 자리 수로만 맞추는 구현이다. 이름의 기법을 배제할 근거가 목적에 없다. `O(L +
 *   log(1/ε))` 도 같은 판정이다 — 원소를 자리마다 새로 해시하는 구현이 나가고 그 배제도 목적에 없다.
 * - **더 약하게 `O(L / ε)` 로 적으면** 넣지 않은 원소 하나를 물을 때 1/ε 자리를 훑는 구현이 들어온다. ε 를 용량의 역수
 *   가까이 낮추면 물음 하나가 담긴 수에 비례하는 셈이 되어, 위 목적의 「담긴 수와 무관한 비용」이 ε 를 고르는 순간 사라진다.
 *
 * **축3은 L · ε 몫을 재지 않는다** — 사다리가 용량 n 만 키우고 L · ε 를 상수로 누른다(§규약2 시나리오 규칙 3). 생성자는 n
 * 에 대해 반복 호출되지 않아 시나리오 면제다(시나리오 규칙 2). 그 행의 `O(n · log(1/ε))` 는 필터를 여는 준비를 허용하는
 * 값이고, 준비를 미루는 구현도 만족한다.
 *
 * **이 계약은 시간과 오차만 말한다.** 원소를 전부 담아 자리를 더 쓰는 구현도 지킨다(위 「공간」). 공간을 계약에 넣는 규격
 * 결정이 나면 이 목적 문단을 다시 연다(불변 사실 58).
 *
 * **주입 정책.**
 * - **주입받는 것이 없다.** 원소 타입은 문자열로 고정하고, 원소의 동등성은 문자열 값이 같은가(`===`)다.
 * - **`hash/hashSet` 처럼 원소를 정수로 펴는 함수를 받지 않는다 — 확률 문장이 주입자에 매달리기 때문이다.** 32비트
 *   정수로 펴면 같은 정수로 가는 서로 다른 원소가 반드시 있고, 그 둘은 **어떤 구현도** 가르지 못한다. 그런 원소를 넣지
 *   않은 쪽으로 물으면 확률이 1 이다. `hash/hashSet` 에서는 그 몫이 비용(조건부 상한)에만 걸렸는데 여기서는 답의 옳음에
 *   걸린다. 문자열 전체를 구현이 읽으면 가르는 일이 구현의 무작위로 넘어간다.
 * - **해시 함수도 씨앗도 주입받지 않는다.** 씨앗을 아는 호출자에게 그 구현은 고정 함수와 같다(`docs/ORD-006-conventions.md`
 *   「무작위를 쓰는 정본과 재현성」 규칙 2).
 * - `capacity` 는 0 이상의 정수여야 하고 아니면 생성자가 `RangeError` 를 던진다. **0 은 정당하다** — 확률 쪽 보장이 빈
 *   필터에만 걸리고, 넘겨 넣은 원소도 참이다.
 * - `falsePositiveRate` 는 0 보다 크고 1 보다 작은 수여야 하고 아니면(`NaN` 포함) `RangeError` 다. ε ≥ 1 은 늘 참으로 답하는
 *   구현을 정당화해 뜻이 없고, ε = 0 은 정확한 집합을 요구해 상한의 log(1/ε) 가 서지 않는다.
 * - `add` · `has` 는 던지지 않는다. 넣지 않은 원소를 묻는 것은 오류가 아니라 답이 있는 물음이다.
 *
 * **검증 등급.** `basic`.
 * 상한이 자명한 구현으로 달성된다 — 비트 배열 하나에 문자열 해시를 k = ⌈log₂(1/ε)⌉ 번 거는 구현은 호출마다 L 과 k 에
 * 비례해 끝나고, **그 시간**에 확률 논증이 들지 않는다. 오차 보장에는 확률 논증이 들지만 등급을 올리지 않는다 — 판정 절차
 * 2번은 시간 상한만 읽는다(불변 사실 203). 등급이 정하는 것은 축3 엄격도이고 오차는 축1이 판정한다. 불변식 절이 비었다.
 *
 * **필요충분조건.**
 * - 의미: 넣은 원소에 거짓 음성이 **없고**, 용량 이내에서 넣지 않은 원소에 참으로 답할 확률이 **ε 이하**여야 한다. 앞을
 *   버리면 늘 거짓으로 답하는 구현이, 뒤를 버리면 늘 참으로 답하는 구현이 계약을 지킨다 — 둘 다 소속에 대해 아무것도 말하지
 *   않는다. 지우기를 더하면 뻐꾸기 필터의 계약이고, 거짓 양성을 없애면 집합이다.
 * - 비용: `add` · `has` 가 담긴 수나 용량에 비례하면 넣은 원소를 늘어놓고 훑는 목록이다 — 답을 틀리게 허용하고도 소속을
 *   담긴 수와 무관하게 묻는다는 값이 남지 않는다.
 */
export class BloomFilter {
  constructor(capacity: number, falsePositiveRate: number) {
    throw new Error("Not implemented");
  }

  add(item: string): void {
    throw new Error("Not implemented");
  }

  has(item: string): boolean {
    throw new Error("Not implemented");
  }
}
