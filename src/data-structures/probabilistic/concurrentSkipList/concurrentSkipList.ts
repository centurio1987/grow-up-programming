/**
 * ConcurrentSkipList — 여러 스레드가 함께 쓰는 정렬 집합. 연산 하나하나가 호출과 반환
 * 사이의 한 시점에 일어난 것으로 보이고(선형화), 어느 스레드가 멈춰도 나머지 중 하나는
 * 자기 연산을 끝낸다(진행 보장).
 *
 * **이 계약이 `probabilistic/skipList` 와 어디서 갈리는지를 맨 앞에 적는다.** B1 의 진단은
 * 둘의 계약이 같다는 것이었고 그 진단은 옳았다 — 물려받은 표면은 원소 하나짜리 집합 연산과
 * 정렬 질의뿐이었고, 단일 스레드에서 그것은 `skipList` 의 계약과 같은 문장이다. 이름만
 * `Concurrent` 였다. 갈리는 것을 **계약에 넣는 것**이 이 재집필이고, 넣은 것은 둘이다.
 *
 * 1. **동시 접근이 계약에 들어왔다.** 선형화와 진행 보장은 순차 계약의 문장으로 쓸 수 없다.
 * 2. **연산 집합이 줄었다.** 크기와 전체 열거가 빠졌다(아래 목적 항목). 남은 다섯은 전부
 *    원소 하나를 다룬다.
 *
 * 그래서 등급도 갈린다 — 이쪽은 `concurrency`, `skipList` 는 그 등급이 아니다. 등급이
 * 다르면 계약이 같을 수 없다(`docs/ORD-006-conventions.md` §규약1 「등급이 다르면 계약이
 * 같을 수 없다」). 반례를 찾기 전에 이것으로 먼저 갈린다.
 *
 * **이 스텁을 채워도 계약을 만족할 수 없다.** 단일 스레드 TypeScript 에는 스레드가 없으므로
 * 선형화도 진행 보장도 표현되지 않는다 — 어길 수도 없고 지킬 수도 없다. 규약4 **(가)** 등급이
 * 그것이고, 정본은 Rust 에 있다(`rust/structures/src/concurrent_skip_list.rs`). 여기 표면을
 * 그대로 두는 이유는 계약이 사는 자리가 `<name>.ts` 헤더 한 곳이기 때문이다(§규약1).
 *
 * **목적.** 여러 스레드가 동시에 부르는 **정렬 집합**을 호출자 쪽 잠금 없이 제공하는 것.
 * 값이 있다·없다를 담고, 넣고 빼고 묻는 일과 양 끝(최소·최대)을 읽는 일이 담긴 원소 수에
 * 비례하지 않는 비용으로 되어야 한다. 같은 값을 두 번 넣어도 하나다.
 *
 * 이 계약이 약속하는 것은 **원소 하나 단위의 관측**뿐이다. 그래서 크기(`size`)와 전체 열거
 * (`toArray`)가 없다. 둘은 여러 원소를 **한 시점의 것으로 함께 보는 관측**이고, 선형화
 * 대상으로 넣는 순간 모든 삽입·삭제가 그 관측과 원자적으로 묶여야 한다 — 원소 하나만 묻는
 * 쓰임에서도 그 값을 치르게 되므로, 넣으면 계약이 배제하는 구현 집합이 통째로 달라진다.
 * 뺀 것이 아니라 다른 계약이다. 근사값을 돌려주는 크기를 두는 길도 있지만, 그것은 이 계약이
 * 내건 「한 시점에 일어난 것으로 보인다」를 그 연산에서만 취소하는 일이라 두지 않는다.
 *
 * 공간 비용도 이 계약에 없다(§규약1 「공간은 어느 계약에도 없다」). 이 자리에서 그 부재가
 * 특별한 이유는 **지운 원소의 메모리를 언제 되돌려주는가**가 lock-free 구조의 실제 난점이고
 * (읽고 있는 스레드가 남아 있을 수 있다), 계약이 시간만 말하므로 그 난점이 계약의 문장이
 * 되지 못하기 때문이다. 자리는 가이드다.
 *
 * **불변식.** 없다.
 * 상태를 읽는 경로는 `has` · `min` · `max` 셋인데, 그 셋의 정합을 `min`·`max` 의 의미 열이
 * 이미 적고 있다 — *담긴 것 중 가장 작은/큰 것* 이라는 말이 「돌려준 값은 담겨 있다」와
 * 「그보다 작은/큰 값은 담겨 있지 않다」를 함께 말한다. 불변식 판별 절차의 2번에서 걸린다
 * (§규약1 「불변식 판별 절차」). 그러므로 공집합이고, 미작성이 아니다.
 *
 * **연산 계약.** n 은 **그 연산이 선형화되는 시점**에 담긴 원소 수다. 동시 실행에서 원소 수는
 * 호출 도중에도 바뀌므로, 상한을 말하려면 어느 시점의 n 인지를 함께 정해야 한다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `insert(value)` | `value` 를 담고 `true`. 이미 있었으면 아무것도 하지 않고 `false` | O(log n) | expected |
 * | `delete(value)` | `value` 를 지우고 `true`. 없었으면 `false` | O(log n) | expected |
 * | `has(value)` | `value` 가 담겨 있는가 | O(log n) | expected |
 * | `min()` | 담긴 것 중 가장 작은 값. 비어 있으면 `null` | O(log n) | expected |
 * | `max()` | 담긴 것 중 가장 큰 값. 비어 있으면 `null` | O(log n) | expected |
 *
 * **위 상한은 홀로 실행에 대한 값이다.** 경합 중에 다른 스레드의 변경 때문에 다시 도는 몫은
 * 상한이 규정하지 않는다 — 그것을 규정하는 것이 아래 진행 보장이다. 둘을 한 문장으로 묶으면
 * 「경합이 없을 때의 비용」과 「경합이 있을 때의 완료」가 뒤섞여 어느 쪽도 검사할 수 없게 된다.
 *
 * **선형화.** 동시 실행이 남긴 기록에 대해, 각 연산을 자기 호출과 반환 사이의 한 시점에 놓는
 * 순차 순서가 존재하고, 그 순차 실행이 위 표의 의미와 같은 값을 내놓아야 한다. `insert` 가
 * `true`/`false` 를 돌려주는 것이 이 약속의 관측 지점이다 — 두 스레드가 같은 값을 동시에
 * 넣으면 **`true` 를 받는 쪽이 정확히 하나**여야 한다. 돌려주는 값이 없으면 그 사실을 아무도
 * 관측하지 못하고, 관측되지 않는 약속은 계약이 아니다.
 *
 * **진행 보장.** 임의의 스레드를 임의 시점에 멈추거나 임의로 느리게 해도, 진행 중인 나머지
 * 스레드 중 적어도 하나는 유한 단계 안에 자기 연산을 끝낸다(lock-freedom). 이것이 배제하는
 * 것은 **잠금으로 감싼 정렬 집합**이다 — 잠금을 쥔 스레드가 멈추면 나머지가 전부 멈추므로,
 * 각 연산이 아무리 빨라도 이 문장을 어긴다. 개별 스레드의 굶주림 부재(wait-freedom)까지는
 * 요구하지 않는다. 요구하면 재시도로 도는 구현 계열이 통째로 나가는데, 배제할 이유가 목적에
 * 없다.
 *
 * **상한을 왜 `expected O(log n)` 으로 골랐는가.** 이보다 약하게(`O(n)`) 적으면 정렬을
 * 유지할 이유가 사라진다 — 값을 훑어 최소를 찾는 lock-free 해시 집합이 다섯 행을 전부
 * 만족하고, 그러면 계약이 자기 목적을 진술하지 못한다. 이보다 강하게(`worst O(log n)`)
 * 적으면 확률에 기대어 균형을 얻는 계열이 통째로 나가는데, **그 배제를 요구하는 것이 목적에
 * 없다**(§규약1 「상한이 목적에서 유일하게 따라 나오지 않는 계약이 있다」). `amortized` 도
 * 같은 자리에서 강하다 — 확률 구조는 개별 시퀀스의 상각 상한을 약속하지 못한다. 셋 중
 * 배제하려는 것(담긴 수에 비례하는 탐색)을 배제하면서 가장 약한 것이 `expected` 다.
 *
 * **주입 정책.** 순서를 주입받는다. 이 표면에서는 비교자이고, 정본에서는 그 언어의 순서
 * 구현이다. 주입자가 지켜야 할 조건이 셋이다.
 *
 * 1. 전순서여야 한다 — 어떤 두 값에 대해서도 대소가 정해지고, 추이적이어야 한다.
 * 2. **순수해야 한다.** 같은 두 값에 대해 언제 불러도 같은 답을 내야 한다. 이 조건은 순차
 *    계약에서도 필요하지만 여기서는 성격이 다르다 — 비교자가 상태를 들고 있으면 두 스레드가
 *    같은 두 값을 다르게 비교할 수 있고, 그때는 「정렬 순서」라는 말 자체가 정의되지 않는다.
 * 3. 자기 안에서 이 구조를 다시 부르지 않아야 한다.
 *
 * 없는 값을 지우면 예외를 던지지 않고 `false` 를 돌려주고, 비어 있을 때의 `min`·`max` 는
 * `null` 이다. 동시 실행에서 「없다」는 오류가 아니라 정상 결과다 — 부르는 쪽이 확인하고
 * 부르더라도 그 사이에 다른 스레드가 지울 수 있으므로, 예외로 만들면 정상 실행이 예외가 된다.
 *
 * **검증 등급.** `concurrency`.
 * 계약에 동시 접근(선형화·진행 보장)이 들어 있으므로 판정 절차 1번에서 걸린다(§규약1
 * 「검증 등급 4종」). 이 등급의 검증은 **TS 스위트가 돌지 않는다** — 축1은 언어 중립 test
 * vector 를 Rust 정본이 재생하는 것으로, 축4는 `loom` 모델 검사기가 선형화·진행 보장을
 * 판정하는 것으로 받는다(§규약2 「축4 — 동시성」).
 *
 * **필요충분조건.**
 * - 의미: 어느 연산이든 호출과 반환 사이 **한 시점**의 결과로 설명돼야 하고, 같은 값에 대한
 *   동시 삽입 중 성공하는 것이 하나여야 한다. 못 지키면 부르는 쪽이 자기 잠금으로 연산을
 *   감싸야 하고, 그러면 남는 것은 **순차 정렬 집합**이다(`probabilistic/skipList`).
 * - 비용: 한 스레드가 멈춰도 나머지가 끝나야 하고(진행 보장), 다섯 연산이 담긴 원소 수에
 *   비례하지 않아야 한다. 앞을 못 지키면 잠금으로 감싼 정렬 집합이고, 뒤를 못 지키면 정렬을
 *   버린 lock-free 집합이다 — 어느 쪽이 되든 이 구조를 따로 둘 이유가 그 자리에서 사라진다.
 */
