/**
 * CountMinSketch — 원소마다 받은 증분의 합(빈도)을 묻는 추정기. 추정은 실제 빈도보다 작지 않고, 실제 빈도를 넘는 양은 정해
 * 둔 확률로 총증분의 정해 둔 몫 이하다.
 *
 * **목적.** 문자열 원소에 음이 아닌 정수 증분을 거듭 넣고 원소마다 「지금까지 몇이 들어왔는가」를 묻는 일을 **넣은 서로
 * 다른 원소의 수와 무관한 비용**에 제공하되, 답이 한쪽으로만 틀리는 것을 허용하는 것. 추정이 실제 빈도보다 작은 일(과소
 * 추정)은 없고, 실제 빈도를 넘는 양(과대 추정)은 생성 때 받은 **목표 오차 ε** 와 **실패 확률 δ** 가 누른다 — 원소 하나를
 * 물었을 때 과대 추정이 총증분 N 의 ε 배를 넘을 확률이 δ 이하다.
 *
 * **두 매개변수가 계약이고, 물려받은 두 매개변수는 표현이었다.** 물려받은 생성자는 `(width, depth)` — 수를 담는 표의 열 수와
 * 줄 수 — 를 받았다. 그것은 한 표현의 눈금이라 오차를 그 둘로 적으면 그 표현을 처방한다(`docs/ORD-006-conventions.md`
 * 「A군 17종 판정」 ④ — `probabilistic/bloomFilter` 가 `(size, hashCount)` 를 뺀 것과 같은 자리). 호출자가 고르는 것은
 * 「얼마나 틀려도 되는가」와 「그 한계를 얼마나 드물게 넘어도 되는가」다. 물려받은 문서의 「width=1, depth=1 이면 전체 합이
 * 추정」은 그 표현에서만 참이라 옮기지 않았다(불변 사실 38). 같은 문서의 「update 를 한 번도 호출하지 않은 문자열의 추정은
 * 0」은 **거짓이다** — 넣지 않은 원소도 넣은 원소와 칸을 함께 쓰면 0 보다 크다. 같은 문서의 폭 1 사례가 그 반례를 스스로
 * 적는다(불변 사실 207). 이 계약에서 넣지 않은 원소에 대해 결정적인 것은 「0 이상」뿐이다.
 *
 * 이 계약에 없는 것은 넷이다.
 *
 * - **공간.** 이 추정기가 존재하는 이유 — 원소를 담지 않고 빈도에 답해 자리를 아낀다 — 는 계약이 아니다(§규약1 「공간은
 *   어느 계약에도 없다」). 그래서 **원소마다 증분을 빠짐없이 세는 정확한 사전도 이 계약을 지킨다** — 과대 추정이 0 이다.
 *   반대로 이 추정기는 정확한 빈도 사전의 계약을 못 지킨다. 이쪽이 **더 적게 약속하는 다른 계약**이다(불변 사실 43).
 * - **음의 증분 · 지우기.** 증분은 0 이상이다. 음의 증분을 받으면 과소 추정 없음이 서지 않는다 — 칸을 함께 쓰는 표현에서 다른
 *   원소의 음의 증분이 이 원소의 칸을 깎는다. 받지 않고 `RangeError` 로 거절한다(「주입 정책」).
 * - **총증분 · 서로 다른 원소 수 · 무거운 원소 목록 · 추정기끼리 합치기.** 물려받은 표면에 없고, 없으면 목적을 진술하지
 *   못하는 연산이 아니다(불변 사실 47). 총증분은 호출자가 넣은 증분을 더해 안다.
 * - **넣지 않은 원소의 결정적 답.** 위의 「0」 문장이 빠진 자리다.
 *
 * **이름은 임시다.** 「카운트-민 스케치」는 수를 담는 줄 여럿에서 가장 작은 값을 고르는 **기법의 이름**이다. 계약이 말하는
 * 것은 「과소 추정 없는 근사 빈도 사전」이고 계약 이름은 KAN-031 이 정한다(불변 사실 198).
 *
 * **불변식.** 없다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 빈도를 읽는 공개 연산이 `estimate` 하나라 첫 물음에서 걸린다. 「추정 ≥
 * 실제 빈도」는 `estimate` 행의 의미이고 축1이 본다. 「어느 칸도 총증분을 넘지 않는다」 같은 조건은 표현의 성질이라 후보가
 * 아니다(불변 사실 36).
 *
 * **연산 계약.** L 은 인자 문자열의 길이(UTF-16 코드 단위 수), ε 는 목표 오차, δ 는 실패 확률, N 은 그 시점까지 받아들인 증분의
 * 합(총증분)이다. 원소 x 의 **실제 빈도** f(x) 는 x 에 받아들인 증분의 합이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(epsilon, delta)` | 목표 오차 ε · 실패 확률 δ 인 빈 추정기를 연다 | O((1/ε) · log(1/δ)) | worst |
 * | `update(item, count)` | `item` 에 증분 `count` 를 더한다. 반환이 없다. 범위 밖 증분은 `RangeError` 이고 상태가 그대로다 | O(L · log(1/δ)) | expected |
 * | `estimate(item)` | `item` 의 추정을 돌려준다. **반드시 f(item) 이상**이고, f(item) 을 넘는 양이 ε · N 을 넘을 확률을 아래 「오차 보장」이 누른다 | O(L · log(1/δ)) | expected |
 *
 * **오차 보장.** 확률 문장 하나와 그것을 판정하는 문장 하나다.
 *
 * - **확률 문장.** 어느 원소 x 에 대해서든, `estimate(x)` 가 f(x) + ε · N 을 넘을 확률이 δ 이하다. N 은 그 `estimate` 를 부른
 *   시점의 총증분이다.
 * - **확률의 출처는 구현이 뽑는 무작위다 — 입력의 분포가 아니다.** 넣을 증분의 흐름과 물을 원소가 **추정기가 무작위를
 *   뽑기 전에** 정해져 있으면 어떤 흐름이든 이 문장이 선다. 추정기의 답을 보고 다음에 넣거나 물을 원소를 고르는 호출자는
 *   덮지 않는다. 근거는 `probabilistic/bloomFilter` 헤더의 셋과 같다 — 문자열에 이름 붙일 분포가 없고 입력 분포로 읽으면 줄지은
 *   원소를 한 칸으로 모는 고정 해시를 배제하지 못한다 · 같은 저장소의 확률 문장이 출처를 하나로 가져야 나란히 읽힌다 ·
 *   스위트가 흐름을 고정 seed 로 줄지어 정할 수 있다. **따라 나오는 것 하나 — 원소를 칸으로 보내는 함수를 고정한 구현은 이
 *   계약을 어긴다.** 그 함수에 대해 무거운 원소와 줄마다 같은 칸으로 가는 원소가 실재하고, 그 원소를 미리 고른 호출자에게
 *   확률이 1 이다. 스위트는 구현을 읽지 않고는 그 원소를 짓지 못하므로(불변 사실 44) 그 위반은 스위트를 통과한다 —
 *   블룸 필터에서 실행으로 보인 모양이고(불변 사실 298) 이 계약에서는 다시 돌리지 않았다.
 * - **판정 문장과 여유.** 스위트는 확률 문장을 축1 안에서 이렇게 판정한다(2026-09-15 유저 결정 — 축을 늘리지 않는다). 고정
 *   seed 로 정한 흐름(ε · N 이 4 안팎이 되도록 빈도 8 인 원소와 빈도 1 인 원소를 섞는다)을 넣고, 넣지 않은 서로 다른 원소 N_q
 *   개(N_q · δ = 64)를 물어 **추정이 ε · N 을 넘은 원소의 수가 2 · δ · N_q 이하인가**를 관측값으로 돌려준다. **여유는 2 다.**
 *   원소마다 따로 확률 δ 로 한계를 넘는 구현 — 확률 문장을 경계에서 지키는 구현 — 이 한 판정에서 떨어질 확률이 체르노프
 *   부등식으로 e^{−64/3}(약 5 × 10^−10) 이하이고, 여유를 줄이면 그 상한이 빠르게 커진다(실측은 `./countMinSketch.contract.ts`
 *   머리말). 과소 추정은 한 번이라도 있으면 떨어진다.
 * - **판정 문장은 확률 문장과 같지 않다 — 틈 하나를 적어 둔다.** 확률 문장은 원소 하나씩에 대한 것이라, **답을 한데 몰아
 *   내는 구현** — 생성 때 동전을 한 번 던져 확률 δ 로 모든 원소에 한계를 넘는 추정을 내는 것 — 도 지킨다. 그 구현은 판정에서
 *   확률 δ 로 떨어진다. 블룸 필터 헤더가 적은 틈과 같은 모양이다.
 *
 * **`update` · `estimate` 가 `expected` 인 이유.** 「기대」의 뜻은 `hash/hashSet` 헤더가 정의한 것과 같다 — 구현이 뽑는 무작위에
 * 대한, 호출 **시퀀스** 총비용의 기댓값이다. 이 계약이 배제하려는 것은 서로 다른 원소 수에 비례하는 구현이고, 그것을 배제하는
 * 가장 약한 한정자가 이 뜻의 `expected` 다(불변 사실 21 · 59). 정본(줄마다 칸 하나)은 호출마다 같은 비용이라 `worst` 로도
 * 지키지만, `worst` 를 적으면 **원소를 무작위 해시로 찾아 빈도를 적는 정확한 사전**이 나간다. 그 배제를 목적이 요구하지 않는다.
 *
 * **상한에 log(1/δ) 가 들고 ε 가 안 드는 이유 — 고른 값이다(불변 사실 48 · 51).**
 *
 * - **더 강하게 `O(L)` 로 적으면** δ 가 작을수록 원소 하나를 줄 여럿에 적는 구현 — 이름이 가리키는 기법 — 이 나간다. 남는 것은
 *   한 자리에만 적고 실패 확률을 다른 방법으로 맞추는 구현이다. 이름의 기법을 배제할 근거가 목적에 없다.
 * - **더 약하게 `O(L / ε)` 로 적으면** 원소 하나에 1/ε 개의 자리를 훑는 구현이 들어온다. ε 를 서로 다른 원소 수의 역수 가까이
 *   낮추면 호출 하나가 담긴 종류 수에 비례하는 셈이 되어, 위 목적의 「서로 다른 원소의 수와 무관한 비용」이 ε 를 고르는 순간
 *   사라진다.
 *
 * **축3은 L · ε · δ 몫을 재지 않는다** — 사다리가 서로 다른 원소 수만 키우고 셋을 상수로 누른다(§규약2 시나리오 규칙 3). 생성자는
 * n 에 대해 반복 호출되지 않아 시나리오 면제다(시나리오 규칙 2). 그 행의 상한은 추정기를 여는 준비를 허용하는 값이고, 준비를
 * 미루는 구현도 만족한다.
 *
 * **이 계약은 시간과 오차만 말한다.** 원소를 전부 담아 자리를 더 쓰는 구현도 지킨다(위 「공간」). 공간을 계약에 넣는 규격
 * 결정이 나면 이 목적 문단을 다시 연다(불변 사실 58).
 *
 * **주입 정책.**
 * - **주입받는 것이 없다.** 원소 타입은 문자열로 고정하고, 원소의 동등성은 문자열 값이 같은가(`===`)다. 원소를 정수로 펴는 함수도
 *   해시 함수도 씨앗도 받지 않는다 — 까닭은 `probabilistic/bloomFilter` 헤더와 같다(확률 문장이 주입자에 매달린다 · 씨앗을 아는
 *   호출자에게 그 구현은 고정 함수다).
 * - `epsilon` · `delta` 는 둘 다 0 보다 크고 1 보다 작은 수여야 하고 아니면(`NaN` 포함) 생성자가 `RangeError` 를 던진다. ε ≥ 1 은
 *   총증분을 돌려주는 구현을 정당화해 뜻이 없고, ε = 0 은 정확한 빈도를 요구한다. δ ≥ 1 은 확률 문장을 비우고, δ = 0 은 결정적
 *   한계를 요구해 log(1/δ) 가 서지 않는다.
 * - `count` 는 0 이상의 안전한 정수(`Number.isSafeInteger`)여야 하고, 받아들이면 총증분이 `Number.MAX_SAFE_INTEGER` 를 넘지 않아야
 *   한다. 아니면 `update` 가 `RangeError` 를 던지고 **상태가 그대로다** — 그 뒤의 추정은 거절된 증분이 없었던 것과 같은 보장을
 *   받는다. 증분 0 은 정당하다. 안전한 정수로 묶은 것은 과소 추정 없음이 수의 표현에서 새지 않게 하려는 것이다 — 그 범위의
 *   합은 64비트 부동소수점에서 정확하다.
 * - `estimate` 는 던지지 않는다. 넣지 않은 원소를 묻는 것은 오류가 아니라 답이 있는 물음이다.
 *
 * **검증 등급.** `basic`.
 * 상한이 자명한 구현으로 달성된다 — 줄 d = ⌈ln(1/δ)⌉ 개에 줄마다 문자열 해시를 한 번씩 거는 구현은 호출마다 L 과 d 에 비례해
 * 끝나고, **그 시간**에 확률 논증이 들지 않는다. 오차 보장에는 확률 논증이 들지만 등급을 올리지 않는다 — 판정 절차 2번은 시간
 * 상한만 읽는다(불변 사실 203). 등급이 정하는 것은 축3 엄격도이고 오차는 축1이 판정한다. 불변식 절이 비었다.
 *
 * **필요충분조건.**
 * - 의미: 과소 추정이 **없고**, 과대 추정이 ε · N 을 넘을 확률이 **δ 이하**여야 한다. 앞을 버리면 늘 0 을 돌려주는 구현이, 뒤를
 *   버리면 **지금까지 들어온 증분 전체의 합**을 돌려주는 구현이 계약을 지킨다 — 둘 다 원소마다의 빈도에 대해 아무것도 말하지
 *   않는다. 과대 추정을 없애면 정확한 빈도 사전이다.
 * - 비용: `update` · `estimate` 가 넣은 서로 다른 원소의 수에 비례하면 원소와 빈도를 늘어놓고 훑는 목록이다 — 답을 틀리게
 *   허용하고도 빈도를 종류 수와 무관하게 묻는다는 값이 남지 않는다.
 */
