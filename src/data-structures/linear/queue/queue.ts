/**
 * Queue — 넣는 끝과 빼는 끝이 서로 고정된 수열. 도착한 순서 그대로 나간다.
 *
 * **목적.** 원소를 **도착한 순서 그대로** 내보내는 것. 넣는 끝과 빼는 끝이 서로 다르고,
 * 어느 쪽이 어느 쪽인지가 **처음부터 끝까지 바뀌지 않는다.** 그래서 먼저 들어온 것이 먼저
 * 나가고, 그 순서를 호출자가 되돌릴 방법이 계약에 없다.
 *
 * 임의 위치 접근·탐색·순회는 이 계약에 없다. 뒤 끝을 보는 일, 앞 끝에 넣는 일도 없다 —
 * 그 둘이 들어오면 끝이 고정되지 않으므로 다른 계약이 된다(`linear/deque`). 담긴 원소 수를
 * 읽는 일과 비었는지 묻는 일도 없다.
 *
 * **뺀 두 행의 판정은 목적 항목 밖에 적는다.** `size()` · `isEmpty()` 는 원칙 A 판정표 ③ 의
 * 판정으로 뺐다 — 판정 줄과 목적 인용은 `docs/ORD-006-conventions.md` 「판정표 ③ 의 103 행을
 * 묶어 판정했다」 절에, 행 단위 대장은 `tools/_baseline/principle-a-verdicts.tsv` 에 있다.
 * 판정의 결론을 목적 문단 안에 적으면 다음 판정이 자기 메아리를 근거로 읽는다(§원칙 A A5′-2).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로, 꺼낸 자리를 되돌려 쓰지
 * 않아 공간이 원소 수보다 많이 드는 구현도 이 계약을 지킨다. 그 사실을 감추지 않고 여기
 * 적어 둔다 — 공간을 계약에 넣을지는 이 구조 하나가 정할 일이 아니다(§규약1 미결).
 *
 * **불변식.** 없다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 **두 행을 뺀 표면에 다시 돌린 결과다.** 관측
 * 경로가 둘인 성질은 하나 남는다 — `front()` 와 `dequeue()` 가 둘 다 "앞 끝 원소"를
 * 가리킨다는 것인데, 그 정합을 아래 표의 `front` 행이 이미 적고 있어 두 번째 물음에서
 * 걸린다. 그러므로 각 연산의 의미이고 대조는 축1이 참조 모델과 하는 일이다. 뺀 두 행이
 * 경로였던 성질(「비었는가와 원소 수가 어긋나지 않는다」)은 후보 자체가 사라졌고, 담긴
 * 원소를 늘어놓는 연산도 없어 남은 표면에 경로가 둘인 성질이 더 생기지 않는다.
 *
 * **연산 계약.** 상한은 원소 수 n 에 대한 것이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `enqueue(item)` | `item` 을 뒤 끝에 놓는다. 이 원소는 지금 담겨 있는 것들이 전부 나간 뒤에 나온다 | O(1) | amortized |
 * | `dequeue()` | 앞 끝 원소를 제거하고 돌려준다. 비어 있으면 `null`, 상태는 불변 | O(1) | amortized |
 * | `front()` | 앞 끝 원소를 제거하지 않고 돌려준다. 비어 있으면 `null`. 직후 `dequeue()` 가 같은 값을 돌려준다 | O(1) | worst |
 *
 * **`dequeue` 를 `amortized` 로 적은 것이 이 계약에서 가장 많은 일을 한다.** `worst` 로
 * 적으면 호출 하나가 상수를 넘는 구현이 전부 배제되는데, 그중에는 **정당한 구현이 있다** —
 * 넣는 자리와 빼는 자리를 나눠 들고 있다가 빼는 쪽이 비면 한 번에 옮기는 구현은 그 옮기는
 * 호출 하나가 O(n) 이고, 원소마다 옮겨지는 횟수가 정해져 있어 n 회의 총비용은 O(n) 이다.
 * 가장 약한 한정자를 적는 규칙(§규약1 「복잡도 한정자」)이 여기서 그 구현을 살린다.
 * `enqueue` 가 `amortized` 인 것은 자리를 미리 늘려 두는 구현을 배제하지 않기 위해서다.
 * `front` 에 `worst` 를 적은 이유는 다르다. **`worst` 는 `amortized` 보다
 * 강한 한정자다** — 호출 하나가 튀지 않는다는 것까지 약속하므로 배제하는 구현이 더 많다.
 * 여기서 배제되는 것은 값을 첫 호출에 만들어 캐시하는 계열인데, 앞 끝 자리를 들고 있는 데
 * 드는 대가가 없으므로 **배제해도 계약이 잃는 것이 없다.** 강한 한정자를 적을 수 있는
 * 조건이 그것이다(§규약1 「복잡도 한정자」).
 *
 * **`linear/deque` 와 같은 계약이 아니다.** 덱 계약은 이 계약이 약속하는 것을 전부 약속하고
 * 그 위에 앞 끝 넣기·뒤 끝 빼기·뒤 끝 보기를 더 약속한다. **담는 쪽이 더 좁다** — 더 많이
 * 약속하면 그것을 만족하는 구현이 줄어들기 때문이다(§규약1 「같은 구조인가」). 반례가 위
 * 문단에 이미 있다: 넣는 자리와 빼는 자리를 나눠 들고 있는 구현이다. 그 구현은 이 계약을
 * 만족하고 **덱 계약이 요구하는 세 연산을 애초에 갖고 있지 않으므로** 덱 계약을 만족하지
 * 못한다. 반례로는 그것으로 충분하다.
 *
 * 그 구현에 세 연산을 붙여 보면 어떻게 되는지는 **덧붙인 방식에 기대므로 반례가 아니다.**
 * 다만 붙이기가 쉽지 않다는 것은 말할 수 있다 — 뒤 끝은 넣는 쪽 무더기의 꼭대기이거나(그쪽이
 * 비어 있지 않을 때) 빼는 쪽 무더기의 바닥이고, 뒤엣것에 닿으려면 그 무더기를 통째로
 * 되돌려야 한다. 이 서술은 계약의 문장이 아니라 관찰이다.
 *
 * 그래서 이 계약은 **덱을 두고도 따로 있을 이유가 있다.** 덜 약속하는 계약은 쓸모가 적은
 * 계약이 아니라 **더 많은 구현을 허용하는 계약**이다.
 *
 * **주입 정책.** 없다. `T` 는 임의 타입이고 비교·해시·동등성을 쓰지 않으므로 주입할 것이
 * 없다. 빈 큐에서 `dequeue`·`front` 는 예외를 던지지 않고 `null` 을 돌려준다 — 이 선택은
 * 계약의 일부이며, 그 대가로 `T` 에 `null` 이 섞이면 "비어 있음"과 "값이 `null` 인 원소"가
 * 구분되지 않는다.
 *
 * **검증 등급.** `basic`.
 * 상한이 자명한 구현으로 달성된다 — 배열 하나에 뒤로 넣고, 앞에서 뺄 때는 원소를 지우는
 * 대신 **다음에 읽을 자리를 정수 하나로 기억한다.** 재균형도 상각 설계도 확률 논증도 없이
 * 세 행이 전부 상한 안이다. 자명한 구현 중에 상한을 넘는 것이 있지만(배열 앞을 실제로
 * 지우면 뒤 원소가 전부 당겨져 `dequeue` 가 O(n) 이다) 그것은 등급을 바꾸지 않는다 —
 * 판정이 묻는 것은 *달성하는 자명한 구현이 있는가*이지 *전부 달성하는가*가 아니다
 * (§규약1 「자명한 구현은 존재 조건이다」). 불변식 절이 비어 있으므로 `invariant` 도 아니다.
 *
 * **덱이 `complexity` 인 것과 여기가 갈린다.** 양쪽 끝을 다 열면 정수 하나로는 안 되고
 * 자리를 돌려 쓰거나 옮기는 설계가 들어온다. **등급은 계약에서 기계적으로 따라 나오므로,
 * 등급이 다르면 계약이 같을 수 없다.**
 *
 * **필요충분조건.**
 * - 의미: 넣는 끝과 빼는 끝이 **서로 다르고 고정**돼 있어야 한다. 같은 끝이면 나중에 들어온
 *   것이 먼저 나오므로 스택이고, 양쪽이 다 열려 있으면 호출자가 순서를 골라 쓸 수 있으므로
 *   덱이다. 이 계약이 약속하는 것은 **호출자가 순서를 고를 수 없다**는 것이다.
 * - 비용: `dequeue` 가 원소 수에 비례하면 그건 배열의 앞을 실제로 지우는 것이다 — 앞을
 *   비우려고 뒤를 전부 당기는 일이고, 그러면 큐를 쓰는 알고리즘이 그 자리에서 한 차수
 *   느려진다. 방향이 반대인 경우도 같다: `enqueue` 가 원소 수에 비례하면 앞에 끼워 넣고
 *   있는 것이다.
 */
