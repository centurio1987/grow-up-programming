/**
 * MonotonicQueue — 뒤 끝에 넣고 앞 끝에서 빼며, 지금 담긴 원소 중 비교자가 가장 크다고 보는 원소를 원소 수와 무관한 비용에 답하는 큐.
 *
 * **목적.** 넣는 끝과 빼는 끝이 서로 고정된 큐에 **지금 담긴 원소 중 가장 큰 것을 묻는 일**을 더해,
 * 넷을 담긴 원소 수와 무관한 (상각) 비용으로 함께 제공하는 것. 요점은 앞 끝에서 빠진 뒤다 — 가장 큰 원소가
 * 앞으로 나간 직후에도 남은 것 중 가장 큰 원소를 같은 비용에 답한다. 한쪽 끝에 넣고 반대쪽 끝에서 빼기를
 * 번갈아 하면 담긴 원소들이 창처럼 밀려가고, 그 창의 최댓값을 호출열 전체가 호출 수에 비례하는 비용에 묻는다.
 *
 * 이 계약에 없는 것은 넷이다.
 *
 * - **넣은 쪽에서 빼기 · 앞 끝에 넣기.** 빼는 끝이 넣는 끝과 같으면 `linear/monotonicStack` 의 계약이고,
 *   양쪽 끝이 다 열리면 덱이다(아래 반례 표).
 * - **창의 크기.** 담을 수 있는 수를 구조가 들지 않는다. 창을 한 칸 미는 일은 호출자가 넣기와 빼기로
 *   한다 — 크기를 정해 두면 가득 찬 뒤 넣기의 의미가 계약에 들어와 다른 계약이 된다(`linear/circularBuffer`
 *   가 그 자리다).
 * - **임의 위치 접근 · 순회 · 둘째로 큰 원소.** 담긴 것을 늘어놓는 연산이 없다.
 * - **물려받은 표면의 함수 둘.** `slidingWindowMax(nums, k)` · `slidingWindowMin(nums, k)` 는 배열과 창
 *   크기를 받아 답을 내고 호출 사이에 남기는 것이 없었다 — 참조 모델이 대조할 상태가 없어 자료구조 계약이
 *   서지 않는다(불변 사실 200). 앞엣것은 알고리즘 트랙
 *   `src/algorithms/array/slidingWindowMaximum/slidingWindowMaximum.ts` 와 서명 · 의미가 같다. 둘을 뺐고
 *   연산 집합을 새로 지었다(2026-09-15 유저 결정 — 「뒤에 넣고 앞에서 빼며 최댓값을 묻는 큐」,
 *   `linear/gapBuffer` 가 연산 집합을 통째로 간 선례). 뒤엣것은 아래 주입 정책에서 비교자로 접힌다.
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 * 물려받은 문서의 기온 감시 이야기는 활용 사례라 계약의 문장이 아니다(§규약1 「금지 — 내부 처방」 5번).
 *
 * **이름은 임시다.** `monotonicQueue` 는 값이 한 방향으로만 늘어선 후보 줄이라는 **담는 모양의 이름**이고,
 * 계약은 그 모양을 요구하지 않는다 — 넣는 무더기와 빼는 무더기를 나눠 드는 구현도 이 계약을 지킨다(아래
 * 한정자 문단). 계약 이름은 KAN-031 이 정한다(불변 사실 64 · 198).
 *
 * **이웃 계약과 같은 계약이 아니다.** 반례를 계약의 문장으로 적고 어느 정본도 보지 않는다(불변 사실 43).
 *
 * | 쌍 | 반례 구현 | 관계 |
 * |---|---|---|
 * | 이 계약 ↔ `linear/queue` | 배열 하나에 뒤로 넣고 읽을 자리를 정수로 기억하는 큐는 저쪽 다섯 행을 지키고 최댓값을 묻는 행이 없다. 붙이면 담긴 수만큼 훑는다(`_contract/_fixtures/scanningMaxQueue.ts` 가 그 모양이다). 이 계약을 지키는 구현은 비교자를 고정해 세우고 최댓값을 안 물으면 저쪽 다섯 행을 그대로 지킨다 | 이 계약이 저쪽을 담는다 — 더 좁다(불변 사실 43). 등급도 갈린다(아래 검증 등급 · 불변 사실 56) |
 * | 이 계약 ↔ `linear/monotonicStack` | 큰 값이 들어올 때 앞선 작은 후보를 버리는 구현은 이 계약의 일곱 행을 지키고, 넣은 쪽에서 빼면 버린 후보가 다시 가장 커지는 자리에서 틀린 값을 답한다. 원소마다 「앞 끝부터 그 원소까지의 최댓값」을 곁에 적는 배열은 저쪽을 지키고, 앞 끝에서 빼면 남은 칸의 적어 둔 값이 뺀 원소를 여전히 품어 전부 다시 적어야 한다 | 서로 담지 않는다(불변 사실 54) — **빼는 끝이 넣는 끝과 다른가 같은가로 갈린다.** 등급도 갈린다(`complexity` ↔ `basic`, 불변 사실 56) |
 * | 이 계약 ↔ `linear/deque` | 자리를 돌려 쓰는 고리 배열은 덱 계약을 지키고 최댓값을 묻는 행이 없다. 넣는 무더기와 빼는 무더기를 나눠 드는 이 계약의 구현은 앞 끝에 넣기 · 뒤 끝에서 빼기를 갖고 있지 않다 | 서로 담지 않는다(불변 사실 54). 양쪽 끝에서 빼며 최댓값을 묻는 덱은 둘 다 지킬 수 있다(논증이고 실행하지 않았다) |
 *
 * **불변식.** 없다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 후보 셋이 각각 다른 자리에서 걸린다.
 *
 * - **「`max()` 는 담긴 어느 원소보다 작지 않다」** — 담긴 원소를 상태를 바꾸지 않고 읽는 연산이
 *   `front()` 하나이고 늘어놓는 연산이 없어, 최댓값과 대조할 둘째 경로가 없다. 빼 가며 견주는 길은 상태를
 *   바꾸므로 관측 경로로 세지 않는다(`docs/ORD-006-conventions.md` 「관측이 상태를 바꾸면 관측 경로로
 *   세지 않는다」). 첫 번째 물음에서 걸리고, 그 조건은 `max` 의 의미라 축1이 본다.
 * - **「`front()` 는 다음 `dequeue()` 가 돌려줄 원소와 같다」** — 아래 표의 `front` 행이 적는다. 두 번째 물음.
 * - **「`isEmpty()` 는 `size() === 0` 과 같다」** — `isEmpty` 행이 적는다. 두 번째 물음.
 *
 * **연산 계약.** 상한은 담긴 원소 수 n 에 대한 것이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator)` | 비교자를 고정한다. 이후 바꿀 수 없다 | O(1) | worst |
 * | `enqueue(item)` | `item` 을 뒤 끝에 놓는다. 이 원소는 지금 담긴 것들이 전부 나간 뒤에 나온다 | O(1) | amortized |
 * | `dequeue()` | 앞 끝 원소를 제거하고 돌려준다. 비어 있으면 `null` 이고 상태는 바뀌지 않는다 | O(1) | amortized |
 * | `front()` | 앞 끝 원소를 제거하지 않고 돌려준다. 비어 있으면 `null`. 직후 `dequeue()` 가 같은 원소를 돌려준다 | O(1) | worst |
 * | `max()` | 지금 담긴 원소 중 비교자가 가장 크다고 보는 원소를 제거하지 않고 돌려준다 — 담긴 어느 원소 `y` 에 대해서도 비교자가 (돌려준 원소, `y`) 에 음수를 내지 않는다. 그런 원소가 여럿이면 어느 것인지 정하지 않는다. 비어 있으면 `null` | O(1) | worst |
 * | `isEmpty()` | `size() === 0` 과 같다 | O(1) | worst |
 * | `size()` | 현재 원소 수 | O(1) | worst |
 *
 * `amortized O(1)` 은 **빈 큐에서 시작한 어떤 호출열 m 회의 총비용이 O(m)** 이라는 뜻이다. 호출 하나가
 * 상수를 넘어도 계약 위반이 아니다. 넣기와 빼기가 섞인 호출열 전체에 대한 약속이라, 넣기만 몰아 재거나
 * 빼기만 몰아 재서 따로 상수이면 되는 것이 아니다.
 *
 * **`enqueue` 와 `dequeue` 를 둘 다 `amortized` 로 적은 것이 이 표에서 가장 많은 일을 한다 — 두 행을 서로
 * 다른 구현 계열이 상각으로만 지킨다.**
 *
 * - **큰 값이 들어올 때 뒤쪽의 작은 후보를 버리는 계열.** 넣기 한 호출이 버리는 후보 수만큼 들고 그 수는
 *   담긴 수까지 간다. 한 번 버린 원소는 다시 후보가 되지 않으므로 원소마다 한 번만 버려지고, 호출열의
 *   총비용이 호출 수에 비례한다. 빼기는 맨 앞 후보가 나가는 원소인지 한 번 보면 된다.
 * - **넣는 무더기와 빼는 무더기를 나눠 들고, 칸마다 「무더기 바닥부터 그 칸까지의 최댓값」을 적는 계열.**
 *   넣기는 상수다. 빼는 무더기가 비었을 때의 빼기가 넣는 무더기를 통째로 옮기며 최댓값을 다시 적으므로 그
 *   호출 하나는 담긴 수에 비례하고, 옮긴 원소는 되돌아가지 않아 원소마다 한 번만 옮겨진다. 최댓값은 두
 *   무더기 꼭대기의 적어 둔 값을 한 번 견준다.
 *
 * `enqueue` 를 `worst` 로 적으면 앞 계열이, `dequeue` 를 `worst` 로 적으면 뒤 계열이 나가고 어느 배제도 그
 * 이유가 목적에 없다(§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」). 같은 시나리오를 한 호출 최대로
 * 다시 재서 확인했다(`src/data-structures/_contract/runContract.monotonicQueue.test.ts`).
 *
 * `front` · `max` · `isEmpty` · `size` 에 `worst` 를 적으면 배제되는 계열은 그 값을 묻는 호출에 몰아 계산해
 * 두는 구현이다. 위 두 계열이 전부 네 값을 상수에 들고 있으므로 **배제해도 계약이 잃는 것이 없다.**
 *
 * **최댓값이 여럿일 때 어느 것을 돌려줄지 정하지 않는 이유.** 크기가 같은 후보를 버리는 구현과 남기는
 * 구현이 둘 다 일곱 행을 지키고, 둘을 가를 이유가 목적에 없다. 원소 타입이 수이고 비교자가 뺄셈이면 둘은
 * 관측되지 않는다 — 계약 스위트가 그렇게 돈다.
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수 · 0 · 양수를 돌려주는 전순서여야 한다. 음수는 「`a` 가 `b` 보다 작다」이고
 *   0 은 「크기가 같다」다. **기본 비교자를 두지 않는다** — 두면 그 방향이 계약의 일부가 되고, 최솟값을
 *   묻는 큐가 다른 계약이 된다. 뒤집은 비교자를 주입하면 같은 구현이 최솟값을 답하므로 **최솟값을 묻는 큐는
 *   이 계약이다**(물려받은 `slidingWindowMin` 의 자리. `heap/minHeap` 과 `heap/maxHeap` 이 같은 계약인 것과
 *   같은 자리 — `docs/ORD-006-conventions.md` 「연산 집합이 계약을 가른다 — 힙 여덟의 판정」). 비교자를 주지
 *   않으면 `TypeError` 다.
 * - 같은 원소를 여러 벌 담을 수 있다. 넣은 수만큼 나온다.
 * - 빈 큐의 `dequeue` · `front` · `max` 는 예외가 아니라 `null` 이다 — 반환 타입에 「없음」을 담을 자리가
 *   있기 때문이다(`docs/ORD-006-conventions.md` 「전제조건을 두는 계약은 축1이 그 자리를 못 잰다」).
 *   그 대가로 `T` 에 `null` 이 섞이면 「비어 있음」과 「값이 `null` 인 원소」가 구분되지 않는다.
 * - 비교자가 같은 두 원소에 호출마다 다른 답을 내면 계약이 성립하지 않는다. 그 조건을 지키는 것은
 *   주입자의 의무이고 이 구조가 검사하지 않는다.
 *
 * **검증 등급.** `complexity`.
 * 일곱 행을 **함께** 지키는 자명한 구현이 없다. 담긴 원소를 순서대로 둔 언어 배열에 최댓값을 얹는 길이
 * 넷이고 넷 다 한 행을 놓는다.
 * - **물을 때 훑으면** `max` 가 담긴 수에 비례한다.
 * - **가장 큰 원소 하나만 들고 있으면** `max` 는 상수지만 그 원소가 앞 끝으로 나갈 때 다음 최댓값을 알 방법이
 *   없어 다시 훑는다. 내림차순으로 넣고 차례로 빼면 빼기마다 그 자리를 만나 상각으로도 비례한다.
 * - **칸마다 「그 칸부터 뒤 끝까지의 최댓값」을 적으면** 빼기와 `max` 는 상수지만, 넣을 때 앞선 칸들의 적어
 *   둔 값을 새 원소로 올려 적어야 한다. 오름차순으로 넣으면 넣기마다 앞선 칸 전부를 고쳐 상각으로도 비례한다.
 * - **칸마다 「앞 끝부터 그 칸까지의 최댓값」을 적으면** 넣기와 `max` 는 상수지만, 앞 끝에서 빼면 남은 칸의
 *   적어 둔 값이 뺀 원소를 품고 있어 전부 다시 적어야 한다.
 *
 * 일곱 행을 함께 지키려면 **원소마다 한 번만 치르는 일을 여러 호출에 나눠 갚는 설계** — 버린 후보를 다시 보지
 * 않는다, 옮긴 원소는 되돌아가지 않는다 — 가 들어오고, 그것은 상각 설계다(§규약1 「검증 등급 4종」).
 *
 * **`linear/monotonicStack` 이 `basic` 인 것과 여기가 갈린다.** 넷째 길이 그쪽에서는 막히지 않는다 — 넣고
 * 빼는 끝이 같으므로 「바닥부터 그 칸까지의 최댓값」이 빼기에 낡지 않는다. **빼는 끝 하나가 등급을 가르고,
 * 등급이 다르면 계약이 같을 수 없다**(불변 사실 56).
 *
 * **필요충분조건.**
 * - 의미: `max()` 가 **지금 담긴** 원소로 답해야 하고, 나가는 순서가 들어온 순서여야 한다. 앞 끝으로 나간
 *   원소를 계속 답하면 그것은 지금까지 넣은 것 중 최댓값을 세는 누적 값이고, 나중에 넣은 것이 먼저 나가면
 *   `linear/monotonicStack` 이다.
 * - 비용: 넣기 · 빼기 · `max` 를 섞은 호출열이 호출 수에 비례해야 한다. `max` 가 담긴 수에 비례하면 큐 옆에서
 *   매번 훑는 것이고, `dequeue` 가 비례하면 가장 큰 원소 하나만 들고 있다가 그것이 나갈 때 훑는 것이며,
 *   `enqueue` 가 비례하면 뒤쪽 최댓값을 칸마다 올려 적는 것이다. 어느 쪽이든 창을 한 칸씩 밀며 최댓값을 묻는
 *   호출열이 창 크기에 곱으로 느려져, 이 구조를 둔 이유가 그 자리에서 사라진다.
 */
