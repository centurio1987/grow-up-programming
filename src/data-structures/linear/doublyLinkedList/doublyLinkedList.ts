/**
 * DoublyLinkedList — 넣기가 돌려준 핸들로 그 원소 뒤에 끼우고 그 원소를 빼는 수열. 끝에 넣기와 핸들 자리 갱신이 담긴 수와 무관한 비용이다.
 *
 * **목적.** 원소를 한 줄의 수열로 담고, **앞 끝에 넣기 · 뒤 끝에 넣기 · 핸들이 가리키는 원소 뒤에
 * 끼우기 · 핸들이 가리키는 원소 빼기**를 담긴 원소 수와 무관한 비용으로 제공하는 것. 넣는 연산 셋은
 * 넣은 원소를 가리키는 **핸들**을 돌려주고, 호출자는 그 핸들을 들고 있다가 나중에 그 자리를 찾지 않고
 * 곧바로 끼우고 뺀다. 담긴 것을 앞 끝에서 뒤 끝 순서로 늘어놓는 일은 담긴 수에 비례한다.
 *
 * **핸들 모형.** 이 계약이 가장 많은 일을 하는 자리다.
 *
 * - 넣기(`prepend` · `append` · `insertAfter`)가 돌려준 핸들은 **그 호출로 들어간 원소 하나**를 가리킨다.
 *   첨자가 아니다 — 그 앞에 원소가 끼거나 빠져도 같은 원소를 가리킨다. 값이 같은 원소가 여럿이어도
 *   핸들마다 가리키는 원소가 다르다.
 * - 핸들이 가리키는 원소가 수열에 남아 있는 동안 그 핸들을 **산 핸들**이라 한다. 산 핸들은 **그 원소를
 *   빼는 `remove` 로만 죽는다.** 다른 원소를 넣거나 빼는 호출은 어느 것도 다른 핸들을 죽이거나 다른
 *   원소를 가리키게 하지 않는다 — **다른 핸들은 그대로 유효하다.**
 * - 죽은 핸들은 다시 살아나지 않는다. 같은 값을 다시 넣으면 새 핸들이 나온다.
 * - 산 핸들이 아닌 것 — 이미 빠진 원소의 핸들 · 다른 수열이 돌려준 핸들 — 을 받으면 `insertAfter` 는
 *   `null`, `remove` 는 `false` 를 돌려주고 상태는 바뀌지 않는다(아래 주입 정책).
 * - 핸들에는 공개 표면이 없다(`ListHandle` 은 `object` 다). 물려받은 표면은 마디 클래스와 그 `prev` ·
 *   `next` 를 공개했다. 핸들을 받는 연산이 있으므로 **핸들 자체는 계약의 일부**이고, 그 안의 이음은
 *   담는 모양의 누출이다(§규약1 「금지 — 내부 처방」 1번). 마디 클래스를 뺐다.
 *
 * 이 계약에 없는 것은 넷이다.
 *
 * - **앞 끝 · 뒤 끝에서 핸들 없이 빼기.** 끝 원소의 핸들로 `remove` 하면 된다. 더해도 배제되는 구현이
 *   없다(`docs/ORD-006-conventions.md` 「A군 17종 판정」 ② — 배제 없는 차이). 양쪽 끝이 다 열린 수열은
 *   `linear/deque` 의 계약이다.
 * - **값으로 찾기.** 핸들을 얻는 두 번째 길이 되지만 담긴 수에 비례하고, 이 표의 행을 지키는 구현이면
 *   누구든 늘어놓기와 같은 계급으로 답한다 — **이 행이 배제하는 구현이 없다**(불변 사실 47 · 70,
 *   `linear/singlyLinkedList` 가 `find` 를 뺀 불변 사실 224 와 같은 판정).
 * - **첨자로 읽고 고치기.** `linear/dynamicArray` 의 계약이다.
 * - **뒤 끝에서 앞 끝으로 늘어놓기.** `toArray()` 를 뒤집으면 같은 계급이라 배제하는 구현이 없다. 두
 *   방향 읽기가 목적인 계약은 `linear/xorLinkedList` 다.
 *
 * **이 계약은 시간만 말한다.** 물려받은 문서의 「배열은 중간 삭제마다 뒤를 민다」는 비용 문장으로 옮겨
 * 아래 표와 필요충분조건에 있고, 원소마다 이음을 둘 드는 저장 비용은 계약의 문장이 못 된다(불변 사실
 * 38 · §규약1 「공간은 어느 계약에도 없다」 — 미결). 「플레이리스트」는 활용 사례다(§규약1 「금지 —
 * 내부 처방」 5번).
 *
 * **이름은 임시다.** `doublyLinkedList` 는 앞뒤로 이은 마디라는 **담는 모양의 이름**이고, 계약은 마디
 * 객체를 요구하지 않는다 — 원소마다 앞뒤 자리를 칸 번호로 적어 둔 배열도 지킨다. 이름이 하나뿐이어도
 * 임시로 적고 계약 이름은 KAN-031 이 정한다(불변 사실 198).
 *
 * **다른 두 리스트와 같은 계약이 아니다.** 반례를 계약의 문장으로 적고 어느 정본도 보지 않는다
 * (불변 사실 43). 판정 전문은 `docs/ORD-006-conventions.md` 「A군 17종 판정」 ②다.
 *
 * | 쌍 | 반례 구현 | 관계 |
 * |---|---|---|
 * | 이 계약 ↔ `linear/singlyLinkedList` | 앞 원소를 모르는 단방향 마디(앞 끝 · 뒤 끝만 기억)는 저쪽의 다섯 행을 지키고, 이쪽 `remove` 가 앞 원소를 찾아 앞 끝에서부터 걷느라 담긴 수에 비례한다. 다음 원소의 값과 이음을 끌어와 제 마디에 덮는 우회는 호출마다 상수지만 다음 원소의 핸들을 죽인다 — **「다른 핸들은 그대로 유효하다」가 `remove` 행에 있어서 반례가 선다** | 다르다. 표면을 맞추면 이쪽이 저쪽을 담는다(불변 사실 43) |
 * | 이 계약 ↔ `linear/dynamicArray` | 언어 배열 하나는 저쪽의 여섯 행을 지키고, 이쪽의 핸들 자리 끼우기 · 빼기가 자리를 찾고 뒤를 미느라 담긴 수에 비례한다. 양방향 마디는 이쪽을 지키고 저쪽의 첨자 읽기가 첨자에 비례한다 | 서로 담지 않는다(불변 사실 54) |
 *
 * **불변식.**
 * 1. `size()` 가 말하는 원소 수와 `toArray()` 가 내놓는 배열의 길이가 같다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 원소 수를 읽는 경로가 둘이고(세어 둔 수 대
 * 늘어놓은 수) 어느 연산의 계약 줄도 그 정합을 적지 않는다. 수를 따로 세는 구현이 산 핸들이 아닌
 * `remove` 에서 수를 깎으면 갈린다.
 *
 * 후보였다가 빠진 것이 둘이다. 「앞 이음과 뒤 이음이 서로를 가리킨다」(물려받은 문서의 핵심 불변식)는
 * 담는 모양의 성질이라 읽는 공개 연산이 없다(불변 사실 36) — 그 정합이 깨진 구현은 뒤따르는 갱신이
 * 엉뚱한 원소를 떼거나 붙이고, 그 결과를 `toArray()` · `size()` 가 드러낸다. 「`remove` 가 `true` 를
 * 돌려주면 그 원소가 `toArray()` 에서 사라진다」는 한쪽 경로가 상태를 바꾸므로 관측 경로로 세지 않고,
 * `remove` 의 의미라 축1이 본다(`docs/ORD-006-conventions.md` 「관측이 상태를 바꾸면 관측 경로로 세지
 * 않는다」).
 *
 * **연산 계약.** 상한은 담긴 원소 수 n 에 대한 것이다. 「산 핸들」은 위 핸들 모형의 뜻이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `prepend(value)` | `value` 를 앞 끝에 놓고 그 원소를 가리키는 산 핸들을 돌려준다 | O(1) | amortized |
 * | `append(value)` | `value` 를 뒤 끝에 놓고 그 원소를 가리키는 산 핸들을 돌려준다 | O(1) | amortized |
 * | `insertAfter(handle, value)` | `handle` 이 산 핸들이면 그 원소 바로 뒤에 `value` 를 놓고 새 원소를 가리키는 산 핸들을 돌려준다. 산 핸들이 아니면 `null` 이고 상태는 바뀌지 않는다 | O(1) | amortized |
 * | `remove(handle)` | `handle` 이 산 핸들이면 그 원소를 빼고 `true` 를 돌려준다. 그 핸들은 죽고 다른 핸들은 그대로다. 산 핸들이 아니면 `false` 이고 상태는 바뀌지 않는다 | O(1) | amortized |
 * | `toArray()` | 담긴 원소를 앞 끝에서 뒤 끝 순서로 늘어놓은 새 배열. 돌려준 배열을 고쳐도 수열은 바뀌지 않는다 | O(n) | worst |
 * | `size()` | 현재 원소 수 | O(1) | worst |
 *
 * **넣기 셋을 `amortized` 로 적은 것은 늘리는 계열을 살리기 위해서다**(불변 사실 194). 원소마다 앞뒤
 * 자리를 칸 번호로 적어 두는 배열은 칸이 모자라면 한 번에 옮기고, 그 호출 하나는 상수가 아니다. 그
 * 계열을 배제할 이유가 목적에 없다.
 *
 * **`remove` 를 `amortized` 로 둔 것은 `worst` 로 올릴 근거를 재지 않았기 때문이다.** 올리려면 그것이
 * **추가로** 배제하는 계열 — 뺀 칸을 비워 두었다가 빈 칸이 산 칸만큼 쌓이면 한꺼번에 치우는 구현 — 이
 * 약한 쪽을 통과함을 재서 보여야 한다(불변 사실 183). `linear/dynamicArray` 의 `set` 과 같은 처분이다.
 *
 * `toArray` · `size` 에 `worst` 를 적은 이유는 다르다. `toArray` 는 호출마다 원소 n 개를 새 배열로
 * 내놓아 어느 구현에서도 n 에 비례하므로 두 한정자가 배제하는 것이 같다(§규약1 「복잡도 한정자」 B9
 * 조건). `size` 는 상태를 바꾸지 않고 값을 읽는 연산이라 그 값을 처음부터 세어 들고 있는 대가가 없다.
 *
 * **주입 정책.**
 * - 주입받는 것이 없다. `T` 는 임의 타입이고 어느 행도 원소끼리 비교하거나 해시하지 않는다. 핸들이
 *   원소를 가리키므로 값이 같은 원소를 가르는 데도 비교가 들지 않는다.
 * - **산 핸들이 아닌 것을 받는 호출을 전제조건으로 막지 않고 값으로 답한다.** 물려받은 문서는 「노드는
 *   반드시 이 리스트에 속해야 한다」를 호출자의 의무로 두었는데, 그러면 이미 뺀 원소를 다시 빼는 호출에서
 *   구현들이 조용히 갈리고 축1이 그 자리를 재지 못한다(`docs/ORD-006-conventions.md` 「전제조건을 두는
 *   계약은 축1이 그 자리를 못 잰다」). 판정 비용은 핸들이 이 수열의 산 원소를 가리키는지 한 번 보는
 *   것이라 상한이 안 바뀐다.
 * - 무엇으로 답할지는 반환 타입이 가른다. `insertAfter` 는 핸들을 돌려주므로 「없음」을 담을 자리가 있어
 *   `null` 이다. `remove` 는 물려받은 표면이 돌려주던 것이 없어 `boolean` 을 붙였다(`tree/linkCutTree`
 *   의 `link` · `cut` 과 같은 전면화). 예외를 던지는 연산은 없다.
 *
 * **검증 등급.** `invariant`.
 * 상한이 자명한 구현으로 달성된다. 원소마다 마디(값 · 앞 마디 · 다음 마디 · 속한 수열)를 두고 앞 끝
 * 마디 · 뒤 끝 마디 · 원소 수를 들면, 넣기 셋과 빼기가 이웃 이음 몇 개를 고치는 상수이고 산 핸들인지는
 * 마디가 기억한 수열을 보는 상수다. `toArray` 는 마디를 한 번 훑는다. **연결 마디는 자명한
 * 구현이다**(`docs/ORD-006-conventions.md:4784`, 2026-09-15 유저 결정). 재균형도 상각 설계도 확률 논증도
 * 없으므로 `complexity` 가 아니고, 불변식 절에 내용이 있으므로 `basic` 도 아니다.
 *
 * **필요충분조건.**
 * - 의미: 핸들이 **원소**를 가리키고 **그 원소를 빼는 호출로만** 죽어야 한다. 핸들이 자리 번호를
 *   가리키면 앞에 끼울 때마다 뒤 원소의 핸들이 다른 원소를 가리켜 첨자로 짚는 수열(`linear/dynamicArray`
 *   쪽)이 되고, 빼기가 이웃 원소의 핸들을 죽이면 호출자가 핸들을 들고 있을 수 없어 넣고 빼기가 끝에서만
 *   되는 수열(`linear/singlyLinkedList` · `linear/deque` 쪽)이 된다.
 * - 비용: `remove` 가 담긴 수에 비례하면 앞 원소를 찾아 앞 끝에서부터 걷는 것이고, `insertAfter` 가
 *   비례하면 핸들의 자리를 찾거나 그 뒤를 미는 것이다. 어느 쪽이든 핸들을 들고 있을 이유 — 찾지 않고 그
 *   자리에서 고친다 — 가 그 자리에서 사라진다.
 */
