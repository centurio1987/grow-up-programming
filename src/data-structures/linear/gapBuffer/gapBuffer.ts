/**
 * GapBuffer — 커서 한 자리를 두는 수열. 그 자리의 편집은 담긴 수와 무관하고, 커서를 옮기는
 * 값은 지나갈 거리에 비례한다.
 *
 * **목적.** 원소를 순서대로 늘어놓고 **커서라는 자리 하나**를 함께 두어, 그 자리의 끼워
 * 넣기와 지우기를 **담긴 수와 무관한 비용**으로 제공하는 것. 커서는 어디로든 옮길 수 있고,
 * 옮기는 값은 **지나갈 거리에 비례한다.** 두 문장이 함께 있어야 이 계약이 성립한다.
 *
 * 임의 위치 읽기·쓰기는 이 계약에 없다. 값으로 찾기·정렬·중복 세기도 없다 — 이 계약은
 * 원소를 비교하지 않는다. 양 끝을 따로 다루는 연산도 없다.
 *
 * **「편집이 한 자리에 몰리면 싸다」가 계약의 문장이 되는가 — 이 구조를 다시 적는 일의
 * 물음이 그것이었고, 답은 「된다」이다.** 되는 자리가 **한 행이 아니라 두 행의 조합**이라
 * 여기 갈라 적는다.
 *
 * - `insert`·`deleteBefore` 행이 「커서 자리의 편집은 담긴 수와 무관하다」를 적는다.
 * - `moveCursor` 행이 「자리를 옮기는 값은 **거리** $d$ 에 비례한다」를 적는다. 담긴 수 n 이
 *   아니라 $d$ 다.
 * - 둘을 함께 읽으면 **한 자리 언저리에서 m 번 고치는 값이 $O(m)$ 이고 멀리 뛰어 가며 m 번
 *   고치는 값이 $O(mn)$ 이다.** 지역성이 값을 갈라 놓는다는 진술이 이 두 행에서 따라 나오고,
 *   그래서 이 계약은 자기 존재 이유를 자기 문장으로 말한다.
 *
 * **`moveCursor` 행을 `O(n)` 으로 적으면 계약이 뜻을 잃는다.** 그러면 한 칸 옮기는 값과 끝에서
 * 끝으로 뛰는 값이 같아지고, 커서를 옮길 때마다 담긴 것을 통째로 다시 늘어놓는 구현이 계약을
 * 만족한다. 그 구현에서는 위 두 값이 $O(mn)$ 으로 같아져 지역성이 약속된 것이 하나도 없다.
 * 실물로 확인했다 — `_contract/_fixtures/rebuildingEditableSequence.ts` 가 나머지 다섯 행을
 * 전부 지키면서 이 행에서만 걸린다.
 *
 * **「갭」은 계약의 문장이 아니다.** 빈 구간을 어디에 얼마나 두는지, 자리를 언제 늘리는지,
 * 캐시가 잘 맞는지는 전부 특정 내부 표현을 지목해야만 참이 되는 진술이라 계약이 될 수 없다
 * (§규약1 「계약의 문장은 구현 전체에 대해 참이어야 한다」가 캐시 지역성을 이름으로 배제한다).
 * 이 구조는 **이름이 곧 내부 표현**이라 그 셋이 계약으로 새어 들어오기 가장 쉬운 자리이므로
 * 여기 적어 둔다. 위 두 행에 남은 것은 비용의 성장 계급뿐이고, 그것이 「갭」 없이도 쓰인다 —
 * 커서 앞뒤를 배열 둘에 나눠 담는 구현도 여섯 행을 전부 지킨다(아래 검증 등급).
 *
 * **그러므로 `GapBuffer` 는 물려받은 구현 이름이고 이 계약의 이름이 아니다.** 계약이 말하는
 * 것을 그대로 부르면 「커서를 가진 편집 가능한 수열」이다. 이름을 여기서 바꾸지 않는 이유는
 * 계약 이름 재편이 별건이기 때문이고(KAN-031), **임시라는 것을 적어 두지 않으면 다음 배치가
 * 구현 이름을 계약 이름으로 읽는다**(불변 사실 64 와 같은 자리다).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로 자리를 원소 수보다 훨씬 많이
 * 잡아 두고 돌려주지 않는 구현도 이 계약을 지킨다. 그 사실을 감추지 않고 여기 적어 둔다 —
 * 공간을 계약에 넣을지는 이 구조 하나가 정할 일이 아니다(§규약1 미결).
 *
 * **`linear/deque`·`linear/queue` 와 서로 담지 않는다.** 덱 계약은 **두 끝**을 담긴 수와 무관한
 * 비용으로 다루겠다고 적고(`src/data-structures/linear/deque/deque.ts:16`), 이 계약은 **한
 * 자리**를 그렇게 다루겠다고 적는다. 어느 쪽도 상대를 담지 않는다.
 *
 * - 덱이 이 계약을 담지 않는다: 덱 계약에는 커서를 옮기는 연산이 없으므로, 앞 끝에서 뒤 끝
 *   까지의 어느 자리에 끼워 넣는 일도 덱 계약이 약속하지 않는다.
 * - 이 계약이 덱을 담지 않는다: 커서를 옮기는 값이 거리에 비례해도 되므로, 앞 끝에 넣는 일
 *   (커서를 0 으로 옮기고 넣기)이 담긴 수에 비례해도 이 계약은 만족된다. 덱의 `pushFront`
 *   행이 그것을 금지한다.
 *
 * **그러나 두 계약을 동시에 만족하는 구현은 있다** — 마디를 양방향으로 이어 두고 커서 마디와
 * 양 끝 마디를 함께 들고 다니면 두 계약의 열네 행이 전부 선다. 그래서 관계가 불변 사실 54
 * 의 「서로 담지 않는다」이고 T5-01 이 `circularBuffer`·`queue` 에서 낸 것보다 **약하다**
 * (불변 사실 181 — 그쪽은 동시에 만족하는 구현이 하나도 없다). 큐와의 관계도 같다: 큐 계약은
 * 넣는 끝과 빼는 끝을 고정하므로(`src/data-structures/linear/queue/queue.ts:27`) 커서가 있는
 * 이 계약과 연산이 겹치지 않고, 두 표면을 함께 갖춘 구현은 있다.
 *
 * **불변식.**
 * 1. `length()` 가 말하는 원소 수와 `toArray()` 가 내놓는 배열의 길이가 같다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 이 성질은 관측 경로가 둘이고(세어 둔
 * 수 · 늘어놓은 수) 어느 계약 줄도 그 정합을 적지 않는다. 커서 앞의 것과 뒤의 것을 따로 담는
 * 구현은 두 수를 따로 들고 다니게 되고, 그 순간 각 연산이 저마다 옳은 채로 둘이 갈린다.
 *
 * 떨어진 후보 셋을 함께 적는다.
 *
 * - **「`cursor()` 는 0 이상 `length()` 이하다」** — 첫 번째 물음에서 걸린다. **공개 연산 둘이
 *   등장한다고 경로가 둘인 것이 아니다** — 물음이 세는 것은 **한 양**을 읽는 경로의 수이고,
 *   축2가 혼자 말할 수 있는 것도 *서로 다른 두 관측이 같은 상태를 같게 읽는가*뿐이다. 이
 *   후보는 **서로 다른 두 양 사이의 순서 관계**라 그 물음의 대상이 아니고, 커서 자리를 읽는
 *   경로는 `cursor()` 하나다. `insert` 가 커서 자리를 드러내기는 하지만 **그 관측이 상태를
 *   바꾸므로 관측 경로로 세지 않는다**(불변 사실 124). 축1이 두 값을 각각 참조 모델과
 *   대조하고 나면 순서 관계는 모델에서 따라 나오므로 축2가 더 잡을 것이 없다.
 * - **「`toArray()` 가 내놓는 순서가 담긴 수열의 순서와 같다」** — 같은 자리에서 걸린다. 순서를
 *   읽는 공개 연산이 `toArray()` 하나이고, 되풀이한 `deleteBefore()` 는 상태를 바꾸는 관측이라
 *   세지 않는다. `toArray()` 가 내놓는 수열 전체는 축1이 참조 모델과 대조한다.
 * - **「빈 구간의 왼쪽 끝이 커서 자리와 같다」** — 그런 구간을 드는 구현을 계약이 요구하지
 *   않으므로 적을 수 없다. 적는 순간 그것이 표현을 처방한다(불변 사실 36). 여기서 「불변식」이
 *   뜻하는 것은 **공개 연산으로 관측 가능하면서 각 연산이 국소적으로 옳아도 깨질 수 있는 상태
 *   성질**뿐이다 — 자료구조 교과서의 클래스 불변식보다 좁고, 좁은 이유는 이 말이 **축2가
 *   검사할 자격**을 정하기 때문이다.
 *
 * **연산 계약.** 상한은 원소 수 n 에 대한 것이고, `moveCursor` 행의 **$d$ 는 커서가 지나갈
 * 거리** $|position - cursor()|$ 다. $d$ 는 언제나 n 이하이므로 `O(d)` 는 `O(n)` 을 담는다 —
 * 두 값이 갈리는 자리가 이 계약의 내용이라 n 으로 접어 적지 않는다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `insert(item)` | `item` 을 커서 자리에 끼워 넣고 그 뒤를 한 칸씩 민다. 커서는 새 원소 뒤로 가므로 직후 `cursor()` 가 하나 크고, 이어 부르면 부른 순서대로 늘어선다 | O(1) | amortized |
 * | `deleteBefore()` | 커서 바로 앞 원소를 제거해 돌려주고 커서를 하나 당긴다. `cursor()` 가 0 이면 `null`, 상태는 불변 | O(1) | worst |
 * | `moveCursor(position)` | 커서를 `position` 자리로 옮긴다. 직후 `cursor()` 는 `position` 이고 담긴 수열은 바뀌지 않는다. `position` 은 0 이상 `length()` 이하의 정수여야 하고, 아니면 `RangeError` 를 던지며 상태는 불변 | O(d) | worst |
 * | `cursor()` | 현재 커서 자리. 0 이상 `length()` 이하다 | O(1) | worst |
 * | `length()` | 현재 원소 수 | O(1) | worst |
 * | `toArray()` | 앞에서부터 순서대로 담은 배열의 사본. 고쳐도 이 구조는 바뀌지 않는다 | O(n) | worst |
 *
 * **자리는 지금 수열 기준의 0-based 순번이고 원소에 붙어 다니는 식별자가 아니다.** 앞쪽이
 * 바뀌면 같은 원소의 자리가 바뀌고, 커서 앞에 무엇을 끼워 넣으면 커서 자리도 함께 는다.
 *
 * **두 행이 갈리는 것을 실제로 쟀다.** 같은 정본의 같은 `moveCursor` 행인데 시나리오가
 * 갈린다 — 한 칸씩만 오가면 호출당 4.00 → 4.00($r = 1.00$)이고, 끝에서 끝으로 뛰면
 * 2,050 → 8,194($r = 4.00$)다. **호출 하나의 값이 n 을 따라 자라느냐가 거리에만 달려 있다**는
 * 것이 이 두 줄이고, 그것이 「편집 지역성」의 실측 형태다. 자리를 옮길 때마다 통째로 다시
 * 짓는 계열은 두 시나리오에서 값이 같아(2,050 → 8,194) 앞에서 걸린다.
 *
 * **`insert` 가 `amortized` 인 것이 이 계약에서 가장 많은 일을 한다.** `worst` 로 적으면 자리를
 * 이따금 다시 잡는 구현이 전부 배제되는데, 그중에 **정당한 구현이 있다** — 빈 자리가 떨어지면
 * 한 번에 늘려 두는 구현은 그 늘리는 호출 하나가 O(n) 이고 다음 늘리기까지 그만큼의 `insert`
 * 가 지나가므로 시퀀스 평균이 상수로 남는다. 실측이 그대로다: 같은 시나리오를 상각 평균으로
 * 재면 2.00 → 2.00 이고 단일 호출 최대로 재면 1,025 → 4,097 이다. 가장 약한 한정자를 적는
 * 규칙(§규약1 「복잡도 한정자」)이 여기서 그 구현을 살린다.
 *
 * **나머지 다섯 행이 `worst` 인 근거는 행마다 다르다.**
 *
 * - `toArray` — 두 한정자가 아무 구현도 다르게 배제하지 않는다. **이 행이 「배열의 사본」을
 *   돌려주라고 적혀 있으므로** 어느 구현이든 원소 n 개를 채워 넣어야 하고, 호출 하나가 n 에
 *   비례해 상각할 여지가 없다(§규약1 「복잡도 한정자」의 B9 조건). 이 근거는 계약 밖으로
 *   일반화되지 않는다 — 사본 대신 훑개나 보기를 돌려주는 계약이면 호출 하나가 상수일 수 있고
 *   그때는 두 한정자가 갈린다.
 * - `cursor`·`length` — 배제되는 것은 값을 첫 호출에 만들어 캐시하는 계열인데, 두 값을 세어
 *   두거나 자리 번호에서 바로 읽는 데 드는 대가가 없으므로 **배제해도 계약이 잃는 것이 없다.**
 * - `deleteBefore`·`moveCursor` — `amortized` 가 이미 배제하는 것은 **호출마다** 담긴 수에
 *   비례하는 계열이고(끼운 자리 뒤를 미는 구현: 상각 평균 513 → 2,049), `worst` 가 **추가로**
 *   배제하는 것은 **이따금 자리를 다시 잡는 계열**이다. 그 계열이 약한 쪽을 통과한다는 것은
 *   바로 위 `insert` 행의 두 수치가 보인다. 배제해도 되는 이유는 그 계열이 아끼는 것이
 *   **저장량**뿐이고 저장량이 이 계약에 없다는 것이다(불변 사실 184 의 판정을 그대로 쓴다).
 *   **그러므로 저장량을 계약에 넣는 규격 결정이 나면 이 두 행의 한정자를 다시 본다.**
 *
 * **`moveCursor` 를 `O(1)` 로 적지 않는 이유는 세 갈래로 갈라 적는다**(불변 사실 165).
 * ① 커서 자리의 편집을 상수로 두면서 자리 이동까지 상수로 두는 구현을 **찾지 못했다.**
 * ② 그런 구현이 **없다는 것을 보이지도 않았다** — 문헌에 하한 결과가 있을 수 있고 이 카드는
 * 확인하지 않았다. ③ **상한을 그렇게 적지 않는 이유는 앞의 둘과 별개로 선다.** 상한은
 * 「무엇을 배제하려는가」에서 고르는 값인데(불변 사실 48·51), `O(1)` 이 배제하는 것은 목적이
 * 배제하려는 계열이 아니라 **목적이 살리려는 계열 전부**다 — 정본도, 배열 둘 구현도, 마디를
 * 이어 두는 구현도 함께 나간다.
 *
 * **주입 정책.**
 * - 주입받는 것이 없다. `T` 는 임의 타입이고 비교·해시·동등성을 쓰지 않으므로 주입할 것이
 *   없다.
 * - **생성자가 인자를 받지 않는다.** 처음 잡을 자리 수를 받는 것은 저장량에 대한 조건이고,
 *   이 계약은 저장량을 말하지 않는다. `linear/circularBuffer` 가 용량을 받는 것과 갈리는 자리다
 *   — 저쪽은 그 값이 `isFull()`·`size` 행에서 관측되지만 여기서는 어느 행도 그것을 관측하지
 *   않는다. 관측되지 않는 인자는 계약이 아니라 구현의 사정이다.
 * - `moveCursor` 의 `position` 은 **0 이상 `length()` 이하의 정수**여야 하고, 아니면
 *   `RangeError` 를 던진다. 범위를 잘라 맞추지(clamp) 않는 이유는 그러면 「옮겨졌다」와
 *   「끝으로 붙었다」가 같은 관측이 되어 호출자가 자기 인자가 유효했는지 알 수 없기 때문이다.
 *   위쪽 끝이 `length() - 1` 이 아니라 `length()` 인 것은 커서가 **원소가 아니라 원소 사이의
 *   자리**를 가리키기 때문이다 — 자리는 원소 수보다 하나 많다.
 * - 커서 앞이 비었을 때 `deleteBefore` 는 예외를 던지지 않고 `null` 을 돌려준다 — 이 선택은
 *   계약의 일부이며, 그 대가로 `T` 에 `null` 이 섞이면 "지울 것이 없음"과 "값이 `null` 인
 *   원소를 지웠음"이 구분되지 않는다. 반환 타입에 「없음」을 담을 자리가 있으므로 예외로
 *   답하지 않는다.
 *
 * **검증 등급.** `invariant`.
 * 상한이 자명한 구현으로 달성된다 — **커서 앞의 것과 뒤의 것을 배열 둘에 나눠 담고 뒤엣것을
 * 뒤집어 두면** 여섯 행이 전부 상한 안이다. 넣고 지우기가 앞쪽 배열의 끝을 만지는 일이고,
 * 커서를 옮기는 일이 한쪽에서 빼 다른 쪽에 넣기를 거리만큼 되풀이하는 일이다. 재균형도
 * 상각 설계도 확률 논증도 없다. 실측으로 확인했다 — 그 구현이 여섯 시나리오를 전부 통과하고
 * 값도 정본과 같다(`insert` 만 1.00 대 2.00 으로 갈리고 나머지 다섯은 같은 수다). 자명한
 * 구현 중에 상한을 넘는 것이 있지만(원소를 배열 하나에 담고 커서를 정수로 들면 끼우기와
 * 지우기가 담긴 수에 비례한다) 그것은 등급을 바꾸지 않는다 — 판정이 묻는 것은 *달성하는
 * 자명한 구현이 있는가*이지 *전부 달성하는가*가 아니다(불변 사실 55). 불변식 절이 비어 있지
 * 않으므로 `basic` 도 아니다.
 *
 * **`linear/deque` 가 `complexity` 인 것과 여기가 갈리는 자리를 적어 둔다.** 덱은 배열 둘로도
 * 자명하지 않다 — 한쪽이 비면 다른 쪽에서 옮겨 오는 재분배가 들어오고 그것이 상각 설계다.
 * 여기서는 그 재분배가 필요 없다. **커서를 옮기는 값을 계약이 이미 치르고 있기 때문**이고,
 * 그래서 등급의 갈림도 결국 `moveCursor` 행에서 나온다. 다만 **등급은 판정의 입력이 아니다**
 * — 등급이 다르면 계약이 같을 수 없다는 것의 역은 성립하지 않는다(불변 사실 56).
 *
 * **필요충분조건.**
 * - 의미: 수열 안에 **자리 하나가 이름을 갖고 살아 있어야** 하고, 편집이 그 자리에서 일어나야
 *   한다. 자리를 가리키는 연산이 없으면 편집할 곳을 매번 인자로 받게 되고, 그러면 자리마다
 *   값이 같아야 하므로 **위치로 읽고 고치는 수열**이다(`linear/unrolledLinkedList`). 자리가
 *   양 끝에 고정돼 있으면 덱이고, 넣는 끝과 빼는 끝이 갈라져 고정되면 큐다.
 * - 비용: 커서 자리의 편집이 담긴 수에 비례하면 **자리 하나를 따로 두는 유일한 값이 사라진다**
 *   — 그러면 커서는 인자를 대신 들고 있는 정수일 뿐이고, 남는 계약은 임의 위치 편집을
 *   $O(n)$ 에 하는 배열이다. 반대쪽도 같다: 커서를 옮기는 값이 거리가 아니라 담긴 수에
 *   비례하면 한 칸 옮기기와 끝으로 뛰기가 같은 값이 되어 **지역성이 아무것도 약속하지 않는다.**
 */
