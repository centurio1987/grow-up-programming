/**
 * SinglyLinkedList — 앞 끝과 뒤 끝 양쪽에 넣고 앞 끝에서만 빼는 수열. 세 갱신이 담긴 수와 무관한 비용이다.
 *
 * **목적.** 원소를 한 줄의 수열로 담고, **앞 끝에 넣기 · 뒤 끝에 넣기 · 앞 끝에서 빼기**를 담긴
 * 원소 수와 무관한 비용으로 제공하는 것. 담긴 것을 앞 끝에서 뒤 끝 순서로 늘어놓는 일은 담긴 수에
 * 비례한다. 넣는 끝은 둘이고 빼는 끝은 하나다 — 앞에 넣고 앞에서 빼면 나중에 온 것이 먼저 나가고,
 * 뒤에 넣고 앞에서 빼면 먼저 온 것이 먼저 나간다. 어느 순서로 내보낼지를 넣는 쪽이 원소마다 고른다.
 *
 * 이 계약에 없는 것은 넷이다.
 *
 * - **뒤 끝에서 빼기.** 빼는 끝이 둘이 되면 양쪽 끝이 다 열린 수열이고, 그것은 `linear/deque` 의
 *   계약이다.
 * - **첨자로 읽고 고치기.** `linear/dynamicArray` 의 계약이다. 두 계약의 관계는 아래 반례 문단에 있다.
 * - **자리를 가리키는 핸들로 가운데에 끼우고 빼기.** `linear/doublyLinkedList` 의 계약이다(반례는 아래
 *   표 첫 행). 물려받은 표면은 넣은 마디를 돌려주고 마디의 다음 마디를 공개했는데,
 *   **그 마디를 받는 연산이 하나도 없었다** — 받는 연산이 없는 핸들은 담는 모양을 밖으로 내보일
 *   뿐이다(§규약1 「금지 — 내부 처방」 1 · 3번). 마디 클래스 · 돌려주던 마디 · private 필드 셋을 뺐다.
 * - **값으로 찾기.** 물려받은 `find(value)` 를 뺐다. `toArray()` 로 늘어놓고 훑으면 같은 뜻이고(원칙 A 의 A2 — 조합),
 *   늘어놓기가 같은 계급(담긴 수에 비례)이라 그 행 때문에 떨어지는 구현 계열이 없는 편의 연산이며(A4), 아래 반례 표 어느
 *   줄도 값 찾기에 기대지 않는다(A5). 판정 줄은 `docs/ORD-006-conventions.md` 「원칙 A — 연산 선정」 판정표 ① 의 4 번째
 *   행이다. 그 행이 반환하던 마디가 위 표현 누출의 입구이기도 했다.
 *
 * **이 계약은 시간만 말한다.** 물려받은 문서의 존재 이유 「이중 연결 리스트보다 메모리가 절반」은
 * 마디를 세운 구현에 대한 진술이라 계약의 문장이 못 되고(불변 사실 38), 저장 공간은 어느 계약에도
 * 없다(§규약1 「공간은 어느 계약에도 없다」 — 미결). 「브라우저 방문 히스토리」는 활용 사례다
 * (§규약1 「금지 — 내부 처방」 5번).
 *
 * **이름은 임시다.** `singlyLinkedList` 는 한 방향으로 이은 마디라는 **담는 모양의 이름**이고, 계약은
 * 마디를 요구하지 않는다(아래 검증 등급 — 자리를 돌려 쓰는 배열도 지킨다). 이름이 하나뿐이어도
 * 임시로 적고 계약 이름은 KAN-031 이 정한다(불변 사실 198).
 *
 * **다른 두 리스트와 같은 계약이 아니다.** 반례를 계약의 문장으로 적고 어느 정본도 보지 않는다
 * (불변 사실 43). 판정 전문은 `docs/ORD-006-conventions.md` 「A군 17종 판정」 ②다.
 *
 * | 쌍 | 반례 구현 | 관계 |
 * |---|---|---|
 * | 이 계약 ↔ `linear/doublyLinkedList` | 앞 마디를 모르는 단방향 마디(앞 끝 · 뒤 끝만 기억)는 이 계약의 다섯 행을 지키고, 저쪽의 핸들 자리 빼기가 앞 마디를 찾느라 담긴 수에 비례한다. 다음 마디의 값을 끌어와 제 마디를 지우는 우회는 다른 핸들을 무효로 만든다 — 저쪽 행이 「다른 핸들은 그대로 유효하다」를 적어야 반례가 선다 | 다르다. 표면을 맞추면 저쪽이 이쪽을 담는다(불변 사실 43) |
 * | 이 계약 ↔ `linear/dynamicArray` | 언어 배열 하나는 저쪽의 첨자 읽기 · 뒤 끝 넣고 빼기를 지키고 이쪽의 앞 끝 넣기가 담긴 수에 비례한다. 단방향 마디는 이쪽을 지키고 저쪽의 첨자 읽기가 첨자에 비례한다 | 서로 담지 않는다(불변 사실 54). 첨자를 가진 순환 버퍼는 둘 다 지킨다 |
 *
 * **불변식.**
 * 1. `size()` 가 말하는 원소 수와 `toArray()` 가 내놓는 배열의 길이가 같다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 원소 수를 읽는 경로가 둘이고(세어 둔 수 대
 * 늘어놓은 수) 어느 연산의 계약 줄도 그 정합을 적지 않는다. 수를 따로 세는 구현이 빈 수열의
 * `removeFirst` 에서 수를 깎으면 갈린다.
 *
 * 후보였다가 빠진 것이 둘이다. 「`removeFirst()` 가 돌려주는 값은 `toArray()[0]` 이다」는 한쪽 경로가
 * 상태를 바꾸므로 관측 경로로 세지 않고, 그 반환값의 조건은 `removeFirst` 의 의미라 축1이 본다
 * (`docs/ORD-006-conventions.md` 「관측이 상태를 바꾸면 관측 경로로 세지 않는다」). 「뒤 끝 참조가
 * 마지막 마디를 가리킨다」는 담는 모양의 성질이다(불변 사실 36).
 *
 * **연산 계약.** 상한은 담긴 원소 수 n 에 대한 것이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `prepend(value)` | `value` 를 앞 끝에 놓는다. 이 원소가 새 앞 끝이다 | O(1) | amortized |
 * | `append(value)` | `value` 를 뒤 끝에 놓는다. 이 원소가 새 뒤 끝이다 | O(1) | amortized |
 * | `removeFirst()` | 앞 끝 원소를 제거하고 돌려준다. 비어 있으면 `null` 이고 상태는 바뀌지 않는다 | O(1) | amortized |
 * | `toArray()` | 담긴 원소를 앞 끝에서 뒤 끝 순서로 늘어놓은 새 배열. 돌려준 배열을 고쳐도 수열은 바뀌지 않는다 | O(n) | worst |
 * | `size()` | 현재 원소 수 | O(1) | worst |
 *
 * **넣기 둘을 `amortized` 로 적은 것은 늘리는 계열을 살리기 위해서다**(불변 사실 194). 자리를 미리
 * 잡아 두는 배열(자리를 돌려 쓰는 순환 버퍼)은 칸이 모자라면 한 번에 옮기고, 그 호출 하나는 상수가
 * 아니다. 그 계열을 배제할 이유가 목적에 없다.
 *
 * **`removeFirst` 를 `amortized` 로 적은 것이 이 표에서 가장 많은 일을 한다.** 넣는 자리를 둘로 나눠
 * 드는 구현이 있다 — 앞에 넣은 것은 앞 무더기 꼭대기에, 뒤에 넣은 것은 뒤 무더기 꼭대기에 쌓고,
 * 빼는데 앞 무더기가 비었으면 뒤 무더기를 통째로 뒤집어 앞 무더기로 옮긴다. 뒤 끝에서 빼는 연산이
 * 없으므로 한 번 앞 무더기로 옮겨진 원소는 되돌아가지 않고, **원소마다 옮겨지는 횟수가 한 번**이라 n
 * 회의 총비용이 O(n) 이다. 옮기는 호출 하나는 O(n) 이므로 `worst` 로 적으면 이 구현이 나가는데, 그
 * 배제의 이유가 목적에 없다(§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」). **뒤 끝 빼기가 이
 * 계약에 없다는 것이 이 구현을 살리는 조건이다** — 덱 계약에서는 두 무더기 사이를 오가는 교대가 생겨
 * 같은 구현이 무너진다(`linear/deque`).
 *
 * `toArray` · `size` 에 `worst` 를 적은 이유는 다르다. `toArray` 는 호출마다 원소 n 개를 새 배열로
 * 내놓아 어느 구현에서도 n 에 비례하므로 두 한정자가 배제하는 것이 같다(§규약1 「복잡도 한정자」 B9
 * 조건). `size` 는 상태를 바꾸지 않고 값을 읽는 연산이라 그 값을 처음부터 세어 들고 있는 대가가 없다.
 *
 * **주입 정책.** 없다. `T` 는 임의 타입이고 이 계약의 어느 행도 원소끼리 비교하거나 해시하지 않는다.
 * 빈 수열에서 `removeFirst` 는 예외를 던지지 않고 `null` 을 돌려준다 — 반환 타입에 「없음」을 담을
 * 자리가 있기 때문이다(`docs/ORD-006-conventions.md` 「전제조건을 두는 계약은 축1이 그 자리를 못
 * 잰다」). 그 대가로 `T` 에 `null` 이 섞이면 「비어 있음」과 「값이 `null` 인 원소」가 구분되지 않는다
 * (`linear/queue` 와 같은 선택).
 *
 * **검증 등급.** `invariant`.
 * 상한이 자명한 구현으로 달성된다. 원소마다 마디(값 · 다음 마디)를 두고 앞 끝 마디 · 뒤 끝 마디 ·
 * 원소 수를 들면 넣기 둘과 빼기가 호출마다 상수이고 `toArray` 는 마디를 한 번 훑는다. **연결 마디는
 * 자명한 구현이다**(`docs/ORD-006-conventions.md:3591`, 2026-09-15 유저 결정). 재균형도 상각 설계도
 * 확률 논증도 없으므로 `complexity` 가 아니고, 불변식 절에 내용이 있으므로 `basic` 도 아니다.
 *
 * **필요충분조건.**
 * - 의미: 넣는 끝이 **앞 · 뒤 둘**이고 빼는 끝이 **앞 하나**여야 한다. 앞 끝에 넣지 못하면 도착한 순서가
 *   고정된 수열(`linear/queue` 쪽)이 되고, 뒤 끝에서도 빼면 양쪽 끝이 다 열린 수열(`linear/deque` 쪽)이
 *   된다. 이 계약이 약속하는 것은 **넣는 쪽이 원소마다 나갈 차례를 앞 · 뒤로 고른다**는 것이다.
 * - 비용: `append` 가 담긴 수에 비례하면 뒤 끝을 기억하지 않고 앞에서부터 훑는 것이고, `prepend` ·
 *   `removeFirst` 가 비례하면 앞 끝을 배열의 첫 칸에 두고 넣고 뺄 때마다 나머지를 미는 것이다. 어느
 *   쪽이든 세 갱신을 상수에 쓰려고 이 구조를 둔 이유가 그 자리에서 사라진다.
 */
