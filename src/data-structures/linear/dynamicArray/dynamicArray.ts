/**
 * DynamicArray — 첨자로 읽고 고치며 뒤 끝에서 넣고 빼는 수열. 첨자 접근과 뒤 끝 갱신이 담긴 수와 무관한 비용이다.
 *
 * **목적.** 원소를 한 줄의 수열로 담고, **첨자로 읽기 · 첨자로 고치기 · 뒤 끝에 넣기 · 뒤 끝에서
 * 빼기**를 담긴 원소 수와 무관한 비용으로 제공하는 것. 수열의 길이를 미리 정하지 않는다는 것이 고정
 * 길이 배열과 갈리는 자리이고, 길이가 늘고 줄어도 첨자 접근이 상수라는 것이 연결 마디와 갈리는
 * 자리다. 담긴 원소 전부를 보는 일도 이 목적의 「첨자로 읽기」를 첨자마다 부르는 것이다.
 *
 * 이 계약에 없는 것은 다섯이다.
 *
 * - **용량과 늘리기 · 줄이기 정책.** 물려받은 표면의 `capacity()` 와 「처음 4칸 · 넘치면 두 배 ·
 *   4분의 1 이하면 절반」을 뺐다. 그 값은 **어느 행의 의미도 바꾸지 않고 칸 수만 읽는다** —
 *   `tree/avlTree` 의 높이와 같은 자리다. 용량이 차도 `push` 가 받는 것이 달라지지 않으므로 불변 사실
 *   67 의 「공간 제약을 관측하는 연산」도 아니다(`linear/circularBuffer` 와 갈리는 자리 — 거기서는
 *   가득 찬 뒤 `write` 의 의미가 바뀐다). 정책을 적으면 담는 모양을 처방한다(§규약1 「금지 — 내부
 *   처방」 1 · 4번). 늘리기 · 줄이기가 상각 비용을 어떻게 지키는지는 가이드의 몫이다.
 * - **앞 끝에서 넣고 빼기.** `linear/singlyLinkedList` · `linear/deque` 의 계약이다.
 * - **가운데 끼우기 · 빼기.** `linear/unrolledLinkedList` 의 계약이다. 언어 배열 하나는 이 계약을 지키고 저쪽의 끼우기가 담긴 수에
 *   비례하며, 칸을 묶음으로 나눈 구현은 저쪽을 지키고 이쪽의 첨자 읽기가 상수를 넘는다 — 서로 담지 않는다(불변 사실 54).
 * - **자리를 가리키는 핸들로 끼우고 빼기.** `linear/doublyLinkedList` 의 계약이다. 두 계약의 관계는 아래
 *   반례 문단에 있다.
 * - **첨자 순서로 늘어놓기.** 물려받은 `toArray()` 를 뺐다. `get(i)` 를 `size()` 번 부르면 같은 뜻이고(원칙 A 의 A2 — 조합),
 *   그 행의 상한 때문에 떨어지는 구현 계열이 없으며(A4 — 편의 연산), 아래 반례 표의 두 줄 어느 것도 이 질의에 기대지 않는다
 *   (A5). 판정 줄은 `docs/ORD-006-conventions.md` 「원칙 A — 연산 선정」 판정표 ① 의 10 번째 행이다.
 *
 * **이 계약은 시간만 말한다.** 칸을 담긴 수보다 더 잡아 두거나 줄이지 않고 들고 있는 구현도 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **이름은 임시다.** `dynamicArray` 는 늘어나는 배열이라는 **담는 모양의 이름**이다. 계약이 말하는 것은 「첨자로 읽고 고치며
 * 뒤 끝이 늘고 주는 수열」이고, 이름이 하나뿐이어도 임시로 적고 계약 이름은 KAN-031 이 정한다(불변 사실 198).
 *
 * **다른 두 리스트와 같은 계약이 아니다.** 반례를 계약의 문장으로 적고 어느 정본도 보지 않는다
 * (불변 사실 43). 판정 전문은 `docs/ORD-006-conventions.md` 「A군 17종 판정」 ②다.
 *
 * | 쌍 | 반례 구현 | 관계 |
 * |---|---|---|
 * | 이 계약 ↔ `linear/singlyLinkedList` | 언어 배열 하나는 이쪽의 다섯 행을 지키고 저쪽의 앞 끝 넣기가 담긴 수에 비례한다. 단방향 마디는 저쪽을 지키고 이쪽의 첨자 읽기가 첨자에 비례한다 | 서로 담지 않는다(불변 사실 54). 첨자를 가진 순환 버퍼는 둘 다 지킨다 |
 * | 이 계약 ↔ `linear/doublyLinkedList` | 언어 배열은 저쪽의 핸들 자리 끼우기가 담긴 수에 비례하고, 양방향 마디는 이쪽의 첨자 읽기가 첨자에 비례한다 | 서로 담지 않는다(불변 사실 54) |
 *
 * **불변식.** 없다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 후보 넷이 각각 다른 자리에서 걸린다.
 *
 * - **「`get(i)` 와 늘어놓은 i 번째 원소가 같다」** — 이 계약이 처음 섰을 때의 불변식이다. 늘어놓기를 뺐으므로(위 목록)
 *   i 번째 원소를 상태를 바꾸지 않고 읽는 연산이 `get` 하나라 첫 번째 물음에서 걸린다. 그 조건은 `get` 의 의미라 축1이 본다.
 * - **「원소 수를 읽는 두 경로가 같다」** — 처음의 다른 불변식(`size()` ↔ 늘어놓은 길이)이 늘어놓기 대신 `get` 을 만나면
 *   `size()` 와 「`get` 이 원소를 돌려주는 첨자의 끝」이 남는다. `get` 행이 「`[0, size())` 안의 정수가 아니면 `null`」로
 *   그 정합을 이미 적으므로 두 번째 물음에서 걸린다.
 * - **「`pop()` 이 돌려주는 값은 `get(size() - 1)` 이다」** — 한쪽 경로가 상태를 바꾸므로 관측 경로로 세지 않는다
 *   (`docs/ORD-006-conventions.md` 「관측이 상태를 바꾸면 관측 경로로 세지 않는다」).
 * - **「담긴 수가 용량의 4분의 1 이상이다」** — 뺀 표면(`capacity()`)의 양이라 읽을 연산이 없고 담는 모양의 성질이다
 *   (불변 사실 36).
 *
 * **연산 계약.** 상한은 담긴 원소 수 n 에 대한 것이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `push(item)` | `item` 을 뒤 끝에 놓는다. 새 원소의 첨자는 호출 직전의 `size()` 다 | O(1) | amortized |
 * | `pop()` | 뒤 끝 원소를 제거하고 돌려준다. 비어 있으면 `null` 이고 상태는 바뀌지 않는다 | O(1) | amortized |
 * | `get(index)` | `index` 번째 원소를 제거하지 않고 돌려준다. `index` 가 `[0, size())` 안의 정수가 아니면 `null` | O(1) | worst |
 * | `set(index, item)` | `index` 번째 원소를 `item` 으로 바꾼다. 다른 원소와 `size()` 는 그대로다. `index` 가 `[0, size())` 안의 정수가 아니면 `RangeError` 를 던지고 상태는 바뀌지 않는다 | O(1) | amortized |
 * | `size()` | 현재 원소 수 | O(1) | worst |
 *
 * **`push` 를 `amortized` 로 적은 것은 늘리는 계열을 살리기 위해서다**(불변 사실 194). 칸이 모자라면
 * 어느 구현이든 어디선가 자리를 더 잡고, 한 번에 옮기는 호출 하나는 상수가 아니다. **`pop` 도
 * `amortized` 다** — 줄이는 계열을 살린다. 물려받은 문서의 정책(4분의 1 이하에서 절반으로)이 바로 그
 * 계열이고, 그 계열을 배제할 이유가 목적에 없다. 다만 상각이 아무 줄이기나 받는 것은 아니다 — 절반
 * 이하에서 곧바로 절반으로 줄이는 구현은 경계에서 넣고 빼기를 번갈아 하면 호출마다 칸을 옮겨 상각
 * 평균이 담긴 수를 따라가고, 이 행을 어긴다(스위트의 적대적 시나리오가 그 자리를 잰다).
 *
 * **`set` 을 `amortized` 로 둔 것은 `worst` 로 올릴 근거를 재지 않았기 때문이다.** 올리려면 그것이
 * **추가로** 배제하는 계열(고친 칸을 따로 적어 두었다가 이따금 한꺼번에 반영하는 구현)이 약한 쪽을
 * 통과함을 재서 보여야 한다(불변 사실 183) — `graph-repr/graphAdjList` 의 `removeEdge` 와 같은 처분이다.
 * `get` · `size` 는 상태를 바꾸지 않고 값을 읽는 연산이라 `worst` 를 적는 대가가 없다(§규약1 「가장 약한
 * 한정자는 셋을 줄 세우지 않는다」).
 *
 * **주입 정책.**
 * - 주입받는 것이 없다. `T` 는 임의 타입이고 어느 행도 원소끼리 비교하거나 해시하지 않는다.
 * - **범위 밖 첨자는 두 연산이 다르게 답한다 — 반환 타입이 가른다.** `get` 은 `T | null` 이라 「그 자리에
 *   원소가 없다」를 담을 자리가 있어 `null` 로 답한다. `set` 은 돌려줄 값이 없어 조용히 넘기면 잘못된
 *   첨자가 아무 흔적 없이 지나가므로 `RangeError` 를 던진다(`docs/ORD-006-conventions.md` 「전제조건을
 *   두는 계약은 축1이 그 자리를 못 잰다」의 범위 밖 인자 판별 · `graph-repr/graphAdjList` 와 같은 선택).
 *   물려받은 문서는 `set` 을 조용히 넘겼다. 정수가 아닌 첨자(`1.5`)도 범위 밖이다.
 * - 빈 수열에서 `pop` 은 `null` 을 돌려준다. 그 대가로 `T` 에 `null` 이 섞이면 「없음」과 「값이 `null` 인
 *   원소」가 구분되지 않는다(`linear/queue` 와 같은 선택).
 *
 * **검증 등급.** `basic`.
 * 상한이 자명한 구현으로 달성된다. 언어 배열 하나에 뒤 끝 넣기 · 빼기 · 칸 읽기 · 칸 쓰기를 맡기면 다섯
 * 행이 전부 상한 안이다. 늘리기는 언어 배열의 것이고 §규약2 계측 단위가 런타임 재할당을 세지 않는데,
 * 계약이 그 행에 적은 한정자가 `amortized` 라 세든 안 세든 계약 안이다(불변 사실 197 — 자명한 구현
 * 판정이 묻는 것은 상각의 존재가 아니라 구현자가 설계를 하나 더 얹는지다). **물려받은 문서가 이 구조의
 * 핵심으로 든 두 배 늘리기는 상각 설계인데 등급이 `complexity` 가 아니다** — 판정은 달성하는 자명한
 * 구현이 하나라도 있는가를 묻는다(불변 사실 55). 그리고 불변식 절이 비어 있다.
 *
 * **처음 섰을 때는 `invariant` 였다.** 늘어놓기(`toArray`)를 원칙 A 의 A5 로 빼자 두 불변식의 한쪽 경로가 사라졌다(위
 * 불변식 절). 등급은 연산 집합에서 따라 나오는 결과이고 연산을 뺀 근거가 아니다(원칙 A 의 A6 ②). 두 등급의 축3
 * 엄격도는 같다(`regression` — `src/data-structures/_contract/judge.ts` 의 `RIGOR_OF_GRADE`).
 *
 * **필요충분조건.**
 * - 의미: 첨자가 **앞 끝에서부터 빈틈 없이** 매겨지고 넣고 빼는 끝이 **뒤 하나**여야 한다. 그래서 넣고
 *   빼도 남은 원소의 첨자가 바뀌지 않는다. 앞 끝에서도 넣고 빼면 호출마다 모든 원소의 첨자가 한 칸씩
 *   밀려 호출자가 들고 있던 첨자가 다른 원소를 가리키게 되고, 길이가 생성 때 정해지면 고정 길이 배열이
 *   된다.
 * - 비용: `get` · `set` 이 첨자에 비례하면 마디를 앞에서부터 세는 것이고, `push` 의 상각 평균이 담긴 수에
 *   비례하면 칸을 일정한 수씩만 늘리며 매번 옮기는 것이다. 앞엣것은 첨자 접근을, 뒤엣것은 길이를 미리
 *   정하지 않는 것을 잃으므로 이 구조를 둔 이유가 그 자리에서 사라진다.
 */
