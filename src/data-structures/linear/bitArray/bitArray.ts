/**
 * BitArray — 자리 수가 생성 때 정해진 켜짐 · 꺼짐의 수열. 자리마다 켜고 끄고 읽는 일이 자리 수와 무관한 비용이다.
 *
 * **이 구조의 이름은 공간에서 왔고, 공간은 계약이 아니다 — 처분은 B15 의 「존치 + 성격 전환」이다**(불변 사실
 * 61 · 67). 물려받은 문서는 존재 이유를 「자리 하나를 비트 하나에 담아 `Set<number>` 대비 32배 절약」으로
 * 적었다. 그 절약은 이 계약을 지키는 **모든** 구현에 대해 참인 문장이 아니고(불변 사실 38), 공간은 이 저장소의
 * 어느 계약에도 없다(§규약1 「공간은 어느 계약에도 없다」 — 미결). 「32배」는 판정의 입력으로 쓰지 않았다(불변
 * 사실 65) — 무엇과 견주느냐로 배수가 갈린다(아래 셋째 걸음의 수치).
 *
 * **같은 계약을 먼저 선 다른 이름이 저장소에 없다 — 짝 정본이 없는 첫 B15 처분이다**(불변 사실 204).
 * `trie/trie` 가 `trie/ternarySearchTree` 의 계약 객체를 이름만 바꿔 쓰는 식의 전환이 여기서는 성립하지 않으므로
 * **이 헤더가 계약을 적는다.** 그래서 이 구조에서 「성격 전환」이 뜻하는 것은 하나다 — 가이드의 주제가 「자리를
 * 비트로 담는 법」에서 「왜 공간이 계약으로 갈리지 않는가」로 바뀐다. 이웃과는 연산 집합부터 달라 같은 계약이
 * 아니다 — `linear/dynamicArray` 는 넣기 · 빼기로 길이가 바뀌고 자리에 임의 값을 담으며, `hash/hashSet` 은 키에
 * 범위가 없고 집합끼리의 연산을 가진다(판정 전문은 `docs/ORD-006-conventions.md` 「A군 17종 판정」 ③).
 *
 * **판별 절차 세 걸음을 이 계약에 실제로 돌렸다**(`docs/ORD-006-conventions.md:2901-2908`, 셋째 걸음의 축은
 * `docs/ORD-006-conventions.md:3068-3071`).
 *
 * 1. 공간 제약을 계약의 용어로 다시 적는다(불변 사실 188). 「자리 하나가 비트 하나」는 자리의 **폭**이라 어느
 *    연산의 반환값에도 나타나지 않는다. 다시 적어도 남는 비용 문장이 없다 — 자리를 여럿 묶어 한 번에 다루는
 *    이득은 상수 배수라 계약이 못 된다(불변 사실 6 · 38).
 * 2. 그 문장이 되는 행이 없다. 고정 자리 수와 범위 밖 첨자의 처분은 관측되지만 **의미 제약**이다 — 자리의 폭과
 *    무관하게 어느 구현이든 똑같이 지킨다.
 * 3. 공간 제약을 무시하는 구현 — 자리마다 불리언 하나를 담는 언어 배열
 *    (`src/data-structures/_contract/_fixtures/booleanSlotBits.ts`) — 을 스위트에 넣었다. 축1 경계 여섯 · 무작위
 *    500 회와 축3 네 시나리오를 **정본과 같은 값으로 전부 통과한다**(축2는 공집합,
 *    `src/data-structures/_contract/runContract.bitArray.test.ts`). 공간 차이는 실재한다 — 자리 1,000,000 개에 힙
 *    증가가 정본 126,044 B · 그 구현 8,004,902 B 다(`bun:jsc` `heapStats`, 할당 한 번 데운 뒤 두 번 같은 값, 벽시계
 *    없음). 제약이 값의 의미도 비용도 말하지 않으므로 그것이 사는 축이 없다.
 *
 * S1 판정과 같은 쪽으로 닫혔다. `graph-repr/graphAdjMatrix` 는 같은 셋째 걸음에서 비용 문장이 남아 계약이
 * 갈렸고(불변 사실 212), 이 구조에는 남는 것이 없다.
 *
 * **메모리 직접 사용 목록(`tools/ord006-escalation.ts`)에 넣지 않는다**(불변 사실 206). 기준은 「TS 안에서 그
 * 절약을 실제 저장으로 보일 수 있는가」이고 위 수치가 답이다. 이 판정은 **정본이 상태를 고정 폭 typed array 에
 * 두기 때문에 선다** — 그것은 이 계약의 요구가 아니라 정본의 선택이고(`./_reference/bitArray.ts` 머리말), 정본을
 * 바꾸면 판정을 다시 연다.
 *
 * **목적.** 자리 `0` 부터 `n-1` 까지를 생성 때 정하고, 자리마다 **켜기 · 끄기 · 켜져 있는지 읽기**를 자리 수와
 * 무관한 비용으로 제공하는 것. 자리마다 담는 값은 켜짐 · 꺼짐 둘뿐이고, 새로 연 배열은 전부 꺼져 있다.
 *
 * 이 계약에 없는 것은 넷이다.
 *
 * - **공간.** 위 문단들이다.
 * - **켜진 자리 수 세기.** 물려받은 `count` 를 뺐다. `get` 을 자리마다 부르면 같은 뜻이고(A2 — 조합), 상한을 무엇으로 적든
 *   켜고 끌 때마다 수 하나를 고치는 상수 보강으로 어느 구현이든 지키므로 떨어지는 계열이 없는 **같은 비용의 편의 연산**이다
 *   (A4). 위 목적이 적는 관찰의 단위는 **자리 하나**이고 자리 전체의 요약은 적지 않으므로 뺀다
 *   (`docs/ORD-006-conventions.md` 「원칙 A5′」 재판정표 ④ 의 22 행). 물려받은 문서의 「워드 수에 비례」는 자리를 묶어 세는 상수 배수라(불변 사실 65) 가이드의 몫이다.
 * - **뒤집기.** 물려받은 `toggle` 을 뺐다. `get` 뒤에 `set` 이나 `clear` 를 부르면 같은 뜻이고(A2) 상수라 떨어지는 계열이
 *   없는 **같은 비용의 편의 연산**이며(A4) 위 목적이 적는 변경은 켜기 · 끄기 둘이다(재판정표 ④ 의 23 행). 셋은 읽기와 함께면 어느 둘로도
 *   나머지를 짓는데(A7 — A1~A5′ 가 무엇을 남길지 정하지 않는다), **호출 직전 상태와 무관하게 결과가 정해지는 둘**을 남겼다.
 * - **자리 수 바꾸기 · 배열끼리의 연산(합 · 교).** 물려받은 표면에 없고, 없으면 목적을 진술하지 못하는 연산이
 *   아니므로 더하지 않는다(불변 사실 47).
 *
 * **이 계약은 시간만 말한다.** 자리마다 바이트를 여럿 쓰는 구현도 이 계약을 지킨다. 공간을 계약에 넣는 규격
 * 결정이 나면 이 처분은 다시 열린다(불변 사실 58 · 61).
 *
 * **이름은 임시다.** `bitArray` 는 자리를 비트로 담는다는 **담는 모양의 이름**이다. 계약이 말하는 것은 「자리
 * 수가 정해진 켜짐 · 꺼짐의 수열」이고, 이름이 하나뿐이어도 임시로 적고 계약 이름은 KAN-031 이 정한다(불변
 * 사실 198).
 *
 * **불변식.** 없다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다.
 *
 * - 「켜진 자리 수 ↔ `get` 이 참인 자리」(S1 처분표의 후보) — `count` 를 빼면서 한쪽 경로가 사라졌다. 켜짐을
 *   읽는 경로가 `get` 하나라 첫 물음에서 걸린다.
 * - 「`size()` ↔ `get` 이 받는 첨자 범위」 — 자리 수를 읽는 경로는 둘이지만 그 정합을 `get` 행이 「`[0, size())`
 *   안의 정수가 아니면 `RangeError`」로 이미 적는다. 둘째 물음에서 걸리고, 그 행의 의미라 축1이 본다.
 * - 「묶음의 남는 비트가 꺼져 있다」 같은 조건은 담는 모양의 성질이라 후보가 아니다(불변 사실 36). 그것을 어긴
 *   구현은 범위 검사와 `get` 에서 드러나고 축1 경계 케이스가 짚는다.
 *
 * **연산 계약.** n 은 생성자가 정한 **자리 수**다. 구조가 사는 동안 바뀌지 않는다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(n)` | 자리 `0` 부터 `n-1` 까지를 두고 모두 끈다 | O(n) | worst |
 * | `set(index)` | `index` 자리를 켠다. 이미 켜져 있으면 상태가 그대로다. 다른 자리는 바뀌지 않는다. `index` 가 `[0, size())` 안의 정수가 아니면 `RangeError` 를 던지고 상태를 바꾸지 않는다 | O(1) | amortized |
 * | `clear(index)` | `index` 자리를 끈다. 이미 꺼져 있으면 상태가 그대로다. 다른 자리는 바뀌지 않는다. 범위 밖 첨자는 `set` 과 같다 | O(1) | amortized |
 * | `get(index)` | `index` 자리가 켜져 있는가. `index` 가 `[0, size())` 안의 정수가 아니면 `RangeError` 를 던진다 | O(1) | worst |
 * | `size()` | n | O(1) | worst |
 *
 * 생성자의 `O(n)` 은 모든 자리를 끈 채 여는 준비를 허용하는 값이다 — 준비를 미루는 구현도 만족한다. 생성자는 n
 * 에 대해 반복 호출되지 않아 시나리오 면제다(§규약2 시나리오 규칙 2).
 *
 * **`set` · `clear` 는 `amortized` 다 — `worst` 가 추가로 배제하는 계열을 재고 나서 약한 쪽을 골랐다**
 * (`docs/ORD-006-conventions.md` 「강한 한정자의 근거는 「추가로 배제되는 계열」을 수치로 낸다」). 이 계약이
 * 배제하려는 것은 호출마다 켜진 수에 비례하는 구현이고, `amortized` 가 이미 그것을 배제한다(결함 둘이 상각
 * 평균에서 걸린다). `worst` 가 **더** 배제하는 것은 **칸을 나중에 잡는 구현**이다 — 가장 큰 켜진 자리까지만 칸을
 * 두 배씩 늘리면 늘리는 호출만 비례해서, 섞은 차례로 켜는 시나리오를 상각 평균 1.02 → 1.02 로 통과하고 한 호출
 * 최대로는 17 → 65 로 걸린다(탐침, 저장소에 두지 않았다). 그 계열이 아끼는 것은 저장량이라 배제해도 형식상 잃는
 * 것은 없다(`linear/circularBuffer` 가 그 논리로 `worst` 를 적었다). 그래도 적지 않는다 — 강한 한정자는 「잃는 것이
 * 없으면 적을 수 있다」이지 「적는다」가 아니고(불변 사실 59), 그 계열을 떨어뜨릴 근거가 목적에 없다. `get` ·
 * `size` 는 상태를 바꾸지 않고 값을 읽는 연산이라 `worst` 를 적는 대가가 없다(§규약1 「가장 약한 한정자는 셋을 줄
 * 세우지 않는다」).
 *
 * **주입 정책.**
 * - 주입받는 것이 없다. 자리에 담는 값이 켜짐 · 꺼짐 둘로 정해져 있고 무엇도 비교하거나 해시하지 않는다.
 * - `n` 은 0 이상의 정수여야 하고, 아니면 생성자가 `RangeError` 를 던진다. **`n === 0` 은 정당하다** — 자리가 없는
 *   배열이고 모든 첨자가 범위 밖이다. 물려받은 문서는 1 이상을 요구했는데 0 을 막을 이유가 이 계약에 없다
 *   (`linear/circularBuffer` 가 0 을 막은 이유 — 두 관측이 서로를 구분하지 못한다 — 가 여기에는 없다).
 * - **범위 밖 첨자는 세 연산이 모두 `RangeError` 다 — 연산마다 반환 타입으로 판별한 결과가 같게 나왔다**(불변
 *   사실 226). `get` 은 `boolean` 이라 「그런 자리가 없다」를 담을 자리가 없고, `false` 로 답하면 「꺼져 있다」로
 *   읽혀 잘못된 첨자가 조용히 지나간다. `set` · `clear` 는 돌려줄 값이 없어 조용히 넘기면 흔적이 없다
 *   (`docs/ORD-006-conventions.md` 「전제조건을 두는 계약은 축1이 그 자리를 못 잰다」의 범위 밖 인자 판별 ·
 *   `graph-repr/graphAdjMatrix` 의 `hasEdge` 와 같은 선택). 물려받은 문서는 셋 다 조용히 넘기고 `get` 은 `false` 로
 *   답했다. 정수가 아닌 첨자(`0.5`)도 범위 밖이다.
 *
 * **검증 등급.** `basic`.
 * 상한이 자명한 구현으로 달성된다 — 자리마다 불리언 하나를 담는 언어 배열 하나면 다섯 행이 전부 상한 안이다(그
 * 구현을 스위트에 넣어 확인했다 — 위 셋째 걸음). 자리를 비트로 묶는 기법은 등급의 근거가 아니다 — 판정은 달성하는
 * 자명한 구현이 하나라도 있는가를 묻는다(불변 사실 55). 불변식 절이 비었으므로 `invariant` 도 아니다. S1 의 예상
 * (`invariant` — 켜진 수 ↔ `get`)과 갈린 것은 `count` 를 뺐기 때문이다.
 *
 * **필요충분조건.**
 * - 의미: 자리 수가 **생성 때 정해지고** 자리마다 **켜짐 · 꺼짐 둘뿐**이며, 범위 밖 첨자가 어느 연산에서도 조용히
 *   지나가지 않아야 한다. 자리 수가 넣기 · 빼기로 바뀌면 첨자 수열(`linear/dynamicArray`)이고, 자리에 임의 값을
 *   담으면 고정 길이 배열이며, 범위 밖 `get` 을 `false` 로 답하면 잘못된 첨자가 꺼진 자리로 읽힌다.
 * - 비용: `set` · `clear` · `get` 이 켜진 자리 수에 비례하면 켜진 자리의 번호를 목록으로 든 것이다. 그러면 자리
 *   번호로 곧장 짚는다는 이 계약의 유일한 값이 사라지고, 남는 것은 켜진 수에 비례하는 정수 집합이다.
 */
