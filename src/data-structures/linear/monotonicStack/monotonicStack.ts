/**
 * MonotonicStack — 한쪽 끝에서만 넣고 빼며, 지금 담긴 원소 중 비교자가 가장 크다고 보는 원소를 원소 수와 무관한 비용에 답하는 스택.
 *
 * **목적.** 넣기 · 빼기 · 보기를 한쪽 끝(top)으로 제한한 스택에 **지금 담긴 원소 중 가장 큰 것을
 * 묻는 일**을 더해, 넷을 담긴 원소 수와 무관한 비용으로 함께 제공하는 것. 요점은 빼기 뒤다 — 가장 큰
 * 원소가 빠진 직후에도 남은 것 중 가장 큰 원소를 같은 비용에 답한다.
 *
 * 이 계약에 없는 것은 넷이다.
 *
 * - **바닥 쪽에서 빼기.** 넣는 끝과 빼는 끝이 갈리면 `linear/monotonicQueue` 의 계약이다. 두 계약은
 *   빼는 끝 하나로 갈린다(아래 반례 표).
 * - **임의 위치 접근 · 순회 · 둘째로 큰 원소.** 담긴 것을 늘어놓는 연산이 없다.
 * - **물려받은 표면의 함수 셋.** `nextGreater(arr)` · `prevGreater(arr)` · `nextSmaller(arr)` 는 배열
 *   하나를 받아 답을 내고 호출 사이에 남기는 것이 없었다 — 참조 모델이 대조할 상태가 없어 자료구조
 *   계약이 서지 않는다(불변 사실 200). 같은 물음은 알고리즘 트랙
 *   `src/algorithms/array/nextGreaterElement/nextGreaterElement.ts` 가 푼다. 셋을 뺐고 연산 집합을
 *   새로 지었다(2026-09-15 유저 결정 — `linear/gapBuffer` 가 연산 집합을 통째로 간 선례).
 * - **넣을 때마다 앞쪽에서 가장 가까운 큰 원소를 답하는 일.** 연산 집합의 다른 후보였고 넣지 않았다.
 *   빼기와 함께 두면 이 이름이 가리키는 기법 — 큰 값이 들어올 때 앞선 작은 후보를 버리는 단조 무더기 —
 *   이 그 행을 상수에 지키지 못한다. 버린 후보를 빼기 뒤에 되살려야 하므로, 내림차순으로 채운 뒤 가장
 *   큰 값 넣기와 빼기를 번갈아 하면 한 쌍이 담긴 수에 비례한다(탐침: 되살리기 기록을 든 무더기 2,050 →
 *   8,194 · 앞 큰 원소 사슬을 타는 구현 1,026 → 4,098, 담긴 수 1,024 → 4,096). 그러면 상한이 목적에서
 *   따라 나오지 않는 고르는 값이 되고(불변 사실 48 · 51) 이름의 기법을 배제한다. 빼기를 두지 않으면 그
 *   기법이 넣기를 상수에 지키지만(같은 탐침 2.00 → 2.00) 원소가 나가지 않아 넣은 역순이라는 스택의
 *   약속이 관측되지 않고, 알고리즘 트랙의 같은 물음을 한 원소씩 흘려 받는 모양이 된다. 이 선택은 규약
 *   절차로 닫히지 않아 사람 결정으로 올렸다(`docs/ORD-006-conventions.md` 「A군 단조 둘」).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도 없다」 —
 * 미결). 물려받은 문서의 주가 분석 이야기는 활용 사례라 계약의 문장이 아니다(§규약1 「금지 — 내부
 * 처방」 5번).
 *
 * **이름은 임시다.** `monotonicStack` 은 값이 한 방향으로만 늘어선 무더기라는 **담는 모양의 이름**이고,
 * 계약은 그 모양을 요구하지 않는다 — 원소마다 「그 원소까지의 최댓값」을 곁에 적는 배열도 이 계약을
 * 지킨다(아래 검증 등급). 계약 이름은 KAN-031 이 정한다(불변 사실 64 · 198).
 *
 * **이웃 계약과 같은 계약이 아니다.** 반례를 계약의 문장으로 적고 어느 정본도 보지 않는다(불변 사실 43).
 *
 * | 쌍 | 반례 구현 | 관계 |
 * |---|---|---|
 * | 이 계약 ↔ `linear/stack` | 언어 배열 하나에 쌓는 스택은 저쪽 다섯 행을 지키고 최댓값을 묻는 행이 없다. 붙이면 담긴 수만큼 훑는다. 이 계약을 지키는 구현은 비교자를 고정해 세우고 최댓값을 안 물으면 저쪽 다섯 행을 그대로 지킨다 | 이 계약이 저쪽을 담는다 — 더 많이 약속하므로 더 좁다(불변 사실 43) |
 * | 이 계약 ↔ `linear/monotonicQueue` | 원소마다 「바닥부터 그 원소까지의 최댓값」을 곁에 적는 배열은 이 계약의 일곱 행을 지키고, 바닥 쪽에서 빼면 남은 칸의 적어 둔 값이 뺀 원소를 여전히 품어 전부 다시 적어야 한다. 큰 값이 들어올 때 앞선 작은 후보를 버리는 구현은 저쪽을 지키고, 넣은 쪽에서 빼면 버린 후보가 다시 가장 커지는 자리에서 틀린 값을 답한다 | 서로 담지 않는다(불변 사실 54) — **빼는 끝이 넣는 끝과 같은가 다른가로 갈린다.** 양쪽 끝에서 빼며 최댓값을 묻는 덱은 둘 다 지킬 수 있다(논증이고 실행하지 않았다) |
 *
 * **불변식.** 없다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 후보 셋이 각각 다른 자리에서 걸린다.
 *
 * - **「`max()` 는 담긴 어느 원소보다 작지 않다」** — 담긴 원소를 상태를 바꾸지 않고 읽는 연산이
 *   `peek()` 하나이고 늘어놓는 연산이 없어, 최댓값과 대조할 둘째 경로가 없다. 빼 가며 견주는 길은 상태를
 *   바꾸므로 관측 경로로 세지 않는다(`docs/ORD-006-conventions.md` 「관측이 상태를 바꾸면 관측 경로로
 *   세지 않는다」). 첫 번째 물음에서 걸리고, 그 조건은 `max` 의 의미라 축1이 본다.
 * - **「`peek()` 은 다음 `pop()` 이 돌려줄 원소와 같다」** — 아래 표의 `peek` 행이 적는다. 두 번째 물음.
 * - **「`isEmpty()` 는 `size() === 0` 과 같다」** — `isEmpty` 행이 적는다. 두 번째 물음.
 *
 * **연산 계약.** 상한은 담긴 원소 수 n 에 대한 것이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator)` | 비교자를 고정한다. 이후 바꿀 수 없다 | O(1) | worst |
 * | `push(item)` | `item` 을 top 에 놓는다. 직후 `peek()` 은 `item` 을 돌려준다 | O(1) | amortized |
 * | `pop()` | top 원소를 제거하고 돌려준다. 비어 있으면 `null` 이고 상태는 바뀌지 않는다 | O(1) | amortized |
 * | `peek()` | top 원소를 제거하지 않고 돌려준다. 비어 있으면 `null`. 직후 `pop()` 이 같은 원소를 돌려준다 | O(1) | worst |
 * | `max()` | 지금 담긴 원소 중 비교자가 가장 크다고 보는 원소를 제거하지 않고 돌려준다 — 담긴 어느 원소 `y` 에 대해서도 비교자가 (돌려준 원소, `y`) 에 음수를 내지 않는다. 그런 원소가 여럿이면 어느 것인지 정하지 않는다. 비어 있으면 `null` | O(1) | worst |
 * | `isEmpty()` | `size() === 0` 과 같다 | O(1) | worst |
 * | `size()` | 현재 원소 수 | O(1) | worst |
 *
 * `amortized O(1)` 은 빈 스택에서 시작한 어떤 호출열 m 회의 총비용이 O(m) 이라는 뜻이다. 호출 하나가
 * 상수를 넘어도 계약 위반이 아니다.
 *
 * **`push` · `pop` 을 `amortized` 로 적은 이유는 `linear/stack` 과 같다** — 자리를 늘리고 줄이는 계열을
 * 살린다(불변 사실 194). `max` 를 `worst` 로 적으면 배제되는 계열은 최댓값을 묻는 호출에 몰아 계산해
 * 두는 구현인데, 그 값을 넣을 때 곁에 적어 두는 대가가 `push` 행의 상수 안에 들어가므로 **배제해도
 * 계약이 잃는 것이 없다**(§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」). `peek` · `isEmpty` ·
 * `size` 는 상태를 바꾸지 않고 들고 있는 값을 읽는 연산이라 같은 이유다.
 *
 * **최댓값이 여럿일 때 어느 것을 돌려줄지 정하지 않는 이유.** 같은 크기 중 먼저 넣은 것을 답하는
 * 구현과 나중에 넣은 것을 답하는 구현이 둘 다 자연스럽고, 둘을 가를 이유가 목적에 없다. 원소 타입이
 * 수이고 비교자가 뺄셈이면 둘은 관측되지 않는다 — 계약 스위트가 그렇게 돈다.
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수 · 0 · 양수를 돌려주는 전순서여야 한다. 음수는 「`a` 가 `b` 보다 작다」이고
 *   0 은 「크기가 같다」다. **기본 비교자를 두지 않는다** — 두면 그 방향이 계약의 일부가 되고, 최솟값을
 *   묻는 스택이 다른 계약이 된다. 뒤집은 비교자를 주입하면 같은 구현이 최솟값을 답하므로 **최솟값을 묻는
 *   스택은 이 계약이다**(`heap/minHeap` 과 `heap/maxHeap` 이 같은 계약인 것과 같은 자리 —
 *   `docs/ORD-006-conventions.md` 「연산 집합이 계약을 가른다 — 힙 여덟의 판정」). 비교자를 주지 않으면
 *   `TypeError` 다.
 * - 같은 원소를 여러 벌 담을 수 있다. 넣은 수만큼 나온다.
 * - 빈 스택의 `pop` · `peek` · `max` 는 예외가 아니라 `null` 이다 — 반환 타입에 「없음」을 담을 자리가
 *   있기 때문이다(`docs/ORD-006-conventions.md` 「전제조건을 두는 계약은 축1이 그 자리를 못 잰다」).
 *   그 대가로 `T` 에 `null` 이 섞이면 「비어 있음」과 「값이 `null` 인 원소」가 구분되지 않는다.
 * - 비교자가 같은 두 원소에 호출마다 다른 답을 내면 계약이 성립하지 않는다. 그 조건을 지키는 것은
 *   주입자의 의무이고 이 구조가 검사하지 않는다.
 *
 * **검증 등급.** `basic`.
 * 상한이 자명한 구현으로 달성된다. 언어 배열 하나에 원소마다 (원소, 바닥부터 그 원소까지 중 가장 큰
 * 원소) 짝을 쌓으면, 넣을 때 바로 아래 짝의 둘째 칸과 한 번 견주고 뺄 때 끝 짝을 버리며 최댓값은 끝 짝의
 * 둘째 칸이다. **넣고 빼는 끝이 같으므로 곁에 적은 값이 빼기에 낡지 않는다.** 재균형도 상각 설계도 확률
 * 논증도 없고, 불변식 절이 비어 있다.
 *
 * `linear/monotonicQueue` 가 `complexity` 인 것과 여기가 갈린다 — 그쪽은 앞 끝에서 빼므로 칸마다 적은
 * 「앞부터의 최댓값」이 빼기에 낡는다. **등급이 다르면 계약이 같을 수 없다**(불변 사실 56). 위 반례 표와
 * 같은 결론에 다른 길로 닿는다.
 *
 * **필요충분조건.**
 * - 의미: `max()` 가 **지금 담긴** 원소로 답해야 하고, 꺼내는 순서가 넣은 순서의 역순이어야 한다. 빼고
 *   난 뒤에도 뺀 원소를 답하면 그것은 지금까지 넣은 것 중 최댓값을 세는 누적 값이고, 꺼내는 순서가
 *   넣은 순서대로면 `linear/monotonicQueue` 다.
 * - 비용: `max` 가 담긴 수에 비례하면 스택 옆에서 매번 훑는 것이고, `pop` 이 비례하면 가장 큰 원소 하나만
 *   기억하다가 그것이 빠질 때 다시 훑는 것이다. 어느 쪽이든 스택 연산 사이사이에 최댓값을 상수에 묻는다는,
 *   이 구조를 둔 이유가 그 자리에서 사라진다.
 */
