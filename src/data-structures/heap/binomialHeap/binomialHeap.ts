/**
 * BinomialHeap — 나무를 크기별로 세워 두고 이진수 덧셈처럼 합치는 우선순위 큐.
 *
 * **이 계약은 `heap/leftistHeap` 의 계약과 같다.** 여섯 행의 이름·의미·상한·한정자가 글자
 * 하나 다르지 않다. 그래서 스위트도 같은 객체를 쓴다(`./binomialHeap.contract.ts`).
 * 두 이름을 남겨 둔 이유는 **기법이 다르기 때문**이고, 다르다는 것을 계약으로는 말할 수
 * 없다는 것이 이 파일이 실증하는 사실이다(§규약1 「성격 전환은 이렇게 적는다」).
 *
 * **갈라 보려 시도한 것 넷이 전부 계약의 문장이 되지 못했다.**
 *
 * - **「넣기가 상각 상수다」.** 참이다 — 자릿수 올림이 이어지는 길이가 평균 두 자리라 실측이
 *   **4.00 고정**이다(좌편향 정본은 9.01 · 11.00 · 13.00 으로 자란다). 그런데 이것을 계약에
 *   적으면 합치기로 넣는 계열이 통째로 나가고, 배제할 이유가 목적에 없다. 상수 시간 넣기를
 *   **약속**하는 계약은 따로 있다(`heap/pairingHeap`). 물려받은 문서가 이 행을 「O(log n)
 *   상각」으로 적어 둔 것은 더 센 사실을 약하게 옮겨 적은 것이었고, 바로잡고 나서야 두
 *   구조의 여섯 행이 같아졌다(불변 사실 65).
 * - **「자리에 선 나무 수가 담긴 수의 이진 표현이다」.** 담는 모양의 성질이라 계약이 관측하지
 *   못한다(불변 사실 36). 관측되는 것은 그 성질이 만들어 내는 **비용**뿐이고, 비용은 같은
 *   계급이다.
 * - **「합치기가 두 수를 더하는 일이라 크기가 갈려도 자릿수만큼만 든다」.** 좌편향 힙의
 *   합치기도 두 오른쪽 길의 합만큼 든다. **실측이 15 · 17 · 19 대 15 · 19 · 21 로 붙어
 *   있다** — 계급이 같으므로 축3이 둘을 가르지 못한다.
 * - **「걸음이 두 배 든다」.** 참이고(넣기 22 · 26 · 30 대 11 · 13 · 15) 상수 배수다.
 *   계약은 성장 계급을 말하고 축3은 그것만 판정한다(불변 사실 6·76).
 *
 * **연산 표면을 정본에 맞췄다.** `insert`·`extractMin` 을 `enqueue`·`dequeue` 로 부르고,
 * `merge` 의 반환을 없앴으며, `peek` 의 상한을 $O(\log n)$ 에서 `O(1)` 로 내렸다. 셋 다
 * 계약이 아니라 **문서가 갈려 있던 자리**다 — 마지막 것만 근거가 다른데, 뿌리 목록을 훑는
 * 구현을 그대로 적은 값이었고 최우선 자리를 따로 드는 데 드는 대가가 갱신의 상한을 바꾸지
 * 않는다. `O(1)` 로 적어도 배제되는 구현 계열이 없다.
 *
 * **목적.** 기본 우선순위 큐(`heap/priorityQueue`)의 다섯에 **두 큐를 하나로 접는 일**을
 * 더하고, 그 접기까지 원소 수의 로그 안에 두는 것. 갱신 셋은 호출 하나하나가 로그 안이고
 * 조회 셋은 상수다. 이 계약에 없는 것 · 상한과 한정자를 그렇게 고른 근거 · 판별 절차의
 * 자세한 서술은 정본 헤더에 있다(`../leftistHeap/leftistHeap.ts`). **정본 이름은 임시다**
 * (불변 사실 64) — 이 이름도 저 이름도 담는 모양을 가리키는 구현 이름이고, 계약 이름은
 * KAN-031 이 정한다.
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도
 * 없다」 — 미결). 나무를 마디로 세우는 이 기법이 배열 한 줄보다 자리를 더 쓴다는 것도 계약의
 * 문장이 아니다.
 *
 * **불변식.** 없다.
 *
 * 정본과 같은 판별 절차를 돌린 결과이고 답도 같다 — 후보 셋(`peek` ↔ 다음 `dequeue`,
 * `isEmpty` ↔ `size`, 합친 뒤의 두 크기) 중 첫째가 관측 경로가 하나라서, 나머지 둘은 그
 * 정합을 계약 줄이 이미 적고 있어서 걸린다(§규약1 「불변식 판별 절차」). **기법이 달라도
 * 절차의 답이 같은 것은 베낀 것이 아니라 절차가 상태의 성질만 보기 때문이다**
 * (불변 사실 108 과 같은 자리). 「자리마다 나무가 하나 이하다」·「자식이 차수 오름차순이다」는
 * 담는 모양의 성질이라 후보조차 아니다.
 *
 * **연산 계약.** n 은 담긴 원소 수다. **`merge` 행에서만 「합친 뒤의 원소 수」로 읽는다.**
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `enqueue(item)` | `item` 을 담는다. 같은 원소를 여러 벌 담을 수 있고 넣은 수만큼 나온다 | O(log n) | worst |
 * | `dequeue()` | 비교자가 가장 앞세우는 원소를 지우고 돌려준다. 비어 있으면 `null` 이고 상태가 바뀌지 않는다 | O(log n) | worst |
 * | `merge(other)` | `other` 에 담긴 원소를 전부 이 큐로 옮기고 `other` 를 비운다. `other` 가 이 큐 자신이면 `TypeError` | O(log n) | worst |
 * | `peek()` | 최우선 원소를 지우지 않고 돌려준다. 비어 있으면 `null` | O(1) | worst |
 * | `size()` | 담긴 원소 수 | O(1) | worst |
 * | `isEmpty()` | `size() === 0` 과 같다 | O(1) | worst |
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. **기본 비교자를 두지
 *   않는다** — 방향은 주입자가 정한다. 비교자를 주지 않으면 `TypeError` 다.
 * - `merge(other)` 의 `other` 는 같은 구현으로 만든, 같은 비교자를 든 큐다. 다른 구현의 큐를
 *   합치는 일을 계약이 약속하지 않는다 — 약속하면 상대의 담는 모양을 읽을 수 있어야 하고,
 *   그 순간 계약이 표현을 정한다. 주입자의 의무이고 이 구조가 검사하지 않는다.
 * - `other` 가 이 큐 자신이면 `TypeError` 다. 「비운다」와 「담는다」가 같은 객체에서 서로를
 *   부정하므로 값으로 답할 자리가 없다.
 * - 같은 원소를 여러 벌 담을 수 있다. 집합이 아니므로 중복을 버리지 않는다.
 * - 빈 큐의 `peek`·`dequeue` 는 예외가 아니라 `null` 이다.
 *
 * **검증 등급.** `complexity`.
 * 일곱 행을 함께 만족하는 자명한 구현이 없다. 정본과 같은 판정이고 근거도 같다 — 배열 한
 * 줄에 접어 담으면 합치기가 원소 수에 비례하고, 늘 정렬해 두면 넣기가 그렇다.
 *
 * **필요충분조건.**
 * - 의미: 기본 우선순위 큐의 다섯에 **두 큐를 하나로 접는 일**이 더해진 것. 접기를 버리면
 *   기본 우선순위 큐이고, 담긴 원소의 우선순위를 낮추는 일을 더하면 `heap/fibonacciHeap`
 *   이다.
 * - 비용: 합치기가 원소 수에 비례하면 배열 한 줄이다. 그리고 일곱을 다 지키더라도 갱신 셋을
 *   상각으로만 지키면 미뤄 두었다 접는 계열이고, 그쪽은 빼기 한 호출이 담긴 수에 비례할 수
 *   있다(`heap/pairingHeap`).
 */
