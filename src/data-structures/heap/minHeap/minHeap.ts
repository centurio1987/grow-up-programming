/**
 * MinHeap — 주입된 비교자가 앞세우는 원소 하나만 꺼낼 수 있는 모음.
 *
 * **이 계약은 `heap/priorityQueue` 의 계약과 같다.** 비슷한 것이 아니라 같은 것이다 —
 * 아래 연산 계약 표의 여섯 행이 그 파일의 여섯 행과 글자까지 같고, 스위트도 그 파일의
 * `ContractSpec` 을 그대로 돌린다(`./minHeap.contract.ts`). 그 사실을 감추지 않고 여기
 * 맨 앞에 적는다 — 이름이 다르다고 계약이 다른 것이 아니다(§규약1 「같은 구조인가」).
 *
 * 두 이름을 가르려고 셋을 시도했고 셋 다 계약의 문장이 되지 못했다.
 *
 * - **「최소」라는 방향.** 이 계약은 비교자를 **주입받고** 「최우선」을 그 비교자로 정의한다.
 *   그러므로 최솟값을 먼저 내놓는 것은 이 구조의 성질이 아니라 주입된 비교자의 성질이고,
 *   뒤집어 주입하면 같은 코드가 최댓값을 먼저 내놓는다. 방향을 계약에 적으려면 기본 비교자를
 *   두어야 하는데, 두는 순간 원소 타입이 `number`·`string` 으로 좁아지고 그 제한을 요구할
 *   이유가 목적에 없다. `heap/maxHeap` 과 갈리지 않는 것이 바로 이 자리다.
 * - **자리 번호를 1 부터 쓰는 것.** 정본은 배열 0 번 칸부터 쓰고 이쪽 정본은 0 번 칸을
 *   비워 둔다. 그러면 부모·자식 계산에서 뺄셈이 사라진다. 그런데 **계약에 「자리 번호」라는
 *   말이 없다** — 담는 모양은 계약이 관측하지 못하고, 적는 순간 그것이 표현을 처방한다
 *   (불변 사실 36). 마디를 이어 담는 구현에는 자리 번호라고 부를 것이 아예 없다.
 * - **빼기가 지나가는 자리 수.** 정본은 내려가는 층마다 자식 둘과 손에 든 원소를 함께
 *   견주고 제자리를 찾으면 멈추는데, 이쪽 정본은 자식끼리만 견주며 잎까지 내려갔다가
 *   되올린다. 실측하면 갈린다 — 크기를 유지하며 번갈아 빼는 시나리오에서 21.2 · 25.2 ·
 *   29.2 대 19.1 · 22.9 · 26.8 이다. **그런데 $r$ 은 1.19 · 1.16 대 1.20 · 1.17 로
 *   붙어 있다.** 상수 배수는 성장률 판정에 들어오지 않는다(불변 사실 6).
 *
 * **그래서 이 구조는 계약이 아니라 이름과 기법으로 갈린다.** 계약이 구현을 처방하지
 * 않기로 한 이상 그 갈림은 계약에 들어올 수 없고, 자리는 가이드다(불변 사실 45).
 * 지우지 않는 이유는 판정이 *"계약이 담지 못한다"* 이지 *"쓸모가 없다"* 가 아니기
 * 때문이다(불변 사실 61).
 *
 * **정본 이름은 임시가 아니다.** 이 계약에 이름이 넷 붙어 있는데 그중 우선순위 큐만이
 * ADT 이름이고 나머지 셋(`minHeap`·`maxHeap`·`daryHeap`)은 전부 구현을 가리킨다. 그래서
 * 이 자리는 KAN-031 로 넘기지 않는다(불변 사실 66).
 *
 * **목적.** 원소를 담는 일·비교자가 가장 앞세우는 원소를 꺼내는 일을 원소 수의 **상각**
 * 로그 비용으로, 그 원소를 꺼내지 않고 보는 일과 담긴 수를 읽는 일을 **최악** 상수 비용으로
 * 함께 제공하는 것. 꺼낼 수 있는 것이 맨 앞 하나뿐이라는 것이 계약의 내용이다.
 *
 * 합치기·우선순위 낮추기는 이 계약에 없고(`heap/leftistHeap`·`heap/fibonacciHeap`),
 * 같은 우선순위 원소들 사이의 순서도 약속하지 않는다. 임의 원소를 찾거나 지우는 일도
 * 없다(`tree/redBlackTree`).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로, 원소 수보다 훨씬 많은
 * 자리를 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **불변식.** 없다.
 *
 * **판별 절차를 돌린 결과다**(§규약1 「불변식 판별 절차」). 후보 둘이 각각 다른 물음에서
 * 걸린다.
 *
 * - **`peek()` 은 다음 `dequeue()` 가 돌려줄 원소와 같다** — 최우선 원소를 **상태를 바꾸지
 *   않고** 읽는 공개 연산이 `peek` 하나뿐이라 **첫 번째 물음에서 걸린다.** `dequeue` 의
 *   반환값에 대한 조건은 그 연산의 의미이므로 축1이 본다(불변 사실 35).
 * - **`isEmpty()` 는 `size() === 0` 과 같다** — 경로가 둘이라 첫 물음은 지나고, 아래 표의
 *   `isEmpty` 행이 그 정합을 이미 적고 있어 **두 번째 물음에서 걸린다.**
 *
 * 「부모가 자식보다 앞선다」는 후보조차 아니다. 이 정본에서만 뜻이 있는 말이고, 계약에
 * 적으면 마디를 이어 담는 구현이 위반이 된다. 그 성질이 깨지면 답이 틀리므로 축1이 잡는다.
 *
 * **연산 계약.** n 은 담긴 원소 수다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `enqueue(item)` | `item` 을 담는다. 같은 원소를 여러 벌 담을 수 있고 넣은 수만큼 나온다 | O(log n) | amortized |
 * | `dequeue()` | 비교자가 가장 앞세우는 원소를 지우고 돌려준다. 비어 있으면 `null` 이고 상태가 바뀌지 않는다 | O(log n) | amortized |
 * | `peek()` | 같은 원소를 지우지 않고 돌려준다. 비어 있으면 `null` | O(1) | worst |
 * | `size()` | 담긴 원소 수 | O(1) | worst |
 * | `isEmpty()` | `size() === 0` 과 같다 | O(1) | worst |
 *
 * **물려받은 표면에서 이름 둘을 고쳤다.** `push`/`pop` 은 `enqueue`/`dequeue` 와 이름만
 * 다른 같은 연산이므로 정본의 이름으로 맞췄다(§규약1 「성격 전환은 이렇게 적는다」 3번).
 * 표면이 맞으면 껍데기가 필요 없다. 그리고 물려받은 문서가 `push`·`pop` 을 한정자 없이
 * `O(log n)` 으로 적어 두었는데, 한정자는 생략할 수 없다 — 위 표가 `amortized` 로 적은
 * 근거는 정본 헤더에 있다.
 *
 * **상한과 한정자의 근거는 `heap/priorityQueue` 헤더와 같다.** 계약이 같으므로 근거도
 * 같다 — 갱신 둘의 상한은 비교 기반 정렬의 하한이 지목하고, 조회 셋이 `worst` 인 것은
 * 강한 한정자를 적는 대가가 없기 때문이다(§규약1, 불변 사실 59). **이쪽 정본은 그
 * `amortized` 를 쓰지 않는다** — 자리를 배로 늘리는 호출 하나를 빼면 모든 호출이 최악
 * 로그 안에 든다. 계약이 약한 쪽을 적었기 때문에 이 정본도, 상각으로만 서는
 * `heap/maxHeap` 정본도 함께 들어온다.
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. **기본 비교자를 두지
 *   않는다** — 두면 방향이 계약의 일부가 되고 위에 적은 첫 번째 갈림 시도가 성립해 버린다.
 *   비교자를 주지 않으면 `TypeError` 다.
 * - 같은 원소를 여러 벌 담을 수 있고, 담은 수만큼 나온다.
 * - 빈 큐의 `peek`·`dequeue` 는 `null` 이다. `T` 에 `null` 이 섞이면 「비어 있음」과 「값이
 *   `null` 인 원소」가 구분되지 않는다.
 * - 비교자가 호출마다 다른 답을 내면 계약이 성립하지 않는다. 지키는 것은 주입자의 의무다.
 *
 * **검증 등급.** `complexity`.
 * 다섯 행을 함께 만족하는 자명한 구현이 없다. 순서 없이 쌓아 두면 빼기와 보기가 원소 수에
 * 비례하고, 늘 정렬해 두면 넣기가 그렇다. 최우선 자리를 캐시해도 빼기는 그대로다 — 지운
 * 뒤 다음 최우선을 다시 찾아야 한다. 다섯을 함께 두려면 **원소를 부분적으로만 정렬해 두고
 * 그 부분 순서를 갱신마다 고쳐 쓰는** 설계가 들어와야 한다.
 *
 * **필요충분조건.**
 * - 의미: 꺼낼 수 있는 것이 비교자 기준 맨 앞 하나라는 것과 그 하나를 지우지 않고 볼 수
 *   있다는 것 중 하나라도 버리면 이 구조가 아니다. 찾기·지우기를 더하면 정렬 집합이고,
 *   합치기를 더하면 `heap/leftistHeap`, 우선순위 낮추기를 더하면 `heap/fibonacciHeap` 이다.
 * - 비용: 넣기와 빼기 중 하나가 원소 수에 비례하면 배열 하나이고, 셋을 다 지키더라도
 *   보기가 로그면 정렬 집합이다.
 */
