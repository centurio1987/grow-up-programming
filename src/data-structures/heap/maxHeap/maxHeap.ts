/**
 * MaxHeap — 주입된 비교자가 앞세우는 원소 하나만 꺼낼 수 있는 모음.
 *
 * **이 계약은 `heap/priorityQueue` 의 계약과 같다.** 비슷한 것이 아니라 같은 것이다 —
 * 아래 연산 계약 표의 다섯 행이 그 파일의 다섯 행과 글자까지 같고, 스위트도 그 파일의
 * `ContractSpec` 을 그대로 돌린다(`./maxHeap.contract.ts`). 그래서 이 클래스의 `dequeue`
 * 는 **오름차순 비교자를 주면 최솟값을 먼저 내놓고, 그것이 계약 위반이 아니다.**
 *
 * 이 이름을 정본과 가르려고 셋을 시도했고 셋 다 계약의 문장이 되지 못했다.
 *
 * - **「최대」라는 방향.** `heap/minHeap` 과 갈리는 자리가 여기여야 하는데, 이 계약은
 *   비교자를 **주입받고** 「최우선」을 그 비교자로 정의한다. 「최댓값을 먼저」와 「최솟값을
 *   먼저」는 비교자를 뒤집은 같은 문장이므로 두 계약을 만족하는 구현 집합이 같다. 방향을
 *   계약에 담으려면 기본 비교자를 두어야 하고, 두면 원소 타입이 좁아진다 — 그 제한을
 *   요구할 이유가 목적에 없다.
 * - **배열이 아니라 마디를 잇는 것.** 이쪽 정본은 자리를 이어 붙이지 않고 마디마다 자식
 *   참조 둘을 둔다. 계약에 적으려면 「자리」나 「참조」를 계약이 말해야 하는데, 그것이 곧
 *   표현의 처방이다(불변 사실 36). 어느 쪽으로 담든 계약이 보는 것은 호출 하나의 비용뿐이다.
 * - **논증이 상각뿐이라는 것.** 이쪽 정본에는 단일 호출을 로그로 묶는 논증이 없다 —
 *   합치기가 오른쪽 길을 타고 내려가는데 그 길의 길이를 묶어 주는 것이 아무것도 없고,
 *   서 있는 것은 「길게 내려간 길을 왼쪽으로 치워 두므로 다음이 짧아진다」는 상각 논증
 *   하나다. 나머지 셋은 나무를 빈틈없이 채우므로 높이가 곧 로그이고 단일 호출도 묶인다.
 *   **그런데 이 차이가 계약의 문장이 되지 못한다** — 계약이 갱신 둘을 `amortized` 로
 *   적었고, 상각만 요구하면 상각 논증이 있는 구현이 들어오기 때문이다.
 *   **적지 않은 이유는 배제할 이유가 목적에 없다는 것이다**(§규약1 「가장 약한 한정자는
 *   셋을 줄 세우지 않는다」).
 *
 *   **다만 「`worst` 로 적었다면 이 정본이 나갔을 것이다」라고는 적지 않는다** — 그것을
 *   보이려면 단일 호출이 원소 수에 비례하는 입력이 있어야 하는데 **일곱 형태를 시도하고
 *   못 찾았다**(내림차순 넣기 1·1·1 · 오름차순 넣기 10·12·14 · 내림차순 채우고 오름차순
 *   더 넣기 11·13·15 · 무작위 채우고 전부 빼기 17·22·28 · 오름차순 채우고 전부 빼기
 *   18·22·26 · 넣기 둘에 빼기 하나 17·25·24 · 내림차순 채우고 번갈아 18·22·26). 계약
 *   스위트의 갱신 네 시나리오를 `worst` 통계로 다시 읽어도 이 정본이 전부 통과한다.
 *   **적을 수 있는 것은 「반례가 없다」가 아니라 「못 찾았다」다**(불변 사실 87 과 같은
 *   자리). 그러므로 `worst` 계약에서 이 정본이 어떻게 되는지는 **미결**이고, 갈리는 것은
 *   구현이 아니라 **요구되는 논증**이다.
 *
 * **그래서 이 구조는 계약이 아니라 이름과 기법으로 갈린다.** 지우지 않는 이유는 판정이
 * *"계약이 담지 못한다"* 이지 *"쓸모가 없다"* 가 아니기 때문이다(불변 사실 61).
 * 정본 이름이 임시가 아닌 것은 넷 중 우선순위 큐만이 ADT 이름이기 때문이다(불변 사실 66).
 *
 * **목적.** 원소를 담는 일·비교자가 가장 앞세우는 원소를 꺼내는 일을 원소 수의 **상각**
 * 로그 비용으로, 그 원소를 꺼내지 않고 보는 일과 담긴 수를 읽는 일을 **최악** 상수 비용으로
 * 함께 제공하는 것. 꺼낼 수 있는 것이 맨 앞 하나뿐이라는 것이 계약의 내용이다.
 *
 * 합치기·우선순위 낮추기는 이 계약에 없다(`heap/leftistHeap`·`heap/fibonacciHeap`).
 * **합치기가 없다는 것이 이쪽 정본에서 특히 눈에 띈다** — 이 정본은 합치기 하나로 넣기와
 * 빼기를 다 하면서도 그것을 표면에 내놓지 않는다. 내놓으면 배열에 담는 나머지 셋이 전부
 * 나가므로 다른 계약이 된다. 비었는지 묻는 일도 이 계약에 없다.
 *
 * **뺀 행의 판정은 목적 항목 밖에 적는다.** `isEmpty()` 는 원칙 A 판정표 ③ 의 판정으로 뺐다 —
 * 판정 줄과 목적 인용은 `docs/ORD-006-conventions.md` 「판정표 ③ 의 103 행을 묶어 판정했다」
 * 절에, 행 단위 대장은 `tools/_baseline/principle-a-verdicts.tsv` 에 있다. 판정의 결론을 목적
 * 문단 안에 적으면 다음 판정이 자기 메아리를 근거로 읽는다(§원칙 A A5′-2).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로, 원소 수보다 훨씬 많은
 * 자리를 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **불변식.** 없다.
 *
 * **판별 절차를 한 행을 뺀 표면에 다시 돌린 결과다**(§규약1 「불변식 판별 절차」). 결과는
 * 그대로 「없다」이고 후보가 둘에서 하나로 줄었다.
 *
 * - **`peek()` 은 다음 `dequeue()` 가 돌려줄 원소와 같다** — 최우선 원소를 **상태를 바꾸지
 *   않고** 읽는 공개 연산이 `peek` 하나뿐이라 **첫 번째 물음에서 걸린다.**
 * - **사라진 후보는 「`isEmpty()` 는 `size() === 0` 과 같다」였다.** 경로가 둘이라 첫 물음을
 *   지나고 둘째 물음에서 걸리던 자리인데, 그 행이 표면에서 빠져 후보 자체가 서지 않는다.
 *
 * 「오른쪽 길이 짧다」는 후보조차 아니다. 이 정본에서만 뜻이 있는 말이고, 애초에 이 정본은
 * 그것을 **상태의 성질로 유지하지도 않는다** — 어느 한 시점에는 길어질 수 있고 갚기가
 * 뒤따를 뿐이다. 상각 계약이 상태의 불변식으로 옮겨지지 않는다는 것이 이 자리다.
 *
 * **연산 계약.** n 은 담긴 원소 수다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `enqueue(item)` | `item` 을 담는다. 같은 원소를 여러 벌 담을 수 있고 넣은 수만큼 나온다 | O(log n) | amortized |
 * | `dequeue()` | 비교자가 가장 앞세우는 원소를 지우고 돌려준다. 비어 있으면 `null` 이고 상태가 바뀌지 않는다 | O(log n) | amortized |
 * | `peek()` | 같은 원소를 지우지 않고 돌려준다. 비어 있으면 `null` | O(1) | worst |
 * | `size()` | 담긴 원소 수 | O(1) | worst |
 *
 * **물려받은 표면에서 이름 둘을 고쳤다.** `push`/`pop` 을 `enqueue`/`dequeue` 로 맞췄다
 * (§규약1 「성격 전환은 이렇게 적는다」 3번). 그리고 물려받은 문서가 *"MinHeap과 구조는
 * 동일하지만 비교 방향이 반전된다"* 고 적어 두었는데, **이 계약에는 「반전」이 없다** —
 * 방향은 주입된 비교자의 성질이지 구조의 성질이 아니다.
 *
 * **상한과 한정자의 근거는 `heap/priorityQueue` 헤더와 같다.** 갱신 둘의 상한은 비교 기반
 * 정렬의 하한이 지목하고, 조회 둘이 `worst` 인 것은 강한 한정자를 적는 대가가 없기
 * 때문이다. **`amortized` 가 실제로 무엇을 사는지는 저쪽 헤더가 수치로 적었다** — 자식들을
 * 미뤄 두었다 한꺼번에 짝지어 접는 계열의 첫 빼기가 1,023 → 4,095 → 16,383 이다.
 * 이쪽 정본은 그 계열이 아니고, 위 세 번째 갈림 시도가 그 구분을 적은 자리다.
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. **기본 비교자를 두지
 *   않는다.** 비교자를 주지 않으면 `TypeError` 다.
 * - 같은 원소를 여러 벌 담을 수 있고, 담은 수만큼 나온다.
 * - 빈 큐의 `peek`·`dequeue` 는 `null` 이다. `T` 에 `null` 이 섞이면 「비어 있음」과 「값이
 *   `null` 인 원소」가 구분되지 않는다.
 * - 비교자가 호출마다 다른 답을 내면 계약이 성립하지 않는다. 지키는 것은 주입자의 의무다.
 *
 * **검증 등급.** `complexity`.
 * 네 행을 함께 만족하는 자명한 구현이 없다. 순서 없이 쌓아 두면 빼기와 보기가 원소 수에
 * 비례하고, 늘 정렬해 두면 넣기가 그렇다. 최우선 자리를 캐시해도 빼기는 그대로다.
 * 넷을 함께 두려면 **원소를 부분적으로만 정렬해 두고 그 부분 순서를 갱신마다 고쳐 쓰는**
 * 설계가 들어와야 한다.
 *
 * **필요충분조건.**
 * - 의미: 꺼낼 수 있는 것이 비교자 기준 맨 앞 하나라는 것과 그 하나를 지우지 않고 볼 수
 *   있다는 것 중 하나라도 버리면 이 구조가 아니다. 찾기·지우기를 더하면 정렬 집합이고,
 *   합치기를 더하면 `heap/leftistHeap`, 우선순위 낮추기를 더하면 `heap/fibonacciHeap` 이다.
 * - 비용: 넣기와 빼기 중 하나가 원소 수에 비례하면 배열 하나이고, 셋을 다 지키더라도
 *   보기가 로그면 정렬 집합이다.
 */
