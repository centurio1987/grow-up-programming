/**
 * DaryHeap — 주입된 비교자가 앞세우는 원소 하나만 꺼낼 수 있는 모음.
 *
 * **이 계약은 `heap/priorityQueue` 의 계약과 같다.** 비슷한 것이 아니라 같은 것이다 —
 * 아래 연산 계약 표의 다섯 행이 그 파일의 다섯 행과 글자까지 같고, 스위트도 그 파일의
 * `ContractSpec` 을 그대로 돌린다(`./daryHeap.contract.ts`).
 *
 * 이 이름을 정본과 가르려고 셋을 시도했고 셋 다 계약의 문장이 되지 못했다.
 *
 * - **갈래 수를 생성자로 받는 것.** 물려받은 표면은 `constructor(d, compare)` 였다. 갈래
 *   수는 **담는 모양의 성질**이라, 표면에 두면 「이 구조는 자리마다 자식이 여럿인 나무다」가
 *   계약의 문장이 된다 — 그 순간 마디를 이어 담는 구현도, 합치기 하나로 짓는 구현도 계약
 *   위반이 된다(불변 사실 36·47). 그래서 뺐다. 갈래 수는 정본 안의 상수 하나로 내려왔다.
 * - **넣기가 싸지고 빼기가 비싸지는 교환.** 갈래를 늘리면 나무가 얕아져 올라가는 층이
 *   줄고, 대신 내려갈 때 견줄 자식이 늘어난다. **그 교환은 실재하고 실측된다** — 갈래
 *   2·3·4·8·16 에서 내림차순 넣기가 9.0 → 6.5 → 5.6 → 4.3 → 3.7 로 싸지는 동안 크기를
 *   유지한 빼기가 19.1 → 17.8 → 20.3 → 29.9 → 46.2 로 비싸진다. **그런데 다섯 벌이 전부
 *   같은 스위트를 통과한다**($r$ 이 1.05~1.28 로 허용 구간 안). $d$ 가 상수이므로
 *   $O(\log_d n)$ 과 $O(d\log_d n)$ 이 둘 다 $O(\log n)$ 이고, 축3은 상수 배수를 판정에
 *   넣지 않는다(불변 사실 6·80). 실측 표는 `daryHeap-guide.mdx` 3단계에 있다.
 * - **캐시 지역성.** 갈래를 늘리면 한 층의 자식들이 메모리에서 이웃하므로 실제 기계에서
 *   유리하다는 주장이 있고, 물려받은 문서도 그렇게 적어 두었다. 이것은 **자리를 이어
 *   붙여 담는 구현을 지목해야만 참인 진술**이라 계약의 문장이 될 수 없다(§규약1 「계약의
 *   문장은 구현 전체에 대해 참이어야 한다」). 마디를 이어 담는 구현에는 「이웃한 자리」가
 *   없다. 게다가 이 저장소의 축3은 벽시계를 쓰지 않으므로 그 이득을 재지도 않는다
 *   (불변 사실 7). 자리는 가이드다.
 *
 * **그래서 이 구조는 계약이 아니라 갈래 수라는 눈금으로 갈린다.** 지우지 않는 이유는
 * 판정이 *"계약이 담지 못한다"* 이지 *"쓸모가 없다"* 가 아니기 때문이다(불변 사실 61).
 * 정본 이름이 임시가 아닌 것은 넷 중 우선순위 큐만이 ADT 이름이기 때문이다(불변 사실 66).
 *
 * **목적.** 원소를 담는 일·비교자가 가장 앞세우는 원소를 꺼내는 일을 원소 수의 **상각**
 * 로그 비용으로, 그 원소를 꺼내지 않고 보는 일과 담긴 수를 읽는 일을 **최악** 상수 비용으로
 * 함께 제공하는 것. 꺼낼 수 있는 것이 맨 앞 하나뿐이라는 것이 계약의 내용이다.
 *
 * 합치기·우선순위 낮추기는 이 계약에 없고(`heap/leftistHeap`·`heap/fibonacciHeap`),
 * 임의 원소를 찾거나 지우는 일도 없다(`tree/redBlackTree`). 비었는지 묻는 일도 없다.
 *
 * **뺀 행의 판정은 목적 항목 밖에 적는다.** `isEmpty()` 는 원칙 A 판정표 ③ 의 판정으로 뺐다 —
 * 판정 줄과 목적 인용은 `docs/ORD-006-conventions.md` 「판정표 ③ 의 103 행을 묶어 판정했다」
 * 절에, 행 단위 대장은 `tools/_baseline/principle-a-verdicts.tsv` 에 있다. 판정의 결론을 목적
 * 문단 안에 적으면 다음 판정이 자기 메아리를 근거로 읽는다(§원칙 A A5′-2).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로, 원소 수보다 훨씬 많은
 * 자리를 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **불변식.** 없다.
 *
 * **판별 절차를 한 행을 뺀 표면에 다시 돌린 결과다**(§규약1 「불변식 판별 절차」). 결과는
 * 그대로 「없다」이고 후보가 둘에서 하나로 줄었다.
 *
 * - **`peek()` 은 다음 `dequeue()` 가 돌려줄 원소와 같다** — 최우선 원소를 **상태를 바꾸지
 *   않고** 읽는 공개 연산이 `peek` 하나뿐이라 **첫 번째 물음에서 걸린다.**
 * - **사라진 후보는 「`isEmpty()` 는 `size() === 0` 과 같다」였다.** 경로가 둘이라 첫 물음을
 *   지나고 둘째 물음에서 걸리던 자리인데, 그 행이 표면에서 빠져 후보 자체가 서지 않는다.
 *
 * 「자리 하나가 자식을 최대 $d$ 개 거느린다」는 후보조차 아니다. 계약에 $d$ 라는 이름이
 * 없으므로 검사할 대상이 정의되지 않는다.
 *
 * **연산 계약.** n 은 담긴 원소 수다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `enqueue(item)` | `item` 을 담는다. 같은 원소를 여러 벌 담을 수 있고 넣은 수만큼 나온다 | O(log n) | amortized |
 * | `dequeue()` | 비교자가 가장 앞세우는 원소를 지우고 돌려준다. 비어 있으면 `null` 이고 상태가 바뀌지 않는다 | O(log n) | amortized |
 * | `peek()` | 같은 원소를 지우지 않고 돌려준다. 비어 있으면 `null` | O(1) | worst |
 * | `size()` | 담긴 원소 수 | O(1) | worst |
 *
 * **물려받은 표면에서 셋을 고쳤다.** 생성자의 갈래 수를 뺐고(위 첫 번째 갈림 시도),
 * `push`/`pop` 을 `enqueue`/`dequeue` 로 맞췄으며(§규약1 「성격 전환은 이렇게 적는다」
 * 3번), 물려받은 상한 $O(\log_d n)$ · $O(d\log_d n)$ 을 $O(\log n)$ 으로 적었다.
 * **$d$ 를 계약에서 뺀 이상 그것을 쓴 상한도 계약에 남을 수 없다** — 표면에 없는 이름으로
 * 적은 상한은 읽을 수 없는 조건이다.
 *
 * **상한과 한정자의 근거는 `heap/priorityQueue` 헤더와 같다.** 갱신 둘의 상한은 비교 기반
 * 정렬의 하한이 지목하고, 조회 둘이 `worst` 인 것은 강한 한정자를 적는 대가가 없기
 * 때문이다.
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. **기본 비교자를 두지
 *   않는다.** 비교자를 주지 않으면 `TypeError` 다.
 * - **갈래 수는 주입점이 아니다.** 주입받는 것은 비교자 하나뿐이고, 담는 모양을 호출자가
 *   고를 자리를 열면 그것이 곧 표현의 처방이 된다.
 * - 같은 원소를 여러 벌 담을 수 있고, 담은 수만큼 나온다.
 * - 빈 큐의 `peek`·`dequeue` 는 `null` 이다. `T` 에 `null` 이 섞이면 「비어 있음」과 「값이
 *   `null` 인 원소」가 구분되지 않는다.
 * - 비교자가 호출마다 다른 답을 내면 계약이 성립하지 않는다. 지키는 것은 주입자의 의무다.
 *
 * **검증 등급.** `complexity`.
 * 네 행을 함께 만족하는 자명한 구현이 없다. 순서 없이 쌓아 두면 빼기와 보기가 원소 수에
 * 비례하고, 늘 정렬해 두면 넣기가 그렇다. 최우선 자리를 캐시해도 빼기는 그대로다.
 * 넷을 함께 두려면 **원소를 부분적으로만 정렬해 두고 그 부분 순서를 갱신마다 고쳐 쓰는**
 * 설계가 들어와야 한다.
 *
 * **필요충분조건.**
 * - 의미: 꺼낼 수 있는 것이 비교자 기준 맨 앞 하나라는 것과 그 하나를 지우지 않고 볼 수
 *   있다는 것 중 하나라도 버리면 이 구조가 아니다. 찾기·지우기를 더하면 정렬 집합이고,
 *   합치기를 더하면 `heap/leftistHeap`, 우선순위 낮추기를 더하면 `heap/fibonacciHeap` 이다.
 * - 비용: 넣기와 빼기 중 하나가 원소 수에 비례하면 배열 하나이고, 셋을 다 지키더라도
 *   보기가 로그면 정렬 집합이다.
 */
