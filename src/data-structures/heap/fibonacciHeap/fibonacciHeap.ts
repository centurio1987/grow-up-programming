/**
 * FibonacciHeap — 담긴 원소를 핸들로 가리켜 우선순위를 앞당길 수 있고, 그 일과 넣기·합치기를 상수에 두는 대신 빼기를 여러 호출에 걸쳐 원소 수의 로그로 갚는 우선순위 큐.
 *
 * **목적.** 넣기·합치기를 상수에 두는 우선순위 큐(`heap/pairingHeap`)의 일곱 행을 **의미·상한·
 * 한정자까지 그대로** 두고 한 행을 더한다 — **이미 담긴 원소 하나를 가리켜 그 우선순위를
 * 앞당기는 일(키 낮추기)을 여러 호출에 걸쳐 상수에** 두는 것. 넣기·합치기를 m 회, 키 낮추기를
 * j 회, 빼기를 k 회 하면 이 계약은 $O(m + j + k\log n)$ 을 약속한다. 앞당기는 일을 로그로 하는
 * 구현에서는 가운데 몫이 $j\log n$ 으로 불어난다. **빼기가 적고 앞당기기가 많은 호출열이 이
 * 계약의 자리다.**
 *
 * **원소를 가리키는 이름 — 핸들.** 키 낮추기는 「어느 원소를」을 받아야 하는데 값으로는 가리킬
 * 수 없다 — 같은 값을 여러 벌 담을 수 있어 값이 한 벌을 가리키지 못한다. 그래서 **`enqueue` 가
 * 담은 원소의 핸들을 돌려준다.** 계약이 핸들에 대해 정하는 것은 **그 값이 어느 원소를 가리키는가**
 * 하나다 — 핸들의 내용·모양·두 핸들을 견주는 법은 정하지 않는다.
 * - 핸들은 **그 넣기가 담은 원소 한 벌**을 가리킨다. 같은 값을 두 번 넣으면 핸들이 둘이다.
 * - **핸들은 원소를 따라간다.** 키 낮추기 뒤에도, 합치기로 다른 큐에 옮겨 간 뒤에도 같은 원소다.
 * - 원소가 빼기로 나가면 그 핸들은 **빠진 원소**를 가리키고 다시 담긴 원소를 가리키지 않는다.
 *   키 낮추기가 그 핸들을 거절한다(`false`).
 * - **번호로 적지 않는다.** 큐마다 넣은 순서 번호를 핸들로 삼으면 합친 두 큐의 번호가 겹치고,
 *   번호를 원소로 바꾸는 일을 모든 구현이 따로 지게 된다.
 *
 * **대가는 호출 하나다.** 빼기 한 호출도, 키 낮추기 한 호출도 담긴 수에 비례해도 이 계약 안이다
 * (아래 「한정자」가 둘 다 실측을 적는다).
 *
 * **이웃 계약과의 관계 — 하나는 담고 하나와는 서로 담지 않는다.**
 * - **`heap/pairingHeap`(넣기·합치기를 상수에 두는 우선순위 큐)을 담는다.** 이 계약의 여덟 행
 *   중 일곱이 그쪽 일곱 행과 같으므로, 이 계약을 지키는 구현은 키 낮추기를 부르지 않는 호출열에서
 *   그쪽을 전부 지킨다. 역은 성립하지 않는다 — 그쪽 정본은 키 낮추기가 없고, 키 낮추기를 붙여도
 *   **원소를 부모와 자리를 바꿔 올리는 구현**(`_contract/_fixtures/siftingLinkingHeap.ts`)은 그쪽
 *   다섯 시나리오를 전부 통과하면서 이쪽의 키 낮추기 행 하나에서만 나간다. 담는 쪽이 더 좁다.
 * - **`heap/leftistHeap`(합칠 수 있는 우선순위 큐)과는 서로 담지 않는다**(불변 사실 54). 그쪽
 *   정본은 키 낮추기가 없고 합치기가 로그다. 이 계약의 정본은 빼기 한 호출이 담긴 수에 비례하는
 *   상태가 있어 그쪽 `worst` 빼기를 못 지킨다 — 그쪽 빼기 두 시나리오에서 걸린다(하네스 자기시험).
 *   **연산 집합으로는 그쪽을 담지만 비용 열로는 담지 못한다.** 힙 여덟의 판정(B18)이 적은
 *   「A ⊂ B ⊂ D」의 뒤쪽 포함은 연산 집합에서만 선다(`docs/ORD-006-conventions.md` 「B군 계약
 *   전환 — 재개 뒤」의 T2-04 절).
 *
 * **이 계약에 없는 것 넷.**
 * - **핸들로 원소를 읽는 일.** 핸들이 가리키는 원소의 지금 값을 돌려주는 연산이 없다. 가리키는
 *   원소가 무엇인지는 키 낮추기의 답과 이후의 보기·빼기로만 드러난다.
 * - **우선순위를 뒤로 미루는 일과 임의 원소를 지우는 일.** 키 낮추기는 앞당기기만 받는다. 뒤로
 *   미루기를 받으면 그 일의 상한을 따로 세워야 하고, 이 계약의 목적은 그 일을 말하지 않는다.
 * - **빼기 한 호출·키 낮추기 한 호출의 상한.** 위 「대가」 문단이 그 자리다.
 * - **같은 우선순위 원소들 사이의 순서.** 비교자가 0 을 돌려주는 원소 중 어느 것이 먼저 나오는지
 *   약속하지 않는다. **그래서 그중 어느 원소의 핸들이 먼저 거절되기 시작하는지도 약속하지 않는다.**
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로, 원소 수보다 훨씬 많은 자리를
 * 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **정본 이름은 임시다**(불변 사실 64·198). `fibonacciHeap` 은 차수가 k 인 마디 아래 마디 수의
 * 하한에 피보나치 수가 나오는 **기법의 이름**이다. 이 계약이 말하는 것은 「원소를 가리켜 앞당길 수 있는 우선순위 큐」
 * 이고 그 이름의 디렉터리가 없다. KAN-031(계약 이름 재편)로 넘긴다.
 *
 * **불변식.** 없다.
 *
 * 후보 넷이 각각 다른 물음에서 걸린다(§규약1 「불변식 판별 절차」). 앞의 셋은
 * `heap/pairingHeap` 과 입력이 같아 결과도 같다.
 *
 * - **`peek()` 은 다음 `dequeue()` 가 돌려줄 원소와 같다** — 상태를 바꾸지 않고 최우선 원소를
 *   읽는 공개 연산이 `peek` 하나뿐이라 **첫 번째 물음에서 걸린다**(불변 사실 124).
 * - **`isEmpty()` 는 `size() === 0` 과 같다** — 아래 표의 `isEmpty` 행이 그 정합을 적고 있어
 *   **두 번째 물음에서 걸린다.**
 * - **합친 뒤 이 큐의 크기는 두 크기의 합이고 넘겨받은 큐는 빈다** — `merge` 행이 적고 있어 두
 *   번째 물음에서 걸린다.
 * - **`size()` 는 거절되지 않는 핸들의 수와 같다** — 핸들이 거절되는지를 읽는 연산은 `decreaseKey`
 *   하나이고, 그 연산은 받아들이는 순간 원소를 바꾼다. 상태를 바꾸는 관측은 관측 경로로 세지
 *   않으므로(불변 사실 124) 거절되지 않는 핸들의 수를 읽는 경로가 없고, **첫 번째 물음에서
 *   걸린다.** 한 핸들이 거절되는지는 `decreaseKey` 행의 의미이고 축1이 본다.
 *
 * 담는 모양의 성질(부모가 자식보다 앞선다, 뿌리의 차수가 서로 다르다, 자식을 잃은 표시)은 후보조차
 * 아니다 — 적는 순간 표현을 처방하고(불변 사실 36), 이 계약을 지키는 다른 구현에는 그런 말이
 * 없다(불변 사실 131). **상각 보장도 상태의 성질로 옮겨지지 않는다**(불변 사실 123).
 *
 * **연산 계약.** n 은 담긴 원소 수다. **`merge` 행에서만 「합친 뒤의 원소 수」로 읽는다**
 * (`heap/pairingHeap` 과 같게 정해 두어야 두 계약의 정본을 서로의 스위트에 넣어 볼 수 있다).
 * **`amortized` 는 한 큐가 받는 호출열 전체에 대한 약속이다** — 빈 큐에서 시작한 어떤 호출열에서도
 * 호출 전부의 총비용이 행마다의 상한을 그 행의 호출 수만큼 더한 것의 상수배 안이고, `worst` 행은
 * 그에 더해 호출마다 제 상한 안이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `enqueue(item)` | `item` 을 담고 그 원소의 핸들을 돌려준다. 같은 원소를 여러 벌 담을 수 있고 벌마다 핸들이 다르며 넣은 수만큼 나온다 | O(1) | worst |
 * | `dequeue()` | 비교자가 가장 앞세우는 원소를 지우고 돌려준다. 그 원소의 핸들은 이후 거절된다. 비어 있으면 `null` 이고 상태가 바뀌지 않는다 | O(log n) | amortized |
 * | `decreaseKey(handle, item)` | `handle` 이 가리키는 원소가 담겨 있고 `item` 이 그 원소보다 뒤서지 않으면(비교자가 0 이하) 원소를 `item` 으로 바꾸고 `true`. 원소가 이미 빠졌거나 `item` 이 뒤서면 `false` 이고 상태가 바뀌지 않는다 | O(1) | amortized |
 * | `merge(other)` | `other` 에 담긴 원소를 전부 이 큐로 옮기고 `other` 를 비운다. `other` 에서 받은 핸들은 옮겨 온 원소를 가리킨다. `other` 가 이 큐 자신이면 `TypeError` | O(1) | worst |
 * | `peek()` | 최우선 원소를 지우지 않고 돌려준다. 비어 있으면 `null` | O(1) | worst |
 * | `size()` | 담긴 원소 수 | O(1) | worst |
 * | `isEmpty()` | `size() === 0` 과 같다 | O(1) | worst |
 *
 * **물려받은 표면을 다섯 고쳤다.** 연산 집합은 그대로 일곱이다.
 *
 * - `insert`/`extractMin` 을 `enqueue`/`dequeue` 로 맞췄다. 이유는 `heap/pairingHeap` 이 같은
 *   자리를 고친 것과 같다 — 방향을 이름에 박지 않고, 이웃 계약과 표면을 맞춰 정본을 서로의
 *   스위트에 넣어 관계를 잰다.
 * - `merge` 의 반환을 없앴다. 물려받은 표면은 합친 새 큐를 돌려줘 두 원본 큐와 그 핸들의 상태를
 *   말하지 않았다.
 * - **스텁이 내보내던 마디 클래스(`FibNode` — 차수·표시·부모·자식·좌우 형제)와 private 필드
 *   셋을 뺐다.** 그 클래스가 곧 핸들이었으므로 **핸들이 담는 모양을 통째로 드러내고 있었다**
 *   (불변 사실 20). 핸들은 내용을 정하지 않는 타입(`FibonacciHeapHandle`)으로 바꿨다.
 * - `decreaseKey(node, newItem): void` 를 `decreaseKey(handle, item): boolean` 으로 전면화했다.
 *   물려받은 표면은 빠진 원소의 마디나 뒤서는 값을 넘기는 호출에 대해 아무 말도 하지 않았다 —
 *   전제조건으로 두면 축1이 그 자리를 못 잰다(불변 사실 82). `boolean` 에는 「바꾸지 않았다」를
 *   담을 자리가 있어 예외를 쓰지 않는다(불변 사실 132).
 * - 물려받은 문서가 적은 「다익스트라 알고리즘의 복잡도를 개선한다」를 뺐다. 이 계약을 쓰는 자리에
 *   대한 진술이라 계약의 문장이 아니다 — 목적 첫 문단의 호출열 총비용이 그 진술의 계약 쪽 형태다.
 *
 * **이름 `decreaseKey` 는 남겼다.** 「낮춘다」는 비교자가 정하는 방향으로 **앞당긴다**는 뜻이고
 * 「키」는 따로 있는 값이 아니라 원소의 우선순위다. `extractMin` 을 고친 이유(이웃과 표면 맞추기)가
 * 이 행에는 없다 — 이웃 계약에 같은 행이 없고, 이 이름이 이 연산을 부르는 통상의 이름이다.
 *
 * **물려받은 상한은 이 표와 같지만 한정자가 달랐고, 둘 다 입력으로 쓰지 않았다**(불변 사실 65).
 * 물려받은 문서는 일곱 행 전부를 「상각」으로 적었다.
 *
 * - **`dequeue` 의 `O(log n)` 은 하한이 지목한다.** `heap/pairingHeap` 과 같은 논증이다 — 비교로만
 *   순서를 아는 구현에서 n 개를 넣고 n 번 빼면 정렬이고 그 하한이 $\Omega(n\log n)$ 인데, 넣기가
 *   상수라 남는 몫을 빼기가 치른다. 둘째 걸음(그 값을 내는 구현이 있다)을 정본이 축3에서 짚는다.
 * - **`decreaseKey` 의 `O(1)` 은 목적이 지목한다.** `O(log n)` 으로 적으면 `heap/pairingHeap` 을
 *   지키는 구현에 앞당기기를 로그로 붙인 것이 전부 들어와 이 계약이 「그쪽 + 로그 앞당기기」의
 *   약한 판이 되고, 목적 첫 문단의 $j$ 대 $j\log n$ 이 사라진다. 더 강하게 적을 자리는 없다.
 * - **`enqueue`·`merge` 의 `O(1)` 은 목적이 지목한다.** `heap/pairingHeap` 과 같은 논증이고, 그 두
 *   행이 그쪽과 같아야 위 「담는다」가 선다.
 * - **`peek`·`size`·`isEmpty` 의 `O(1)`.** 목적이 지목하고 강하게 적는 대가가 없다.
 *
 * **한정자.** 셋은 줄 세워지지 않으므로(불변 사실 59) 행마다 정했고, 강한 쪽을 적은 행은 그것이
 * 추가로 배제하는 계열을 쟀다(§규약1 「강한 한정자의 근거는 추가로 배제되는 계열을 수치로 낸다」).
 *
 * - **`decreaseKey` 가 `amortized` 인 이유.** `worst` 로 적으면 이 계약의 정본이 나간다. 정본은
 *   앞당긴 원소를 떼어 뿌리로 올리고 **떼인 부모가 이미 자식을 잃었던 마디면 그 떼기를 위로 이어
 *   가는데**, 공개 연산만으로 그 이어 떼기가 담긴 원소 전부를 지나가는 상태를 지을 수 있다 — 원소가
 *   1,026 · 4,098 · 16,386 개인 큐에서 호출 하나가 1,026 · 4,098 · 16,386 걸음이고, 그 상태를 짓는
 *   호출열 전체의 호출 평균은 4.35 다(하네스 자기시험). 그 계열을 배제할 이유가 목적에 없다 —
 *   목적은 호출열의 총비용을 말한다. **이 입력은 계약 스위트의 시나리오가 아니다** — 정본이 뿌리를
 *   차수로 잇는다는 것을 알아야 지을 수 있다(불변 사실 44). `expected` 는 `amortized` 와 서로를
 *   함의하지 않는 다른 계약이고 무작위를 뽑는 구현을 요구하게 되므로 적지 않는다.
 * - **`dequeue` 가 `amortized` 인 이유.** `heap/pairingHeap` 과 같다. 크기를 n 으로 유지하며 번갈아
 *   부르는 같은 실행에서 이 계약의 정본은 호출 평균 52.57 · 61.29 · 70.54 로 통과하고 단일 호출
 *   최대 4,106 · 16,396 · 65,550 으로 걸린다.
 * - **`enqueue`·`merge` 가 `worst` 인 이유.** `heap/pairingHeap` 과 같고 **재는 시나리오도 같은
 *   객체다.** `amortized` 로 적으면 쌓아 두었다 이따금 한꺼번에 잇는 계열이 들어오는데
 *   (`_contract/_fixtures/bufferedLinkingHeap.ts` — 넣기 단일 호출 1,025 · 4,097 · 16,385, 합치기
 *   520 · 2,056 · 8,200), 그 계열이 이따금 하는 일을 빼기로 미룬 구현이 나머지 행을 그대로 지키므로
 *   배제해도 잃는 것이 없다(불변 사실 194). 그리고 **이 두 행이 약해지면 위 「담는다」가 깨진다.**
 * - **`peek`·`size`·`isEmpty` 가 `worst` 인 이유.** `worst` 가 추가로 배제하는 것은 최우선 자리를
 *   읽을 때 만들어 두는 계열이고, 그 자리를 처음부터 들고 있는 대가가 없다 — 이 계약에는 그 자리를
 *   바꾸는 연산이 하나 더(키 낮추기) 있지만 그 연산이 자리를 고쳐 드는 데 드는 것은 비교 한 번이다.
 *   (앞당긴 뒤 보기가 뿌리를 다시 훑는 계열 `_contract/_fixtures/rescanningTopHeap.ts` 는 이 계약의
 *   조회 시나리오에서 1,027 · 4,099 · 16,387 로 걸리는데 `amortized` 로 다시 재도 같다 — 그
 *   fixture 가 재는 것은 한정자가 아니라 **채우기에 키 낮추기가 들어가야 한다**는 것이다.)
 * - `constructor` 만 축3에서 면제된다. n 에 대해 반복 호출되는 연산이 아니다(§규약2 축3 면제).
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. 음수는 「`a` 가 먼저 나온다」이고
 *   0 은 「순서를 정하지 않는다」다. **기본 비교자를 두지 않는다** — 기본값을 두면 그 방향이 계약의
 *   일부가 된다. 비교자를 주지 않으면 `TypeError` 다.
 * - **`merge(other)` 의 `other` 는 같은 구현으로 만든, 같은 비교자를 든 큐다.** 다른 구현의 큐를
 *   합치는 일을 약속하면 상대의 담는 모양을 읽어야 한다. 주입자의 의무이고 검사하지 않는다.
 * - **`other` 가 이 큐 자신이면 `TypeError` 다.** 「`other` 를 비운다」와 「`other` 의 원소를 담는다」가
 *   같은 객체에서 서로를 부정해 값으로 답할 자리가 없다(불변 사실 132).
 * - **`decreaseKey` 의 `handle` 은 같은 구현이 내준 핸들이고, 그 원소를 지금 담고 있는 큐에
 *   넘긴다** — 합치기로 옮겨 간 원소의 핸들은 받은 큐에. 다른 큐에 넘기면 계약이 성립하지 않는다.
 *   **주입자의 의무이고 이 구조가 검사하지 않는다.** 검사를 약속하면 원소마다 제 큐를 판정할 길을
 *   계약이 요구하고, 합치기가 넘겨받은 원소 전부의 소속을 바꿔야 한다. 그 요구가 상수 합치기와
 *   함께 서는지는 판정하지 않았다 — 의무로 두면 그 물음이 계약에 들어오지 않는다.
 * - **빠진 원소의 핸들과 뒤서는 값은 의무가 아니다** — 받고 `false` 로 답한다(표). 거절은 상태를
 *   바꾸지 않으므로 거절된 호출은 없던 일이다.
 * - 같은 원소를 여러 벌 담을 수 있다. `enqueue` 도 `merge` 도 중복을 버리지 않는다.
 * - 빈 큐의 `peek`·`dequeue` 는 예외가 아니라 `null` 이다. 그 대가로 `T` 에 `null` 이 섞이면
 *   「비어 있음」과 「값이 `null` 인 원소」가 구분되지 않는다.
 * - 비교자가 호출마다 다른 답을 내면 계약이 성립하지 않는다. 그것도 주입자의 의무다.
 *
 * **검증 등급.** `complexity`.
 * 여덟 행을 **함께** 만족하는 자명한 구현이 없다. 원소를 순서 없이 이어 두고 최우선 자리를 따로
 * 들면 넣기·합치기·키 낮추기·보기가 상수로 서지만 빼기가 다음 최우선을 찾으려 남은 원소를 **호출마다**
 * 훑는다. 늘 정렬해 두면 넣기와 키 낮추기가 원소 수에 비례한다. 배열 이진 힙에 원소의 자리를 적은
 * 표를 붙이면 키 낮추기가 로그에 서지만 상수가 아니고, 합치기가 원소 수에 비례한다. 여덟이 함께
 * 서려면 빼기가 밀린 일을 갚으면서 부분 순서를 남기고, **앞당긴 원소를 그 부분 순서에 다시 맞추는
 * 일을 상각 상수로 하되 그 일이 다음 빼기들의 비용을 불리지 않게 하는** 상각 설계가 들어와야 한다.
 *
 * **필요충분조건.**
 * - 의미: `heap/pairingHeap` 의 일곱에 **핸들로 가리킨 원소를 앞당기는 일**을 더한 것. 앞당기기를
 *   버리면 그 계약이다. 핸들이 원소를 따라가지 않으면(앞당긴 뒤나 합친 뒤에 다른 원소를 가리키면)
 *   키 낮추기가 무엇을 바꿨는지 계약이 말하지 못하고, 빠진 원소의 핸들을 거절하지 않으면 그 호출이
 *   무엇을 바꾸는지 계약이 말하지 못한다.
 * - 비용: **넣기·합치기를 호출마다 상수, 빼기를 상각 로그에 둔 채 키 낮추기를 상각 상수에 두는 것.**
 *   키 낮추기가 로그를 써도 되면 `heap/pairingHeap` 에 한 행을 붙인 약한 계약이고, 원소 수에
 *   비례해도 되면 자리를 바꿔 올리는 계열이 들어온다. 나머지 일곱 중 하나라도 약해지면 그 계약을
 *   담지 못한다.
 */

