/**
 * BinarySearchTree — 전순서를 유지하는 집합. **비용에 대해 로그를 약속하지 않는다.**
 *
 * **목적.** 같은 원소를 두 벌 담지 않으면서 전순서를 유지하고, 담기·지우기·찾기·양 끝
 * 읽기·구간 읽기를 **원소 수에 비례하는 비용 안에** 제공하는 것. 나란한 넷은 여기에 로그를
 * 약속하고 이 계약만 약속하지 않는다 — **덜 약속하는 것이 이 계약의 내용 전부다.**
 *
 * **덜 약속하는 계약을 왜 따로 두는가.** 넓은 쪽이 배제하는 구현을 좁은 쪽이 허용하기
 * 때문이다. 로그를 약속하면 **높이를 스스로 묶지 않는 구현이 통째로 나간다** — 넣는 값이
 * 늘 앞선 값보다 크면 한쪽으로만 자라 찾기 하나가 원소 수에 비례하는 그 계열이다. 이
 * 계약은 그 계열을 담고, 담는 것이 목적이다. 같은 이유로 **정렬 배열도 이 계약을
 * 만족한다** — 그것은 결함이 아니라 계약의 내용이다(§규약1 「한정자가 계약을 가른다」 2단계).
 *
 * **상한을 O(n) 으로 고른 근거.** 상한은 규칙에서 따라 나오지 않고 고르는 값이다(불변 사실
 * 48). 양쪽에서 조인다.
 * - **더 강하게(로그로) 적으면** 위의 두 계열이 전부 나간다. 배제할 이유가 목적에 없다 —
 *   그것을 배제하는 계약이 이미 넷 있다.
 * - **더 약하게(초선형으로) 적으면** 「전순서를 유지한다」가 뜻을 잃는다. 넣을 때 아무렇게나
 *   쌓아 두고 물어볼 때마다 정렬해서 답하는 구현이 들어오는데, 그것은 순서를 **유지하는**
 *   것이 아니라 관측 시점에 **만드는** 것이다. 유지 여부는 원소 수에 비례하는 비용
 *   안에서만 관측된다.
 *
 * **나란한 넷과의 관계.** 넷이 전부 이 계약에 **담긴다** — 로그 안에 드는 구현은 선형 안에도
 * 든다. 이 계약은 그중 가장 넓고, **넓다는 것이 곧 약속이 적다는 것이다.**
 * `tree/redBlackTree`(전 `worst`) ⊂ `tree/scapegoatTree`(조회 `worst` + 갱신 `amortized`)
 * ⊂ `tree/splayTree`(전 `amortized`) ⊂ 이 계약. `tree/treap`(전 `expected`)도 이 계약에
 * 담긴다.
 *
 * 같은 값을 여러 벌 담는 일은 이 계약에 없다(`tree/multiset`). 위치로 읽는 일도 없다
 * (`tree/orderStatisticTree`). 담긴 원소 수를 읽는 일도 없다.
 *
 * **뺀 행의 판정은 목적 항목 밖에 적는다.** `size()` 는 원칙 A 판정표 ③ 의 판정으로 뺐다 —
 * 판정 줄과 목적 인용은 `docs/ORD-006-conventions.md` 「판정표 ③ 의 103 행을 묶어 판정했다」
 * 절에, 행 단위 대장은 `tools/_baseline/principle-a-verdicts.tsv` 에 있다. 판정의 결론을 목적
 * 문단 안에 적으면 다음 판정이 자기 메아리를 근거로 읽는다(§원칙 A A5′-2).
 *
 * **이 이름은 계약을 정당화하지 않는다.** 계약의 어느 문장도 노드·자식·높이를 말하지
 * 않는다 — 명세는 내부 표현을 처방하지 않는다. 물려받은 표면이 `number` 만 담고
 * `search`·`inorder` 라는 이름을 쓰고 있었는데, 나란한 넷과 **같은 연산 집합**으로 다시
 * 냈다(§규약1 「연산 집합은 계약의 결과가 아니라 계약의 일부다」). 다섯 계약이 상한 주장
 * 하나로만 갈린다는 것이 B17 판정의 내용이므로, 표면이 저 넷과 다르면 그 판정이 서지
 * 않는다. **이름은 임시다**(불변 사실 64 — 계약 이름 전환은 KAN-031).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도
 * 없다」 — 미결).
 *
 * **불변식.** 셋이다. 셋 다 **관측 경로가 둘**이라 성립한다 — 구현이 두 경로를 따로
 * 유지할 수 있고, 따로 유지하는 순간 갈린다. 어떤 연산 뒤에도 성립해야 한다.
 * 1. 임의의 `x` 에 대해 `has(x)` 는 `toArray()` 안에 `x` 와 동등한(비교자가 0) 원소가
 *    있는가와 같다. 담김 여부를 읽는 길이 둘이다.
 * 2. 비어 있지 않으면 `min()` 은 `toArray()` 의 첫 원소와, `max()` 는 마지막 원소와
 *    같다. 양 끝을 읽는 길이 둘이다.
 * 3. 임의의 `low ≤ high` 에 대해 `range(low, high)` 는 `toArray()` 에서 그 구간에 드는
 *    원소만 남긴 것과 같다. 구간을 읽는 길이 둘이다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 **한 행을 뺀 표면에 다시 돌린 결과다.** 넷
 * 가운데 「`toArray().length === size()`」가 사라졌다 — 원소 수를 읽는 두 경로 가운데
 * 세어 둔 쪽이 표면에서 사라져 경로가 `toArray()` 하나로 줄었고 첫 번째 물음에서 걸린다.
 *
 * **셋이 나란한 넷의 셋과 같다.** 베낀 것이 아니라 판별 절차가 같은 답을 내기 때문이고
 * (§규약1 「불변식 판별 절차」), 그 절차가 **상한을 읽지 않기** 때문이다. 불변식은 상태의
 * 성질이고 상한은 비용의 성질이라 서로를 건드리지 않는다 — 한정자가 연산마다 갈려도 절이
 * 안 움직였고(불변 사실 108), **상한을 통째로 내려도 안 움직인다.**
 *
 * 트리의 치우침은 불변식이 아니다 — 계약에 적혀 있어야 검사할 수 있는데 적는 순간 그것이
 * 처방이다. 그리고 이 계약에서는 **치우침이 결함도 아니다.**
 *
 * **연산 계약.** n 은 담긴 원소 수, k 는 `range` 가 돌려주는 원소 수다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator?)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `insert(item)` | `item` 을 담는다. 동등한 원소가 이미 있으면 **상태가 바뀌지 않는다** | O(n) | worst |
 * | `delete(item)` | 동등한 원소를 지우고 `true`. 없으면 `false`, 상태는 불변 | O(n) | worst |
 * | `has(item)` | 동등한 원소가 담겨 있으면 `true` | O(n) | worst |
 * | `min()` / `max()` | 비교자 기준 최소·최대. 비어 있으면 `null` | O(n) | worst |
 * | `range(low, high)` | `low ≤ v ≤ high` 인 원소를 비내림차순 배열로. 사본이다 | O(n) | worst |
 * | `toArray()` | 비내림차순 배열의 사본. 반환값을 고쳐도 원본은 바뀌지 않는다 | O(n) | worst |
 *
 * **일곱 행이 전부 `worst` 인 것은 약한 쪽을 고른 결과다.** 규칙은 「배제하려는 것을 배제하는
 * 것 중 가장 약한 것을 적되, 강한 것을 적으려면 그것이 배제하는 계열을 배제해도 계약이
 * 잃는 것이 없어야 한다」이고(§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」),
 * **상한이 이미 선형이라 뒷문장이 자동으로 성립한다.** `amortized O(n)` 이나 `expected O(n)`
 * 을 적어서 들어올 구현은 「가끔·평균적으로만 선형이고 어떤 호출은 초선형인」 것인데, 그
 * 계열을 담으면 위에서 적은 「너무 약하면」 쪽으로 넘어간다. 배제하는 대가가 없다.
 *
 * `range` 의 상한에서 `k` 가 사라진 것도 같은 이유다. 나란한 넷은 O(log n + k) 인데
 * 여기서는 `k ≤ n` 이므로 O(n) 이 그것을 덮는다.
 *
 * **`min`·`max`·`range` 를 넣은 근거는 「배제하는 것이 없다」다.** 나머지 계약을 만족하는
 * 구현은 전부 이 셋을 위 상한 안에 한다. 넣어도 만족하는 구현 집합이 그대로이므로 넣고
 * 빼는 것이 계약을 바꾸지 않는다. 넣은 쪽을 고른 이유는 전순서를 유지한다는 목적이 이
 * 셋으로만 관측되기 때문이고, 나란한 넷과 표면을 맞추기 위해서다.
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. 0 은 「동등」을 뜻하고,
 *   **동등한 두 원소는 이 집합에 함께 담기지 않는다.** 나중에 넣은 쪽이 버려지는지 앞의
 *   것을 덮는지는 계약이 약속하지 않는다 — 동등하므로 구분할 방법이 계약 안에 없다.
 * - 미제공 시 기본 비교자는 `<`·`>` 를 쓴다. 따라서 `number`·`string` 밖의 `T` 에는
 *   비교자 주입이 **필수다.** 물려받은 표면은 `number` 만 담았는데, 그것은 계약이 아니라
 *   문제 문서가 정한 범위였다.
 * - 빈 집합의 `min`·`max` 는 예외가 아니라 `null` 이다. 그 대가로 `T` 에 `null` 이 섞이면
 *   「비어 있음」과 「값이 `null` 인 원소」가 구분되지 않는다.
 * - `range(low, high)` 에서 `low > high` 면 빈 배열이다. 예외가 아니다.
 *
 * **검증 등급.** `invariant`.
 * 판정 절차를 위에서 아래로 읽는다(§규약1 「검증 등급 4종」). 동시 접근이 없고, 상한이
 * **자명한 구현으로 달성된다** — 정렬 배열 하나가 여덟 행을 전부 상한 안에 한다(찾기·양
 * 끝·구간은 이진 탐색이나 끝 읽기로 로그와 상수, 담기·지우기는 뒤를 미느라 선형, 크기는
 * 세어 둔 수). 그래서 `complexity` 가 아니고, 불변식 절에 넷이 있으므로 `invariant` 다.
 *
 * **등급이 나란한 넷과 갈리는 것이 계약이 갈린다는 증거다**(불변 사실 56). 저 넷은 로그를
 * 약속해서 자명한 구현이 전부 막히고 `complexity` 인데, 여기서는 같은 정렬 배열이 통과한다.
 * 반례를 찾기 전에 갈렸다.
 *
 * **축3이 이 계약을 판정하지 못한다는 것을 여기 적어 둔다.** 등급이 `invariant` 라 축3은
 * 회귀 수준으로 돌지만, 그 수준에서도 축3은 **성장 계급**을 본다(불변 사실 49). 이 계약을
 * 만족하는 구현들의 계급이 같은 입력에서 갈리므로(정렬 배열의 찾기는 로그, 한쪽으로 자란
 * 트리의 찾기는 선형) 어느 계급으로 걸어도 나머지가 걸린다. 스위트는 **정본의 계급**으로
 * 걸고(불변 사실 74), 그래서 **이 스위트를 통과하는 것과 이 계약을 만족하는 것은 다르다.**
 * 자세한 것은 `./binarySearchTree.contract.ts` 헤더에 적었다.
 *
 * **필요충분조건.**
 * - 의미: 순서와 유일성 중 하나라도 버리면 이 구조가 아니다. 순서를 버리면 해시 집합이고
 *   (`hash/hashSet`), 유일성을 버리면 다중집합이다(`tree/multiset`).
 * - 비용: **어느 한 행이라도 원소 수에 비례하는 비용을 넘으면 이 구조가 아니다.** 넘는
 *   방법이 하나뿐이다 — 순서를 유지하지 않고 관측할 때마다 만드는 것이고, 그러면 이것은
 *   집합이 아니라 정렬을 미뤄 둔 가방이다. 반대쪽에는 조건이 없다: 어느 행이 로그 안에
 *   들어도 이 계약을 어기지 않는다. **그것이 나란한 넷이고, 넷은 이 계약에 담긴다.**
 */
