/**
 * OrderStatisticTree — 정렬 다중집합에 **위치 좌표계**를 더한 컨테이너.
 *
 * **목적.** 원소의 중복 다중도와 전순서를 유지하면서, 담기·지우기·다중도 조회에 더해
 * **순위와 위치를 서로 바꾸는 두 연산**을 원소 수의 로그 비용으로 제공하는 것.
 * 순위는 「이 값보다 앞선 원소가 몇인가」이고 위치는 「앞에서 i 번째가 무엇인가」다.
 * 둘은 서로의 역이고, 그 한 쌍이 이 계약이 `tree/multiset` 에 더하는 전부다.
 *
 * 구간에 드는 원소를 **돌려주는** 연산은 이 계약에 없다(나란한 정렬 집합 다섯의 `range`).
 * 순위 둘을 빼면 구간의 **크기**는 나오지만 원소를 열거하는 일은 다른 약속이고, 넣을 근거가
 * 「있으면 쓸모 있겠다」뿐이라 넣지 않는다(§규약1 「연산 집합은 계약의 결과가 아니라 계약의
 * 일부다」). 키에 값을 붙여 두는 일도 없다 — 담는 것은 원소뿐이다. 양 끝(최소·최대)을 읽는
 * 일과 중복을 포함한 총 원소 수를 읽는 일도 없다.
 *
 * **뺀 세 행의 판정은 목적 항목 밖에 적는다.** `min()` · `max()` · `size()` 는 원칙 A 판정표
 * ③ 의 판정으로 뺐다 — 판정 줄과 목적 인용은 `docs/ORD-006-conventions.md` 「판정표 ③ 의
 * 103 행을 묶어 판정했다」 절에, 행 단위 대장은 `tools/_baseline/principle-a-verdicts.tsv` 에
 * 있다. **순서 질의 36 가운데 제거가 난 자리가 `tree/multiset` 과 이 계약 둘뿐이고**, 그 절의
 * 「갈라진 계약」 소절이 까닭을 적는다. 판정의 결론을 목적 문단 안에 적으면 다음 판정이 자기
 * 메아리를 근거로 읽는다(§원칙 A A5′-2).
 *
 * **`tree/multiset` 을 담는다.** 이 계약을 만족하는 구현은 전부 그 계약을 만족한다 — 일곱
 * 행이 같고 `rankOf`·`at` 둘이 더 있을 뿐이다. 역은 거짓이고 **반례가 실물로 있다**:
 * 서로 다른 키만 담는 무작위 균형 트리에 키마다 다중도 정수와 총합 카운터를 붙인 구현이
 * 그것이다(`_contract/_fixtures/keyCountingMultiset.ts`). 그 구현은 `tree/multiset` 의 일곱
 * 행을 전부 상한 안에 하면서 `rankOf`·`at` 만 **서로 다른 키의 수**에 비례한다.
 * **담는 쪽이 좁으므로 다른 구조다** — 포섭은 같음의 증거가 아니라 반대 방향의 증거다
 * (§처분 결정 「`tree/multiset` 과 `tree/orderStatisticTree` — 합치지 않는다」).
 *
 * **한정자를 고를 자유가 포섭에 묶여 있다.** `expected` 를 적은 것은 물려받은 값이 아니라
 * 두 단계를 거친 결과다. ① 포섭이 후보를 자른다 — 담기는 쪽이 `expected` 를 요구하므로 이
 * 계약의 같은 행은 `expected` 이거나 그것을 함의하는 `worst` 여야 한다. `amortized` 로 적으면
 * 상각만 보장하는 구현이 이 계약을 만족하면서 담기는 쪽을 어기고, 그 순간 두 계약은 서로
 * 담지 않는 관계가 되어 위 판정이 무너진다. ② 남은 둘에서 약한 쪽을 고른다 — `worst` 는
 * 무작위성으로 로그를 얻는 계열을 통째로 배제하는데, 배제할 이유가 목적에 없다
 * (§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」).
 *
 * **기댓값은 구현이 만드는 무작위성에 대한 값이다.** 「입력 분포에 대한 기댓값」으로 읽으면
 * 균형을 잡지 않는 평범한 탐색 트리가 이 계약을 만족하고(무작위 순열이면 기대 높이가 로그다)
 * 계약이 아무것도 배제하지 못한다. 호출자가 어떤 입력을 주든 상한이 서야 하므로, 그 보장을
 * 낼 무작위성은 구현 안에 있어야 한다(`tree/treap` 과 같은 읽기).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도
 * 없다」 — 미결).
 *
 * **이 이름은 계약을 정당화하지 않는다.** 계약의 어느 문장도 노드·부분트리 크기를 말하지
 * 않는다. 물려받은 표면은 `number` 전용에 `kth`(1-기반)·`rank` 였고 `delete` 가 성공을
 * 돌려주지 않았는데, 그것은 계약이 아니라 문제 문서가 정한 범위였다. **이름은 임시다**
 * (불변 사실 64 — 계약 이름 전환은 KAN-031).
 *
 * **불변식.** 셋이다. 셋 다 **관측 경로가 둘**이라 성립한다 — 구현이 두 경로를 따로
 * 유지할 수 있고, 따로 유지하는 순간 갈린다. 어떤 연산 뒤에도 성립해야 한다.
 * 1. 임의의 `x` 에 대해 `count(x)` 는 `toArray()` 안에서 `x` 와 동등한(비교자가 0) 원소의
 *    개수와 같다. 다중도를 읽는 길이 둘이다.
 * 2. 임의의 `x` 에 대해 `rankOf(x)` 는 `toArray()` 안에서 `x` 보다 앞선 원소의 수와 같다.
 *    순위를 읽는 길이 둘이다.
 * 3. `0 ≤ i < toArray().length` 인 임의의 `i` 에 대해 `at(i)` 는 `toArray()[i]` 와 동등하다.
 *    위치를 읽는 길이 둘이다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 **세 행을 뺀 표면에 다시 돌린 결과다.** 다섯 가운데
 * 둘이 사라졌다. 「`toArray().length === size()`」는 원소 수를 읽는 두 경로 가운데 세어 둔 쪽이,
 * 「`min()`·`max()` 가 양 끝과 동등하다」는 양 끝을 읽는 두 경로 가운데 끝점 행 쪽이 표면에서
 * 사라져 둘 다 경로가 `toArray()` 하나로 줄었고 첫 번째 물음에서 걸린다.
 *
 * **뒤의 둘이 이 계약에서 새로 생긴 자리다.** 앞의 하나는 `tree/multiset` 의 하나와 같고, 둘째와
 * 셋째는 `rankOf`·`at` 가 들어오면서 관측 경로가 둘이 된 성질이다. 이것이 이 계약과 나란한
 * 정렬 집합 다섯의 실질적인 차이다 — 저쪽에서는 위치를 세는 값이 **어느 공개 연산으로도
 * 관측되지 않아서** 그 값이 어긋나도 네 축이 전부 통과시킨다(불변 사실 109). 여기서는
 * 같은 어긋남에 **적어도** 둘째·셋째가 걸린다. 「적어도」인 것은 그 값을 다른 연산에도
 * 쓰는 구현이 있기 때문이고(정본이 그렇다), 어느 불변식이 걸리는지는 계약이 아니라 구현이
 * 정한다. 계약이 약속하는 것은 **그 값을 안 드는 구현이 걸러진다**까지다.
 *
 * 트리의 치우침은 불변식이 아니다 — 계약에 적혀 있어야 검사할 수 있는데 적는 순간 그것이
 * 처방이다(§규약1 금지 1번).
 *
 * **연산 계약.** n 은 중복을 포함한 원소 수, k 는 `deleteAll` 이 건드리는 동등 원소의 수다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator?)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `add(item)` | `item` 의 다중도를 1 늘린다 | O(log n) | expected |
 * | `delete(item)` | 다중도를 1 줄이고 `true`. 없으면 `false`, 상태는 불변 | O(log n) | expected |
 * | `deleteAll(item)` | 동등 원소를 전부 지우고 지운 수를 돌려준다 | O(log n + k) | expected |
 * | `has(item)` | `count(item) > 0` 과 같다 | O(log n) | expected |
 * | `count(item)` | 동등 원소의 수 | O(log n) | expected |
 * | `rankOf(item)` | `item` 보다 앞선 원소의 수. 담기지 않은 값에도 답한다 | O(log n) | expected |
 * | `at(index)` | 비내림차순 `index` 번째(0-기반) 원소. 범위 밖이면 `null` | O(log n) | expected |
 * | `toArray()` | 비내림차순 배열의 사본. 반환값을 고쳐도 원본은 바뀌지 않는다 | O(n) | worst |
 *
 * **위치가 0-기반인 것은 두 연산을 같은 좌표계에 세우기 위해서다.** `rankOf(x)` 가 `x` 보다
 * 앞선 원소의 수이므로 `at(rankOf(x))` 는 `x` 와 동등한 첫 원소이고, 담기지 않은 값에서는
 * `x` 뒤에 올 첫 원소다. **`x` 가 담긴 것 전부보다 뒤면 그 자리가 없어 `null` 이다** —
 * `rankOf(x)` 가 담긴 원소 수와 같아지는 자리이고, 합성이 전사(全射)가 아니라는 것이지 좌표계가
 * 어긋난다는 뜻은 아니다. 1-기반으로 적으면 이 합성에 상수 하나가 끼어 두 연산이 서로의
 * 역이 아니게 된다. 물려받은 표면이 1-기반이었던 것은 문제 문서의 서술 편의였다.
 *
 * `count` 의 상한에 `k` 가 없는 것은 `tree/multiset` 과 같은 의도된 계약이다 — 동등 원소를
 * 하나씩 세어 답하는 구현은 다중도에 비례하는 비용을 쓰므로 이 계약을 만족하지 않는다.
 * `rankOf` 도 같다: 앞선 원소를 하나씩 세는 구현은 이 행을 넘는다.
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. 0 은 「동등」을 뜻하고,
 *   동등한 원소끼리의 상대 순서는 계약이 약속하지 않는다. 그래서 `at` 이 동등 원소 무리
 *   안에서 어느 벌을 돌려주는지도 약속하지 않는다 — 동등하므로 구분할 방법이 계약 안에 없다.
 * - 미제공 시 기본 비교자는 `<`·`>` 를 쓴다. 따라서 `number`·`string` 밖의 `T` 에는 비교자
 *   주입이 **필수다.** 주입 없이 객체를 넣으면 `toArray()` 가 비내림차순을 잃고, 그 순간
 *   `rankOf`·`at` 도 뜻을 잃는다.
 * - 없는 원소의 `delete` 는 예외가 아니라 `false` 이고, 범위 밖 `at` 은 `null` 이다. 그 대가로
 *   `T` 에 `null` 이 섞이면 「없음」과 「값이 `null` 인 원소」가 구분되지 않는다.
 * - `at(index)` 의 `index` 가 정수가 아니면 범위 밖으로 본다. `rankOf` 는 담기지 않은 값에도
 *   답하므로 예외 자리가 없다 — 결과는 항상 `0` 과 담긴 원소 수 사이다.
 *
 * **검증 등급.** `complexity`.
 * 판정 절차를 위에서 아래로 읽는다(§규약1 「검증 등급 4종」). 동시 접근이 없고, 상한이
 * **자명한 구현으로 달성되지 않는다** — 정렬 배열은 `at` 과 `rankOf` 를 상수·로그에 하지만
 * `add`·`delete` 가 선형이고, 값→개수 맵은 순서를 잃어 `at` 을 못 한다. 앞의 반례
 * (키마다 다중도를 든 균형 트리)는 자명하지도 않으면서 `rankOf`·`at` 에서 걸린다.
 * 상한을 지키려면 비자명한 설계가 필요하다.
 *
 * **등급이 `tree/multiset` 과 같은 것은 두 계약이 같다는 뜻이 아니다.** 등급이 다르면 계약이
 * 같을 수 없다는 것의 역은 성립하지 않는다(불변 사실 56). 여기서는 반례가 먼저 있다.
 *
 * **필요충분조건.**
 * - 의미: 순서·다중도·위치 셋 중 하나라도 버리면 이 구조가 아니다. 위치를 버리면
 *   `tree/multiset` 이고, 다중도를 버리면 순위를 가진 정렬 집합이며, 순서를 버리면
 *   값→개수 맵이다.
 * - 비용: 셋을 다 지키더라도 `rankOf`·`at` 가 **서로 다른 키의 수**에 비례하면 이 구조가
 *   아니라 `tree/multiset` 이다. 그 구현이 실물로 있고 저쪽 계약을 전부 만족한다 — 비용
 *   조건이 두 계약을 가르는 자리가 정확히 여기다.
 */
