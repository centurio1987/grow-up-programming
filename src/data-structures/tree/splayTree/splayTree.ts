/**
 * SplayTree — 전순서를 유지하는 집합. 호출을 **모아 놓고 보면** 하나하나가 로그 안에 든다.
 *
 * **목적.** 같은 원소를 두 벌 담지 않으면서 전순서를 유지하고, 담기·지우기·찾기·양 끝
 * 읽기·구간 읽기를 원소 수의 **상각** 로그 비용으로 제공하는 것. 「상각」이 이 계약의
 * 내용이다 — 호출 하나가 원소 수에 비례해 튀어도 계약을 어기지 않고, 튄 만큼을 뒤의
 * 호출들이 싸게 갚으면 된다.
 *
 * **이 계약은 `tree/redBlackTree` 의 계약과 연산 집합도 상한도 같고 한정자만 다르다.**
 * 그래서 저쪽 계약을 만족하는 구현은 **전부** 이 계약을 만족한다 — 최악까지 로그면 평균도
 * 로그다. 담는 쪽이 넓으므로 둘은 다른 구조다(불변 사실 59·63). 이 계약이 더 넓다는 것은
 * **덜 약속한다**는 뜻이고, 덜 약속하는 계약을 따로 두는 이유는 그 차이가 실재하는 구현
 * 계열을 가르기 때문이다: **단일 호출이 원소 수에 비례해 튀는 것을 허용받아야만 성립하는
 * 구현**이 여기 들어오고 저기 못 들어온다. 갈림의 기준은 「조회가 담는 모양을 고쳐 쓰는가」가
 * **아니다** — 고쳐 쓰면서 최악까지 로그를 지키는 구현이 있다면 그 구현은 두 계약을 다
 * 만족한다.
 *
 * 같은 값을 여러 벌 담는 일은 이 계약에 없다(`tree/multiset`). 위치로 읽는 일
 * (k 번째 원소·순위)도 없다(`tree/orderStatisticTree`). 담긴 원소 수를 읽는 일도 없다.
 *
 * **뺀 행의 판정은 목적 항목 밖에 적는다.** `size()` 는 원칙 A 판정표 ③ 의 판정으로 뺐다 —
 * 판정 줄과 목적 인용은 `docs/ORD-006-conventions.md` 「판정표 ③ 의 103 행을 묶어 판정했다」
 * 절에, 행 단위 대장은 `tools/_baseline/principle-a-verdicts.tsv` 에 있다. 판정의 결론을 목적
 * 문단 안에 적으면 다음 판정이 자기 메아리를 근거로 읽는다(§원칙 A A5′-2).
 *
 * **이 이름은 계약을 정당화하지 않는다.** 계약의 어느 문장도 끌어올리기나 회전을 말하지
 * 않고, 말할 수 없다 — 명세는 내부 표현을 처방하지 않는다. 레드블랙 트리도 AVL 트리도 이
 * 계약을 지킨다. 이름이 가리키는 기법은 **이 계약이 배제하지 않기로 한 계열**의 대표일
 * 뿐이다.
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로, 원소 수보다 훨씬 많은
 * 자리를 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **불변식.** 셋이다. 셋 다 **관측 경로가 둘**이라 성립한다 — 구현이 두 경로를 따로
 * 유지할 수 있고, 따로 유지하는 순간 갈린다. 어떤 연산 뒤에도 성립해야 한다.
 * 1. 임의의 `x` 에 대해 `has(x)` 는 `toArray()` 안에 `x` 와 동등한(비교자가 0) 원소가
 *    있는가와 같다. 담김 여부를 읽는 길이 둘이다.
 * 2. 비어 있지 않으면 `min()` 은 `toArray()` 의 첫 원소와, `max()` 는 마지막 원소와
 *    같다. 양 끝을 읽는 길이 둘이다.
 * 3. 임의의 `low ≤ high` 에 대해 `range(low, high)` 는 `toArray()` 에서 그 구간에 드는
 *    원소만 남긴 것과 같다. 구간을 읽는 길이 둘이다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 **한 행을 뺀 표면에 다시 돌린 결과다.** 넷
 * 가운데 「`toArray().length === size()`」가 사라졌다 — 원소 수를 읽는 두 경로 가운데
 * 세어 둔 쪽이 표면에서 사라져 경로가 `toArray()` 하나로 줄었고 첫 번째 물음에서 걸린다.
 *
 * 셋이 `tree/redBlackTree` 의 셋과 같은 것은 베낀 것이 아니라 **판별 절차가 같은 답을
 * 내기 때문이다**(§규약1 「불변식 판별 절차」). 불변식은 상태의 성질이고 한정자는 비용의
 * 성질이라 서로를 건드리지 않는다 — **한정자가 갈린 두 계약의 불변식 절이 같은 것은
 * 우연이 아니다.**
 *
 * 조회가 트리를 고쳐 쓴다는 사실도 불변식이 아니다. 그것은 내부 표현의 변화이고, 계약이
 * 말하는 상태(담긴 원소의 모음)는 조회 전후로 같다(불변 사실 79 와 같은 자리).
 *
 * **연산 계약.** n 은 담긴 원소 수, k 는 `range` 가 돌려주는 원소 수다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator?)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `insert(item)` | `item` 을 담는다. 동등한 원소가 이미 있으면 **상태가 바뀌지 않는다** | O(log n) | amortized |
 * | `delete(item)` | 동등한 원소를 지우고 `true`. 없으면 `false`, 상태는 불변 | O(log n) | amortized |
 * | `has(item)` | 동등한 원소가 담겨 있으면 `true` | O(log n) | amortized |
 * | `min()` / `max()` | 비교자 기준 최소·최대. 비어 있으면 `null` | O(log n) | amortized |
 * | `range(low, high)` | `low ≤ v ≤ high` 인 원소를 비내림차순 배열로. 사본이다 | O(log n + k) | amortized |
 * | `toArray()` | 비내림차순 배열의 사본. 반환값을 고쳐도 원본은 바뀌지 않는다 | O(n) | amortized |
 *
 * **일곱 행 중 여섯이 `amortized` 이고 첫 행만 `worst` 인 것에 근거가 있다.** 상각은
 * **한 인스턴스에 대한 호출 시퀀스**의 총비용을 그 시퀀스 길이로 나눈 값이다. 생성자는 그
 * 시퀀스를 여는 연산이라 나눌 시퀀스 **안에 없고**, 그래서 축3도 이 행을 재지 않는다
 * (§규약2 축3 면제 — n 에 대해 반복 호출되는 연산이 아니다). 상각을 여러 인스턴스에 걸쳐
 * 정의하는 것도 형식으로는 가능하지만 그 값은 이 계약이 말하려는 것이 아니다 — 이 계약의
 * 상각은 **하나의 집합을 오래 쓸 때** 무엇이 보장되는가에 대한 진술이다. 잴 시퀀스가 없는
 * 자리에 상각을 적으면 읽는 사람이 그 진술을 찾게 되므로 `worst` 로 적었다.
 *
 * `toArray` 의 한정자도 `amortized` 다. 「가장 약한 한정자를 적는다」를 그대로 따른 것이고
 * (불변 사실 21), 강하게 적을 대가가 없다 — `worst` 로 적으면 「늘어놓기를 게으르게 고쳤다가
 * 어쩌다 한 번 다시 짓는」 계열이 배제되는데, **이 계약이 그 계열을 배제할 이유를 어디에서도
 * 갖지 않는다**(§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」의 뒷문장).
 *
 * **`amortized` 로 적어서 들어오는 것과 나가는 것.** 들어오는 것은 **단일 호출의 비용을
 * 원소 수 아래로 묶지 못하는 구현**이다 — 찾은 자리를 위로 끌어올리는 계열이 그 예이고,
 * 거기서는 **사슬인 채로 맞는 첫 조회 하나**가 원소 수에 비례하며 그 하나를 뒤 호출들이
 * 갚는다. 나가는 것은 없다: `worst` 계약의 구현이 전부 남는다. **그래서 이 계약은 저쪽보다
 * 약하고, 약한 것이 목적이다.**
 * 「호출 하나가 튀지 않는다」를 약속받아야 하는 자리(응답 시간 상한이 있는 자리)에는
 * `tree/redBlackTree` 계약이 있다.
 *
 * `range` 의 상한에 `k` 가 있는 것은 돌려주는 원소를 적는 비용이 어느 구현에서도 그
 * 수에 비례하기 때문이다. `k` 를 상한에서 빼면 아무 구현도 만족하지 못한다.
 *
 * **`min`·`max`·`range` 를 넣은 근거는 「배제하는 것이 없다」다.** 나머지 계약을
 * 만족하는 구현은 전부 이 셋을 위 상한 안에 한다. **넣어도 만족하는 구현 집합이
 * 그대로이므로** 넣고 빼는 것이 계약을 바꾸지 않는다. 넣은 쪽을 고른 이유는 전순서를
 * 유지한다는 목적이 이 셋으로만 관측되기 때문이다 — `toArray()` 하나로는 「전부
 * 늘어놓기」밖에 못 하고, 그것은 순서를 쓰는 것이 아니라 순서를 확인하는 것이다.
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. 0 은 「동등」을 뜻하고,
 *   **동등한 두 원소는 이 집합에 함께 담기지 않는다.** 나중에 넣은 쪽이 버려지는지 앞의
 *   것을 덮는지는 계약이 약속하지 않는다 — 동등하므로 구분할 방법이 계약 안에 없다.
 * - 미제공 시 기본 비교자는 `<`·`>` 를 쓴다. 따라서 `number`·`string` 밖의 `T` 에는
 *   비교자 주입이 **필수다.** 주입 없이 객체를 넣으면 `toArray()` 가 비내림차순을 잃는다.
 * - 빈 집합의 `min`·`max` 는 예외가 아니라 `null` 이다. 그 대가로 `T` 에 `null` 이 섞이면
 *   「비어 있음」과 「값이 `null` 인 원소」가 구분되지 않는다.
 * - `range(low, high)` 에서 `low > high` 면 빈 배열이다. 예외가 아니다.
 *
 * **검증 등급.** `complexity`.
 * 상한이 **어떤 자명한 구현으로도** 달성되지 않는다. 언어가 내주는 것이 둘인데 둘 다
 * 한쪽을 놓는다 — 배열은 순서를 주지만 가운데에 넣으면 뒤가 전부 밀리므로 `insert`·
 * `delete` 가 O(n) 이고, 상각으로 봐도 O(n) 이다(n 회 넣기의 총비용이 n² 이다).
 * 객체(해시)는 갱신을 상수에 주지만 순서를 잃으므로 `min`·`max`·`range`·`toArray` 를
 * 상한 안에 못 한다. **한정자를 약하게 적어도 자명한 구현이 들어오지 않는다** — 상각이
 * 구해 주는 것은 「가끔 비싼 호출」이지 「늘 비싼 호출」이 아니기 때문이고, 자명한 두
 * 구현이 실패하는 방식이 후자다.
 *
 * **필요충분조건.**
 * - 의미: 순서와 유일성 중 하나라도 버리면 이 구조가 아니다. 순서를 버리면 해시 집합이고
 *   (`hash/hashSet`), 유일성을 버리면 다중집합이다(`tree/multiset`).
 * - 비용: 둘 다 지키더라도 `insert`·`delete` 의 **시퀀스 평균**이 n 에 비례하면 정렬
 *   배열이다. 그리고 **상각으로 로그를 지키는 것이 이 계약의 전부다** — 최악까지 지키면
 *   `redBlackTree` 계약을 **함께** 지키는 것이고(그쪽이 좁다), 기댓값만 지키면 `treap`
 *   이며 그쪽과는 서로 담지 않는다(불변 사실 54·59).
 */
