/**
 * BPlusTree — 전순서를 유지하는 집합. 모든 연산이 **호출 하나하나** 로그 안에 든다.
 *
 * **이 계약은 `tree/redBlackTree` 의 계약과 같다.** 비슷한 것이 아니라 같은 것이다 —
 * 아래 연산 계약 표의 여덟 행이 그 파일의 여덟 행과 글자까지 같고, 스위트도 그 파일의
 * `ContractSpec` 을 그대로 돌린다(`./bPlusTree.contract.ts`). 그 사실을 감추지 않고 여기
 * 맨 앞에 적는다 — 이름이 다르다고 계약이 다른 것이 아니다(§규약1 「같은 구조인가」).
 *
 * 두 이름을 가르려고 셋을 시도했고 셋 다 계약의 문장이 되지 못했다.
 *
 * - **잎을 잇는 사슬.** 이 기법이 다른 넷과 갈리는 가장 큰 자리다. 그런데 사슬이 계약에
 *   들어오는 형태는 `range` 하나뿐이고, **`range` 는 아무것도 배제하지 못한다** — 사슬이
 *   없는 구현도 양 끝으로 두 번 내려간 뒤 사이를 훑으면 $O(\log n + k)$ 안에 한다. 다섯
 *   정본이 전부 그렇게 하고 있다. 배제하는 것이 없으면 계약이 갈리지 않는다(B17 판정).
 * - **원소가 잎에만 있다는 것.** 내부 자리는 길잡이만 들고 값을 담지 않는다. 그런데 이것은
 *   **어디에 담느냐에 대한 진술**이고, 계약에는 담긴 자리를 묻는 연산이 없다. 계약이
 *   관측하는 것은 무엇이 담겼는가와 그 값을 얻는 비용뿐이다(불변 사실 38).
 * - **조회가 늘 잎까지 내려간다는 것.** 값이 잎에만 있으므로 `has` 가 중간에서 끝나지
 *   않는다. 반대로 내부 자리에도 값을 담는 구현은 운이 좋으면 위에서 끝난다 — 원소
 *   16,384 개를 담고 전부 한 번씩 찾아 보면 `tree/bTree` 정본은 호출 하나가 1~9 걸음이고
 *   이쪽은 **전부 9 걸음**이다. 이것은 **최선의 경우의 차이**이고 계약은 최선을 말하지
 *   않는다 — 여덟 행이 전부 `worst` 이고 최악은 양쪽 다 높이만큼이다.
 *
 * **그래서 실제로 갈리는 것은 상수 배수뿐이다.** 사슬을 타면 구간을 읽을 때 위로 되짚어
 * 올라가는 걸음이 없어져 같은 답을 더 적은 걸음으로 낸다(계약 스위트의 `range` 시나리오에서
 * 8·8·10 걸음, 색으로 묶는 정본은 20·21·26). 그런데 축3이 보는 것은 성장률
 * $r = C(4n)/C(n)$ 이고 상수 배수는 판정에 들어오지 않는다(불변 사실 6·76) — 다섯 정본의
 * $r$ 이 1.13~1.25 로 붙어 있다. 계약을 그 갈림에 맞춰 적으려면 상수 배수를 계약의 문장으로
 * 삼아야 하는데, 그러면 **가장 빠른 구현 하나만 계약을 지키게 된다.**
 *
 * **계약 이름은 아직 없다.** 같은 계약에 이름이 다섯 붙어 있고(`redBlackTree`·`avlTree`·
 * `twoThreeTree`·`bTree`) 다섯이 전부 구현 이름이다. 계약을 적어 둘 자리로 `redBlackTree`
 * 를 골랐지만 그 이름도 **임시다** — 계약 이름으로 옮기는 것은 KAN-031 의 일이다
 * (불변 사실 64).
 *
 * **목적.** 같은 원소를 두 벌 담지 않으면서 전순서를 유지하고, 담기·지우기·찾기·양 끝
 * 읽기·구간 읽기를 원소 수의 **최악** 로그 비용으로 제공하는 것. 「최악」이 이 계약의
 * 내용이다 — 호출을 모아 평균 내면 로그인 구현도, 기댓값이 로그인 구현도 이 계약을
 * 만족하지 못한다.
 *
 * 같은 값을 여러 벌 담는 일은 이 계약에 없다(`tree/multiset`). 위치로 읽는 일
 * (k 번째 원소·순위)도 없다(`tree/orderStatisticTree`).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로, 원소 수보다 훨씬 많은
 * 자리를 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 * 이 이름의 기법이 같은 값을 길잡이와 잎에 두 벌 두는 것도 그래서 계약 밖이다.
 *
 * **불변식.** 넷이다. 넷 다 **관측 경로가 둘**이라 성립한다 — 구현이 두 경로를 따로
 * 유지할 수 있고, 따로 유지하는 순간 갈린다. 어떤 연산 뒤에도 성립해야 한다.
 * 1. `toArray().length === size()`. 원소 수를 읽는 길이 둘이다.
 * 2. 임의의 `x` 에 대해 `has(x)` 는 `toArray()` 안에 `x` 와 동등한(비교자가 0) 원소가
 *    있는가와 같다. 담김 여부를 읽는 길이 둘이다.
 * 3. 비어 있지 않으면 `min()` 은 `toArray()` 의 첫 원소와, `max()` 는 마지막 원소와
 *    같다. 양 끝을 읽는 길이 둘이다.
 * 4. 임의의 `low ≤ high` 에 대해 `range(low, high)` 는 `toArray()` 에서 그 구간에 드는
 *    원소만 남긴 것과 같다. 구간을 읽는 길이 둘이다.
 *
 * 정렬됨과 유일함은 불변식이 **아니다.** 둘 다 `toArray()` 하나로만 읽히므로 대조할
 * 상대가 없고, 그 조건은 축1이 참조 모델과 하는 일이다(§규약1 「불변식 판별 절차」 ①).
 * 잎 사슬이 왼쪽부터 오른쪽까지 이어져 있다는 것도 불변식이 아니다 — 사슬이라는 말이
 * 계약에 없다. 사슬이 어긋난 구현은 **관측 가능한 동작이 달라지는 순간** 축1이 잡는다
 * (사슬이 고리를 이루면 `toArray()` 가 끝나지 않는데, 멈추지 않는 것도 통과가 아니다).
 *
 * **연산 계약.** n 은 담긴 원소 수, k 는 `range` 가 돌려주는 원소 수다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator?)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `insert(item)` | `item` 을 담는다. 동등한 원소가 이미 있으면 **상태가 바뀌지 않는다** | O(log n) | worst |
 * | `delete(item)` | 동등한 원소를 지우고 `true`. 없으면 `false`, 상태는 불변 | O(log n) | worst |
 * | `has(item)` | 동등한 원소가 담겨 있으면 `true` | O(log n) | worst |
 * | `min()` / `max()` | 비교자 기준 최소·최대. 비어 있으면 `null` | O(log n) | worst |
 * | `range(low, high)` | `low ≤ v ≤ high` 인 원소를 비내림차순 배열로. 사본이다 | O(log n + k) | worst |
 * | `size()` | 담긴 원소 수 | O(1) | worst |
 * | `toArray()` | 비내림차순 배열의 사본. 반환값을 고쳐도 원본은 바뀌지 않는다 | O(n) | worst |
 *
 * **`range` 의 상한에 사슬이 적혀 있지 않다는 점을 짚어 둔다.** $O(\log n + k)$ 는 사슬을
 * 타는 구현과 위로 되짚는 구현을 **둘 다** 담는다. 상한을 사슬 쪽에 맞춰 더 강하게 적을
 * 방법이 없다 — 두 방식의 걸음 수가 같은 계급이라 부등식으로 갈라 적을 자리가 없다.
 *
 * **물려받은 표면에서 생성자의 `t` 가 빠졌고 `inOrder()` 가 `toArray()` 로 바뀌었다.**
 * 자리 하나가 담는 개수는 내부 표현이라 계약 표면에 두지 않고(`tree/bTree` 헤더와 같은
 * 자리), 「중위 순회」는 이진 자리를 전제한 말이라 걷어 냈다. 계약이 약속하는 것은 순회
 * 방법이 아니라 **비내림차순 배열의 사본**이다. `min`·`max` 는 물려받은 표면에 없던 것을
 * 넣었다 — 근거는 「배제하는 것이 없다」이고 `tree/redBlackTree` 헤더가 적은 것과 같다.
 *
 * **여덟 행이 전부 `worst` 인 것이 이 계약이 하는 일의 거의 전부다.** `amortized` 로
 * 적으면 조회가 트리를 고쳐 쓰는 계열이 들어오고(`tree/splayTree`), `expected` 로 적으면
 * 무작위 우선순위로 균형을 얻는 계열이 들어온다(`tree/treap`). 두 계열은 **호출 하나가
 * 튀지 않는다는 것을 약속하지 못하고**, 이 계약이 약속하려는 것이 정확히 그것이다
 * (§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」, 불변 사실 59).
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. 0 은 「동등」을 뜻하고,
 *   **동등한 두 원소는 이 집합에 함께 담기지 않는다.** 나중에 넣은 쪽이 버려지는지 앞의
 *   것을 덮는지는 계약이 약속하지 않는다 — 동등하므로 구분할 방법이 계약 안에 없다.
 * - 미제공 시 기본 비교자는 `<`·`>` 를 쓴다. 따라서 `number`·`string` 밖의 `T` 에는
 *   비교자 주입이 **필수다.**
 * - 빈 집합의 `min`·`max` 는 예외가 아니라 `null` 이다. 그 대가로 `T` 에 `null` 이 섞이면
 *   「비어 있음」과 「값이 `null` 인 원소」가 구분되지 않는다.
 * - `range(low, high)` 에서 `low > high` 면 빈 배열이다. 예외가 아니다.
 *
 * **검증 등급.** `complexity`.
 * 상한이 **어떤 자명한 구현으로도** 달성되지 않는다. 언어가 내주는 것이 둘인데 둘 다
 * 한쪽을 놓는다 — 배열은 순서를 주지만 가운데에 넣으면 뒤가 전부 밀리므로 `insert`·
 * `delete` 가 O(n) 이고, 객체(해시)는 갱신을 상수에 주지만 순서를 잃으므로 `min`·
 * `max`·`range`·`toArray` 를 상한 안에 못 한다. 둘을 함께 하려면 **담는 모양을 갱신
 * 도중에 고쳐 주는 설계**가 들어오고, 그 설계가 자명하지 않다는 것이 이 등급의 내용이다
 * (§규약1 「자명한 구현은 존재 조건이다」).
 *
 * **필요충분조건.**
 * - 의미: 순서와 유일성 중 하나라도 버리면 이 구조가 아니다. 순서를 버리면 해시 집합이고
 *   (`hash/hashSet`), 유일성을 버리면 다중집합이다(`tree/multiset`).
 * - 비용: 둘 다 지키더라도 `insert`·`delete` 가 n 에 비례하면 정렬 배열이다. 그리고
 *   **로그를 지키더라도 최악이 아니면 이 구조가 아니다** — 상각만 지키면 `splayTree`,
 *   기댓값만 지키면 `treap` 이고, 셋은 서로를 함의하지 않으므로 만족하는 구현 집합이
 *   갈린다(불변 사실 59).
 */
