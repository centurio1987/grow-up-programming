/**
 * LinkCutTree — 마디가 고정된 숲에서 간선을 넣고 빼며 두 마디가 같은 나무에 있는지 묻는 구조.
 *
 * **목적.** 마디 수를 생성 시점에 고정한 숲 하나를 두고, 간선을 넣는 일·빼는 일·두 마디가
 * 같은 나무에 있는지 묻는 일을 마디 수의 **상각** 로그 비용으로 제공하는 것. 담는 것이
 * 숲이라는 것은 편의가 아니라 계약의 내용이다 — 넣기가 사이클을 만들지 않으므로 두 마디를
 * 잇는 길은 있으면 하나뿐이고, **간선 하나를 빼는 것이 나무 하나를 둘로 가르는 일**이 된다.
 *
 * **「상각」이 두 번째 내용이다.** 호출 하나가 마디 수에 비례해 튀어도 계약을 어기지 않고,
 * 튄 만큼을 뒤의 호출들이 싸게 갚으면 된다. 응답 시간의 상한을 약속받아야 하는 자리에는
 * 이 계약이 맞지 않는다.
 *
 * **길을 따라 값을 모으는 일은 이 계약에 없다.** 두 마디 사이 길 위의 합·최대·개수를 묻는
 * 연산을 넣으면 계약이 배제하는 구현 집합이 통째로 달라진다 — 마디마다 값을 들고 그 값을
 * 길 단위로 접어 두는 일이 새로 요구되고, 연결 여부만 답하면 되는 구현이 전부 나간다.
 * 여기서 약속하는 것은 **어느 마디가 어느 나무에 있는가** 하나다.
 *
 * **사이클이 있는 그래프의 연결성도 이 계약에 없다.** 사이클을 만들지 않는 것은 호출자의
 * 의무가 아니라 **이 구조가 지는 약속**이다 — 아래 표의 `link` 행이 이미 같은 나무인 쌍을
 * 상태 변화 없이 거절한다. 그래서 상태는 언제나 숲이다. 일반 그래프에서 간선을 넣고 빼며
 * 연결성을 묻는 것은 다른 계약이고 아래 상한이 성립하지 않는다.
 *
 * **`disjoint-set/unionFind` 와 갈리는 자리는 `cut` 하나다.** 합치기만 있는 계약은 되돌릴
 * 수 없는 대신 상한을 상수 계급까지 내릴 수 있고, 여기서는 되돌릴 수 있는 대신 그 값을
 * 포기한다. `disjoint-set/disjointSetRollback` 과도 갈린다 — 그쪽이 되돌리는 것은
 * **마지막에 넣은 간선**이고 여기서는 **아무 간선이나** 뺀다. 두 계약이 아직 규약1로
 * 옮겨지지 않았으므로 포섭 판정은 그 카드(T3-04·T3-05)가 하고, 여기서는 갈리는 자리만
 * 적는다(불변 사실 65 — 물려받은 상한 주장을 판정의 입력으로 쓰지 않는다).
 *
 * **이 이름은 계약을 정당화하지 않는다.** 계약의 어느 문장도 접힌 길이나 끌어올리기를
 * 말하지 않고, 말할 수 없다 — 명세는 내부 표현을 처방하지 않는다. 나무를 오일러 지나기
 * 수열로 펴서 균형 이진 탐색 트리에 담는 구현도 세 행을 전부 지킨다. 이름이 가리키는
 * 기법은 **이 계약이 배제하지 않기로 한 계열**의 대표일 뿐이다.
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로, 마디 수보다 훨씬 많은
 * 자리를 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **불변식.** 없다.
 *
 * **연산이 셋뿐이라 자동으로 비는 것이 아니다.** 판별 절차(§규약1 「불변식 판별 절차」)를
 * 돌린 결과이고, 후보 셋이 각각 다른 물음에서 걸린다.
 *
 * - **`connected` 가 동치관계다** — 자기 자신과 연결돼 있고, 대칭이고, 추이적이다. 「어느
 *   마디가 어느 나무에 있는가」를 읽는 공개 연산이 `connected` 하나뿐이므로 **첫 번째
 *   물음에서 걸린다.** 대조할 상대가 없고, 그 하나가 내놓는 것이 곧 상태다. 세 성질은
 *   축1이 참조 모델과 대조하며 본다.
 * - **`link` 가 `false` 를 돌려주는 것과 `connected` 가 `true` 인 것이 같다** — 관측 경로가
 *   둘이라 첫 물음은 지난다. **두 번째 물음에서 걸린다**: 아래 표의 `link` 행이 그 정합을
 *   이미 적고 있다(같은 나무면 상태가 바뀌지 않고 `false`). 두 연산이 갈리면 `link` 가
 *   자기 행을 어긴 것이다.
 * - **`cut` 이 `true` 를 돌려준 뒤에는 그 두 마디가 갈라져 있다** — 같은 자리다. 숲에서
 *   간선 `(u, v)` 는 `u`·`v` 를 잇는 유일한 길이므로 이것은 `cut` 행의 의미에서 그대로
 *   따라 나온다.
 *
 * 담는 모양의 성질(나무가 얼마나 깊은가, 길이 어떻게 갈라져 있는가)은 후보가 아니다.
 * 계약에 적어야 검사할 수 있는데 **적는 순간 그것이 표현을 처방한다**(불변 사실 36).
 *
 * **연산 계약.** n 은 생성자가 고정한 **마디 수**다. 담긴 원소 수가 아니라 미리 정해진
 * 자리의 수이고, 구조가 사는 동안 바뀌지 않는다. 나무 하나에 든 마디 수가 그보다 훨씬
 * 적어도 상한은 n 으로 적는다 — 호출자가 어느 나무를 만질지 계약이 알지 못한다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(n)` | 마디 `0`부터 `n-1`까지를 각각 홀로 둔다. 간선은 하나도 없다 | O(n) | worst |
 * | `link(u, v)` | `u`·`v` 가 다른 나무에 있으면 그 둘을 잇는 간선을 넣고 `true`. 같은 나무면(같은 마디인 경우를 포함해) **상태가 바뀌지 않고** `false` | O(log n) | amortized |
 * | `cut(u, v)` | `u`·`v` 를 잇는 간선이 있으면 지우고 `true`. 없으면 상태가 바뀌지 않고 `false` | O(log n) | amortized |
 * | `connected(u, v)` | 같은 나무에 있으면 `true`. `u === v` 면 `true` | O(log n) | amortized |
 *
 * **갱신 둘이 `boolean` 을 돌려주는 것은 계약의 일부다.** 물려받은 표면은 반환값이 없었고
 * 대신 호출자에게 둘을 요구했다 — 「사이클을 만들지 않을 것」과 「없는 간선을 빼지 말 것」.
 * 그렇게 적으면 **숲을 유지하는 일이 이 구조의 약속이 아니라 호출자의 의무가 되고**, 지키지
 * 않은 호출에 대해 계약이 아무 말도 하지 않는다. 관측되지 않는 약속은 계약이 아니다.
 * 반환값을 붙이면 세 연산이 모든 입력에 대해 정의되고, 그 대가로 두 갱신이 각각 판정을
 * 하나씩 지게 된다 — 판정 비용이 갱신 자체와 같은 계급이라 상한은 바뀌지 않는다.
 *
 * **상한을 `O(log n)` 으로 적은 것은 고른 것이다.** 목적에서 유일하게 따라 나오지 않는다
 * (§규약1 「상한이 목적에서 유일하게 따라 나오지 않는 계약이 있다」). 축3 사다리가 고를 수
 * 있게 두는 값 중 셋을 보고 하나를 골랐다.
 *
 * - **`O(n)` 은 계약이 뜻을 잃는다.** 간선을 적어 두고 질의마다 밟아 가면 그 상한이 나오고,
 *   그것이 상한이면 이 구조를 따로 둘 이유를 계약이 말하지 못한다.
 * - **`O(1)` 은 나무를 접어 두는 계열을 통째로 배제한다.** 배제할 이유가 목적에 없다 —
 *   목적은 갱신과 질의를 **함께** 싸게 두는 것이지 질의를 상수로 두는 것이 아니고, 상수를
 *   요구하는 계약은 되돌리기를 포기한 쪽(`disjoint-set/unionFind`)이 이미 맡고 있다.
 * - **`O(sqrt n)` 은 남는 후보이고 하한이 아니다.** 그러므로 여기서는 정본이 서는 계급을
 *   적는다(§규약2 「축3은 상한이 아니라 성장 계급을 판정한다」가 그것을 요구한다 — 계약의
 *   상한이 정본의 계급과 어긋나면 정본이 자기 스위트에서 걸린다).
 *
 * 순환이 아니다: 목적이 후보를 선형 아래로 자르고, 그 안에서 하나를 고르는 일만 정본이 한다.
 *
 * **한정자가 `amortized` 인 것도 고른 것이다.** `worst` 로 적으면 「접근한 길을 그 자리에서
 * 고쳐 쓰고 그 대가를 뒤가 갚는」 계열이 통째로 나간다 — 그 계열에서는 사슬이 된 나무를
 * 처음 만지는 호출 하나가 마디 수에 비례한다. 배제할 이유가 목적에 없으므로 약한 쪽을
 * 적는다(§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」). `expected` 는 이 계약과
 * 비교 불가이고(서로를 함의하지 않는다) 무작위를 실제로 뽑는 구현을 요구하게 되므로 적지
 * 않는다. `constructor` 만 `worst` 인 것은 상각이 **한 인스턴스에 대한 호출 시퀀스**의
 * 값인데 생성자가 그 시퀀스를 여는 연산이라 나눌 시퀀스 안에 없기 때문이고, 그래서 축3도
 * 이 행을 재지 않는다(§규약2 축3 면제).
 *
 * **주입 정책.**
 * - 주입받는 것이 없다. 마디는 정수 하나로 이름 붙고 값을 담지 않으므로 비교자도 해시도
 *   들어올 자리가 없다. **주입점이 없는 것이 계약의 일부다** — 마디에 값을 달 수 있게 열면
 *   길 위의 값을 묻는 연산이 따라 들어오고, 그것은 위에서 다른 계약으로 판정한 자리다.
 * - `n` 은 0 이상의 정수여야 하고, 아니면 `RangeError` 를 던진다. `n === 0` 은 정당하다 —
 *   마디가 없는 숲이고, 그 뒤로 부를 수 있는 연산이 없다.
 * - 마디 번호는 `0` 이상 `n` 미만이어야 하고, 벗어나면 세 연산 모두 `RangeError` 를 던진다.
 *   **`false` 를 돌려주지 않는 이유는 반환 타입에 「그런 마디는 없다」를 담을 자리가 없기
 *   때문이다.** `false` 로 답하면 「그 마디는 아무와도 연결되지 않았다」로 읽혀 잘못된 색인이
 *   조용히 지나간다. 반환 타입에 자리가 있는 계약은 다르게 고른다(`trie/suffixArray` 의 범위
 *   밖 접근은 `null` 이다).
 * - 같은 두 마디를 잇는 간선을 두 번 넣을 수 없다. 첫 호출 뒤로 둘은 같은 나무에 있으므로
 *   두 번째 `link` 는 `false` 다. 간선에 무게나 이름을 다는 일은 이 계약에 없다.
 *
 * **검증 등급.** `complexity`.
 * 세 행을 **함께** 만족하는 자명한 구현이 없다. 언어가 내주는 배열·객체로 숲을 적는 길은
 * 둘뿐이고 둘 다 한쪽을 놓는다.
 * - **간선을 적어 두면** 갱신이 상수인 대신 연결 판정이 간선을 밟아 가므로 마디 수에
 *   비례한다. 사이클을 막으려면 `link` 도 같은 판정을 해야 하므로 함께 끌려간다.
 * - **마디마다 어느 덩어리인지 적어 두면** 판정이 상수인 대신 갱신이 덩어리를 다시 적는다.
 *   `link` 는 작은 쪽만 다시 적어 상각 로그 안에 들지만 **`cut` 은 그 논증이 서지 않는다** —
 *   빼기는 덩어리를 둘로 가르는 일이라 「크기가 두 배가 될 때까지 기다린다」로 갚을 수 없고,
 *   어느 쪽이 작은지 알아내는 일 자체가 한쪽을 끝까지 훑는 일이다.
 * - 둘을 함께 들어도 각자의 약점이 그대로 남는다. 셋을 함께 로그 안에 두려면 **나무를 로그
 *   깊이의 모양으로 접어 두고 그 모양을 갱신마다 고쳐 쓰는** 설계가 들어와야 하고, 그것은
 *   배열·객체의 기본 연산에서 나오지 않는다.
 *
 * **필요충분조건.**
 * - 의미: 간선을 **빼는 일**과 상태가 **숲이라는 것** 중 하나라도 버리면 이 구조가 아니다.
 *   빼기를 버리면 분리 집합이고(`disjoint-set/unionFind`), 빼는 것을 마지막에 넣은 것부터로
 *   묶으면 되돌릴 수 있는 분리 집합이며(`disjoint-set/disjointSetRollback`), 숲을 버리고
 *   사이클을 허용하면 일반 그래프의 동적 연결성이라 이 상한이 성립하지 않는다.
 * - 비용: 셋을 다 지키더라도 세 연산의 **시퀀스 평균**이 마디 수에 비례하면 간선 목록이다.
 *   한쪽만 로그 안에 두는 것으로는 부족하다 — 질의를 상수로 두고 갱신을 선형에 두면 덩어리
 *   번호표이고, 갱신을 상수로 두고 질의를 선형에 두면 간선 목록이다. 이 계약이 요구하는
 *   것은 **셋을 함께** 로그 안에 두는 것이다.
 */
export class LinkCutTree {
  constructor(n: number) {
    throw new Error("Not implemented");
  }

  link(u: number, v: number): boolean {
    throw new Error("Not implemented");
  }

  cut(u: number, v: number): boolean {
    throw new Error("Not implemented");
  }

  connected(u: number, v: number): boolean {
    throw new Error("Not implemented");
  }
}
