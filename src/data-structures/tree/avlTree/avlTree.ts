/**
 * AVLTree — 전순서를 유지하는 집합. 모든 연산이 **호출 하나하나** 로그 안에 든다.
 *
 * **이 계약은 `tree/redBlackTree` 의 계약과 같다.** 비슷한 것이 아니라 같은 것이다 —
 * 아래 연산 계약 표의 일곱 행이 그 파일의 일곱 행과 글자까지 같고, 스위트도 그 파일의
 * `ContractSpec` 을 그대로 돌린다(`./avlTree.contract.ts`). 그 사실을 감추지 않고 여기
 * 맨 앞에 적는다 — 이름이 다르다고 계약이 다른 것이 아니다(§규약1 「같은 구조인가」).
 *
 * 두 이름을 가르려고 셋을 시도했고 셋 다 계약의 문장이 되지 못했다.
 *
 * - **높이.** 높이 차를 1 이하로 묶으면 높이가 $\log_\phi n$ 에 묶이고($\phi$ 는 황금비),
 *   색으로 묶으면 $2\log_2 n$ 이다. 둘은 **상수 배수 차이**이고 축3은 상수 배수를 판정에
 *   넣지 않는다(불변 사실 6). 계약에 적으려면 「높이」를 계약이 말해야 하는데, 높이는
 *   내부 표현의 성질이라 적는 순간 그것이 처방이다(불변 사실 36).
 * - **재균형 횟수.** 지우기 한 번에 도는 횟수가 이쪽은 최악에 높이만큼, 색으로 묶는 쪽은
 *   세 번 안이다. 그런데 **계약에 회전이라는 말이 없다.** 돌든 나누든 다시 짓든 계약이
 *   보는 것은 호출 하나의 비용뿐이고, 두 기법 모두 그 비용이 $O(\log n)$ 이다. 횟수를
 *   상한으로 적는 것은 재균형 기법을 처방하는 것이다.
 * - **노드에 드는 자리.** 높이를 들고 다니면 정수 하나, 색을 들고 다니면 한 비트다. 이것이
 *   두 기법의 진짜 차이인데 **공간은 이 저장소의 어느 계약에도 없고**(§규약1 「공간은 어느
 *   계약에도 없다」), 게다가 그 제약을 관측하는 연산이 이 계약에 없다 — 있으면 계약이
 *   갈렸을 것이다(불변 사실 67).
 *
 * **그래서 이 구조는 계약이 아니라 재균형 기법으로 갈린다.** 계약이 구현을 처방하지
 * 않기로 한 이상 그 갈림은 계약에 들어올 수 없고, 자리는 가이드다(불변 사실 45).
 * 지우지 않는 이유는 판정이 *"계약이 담지 못한다"* 이지 *"쓸모가 없다"* 가 아니기
 * 때문이다(불변 사실 61).
 *
 * **계약 이름은 아직 없다.** 같은 계약에 이름이 다섯 붙어 있고(`redBlackTree`·
 * `twoThreeTree`·`bTree`·`bPlusTree`) 다섯이 전부 구현 이름이다. 계약을 적어 둘 자리로
 * `redBlackTree` 를 골랐지만 그 이름도 **임시다** — 계약 이름으로 옮기는 것은 KAN-031 의
 * 일이다(불변 사실 64).
 *
 * **목적.** 같은 원소를 두 벌 담지 않으면서 전순서를 유지하고, 담기·지우기·찾기·양 끝
 * 읽기·구간 읽기를 원소 수의 **최악** 로그 비용으로 제공하는 것. 「최악」이 이 계약의
 * 내용이다 — 호출을 모아 평균 내면 로그인 구현도, 기댓값이 로그인 구현도 이 계약을
 * 만족하지 못한다.
 *
 * 같은 값을 여러 벌 담는 일은 이 계약에 없다(`tree/multiset`). 위치로 읽는 일
 * (k 번째 원소·순위)도 없다(`tree/orderStatisticTree`). 담긴 원소 수를 읽는 일도 없다.
 *
 * **뺀 행의 판정은 목적 항목 밖에 적는다.** `size()` 는 원칙 A 판정표 ③ 의 판정으로 뺐다 —
 * 판정 줄과 목적 인용은 `docs/ORD-006-conventions.md` 「판정표 ③ 의 103 행을 묶어 판정했다」
 * 절에, 행 단위 대장은 `tools/_baseline/principle-a-verdicts.tsv` 에 있다. 판정의 결론을 목적
 * 문단 안에 적으면 다음 판정이 자기 메아리를 근거로 읽는다(§원칙 A A5′-2).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로, 원소 수보다 훨씬 많은
 * 자리를 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **불변식.** 셋이다. 셋 다 **관측 경로가 둘**이라 성립한다 — 구현이 두 경로를 따로
 * 유지할 수 있고, 따로 유지하는 순간 갈린다. 어떤 연산 뒤에도 성립해야 한다.
 * 1. 임의의 `x` 에 대해 `has(x)` 는 `toArray()` 안에 `x` 와 동등한(비교자가 0) 원소가
 *    있는가와 같다. 담김 여부를 읽는 길이 둘이다.
 * 2. 비어 있지 않으면 `min()` 은 `toArray()` 의 첫 원소와, `max()` 는 마지막 원소와
 *    같다. 양 끝을 읽는 길이 둘이다.
 * 3. 임의의 `low ≤ high` 에 대해 `range(low, high)` 는 `toArray()` 에서 그 구간에 드는
 *    원소만 남긴 것과 같다. 구간을 읽는 길이 둘이다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 **한 행을 뺀 표면에 다시 돌린 결과다.** 넷
 * 가운데 「`toArray().length === size()`」가 사라졌다 — 원소 수를 읽는 두 경로 가운데
 * 세어 둔 쪽이 표면에서 사라져 경로가 `toArray()` 하나로 줄었고 첫 번째 물음에서 걸린다.
 * 늘어놓은 배열이 담긴 원소 전부인지는 `toArray` 행의 의미라 축1이 참조 모델과 대조한다.
 *
 * 정렬됨과 유일함은 불변식이 **아니다.** 둘 다 `toArray()` 하나로만 읽히므로 대조할
 * 상대가 없고, 그 조건은 축1이 참조 모델과 하는 일이다(§규약1 「불변식 판별 절차」 ①).
 * 높이 차도 불변식이 아니다 — 위에 적은 대로 계약에 없는 성질이고, 균형이 깨진 구현은
 * 축3의 성장률이 잡는다.
 *
 * **연산 계약.** n 은 담긴 원소 수, k 는 `range` 가 돌려주는 원소 수다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(comparator?)` | 비교자를 고정한다. 이후 교체할 수 없다 | O(1) | worst |
 * | `insert(item)` | `item` 을 담는다. 동등한 원소가 이미 있으면 **상태가 바뀌지 않는다** | O(log n) | worst |
 * | `delete(item)` | 동등한 원소를 지우고 `true`. 없으면 `false`, 상태는 불변 | O(log n) | worst |
 * | `has(item)` | 동등한 원소가 담겨 있으면 `true` | O(log n) | worst |
 * | `min()` / `max()` | 비교자 기준 최소·최대. 비어 있으면 `null` | O(log n) | worst |
 * | `range(low, high)` | `low ≤ v ≤ high` 인 원소를 비내림차순 배열로. 사본이다 | O(log n + k) | worst |
 * | `toArray()` | 비내림차순 배열의 사본. 반환값을 고쳐도 원본은 바뀌지 않는다 | O(n) | worst |
 *
 * **물려받은 표면에서 `height()` 가 빠졌다.** 루트의 높이를 돌려주는 연산은 내부 표현을
 * 그대로 내보이는 것이고, 그것을 계약에 두면 높이를 들고 다니지 않는 구현이 전부
 * 배제된다 — 색으로 묶는 구현도, 노드에 원소를 둘까지 담는 구현도 이 계약을 못 지키게
 * 된다. 배제할 이유가 목적에 없으므로 뺐다(§규약1, 불변 사실 47). 대신 `range` 를
 * 넣었다 — 근거는 「배제하는 것이 없다」이고 `tree/redBlackTree` 헤더가 적은 것과 같다.
 *
 * **일곱 행이 전부 `worst` 인 것이 이 계약이 하는 일의 거의 전부다.** `amortized` 로
 * 적으면 조회가 트리를 고쳐 쓰는 계열이 들어오고(`tree/splayTree`), `expected` 로 적으면
 * 무작위 우선순위로 균형을 얻는 계열이 들어온다(`tree/treap`). 두 계열은 **호출 하나가
 * 튀지 않는다는 것을 약속하지 못하고**, 이 계약이 약속하려는 것이 정확히 그것이다
 * (§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」, 불변 사실 59).
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. 0 은 「동등」을 뜻하고,
 *   **동등한 두 원소는 이 집합에 함께 담기지 않는다.** 나중에 넣은 쪽이 버려지는지 앞의
 *   것을 덮는지는 계약이 약속하지 않는다 — 동등하므로 구분할 방법이 계약 안에 없다.
 * - 미제공 시 기본 비교자는 `<`·`>` 를 쓴다. 따라서 `number`·`string` 밖의 `T` 에는
 *   비교자 주입이 **필수다.**
 * - 빈 집합의 `min`·`max` 는 예외가 아니라 `null` 이다. 그 대가로 `T` 에 `null` 이 섞이면
 *   「비어 있음」과 「값이 `null` 인 원소」가 구분되지 않는다.
 * - `range(low, high)` 에서 `low > high` 면 빈 배열이다. 예외가 아니다.
 *
 * **검증 등급.** `complexity`.
 * 상한이 **어떤 자명한 구현으로도** 달성되지 않는다. 언어가 내주는 것이 둘인데 둘 다
 * 한쪽을 놓는다 — 배열은 순서를 주지만 가운데에 넣으면 뒤가 전부 밀리므로 `insert`·
 * `delete` 가 O(n) 이고, 객체(해시)는 갱신을 상수에 주지만 순서를 잃으므로 `min`·
 * `max`·`range`·`toArray` 를 상한 안에 못 한다. 둘을 함께 하려면 **담는 모양을 갱신
 * 도중에 고쳐 주는 설계**가 들어오고, 그 설계가 자명하지 않다는 것이 이 등급의 내용이다
 * (§규약1 「자명한 구현은 존재 조건이다」).
 *
 * **필요충분조건.**
 * - 의미: 순서와 유일성 중 하나라도 버리면 이 구조가 아니다. 순서를 버리면 해시 집합이고
 *   (`hash/hashSet`), 유일성을 버리면 다중집합이다(`tree/multiset`).
 * - 비용: 둘 다 지키더라도 `insert`·`delete` 가 n 에 비례하면 정렬 배열이다. 그리고
 *   **로그를 지키더라도 최악이 아니면 이 구조가 아니다** — 상각만 지키면 `splayTree`,
 *   기댓값만 지키면 `treap` 이고, 셋은 서로를 함의하지 않으므로 만족하는 구현 집합이
 *   갈린다(불변 사실 59).
 */
