/**
 * CartesianTree — 고정된 수열이 유일하게 정하는 이진 트리를, 한 번 훑는 비용에 짓는 구조.
 *
 * **목적.** 값의 수열 하나를 받아 **중위 순회가 그 수열이면서 부모의 값이 자식의 값보다
 * 비교자 기준 앞서는** 이진 트리를 세우고, 그 트리를 마디 단위로 상수 비용에 훑게 하는 것. 두 성질을 함께
 * 만족하는 트리는 수열마다 하나뿐이므로(동등한 값의 처분을 아래 주입 정책이 정한다) 이
 * 계약이 약속하는 것은 **선택이 아니라 그 하나**다.
 *
 * 수열은 **생성 시점에 정해지고 그 뒤로 바뀌지 않는다.** 이 계약에는 상태를 바꾸는 연산이
 * 하나도 없다. 값을 더하거나 지우는 일, 수열을 이어 붙이는 일은 이 계약에 없다.
 *
 * **구간을 받는 질의가 이 계약에 없다.** 이 트리에서 구간 `[l, r)` 의 최솟값이 자리 `l` 과
 * 자리 `r-1` 의 가장 가까운 공통 조상이라는 사실은 참이지만, 그 질의를 연산으로 두면 계약이 배제하는
 * 구현 집합이 통째로 달라진다 — 트리를 짓지 않고 구간 질의만 답하는 구현이 전부 들어오고,
 * 그것은 **다른 계약**이다(`range-query/` 계열). 여기서 약속하는 것은 트리 그 자체이고,
 * 구간 질의는 이 트리를 훑는 호출자의 몫이다(§규약1 「연산 집합은 계약의 결과가 아니라
 * 계약의 일부다」 — 넣을 근거가 「있으면 쓸모 있겠다」뿐이면 넣지 않는다).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도
 * 없다」 — 미결). 마디 수만큼의 자리를 쓰는 구현과 수열만 들고 있는 구현을 가르는 것은
 * 공간 조건이 아니라 아래 훑기 상한이다.
 *
 * **이름은 임시가 아니다.** 「카르테시안 트리」는 이 수학적 대상의 이름이지 트리를 짓는
 * 기법의 이름이 아니고, 이 계약에 묶인 다른 이름도 없다(불변 사실 64 의 대상이 아니다).
 * 카테고리 `tree/` 가 구현 이름인 것은 별건이다(불변 사실 66 — KAN-031).
 *
 * **불변식.** 없다.
 *
 * **상태를 바꾸는 연산이 없다는 것만으로 비는 것이 아니다.** 판별 절차(§규약1 「불변식
 * 판별 절차」)를 돌린 결과이고, 후보 셋이 모두 두 번째 물음에서 걸린다.
 *
 * - **중위 순회가 수열을 복원한다.** 「이 부분트리에 담긴 값들」을 읽는 경로가 둘이다 —
 *   `inOrder()` 와 `value()`·`left()`·`right()` 로 훑어 모으는 길. 그러나 그 정합은 각
 *   연산의 계약 줄이 이미 적고 있다: 아래 표의 네 행이 전부 **같은 하나의 트리**를 다른
 *   방향에서 읽는다고 적으므로, 대조는 축1이 참조 모델과 하는 일이다.
 * - **부모의 값이 자식의 값보다 비교자 기준 앞선다(힙 순서).** 「담긴 값」을 읽는 경로는
 *   `value()` 와 `inOrder()` 둘이므로 첫 번째 물음을 지난다. 두 번째 물음에서 걸린다 —
 *   `value()` 행이 그 값을 **「담긴 값 중 비교자 기준 최소」** 로 적고 있고, `inOrder()` 행이
 *   담긴 값을 내놓으므로, 힙 순서는 두 행의 의미에서 그대로 따라 나온다. 부모의 값이 자식
 *   부분트리의 최소보다 뒤서면 `value()` 가 자기 행을 어긴 것이지 두 연산이 갈린 것이 아니다.
 * - **`size()` 가 `inOrder()` 의 길이와 같다.** 경로가 둘이지만 두 연산의 의미가 각각
 *   「담긴 마디 수」와 「담긴 값의 배열」이라 정합이 그 둘의 논리적 귀결이다.
 *
 * 담는 모양의 성질(높이가 얼마인가, 자식의 크기가 부모와 어떻게 맞물리는가)은 불변식
 * 후보가 아니다. 계약에 적어야 검사할 수 있는데 **적는 순간 그것이 표현을 처방한다**
 * (불변 사실 36).
 *
 * 여기에 하나가 더 붙는다. 상태를 바꾸는 연산이 없으므로 축2가 볼 수 있는 상태가 생성
 * 직후 하나뿐이고, 그 하나에서 관측값들이 서로 맞는지는 축1이 이미 매 연산 대조한다.
 * **불변 구조에서는 판별 결과와 무관하게 축2가 축1보다 더 잡는 것이 없다**(불변 사실 52 ①).
 *
 * **연산 계약.** n 은 이 트리에 담긴 마디 수다. 뿌리에서는 색인한 수열의 길이와 같고
 * 부분트리에서는 그 부분트리의 크기다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(seq, comparator?)` | 길이 n 의 수열 `seq` 가 정하는 트리를 세운다. 돌아온 뒤의 질의는 아래 상한을 지킨다 | O(n) | worst |
 * | `size()` | 이 부분트리에 담긴 마디 수. 빈 트리면 0 | O(1) | worst |
 * | `value()` | 이 부분트리의 뿌리 값 — 담긴 값 중 비교자 기준 최소이고, 최소가 여럿이면 **수열에서 가장 먼저 온** 것. 빈 트리면 `null` | O(1) | worst |
 * | `left()` / `right()` | 뿌리보다 **수열에서 먼저 온** 값들의 부분트리 / 나중에 온 값들의 부분트리. 비면 `null` | O(1) | worst |
 * | `inOrder()` | 이 부분트리에 담긴 값을 **수열 순서로** 담은 배열의 사본. 뿌리에서는 색인한 수열과 같다. 반환값을 고쳐도 트리는 바뀌지 않는다 | O(n) | worst |
 *
 * **구성 시점을 계약이 정한다.** 위 표의 질의 상한은 `constructor` 가 돌아온 **뒤**에 대한
 * 것이다(불변 사실 52 ③). 적지 않으면 아무것도 안 하는 생성자와 첫 질의에서 다 짓는 구현이
 * 두 상한을 모두 만족해, 구성 상한도 질의 상한도 아무 구현을 배제하지 못한다.
 *
 * **인자 없는 질의를 구성과 묶지 않는다.** 불변 구조의 인자 없는 질의는 값이 색인 시점에
 * 이미 정해져 있어 미리 계산과 호출 때 계산이 둘 다 정당하고, 그래서 상한을 구성과 묶어
 * 적는 것이 규격이다(불변 사실 52 ②). `size()`·`value()` 는 그 규격의 대상이 **아니다** —
 * 인자가 표면에서 안 보일 뿐 `left()`·`right()` 가 돌려주는 객체가 인자 자리를 나르고 있고,
 * 그래서 이 둘은 **마디마다 한 번씩 n 번 불린다.** 호출 때 계산하는 구현은 마디 하나를
 * 읽는 데 그 부분트리를 훑게 되어 훑기 전체가 이차가 되므로, 「둘 다 정당하다」가 성립하지
 * 않는다. §규약1 「불변 구조」 표의 셋째 줄(`at`·`rankOf`)과 같은 자리다.
 *
 * **구성 상한 `O(n)` 은 고른 값이 아니다 — 하한이 지목한다.** 수열의 어느 한 자리를 읽지
 * 않고 트리를 정할 수는 없다. 안 읽은 자리의 값을 바꾸면 트리가 달라지기 때문이고, 그래서
 * 어떤 구현도 $\Omega(n)$ 을 쓴다. 더 강하게 적을 자리가 없다는 뜻이다.
 *
 * **이 하한은 아래 주입 정책의 「생성자가 돌아온 뒤 호출자가 배열을 고쳐도 트리는 바뀌지
 * 않는다」에 기대고 있다.** 그 조항이 없으면 배열 참조만 들고 첫 질의까지 아무것도 안 하는
 * 구현이 생성자를 $O(1)$ 에 끝내므로 하한이 서지 않는다. 두 조항이 한 몸이다.
 *
 * 더 약하게 — 이를테면 정렬 계급으로 — 적으면 **구간 최솟값 색인을 먼저 $O(n\log n)$ 에 짓고
 * 그 위에서 자리마다 최솟값을 찾아 나누는 구현**이 들어온다. 그 순간 이 계약이 「수열을 한 번
 * 훑는 비용에 짓는다」를 진술하지 못한다. 그것이 이 구조를 따로 둘 이유이므로 계약이 뜻을
 * 잃는다(§규약1 「약한 쪽 규칙은 상한으로 확장되지 않는다」의 양쪽 조이기). **B12 형이고
 * B13 형이 아니다** — 후보가 여럿 남아 정본이 고른 것이 아니라 하한이 값을 지목했다
 * (불변 사실 48·51).
 *
 * **훑기 상한 `O(1)` 이 배제하는 것.** 수열만 들고 물을 때마다 구간의 최솟값을 다시 찾는
 * 구현이 여기서 걸린다. 그 구현도 위 표 다섯 행의 **값**은 전부 옳게 내놓는다 — 갈리는 것은
 * 비용뿐이고, 그래서 이 한 줄이 이 계약이 수열 그대로와 다른 유일한 자리다.
 *
 * **여섯 연산이 모두 `worst` 인 근거.** `worst` 는 셋 중 **가장 강한** 한정자이므로(불변 사실 59)
 * 적으려면 그것이 배제하는 계열을 배제해도 계약이 잃는 것이 없어야 한다. 배제되는 계열은
 * 둘이고 이 계약에는 둘 다 없다 — ① 비용을 뒤 호출로 미루는 계열은 **상태를 바꾸는 연산이
 * 있어야** 성립하는데 이 계약에는 하나도 없다. ② 무작위성으로 상한을 얻는 계열은 답이 입력의
 * 함수로 유일하게 정해지는 자리에서는 아무것도 덜 하지 못한다. 상태가 하나뿐인 구조에서
 * `amortized` 나 `expected` 를 적는 것은 약하게 적는 것이 아니라 **아무것도 다르게 배제하지
 * 않으면서 상한을 흐리는 것**이다.
 *
 * **주입 정책.**
 * - `comparator(a, b)` 는 음수·0·양수를 돌려주는 전순서여야 한다. 미제공 시 기본 비교자는
 *   `<`·`>` 를 쓴다. 따라서 `number`·`string` 밖의 `T` 에는 비교자 주입이 **필수다.**
 * - 서로 견줄 수 없는 값이 섞이면 전순서가 아니다. 기본 비교자는 `NaN` 에 대해 `<`·`>` 가
 *   둘 다 거짓이라 「동등」으로 답하므로, 그 수열에서는 트리의 유일성부터 서지 않는다.
 *   계약이 요구하는 것은 전순서이고, 그것을 어긴 입력에 대한 약속은 이 계약에 없다.
 * - **동등한 값이 여럿이면 수열에서 먼저 온 자리가 조상이 된다.** 이것이 계약의 문장인 이유는
 *   그 처분이 관측되기 때문이다 — 수열 `[1, 1]` 에서 앞을 조상으로 두면 뿌리의 `right()` 가
 *   차고 뒤를 조상으로 두면 `left()` 가 찬다. 정하지 않으면 두 트리가 같은 `inOrder()` 를
 *   내놓으면서 `left()`·`right()` 만 갈리고, 그때 계약은 무엇을 돌려줄지 말하지 않은 채
 *   돌려주기를 요구하는 것이 된다.
 * - 생성자는 받은 수열을 **읽기만 한다.** 돌아온 뒤 호출자가 그 배열을 고쳐도 트리는 바뀌지
 *   않는다. `inOrder()` 가 돌려주는 배열도 사본이라 같은 방향으로 새지 않는다.
 * - 빈 트리에서 `value()`·`left()`·`right()` 는 예외가 아니라 `null` 이다. 그 대가로 `T` 에
 *   `null` 이 섞이면 「없음」과 「값이 `null` 인 마디」가 구분되지 않는다.
 *
 * **검증 등급.** `complexity`.
 * 판정 절차를 위에서 아래로 읽는다(§규약1 「검증 등급 4종」). 동시 접근이 없고, **상한이
 * 어떤 자명한 구현으로도 달성되지 않는다.** 자명하게 지으면 구간의 최솟값을 찾아 좌우로
 * 나누기를 되풀이하게 되는데, 그 나눔은 이미 정렬된 수열에서 한쪽으로만 몰려 $\Theta(n^2)$
 * 이다. 나누지 않고 수열을 든 채 물을 때마다 최솟값을 찾으면 구성은 선형이지만 훑기가
 * 선형이 된다. 남는 길은 오른쪽 경계를 자리로 들고 한 번 훑는 것 하나인데, 그 선형은
 * 안쪽 반복의 회수를 따로 묶어서는 나오지 않고 **자리 하나가 들어가고 나오는 횟수를 수열
 * 전체에 걸쳐 합해야** 나온다. 셋 다 「자명한 구현」의 정의 밖이다. 불변식 절이 비었지만
 * 등급은 그 아래 단계에서 정해지지 않는다(`linear/deque` 와 같은 자리).
 *
 * **이 총합 논증을 상각이라 부르지 않는다.** 재는 것이 `constructor` **한 호출 안쪽**의
 * 총비용이고, 그 값이 어떤 수열에서도 선형이라 한정자는 `worst` 다. 상각은 호출 하나의
 * 비용을 여러 호출에 나눠 갚을 때 쓰는 말인데 여기에는 나눠 갚을 상대가 없다. 등급 판정이
 * 이 논증을 「자명하지 않다」로 치는 이유는 상각이어서가 아니라 **상한이 코드를 국소적으로
 * 읽어서는 안 나오기 때문**이다.
 *
 * **필요충분조건.**
 * - 의미: 중위 순회가 수열을 복원하는 것과 부모의 값이 자식의 값보다 비교자 기준 앞서는 것,
 *   둘 중 하나를 버리면 이 구조가 아니다. 앞을 버리면 수열의 값으로 지은 그냥 힙이고, 뒤를 버리면 수열을 담은
 *   아무 이진 트리다. 동등한 값의 처분까지 정해야 트리가 하나로 정해진다.
 * - 비용: 두 성질을 다 지키더라도 **구성이 수열 길이를 넘거나 마디 훑기가 상수를 넘으면**
 *   이 구조가 아니다. 물을 때마다 구간의 최솟값을 다시 찾는 것이고, 그때 남는 것은 수열
 *   그대로다 — 트리를 미리 세운다는 말이 그 자리에서 뜻을 잃는다.
 */
