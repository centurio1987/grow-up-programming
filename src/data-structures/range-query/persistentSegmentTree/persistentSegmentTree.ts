/**
 * PersistentSegmentTree — 자리 하나를 고칠 때마다 새 버전을 짓고, 지은 어느 버전이든 임의 구간을 주입받은 결합으로 접어 읽는 일을 로그 비용에 두는 수열.
 *
 * **목적.** 자리 수를 생성 시점에 고정한 수열의 **버전들**을 두고, **이미 지은 어느 버전에서든 자리 하나만 바꾼 새 버전을
 * 짓는 일**과 **어느 버전의 임의 구간을 접어 읽는 일**을 둘 다 자리 수의 로그 비용으로 제공하는 것. 지은 버전은 전부
 * 그대로 남고, 비용이 **지금까지 지은 버전의 수와 무관하다**는 것이 계약의 내용이다.
 *
 * **`range-query/segmentTree` 를 담는다 — 진부분이다.** 두 방향을 다 실행해 확인했다
 * (`src/data-structures/_contract/runContract.persistentSegmentTree.test.ts` 넷째 묶음).
 *
 * - **이쪽 구현은 저쪽을 지킨다.** 마지막으로 받은 버전 번호 하나를 드는 껍데기만 씌우면(고치기는 그 버전에서 짓고 번호를
 *   바꾸기, 묻기는 그 버전에 묻기) 저쪽 스위트의 경계 케이스 · 무작위 시퀀스 · 시나리오 셋(21 · 25 · 29 / 30 · 36 · 42 /
 *   55 · 67 · 79)을 전부 통과한다. 껍데기는 결합에 기대지 않는다.
 * - **저쪽 구현은 이쪽을 못 지킨다.** 저쪽 정본을 제자리에서 고치고 번호만 세는 구현(`_contract/_fixtures/latestOnlyPersistentFold.ts`)이
 *   이쪽 첫 경계 케이스의 셋째 걸음(옛 버전을 묻는 자리)에서 관측 7 / 모델 0 으로 갈린다. **포섭은 「같다」가 아니라
 *   「다르다」의 증거다**(불변 사실 43).
 *
 * **공간은 이 계약에 들어오는 만큼만 들어온다**(불변 사실 67 · §「공간 제약이 계약에 들어오는 자리」의 세 걸음).
 *
 * 1. **계약의 용어로** — 「지은 버전은 전부 끝까지 물을 수 있다」.
 * 2. **그 문장이 되는 행** — `update` 행의 「이미 있는 버전은 어느 것도 바뀌지 않는다」와 `query` 행의 버전 인자.
 * 3. **그 제약을 무시하는 구현을 축1이 갈라내는가** — 그렇다(위 둘째 반례). 그래서 계약이 갈린다.
 *
 * **버전 하나가 얼마나 차지하는지는 계약에 없다**(§규약1 「공간은 어느 계약에도 없다」 — 미결). 갱신이 호출마다 로그 안이면
 * 한 호출이 새로 적는 자리도 그만큼으로 묶이지만, 그것은 §규약2 계측 단위(지나간 수)를 정직하게 셀 때의 논증이고 저장량을
 * 재는 축은 없다.
 *
 * **이 계약에 없는 것.**
 * - **버전 지우기 · 두 버전 합치기.** 지은 버전은 구조가 사는 동안 전부 남는다.
 * - **구간을 한 번에 고치기** — `range-query/segmentTreeLazy` 의 계약이다.
 * - **자리를 넣고 빼기.** `n` 은 미리 정해진 자리의 수이고 모든 버전이 같다.
 * - **지은 버전의 수를 묻기.** 번호가 지은 차례라 호출자가 받은 번호로 이미 안다(아래 「물려받은 표면」).
 *
 * **이 이름은 계약을 정당화하지 않는다.** 계약의 어느 문장도 마디를 나눠 쓰라고 적지 않는다. 이름이 가리키는 기법은 이
 * 계약이 배제하지 않기로 한 계열의 대표일 뿐이고, 계약 이름을 다시 붙이는 일은 KAN-031 의 몫이다.
 *
 * **불변식.** 없다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과이고, 후보가 넷이었다.
 *
 * - **「구간을 둘로 쪼개 접으면 통째 구간과 같다」** — 그 값을 읽는 공개 연산이 `query` 하나라 첫 물음에서 걸린다
 *   (`range-query/segmentTree` 와 같다).
 * - **「옛 버전의 답은 뒤 갱신으로 바뀌지 않는다」** — 두 상태에 걸친 성질이고, `update` 행이 「이미 있는 버전은 어느 것도
 *   바뀌지 않는다」로 이미 적는다. 둘째 물음에서 그 연산의 의미가 되고 축1이 매 연산 대조한다.
 * - **「버전 수는 받아들여진 갱신 수 + 1」** — 버전 수를 읽는 경로가 `update` 의 반환값 하나라 첫 물음에서 걸린다.
 * - **담는 모양의 성질**(버전 사이에 무엇을 나눠 쓰는가)은 후보가 아니다. 적는 순간 표현을 처방한다(불변 사실 36).
 *
 * **연산 계약.** n 은 생성자가 고정한 **자리 수**(`values.length`)다. **지은 버전의 수는 어느 상한에도 없다** — 그것이
 * 계약의 내용이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(values, combine, identity)` | 버전 `0` 을 짓는다 — 자리 `0` 부터 `n-1` 까지가 `values` 의 값이다. 돌아온 뒤 호출자가 `values` 를 고쳐도 버전 `0` 은 바뀌지 않는다 | O(n) | worst |
 * | `update(version, i, value)` | 버전 `version` 과 자리 `i` 만 다르고 그 자리가 `value` 인 **새 버전**을 짓고 그 번호를 돌려준다. 번호는 **지은 차례**다 — 생성자의 버전이 `0` 이고 받아들여진 `update` 마다 1 씩 는다. 이미 있는 버전은 어느 것도 바뀌지 않는다 | O(log n) | worst |
 * | `query(version, from, to)` | 버전 `version` 의 자리 `from` 이상 `to` 미만을 **왼쪽에서 오른쪽으로** `combine` 으로 접은 값. `from === to` 면 `identity` | O(log n) | worst |
 *
 * **상한에 버전 수가 없어서 배제되는 계열이 둘이다.** 스위트가 자리 수만큼 버전을 한 줄로 쌓고 첫 버전과 사슬 끝을 번갈아
 * 가리키면 둘 다 사슬 길이를 따라 자란다.
 *
 * - **바뀐 자리만 적어 두고 물을 때 조상 버전을 거슬러 모으는 구현**(`_contract/_fixtures/replayingPersistentFold.ts`) — 갱신은
 *   상수이고 질의가 4,092 · 16,380 · 65,532 로 걸린다.
 * - **살아 있는 구조 하나를 버전 사이로 옮겨 다니는 구현**(`_contract/_fixtures/rerootingPersistentFold.ts`) — 가까운 버전을
 *   이어 쓰면 정본과 같은 계급이고, 먼 버전을 번갈아 쓰면 갱신 22,905 · 106,941 · 492,033 · 질의 22,565 · 106,541 ·
 *   491,573 으로 걸린다.
 *
 * **번호를 계약이 정한다.** 정하는 일이 계급을 바꾸지 않고(받아들인 호출을 세는 상수 하나) 표현을 처방하지도 않는다(호출
 * 이력만으로 정해진다) — §「분할을 담는 계약은 대표를 분할만으로 정해지는 값으로 정한다」의 표에서 둘 다 「아니다」다.
 * 정하지 않으면 참조 모델이 기대할 번호가 없어 버전을 가리키는 인자를 축1이 재지 못한다.
 *
 * **상한 `O(log n)` 은 정본이 서는 계급으로 골랐다**(불변 사실 51).
 *
 * - **`O(n)` 은 계약이 뜻을 잃는다.** 버전마다 자리 값 배열의 사본을 지으면 그 상한이 나온다(축1 참조 모델이 그 모양이다).
 * - **`O(sqrt n)` 은 남는 후보이고 하한이 아니다.** 자리를 묶음으로 나눠 바뀐 묶음만 새로 짓는 구현이 그 상한에 들 것이고
 *   사본은 여전히 배제된다 — 짓지 않았다. 목적이 이 계열을 자르지 못하므로 정본이 서는 계급을 적는다.
 * - **`O(1)` 은 만족하는 구현을 찾지 못했고, 없다는 것을 보이지도 않았다**(불변 사실 165).
 *
 * **상한이 세는 것은 주입된 결합을 부른 횟수다**(`segmentTree` 와 같다). 한 번이 얼마나 비싼지는 주입자가 정한다.
 *
 * **두 행이 `worst` 인 것.** 강한 쪽을 적는 조건 둘(불변 사실 59 · §「한정자의 강한 읽기는 축이 그 강함을 잴 때만 적는다」)을
 * 둘 다 채운다.
 *
 * - **추가로 배제되는 계열은 갱신을 적어만 두었다가 그 버전을 처음 물을 때 한꺼번에 짓는 계열이다**
 *   (`_contract/_fixtures/bufferedPersistentFold.ts`). 버전 n 개를 한 줄로 쌓는 갱신 n 번과 질의 n 번을 전부 재면 단일 호출
 *   최대가 22,583 · 106,563 · 491,599 로 걸리고 호출 평균은 39 · 47 · 55 로 통과한다. **정본이 두 행을 호출마다 지키므로
 *   (21 · 25 · 29 / 55 · 67 · 79) 그 계열을 배제해도 잃는 것이 없다**(`range-query/segmentTreeLazy` 의 같은 근거).
 * - 축3의 `worst` 통계(단일 호출 최대)가 그 강함을 잰다 — 스위트의 질의 시나리오에서 그 계열이 걸린다.
 * - `constructor` 는 n 에 대해 반복 호출되지 않아 강한 한정자를 적는 대가가 없고 축3도 재지 않는다(§규약2 시나리오 규칙 2 — 면제).
 *
 * **주입 정책.**
 *
 * - **결합과 그 항등원을 생성자로 받는다.** `range-query/segmentTree` 가 연 근거(닫으면 · 가환군으로 좁혀 열면 · 모노이드보다
 *   넓게 열면 — §「주입 정책도 상한과 같은 두 물음으로 정한다」)를 그대로 물었고 답도 같다. **버전이 주입 정책에 새로
 *   더하는 물음은 없다** — 버전은 어느 수열을 접는지를 고를 뿐 접는 방법을 바꾸지 않는다.
 * - **결합법칙과 항등원은 주입자의 의무다.** 계약이 접는 차례를 정하지 않으므로 답이 하나로 정해지려면 결합이 결합적이어야
 *   하고, `identity` 는 값의 정의역 안에서 실제로 항등원이어야 한다. **교환법칙은 요구하지 않는다** — 자리 순서를 계약이
 *   고정한다(`segmentTree` 와 같다).
 * - **버전 번호가 정수가 아니거나 아직 짓지 않은 번호면 두 연산 모두 `RangeError` 를 던진다.** 자리 번호 · 구간 경계가 범위
 *   밖이거나 `from > to` 인 것도 같다. **던진 `update` 는 버전을 짓지 않는다** — 다음 받아들여진 갱신의 번호가 그대로다.
 *   값으로 답하지 않는 이유는 `segmentTree` 와 같은 판별이다(불변 사실 82) — 반환 타입에 「그런 버전은 없다」를 담을 자리가 없다.
 * - **`values` 가 빈 배열인 것은 정당하다.** 버전은 `0` 하나뿐이고 부를 수 있는 것은 `query(0, 0, 0)` 하나다.
 * - **생성자는 `values` 를 읽기만 한다** — 돌아온 뒤의 수정이 버전 `0` 을 바꾸면 「이미 있는 버전은 바뀌지 않는다」가 깨진다.
 *
 * **물려받은 표면을 다섯 고쳤다.** 물려받은 상한 주장(`update`·`query` `O(log n)` · 공간 `O((n + v) log n)`)은 판정 입력으로 쓰지
 * 않았다(불변 사실 65) — 공간 줄은 위 「공간」 문단대로 계약에 없다.
 *
 * - **주입을 열었다** — 합 고정을 결합 · 항등원 주입으로(`segmentTree` 와 같다).
 * - **닫힌 구간 → 반열린 구간.** 빈 구간을 값으로 적어야 항등원 요구가 관측된다(불변 사실 170).
 * - **`versionCount()` 를 뺐다.** 번호가 지은 차례라 호출자가 받은 번호로 이미 알고, 그 연산이 없어도 목적이 진술된다
 *   (불변 사실 47 — `disjoint-set/disjointSetRollback` 이 `groupCount` 를 뺀 것과 같은 판별).
 * - **내부 표면을 걷었다** — 마디 타입 · 뿌리 배열 필드(불변 사실 20)와 「경로의 마디만 복사」 처방.
 * - **스토리 · 크기 제약 · 벽시계 성능 시험을 뺐다**(불변 사실 7·38). 범위 밖 인자를 `RangeError` 로 적었다.
 *
 * **검증 등급.** `complexity`.
 * 두 행을 **함께** 만족하는 자명한 구현이 없다. 배열로 적는 길이 셋이고 전부 한쪽을 놓는다.
 *
 * - **버전마다 배열 사본을 지으면** 갱신이 자리 수에 비례한다.
 * - **바뀐 자리만 적어 두면** 갱신이 상수인 대신 질의가 조상 버전의 사슬 길이 + 구간 폭이다(위 수치).
 * - **버전마다 모든 구간의 답을 미리 접어 두면** 질의가 상수인 대신 갱신이 자리 수의 제곱이다.
 *
 * 두 행을 함께 로그 안에 두려면 **버전 사이에 안 바뀐 부분을 나눠 쓰면서** 서로 다른 길이의 구간을 접어 두는 설계가
 * 들어와야 하고, 그것은 배열의 기본 연산에서 나오지 않는다.
 *
 * **필요충분조건.**
 * - 의미: 어느 버전에서든 자리 하나를 바꾼 새 버전을 짓는 일, 그리고 **지은 어느 버전이든** 임의 구간을 주입받은 결합으로
 *   접어 읽는 일. 옛 버전을 버리면 `range-query/segmentTree` 이고(위 둘째 반례), 새 버전을 짓지 않으면 한 번 짓고 묻기만 하는
 *   표다.
 * - 비용: 둘 다 지키더라도 **한쪽이 자리 수나 지은 버전의 수에 비례하면** 이 구조가 아니다 — 버전마다 사본이거나, 적어 둔
 *   것을 다시 모으거나, 살아 있는 하나를 옮겨 다니는 구현이다. 호출열 평균으로만 로그이고 한 호출이 쌓인 갱신 수에 비례하면
 *   짓기를 미루는 계열이고 그것도 이 계약이 아니다. 이 계약이 요구하는 것은 **둘을 호출마다** 로그 안에 두는 것이다.
 */
export class PersistentSegmentTree {
  constructor(
    values: number[],
    combine: (a: number, b: number) => number,
    identity: number,
  ) {
    throw new Error("Not implemented");
  }

  update(version: number, i: number, value: number): number {
    throw new Error("Not implemented");
  }

  query(version: number, from: number, to: number): number {
    throw new Error("Not implemented");
  }
}
