/**
 * FenwickTree — 자리 하나를 고치는 일과 앞에서부터 이어진 자리들의 합을 함께 로그 비용에 두는 표.
 *
 * **목적.** 자리 수를 생성 시점에 고정한 수 표 하나를 두고, **자리 하나의 값을 고치는 일**과
 * **앞에서부터 이어진 자리들의 합을 읽는 일**을 둘 다 자리 수의 로그 비용으로 제공하는 것.
 * 두 일을 **함께** 그 비용에 두는 것이 계약의 내용이다 — 하나만 필요하면 배열 하나로 끝나고,
 * 그때 이 구조를 쓸 이유를 계약이 말하지 못한다.
 *
 * **`range-query/segmentTree` 와 갈리는 자리는 접는 연산 하나다.** 저쪽 계약은 **임의의
 * 결합**으로 구간을 접는 일을 요구하고(최솟값·최대값·곱), 이 계약은 **덧셈** 하나만 요구한다.
 * 반례는 계약의 용어만으로 적힌다 — **구간의 답을 두 앞구간의 차로 내는 구현**은 아래 표의 네
 * 행을 전부 지키고, 최솟값을 접는 계약은 지키지 못한다. 최솟값에는 되돌리는 값이 없어 「전체에서
 * 앞을 뺀다」가 성립하지 않기 때문이다. 이 반례는 정본을 읽어서 나온 것이 아니라 **덧셈에
 * 되돌리는 값이 있다는 계약의 성질**에서 나온다(불변 사실 43 — 반례를 정본에서 찾지 않는다).
 * 반대 방향은 담긴다: 임의의 결합을 접을 수 있으면 덧셈도 접을 수 있으므로 저쪽 계약을 만족하는
 * 구현은 이 계약도 만족한다. **포섭은 「같다」가 아니라 「다르다」의 증거다** — 더 많이 약속하는
 * 계약이 더 적은 구현을 남긴다.
 *
 * **구간을 한 번에 고치는 일은 이 계약에 없다.** 여기서 고치는 것은 자리 하나이고, `k` 개
 * 자리를 고치려면 호출이 `k` 번이다. 구간을 통째로 고치는 연산을 넣으면 배제하는 구현 집합이
 * 통째로 달라진다 — 고치는 일을 표시만 해 두었다가 나중에 내려보내는 설계가 새로 요구되고,
 * 자리 하나씩만 고칠 줄 아는 구현이 전부 나간다. 그것은 `range-query/segmentTreeLazy` 가
 * 받는 계약이다.
 *
 * **자리를 넣고 빼는 일도, 지난 상태를 다시 묻는 일도 이 계약에 없다.** 자리 수는 생성자가
 * 정하고 그 뒤로 바뀌지 않으므로 `n` 은 담긴 원소 수가 아니라 **미리 정해진 자리의 수**이고,
 * 값이 `0` 인 자리도 자리다. 지난 상태를 되묻는 것은 `range-query/persistentSegmentTree` 의
 * 계약이다.
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없으므로 자리 수보다 훨씬 많은 자리를
 * 쓰는 구현도 이 계약을 지킨다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 *
 * **이 이름은 계약을 정당화하지 않는다.** 계약의 어느 문장도 비트나 겹쳐 둔 칸을 말하지 않고,
 * 말할 수 없다 — 명세는 내부 표현을 처방하지 않는다. 자리들을 이진 트리의 잎에 놓고 마디마다
 * 부분합을 들고 있는 구현도 네 행을 전부 지킨다. 이름이 가리키는 기법은 **이 계약이 배제하지
 * 않기로 한 계열**의 대표일 뿐이고, 계약 이름을 다시 붙이는 일은 KAN-031 의 몫이다.
 *
 * **불변식.** 하나다.
 *
 * 1. **앞구간과 구간이 갈리지 않는다.** `0 <= from <= to <= n` 인 어떤 `from`·`to` 에
 *    대해서도 `prefixSum(from) + rangeSum(from, to)` 와 `prefixSum(to)` 가 같다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 「자리 `from` 이상 `to` 미만의 합」을
 * 읽는 경로가 둘이라(`rangeSum` 하나와 두 앞구간의 차) 첫 번째 물음을 지나고, **두 번째
 * 물음에서 남는다** — 아래 표의 어느 행도 둘이 같아야 한다고 적지 않는다. 두 행은 각자 자기가
 * 무엇의 합인지만 적는다. 두 질의를 따로 유지하는 구현이 정확히 여기서 갈리고, 갈리기 전까지
 * 두 연산은 각자 자기 자리에서 옳다. `tree/multiset` 의 최소를 읽는 경로 둘과 같은 자리다.
 *
 * 후보였다가 빠진 것이 둘이다.
 *
 * - **「고친 만큼 앞구간이 는다」** — 갱신 전후 두 상태에 걸친 성질이라 상태의 성질이 아니고,
 *   `update` 행과 `prefixSum` 행의 의미에서 그대로 따라 나온다. 축1의 몫이다.
 * - **담는 모양의 성질**(어느 값이 어느 칸에 몇 번 겹쳐 들어가 있는가)은 후보가 아니다.
 *   계약에 적어야 검사할 수 있는데 **적는 순간 그것이 표현을 처방한다**(불변 사실 36).
 *
 * **연산 계약.** n 은 생성자가 고정한 **자리 수**다. 담긴 원소 수가 아니라 미리 정해진 자리의
 * 수이고, 구조가 사는 동안 바뀌지 않는다. 값이 `0` 인 자리가 아무리 많아도 상한은 n 으로 적는다
 * — 호출자가 어느 자리를 만질지 계약이 알지 못한다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(n)` | 자리 `0`부터 `n-1`까지를 값 `0` 으로 둔다 | O(n) | worst |
 * | `update(i, delta)` | 자리 `i` 의 값에 `delta` 를 더한다 | O(log n) | worst |
 * | `prefixSum(i)` | 앞의 `i` 개 자리(`0` 이상 `i` 미만)에 담긴 값의 합. `i === 0` 이면 `0` | O(log n) | worst |
 * | `rangeSum(from, to)` | 자리 `from` 이상 `to` 미만에 담긴 값의 합. `from === to` 면 `0` | O(log n) | worst |
 *
 * **앞구간을 길이로 적은 것은 경계를 하나로 두기 위해서다.** `prefixSum` 의 인자는 자리 번호가
 * 아니라 **개수**이므로 `[0, n]` 을 받고, 그래서 「앞이 하나도 없다」와 「전부」가 둘 다 값
 * 하나로 적힌다. `rangeSum` 의 두 인자도 같은 눈금이라 `rangeSum(0, i)` 와 `prefixSum(i)` 가
 * 같은 것을 묻는다 — 위 불변식이 그 정합이다.
 *
 * **상한을 `O(log n)` 으로 적은 것은 고른 것이다.** 목적에서 유일하게 따라 나오지 않는다
 * (§규약1 「상한이 목적에서 유일하게 따라 나오지 않는 계약이 있다」). 축3 사다리가 고를 수 있게
 * 두는 값 중 셋을 보고 하나를 골랐다.
 *
 * - **`O(n)` 은 계약이 뜻을 잃는다.** 값을 그대로 적어 두고 물을 때마다 앞을 훑으면 그 상한이
 *   나오고, 그것이 상한이면 배열 하나와 달라지는 것이 없다.
 * - **`O(1)` 은 만족하는 구현을 못 찾았다.** 고치기와 앞구간 읽기를 **둘 다** 상수에 두는
 *   구현을 이 카드가 찾지 못했다. 있는지 모르는 값을 상한으로 적으면 계약이 아니라 미해결
 *   문제를 적는 것이 된다.
 * - **`O(sqrt n)` 은 남는 후보이고 하한이 아니다.** 자리를 $\sqrt n$ 개씩 묶고 묶음마다 합을
 *   하나씩 들면 고치기도 질의도 그 안에 들어오므로, 그 상한을 적어도 배열은 여전히 배제된다.
 *   **목적이 이 계열을 자르지 못한다.** 그러므로 여기서는 정본이 서는 계급을 적는다
 *   (§규약2 「축3은 상한이 아니라 성장 계급을 판정한다」가 그것을 요구한다 — 계약의 상한이
 *   정본의 계급과 어긋나면 정본이 자기 스위트에서 걸린다).
 *
 * 순환이 아니다: 목적이 후보를 선형 아래로 자르고, 그 안에서 하나를 고르는 일만 정본이 한다.
 * **이 선택이 배제하는 계열은 묶음으로 나누는 구현 전부**이고, 그 배제는 축3에 실제로 보인다
 * (`_contract/_fixtures/blockedPrefixSums.ts` 의 앞구간 질의가 62 → 126 → 254 로 $r$ = 2.03 ·
 * 2.02, `O(log n)` 의 허용 상단 1.56 밖이다).
 *
 * **한정자가 넷 다 `worst` 인 것은 배제될 계열이 없기 때문이다.** `worst` 는 셋 중 가장 강하므로
 * (불변 사실 59) 적으려면 그것이 배제하는 계열을 배제해도 계약이 잃는 것이 없어야 한다. 배제되는
 * 계열이 둘인데 둘 다 이 계약에서 얻을 것이 없다.
 *
 * - **비용을 뒤 호출로 미루는 계열**(`amortized`)은 미룬 것을 갚을 자리가 있어야 성립하고, 그
 *   자리는 **담는 모양이 호출에 따라 나빠질 때** 생긴다. 여기서는 자리 수가 생성자에 고정되고
 *   자리의 순서도 처음부터 정해져 있어, 호출이 바꾸는 것은 값뿐이고 모양은 그대로다.
 * - **무작위로 상한을 얻는 계열**(`expected`)이 하는 일은 호출자가 고를 수 있는 나쁜 모양을
 *   흩는 것인데, 호출자가 고를 수 있는 것이 자리 번호와 값뿐이고 그 둘이 모양을 바꾸지 못한다.
 *   자리들을 무작위 높이로 이어 두는 구현을 지을 수는 있으나, 그 무작위가 사 오는 것이 없다.
 *
 * `constructor` 는 셋째 이유로 `worst` 다 — n 에 대해 반복 호출되지 않으므로 강한 한정자를
 * 적는 대가가 없고, 그래서 축3도 이 행을 재지 않는다(§규약2 축3 면제).
 *
 * **주입 정책.**
 * - **주입받는 것이 없다. 접는 연산을 열지 않는 것이 이 계약의 내용이다.** 두 방향 다 대가가
 *   있고, 양쪽을 보고 닫는 쪽을 골랐다.
 *   - **임의의 결합을 열면** 되돌리는 값이 없는 결합이 들어오고, 구간을 두 앞구간의 **차**로
 *     답하는 구현이 전부 나간다. 배제한 적 없는 계열을 통째로 배제하는 것이고, 그렇게 적은
 *     계약은 이미 `range-query/segmentTree` 의 것이다.
 *   - **가환군만 받도록 좁혀 열면**(더하기·되돌리기·항등원을 함께 주입받는 형태) 위 문제는
 *     없지만 이번에는 **수의 덧셈 하나만 아는 구현**이 나간다. 배제할 이유가 목적에 없으므로
 *     강하게 적지 않는다(불변 사실 51 의 두 번째 물음과 같은 판정).
 * - **값은 정수다.** `delta` 가 정수가 아니거나 유한하지 않으면 `RangeError` 를 던진다. 이
 *   계약의 어느 줄도 **더하는 순서**를 정하지 않고, 정하면 그것이 처방이다. 순서를 정하지
 *   않고도 답이 하나로 정해지려면 덧셈이 결합적이어야 하는데 **부동소수 덧셈은 결합적이지
 *   않다** — `(0.1 + 0.2) + 0.3` 은 `0.6000000000000001` 이고 `0.1 + (0.2 + 0.3)` 은 `0.6` 이다
 *   (실행해 확인했다). 실수를 허용하면 「같은 답」이 정의되지 않는다.
 * - **합이 안전 정수 범위 안에 있는 것은 호출자의 의무다.** 넘으면 정수 덧셈도 결합성을 잃어
 *   위와 같은 자리가 된다. 계약이 막지 않는 이유는 막으려면 부분합마다 검사해야 하고, 무엇이
 *   부분합인지가 곧 더하는 순서라서 그 검사가 처방이 되기 때문이다.
 * - **자리 번호와 앞구간 길이가 범위 밖이면 세 연산 모두 `RangeError` 를 던진다.** 값으로
 *   답하지 않는 이유는 **반환 타입에 「그런 자리는 없다」를 담을 자리가 없기 때문이다** —
 *   `0` 을 돌려주면 「그 자리들의 합이 0 이다」로 읽혀 잘못된 색인이 조용히 지나간다.
 *   `rangeSum(from, to)` 의 `from > to` 도 같다(불변 사실 82 의 판별. 반환 타입에 자리가 있는
 *   계약은 다르게 고른다 — `trie/suffixArray` 의 범위 밖 접근은 `null` 이다).
 * - **`n` 은 0 이상의 정수여야 하고, 아니면 `RangeError` 다.** `n === 0` 은 정당하다 — 자리가
 *   없는 표이고, 그 뒤로 부를 수 있는 것은 `prefixSum(0)` 과 `rangeSum(0, 0)` 뿐이다.
 *
 * **검증 등급.** `complexity`.
 * 네 행을 **함께** 만족하는 자명한 구현이 없다. 언어가 내주는 배열·객체로 적는 길이 셋이고
 * 셋 다 한쪽을 놓는다.
 * - **값을 그대로 적어 두면** 고치기가 상수인 대신 앞구간이 앞자리 수에 비례한다.
 * - **앞구간 합을 미리 다 적어 두면** 질의가 상수인 대신 고치기가 뒤 자리 수에 비례한다.
 *   뒤에서부터 접어 두어도 방향만 바뀌고 같다 — 그때는 **앞자리**를 고치는 것이 최악이다.
 * - **둘을 함께 들어도** 고치기가 두 표를 다 손봐야 하므로 뒤엣것의 약점이 그대로 남는다.
 *
 * 네 행을 함께 로그 안에 두려면 값 하나가 서로 다른 길이의 답에 함께 쓰이도록 **미리 겹쳐
 * 접어 두는** 설계가 들어와야 하고, 그것은 배열의 기본 연산에서 나오지 않는다.
 *
 * **필요충분조건.**
 * - 의미: 자리 하나를 고치는 일과 앞에서부터 이어진 자리들의 합을 읽는 일 중 하나라도 버리면
 *   이 구조가 아니다. 고치기를 버리면 한 번 짓고 마는 누적합 표이고, 합 읽기를 버리면 그냥
 *   배열이다. 그리고 답이 **덧셈 하나에 대해** 나오는 것까지가 이 계약이다 — 임의의 결합에
 *   대해 답해야 하면 더 많이 약속하는 다른 계약이고(`range-query/segmentTree`), 그 약속을
 *   지우지 않으면 두 앞구간의 차로 답하는 구현을 이 계약이 배제하게 된다.
 * - 비용: 셋을 다 지키더라도 **한쪽이 자리 수에 비례하면** 이 구조가 아니다. 고치기를 상수로
 *   두고 질의를 선형에 두면 값 배열이고, 질의를 상수로 두고 고치기를 선형에 두면 누적합 표다.
 *   둘 다 자리 수의 제곱근이면 묶음 표이고 그것도 이 계약이 아니다. 이 계약이 요구하는 것은
 *   **둘을 함께** 로그 안에 두는 것이다.
 */
export class FenwickTree {
  constructor(n: number) {
    throw new Error("Not implemented");
  }

  update(i: number, delta: number): void {
    throw new Error("Not implemented");
  }

  prefixSum(i: number): number {
    throw new Error("Not implemented");
  }

  rangeSum(from: number, to: number): number {
    throw new Error("Not implemented");
  }
}
