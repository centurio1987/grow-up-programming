/**
 * DAG — 정점을 늘리며 간선을 넣고, 사이클을 닫는 간선은 넣는 그 호출이 거부하는 방향 그래프. 모든 간선 방향을 지키는 정점 순서를 묻는다.
 *
 * **목적.** 정점 수를 미리 정하지 않는 방향 그래프 하나를 두고, 간선을 넣는 **동안** 사이클이
 * 생기지 않게 지키는 것. 사이클을 닫는 간선은 넣는 그 호출이 `false` 로 거부하고 상태를 바꾸지
 * 않는다. 그래서 그래프는 언제나 비순환이고, 모든 간선 u→v 에서 u 가 v 보다 앞에 오는 정점 순서를
 * 언제든 물을 수 있다. 비용 쪽 내용은 **간선 하나를 넣는 비용이 그 간선이 닿는 부분에 비례한다**는
 * 것이다 — 새 간선이 그래프의 작은 부분에만 닿으면 그래프 전체의 크기가 들지 않는다.
 *
 * 이 계약에 없는 것은 여섯이다.
 *
 * - **순서를 하나로 정하는 일.** 모든 간선 방향을 지키는 순서가 여럿일 때 어느 것을 돌려줄지 적으면
 *   그 순서를 짓는 방법까지 계약이 정하게 된다(§규약1 금지 2 —
 *   `src/data-structures/trie/ternarySearchTree/ternarySearchTree.ts:73-75` 와 같은 이유). 계약은
 *   「모든 간선 방향을 지킨다」만 적고, 축1은 돌려받은 순서가 그것을 지키는지를 본다.
 * - **최장 경로와 간선 무게.** 물려받은 표면의 `longestPath` 는 순서를 따라 앞 정점의 값을 뒤로 넘기는
 *   계산이다. 이 계약을 지키는 구현이면 누구든 순서 하나와 간선 목록으로 정점 수 + 간선 수에 답하므로
 *   그 행이 배제하는 구현이 없다(불변 사실 47 · 70 · 210). 무게는 그 연산 말고 읽는 연산이 없어 관측되지
 *   않는 약속이 되므로 함께 뺐다(불변 사실 69 ③). 비순환 그래프 위의 경로 계산은 알고리즘 트랙이
 *   받는다(`src/algorithms/shortest-path/dagShortestPath/dagShortestPath.ts:1`).
 * - **사이클 유무 질의.** 물려받은 `hasCycle()` 은 늘 거짓이라 배제하는 구현이 없다.
 * - **간선 지우기 · 정점 지우기.** 간선을 지워서는 사이클이 생기지 않으므로 목적이 요구하지 않는다(불변
 *   사실 47). 정점 지우기는 아래 정점 번호 문단의 약속과 부딪힌다(불변 사실 209).
 * - **이웃 열거 · 두 정점 사이에 간선이 있는지 묻기.** `graph-repr/graphAdjList` · `graph-repr/graphAdjMatrix`
 *   의 계약이다. 이 계약의 목적(비순환을 지키며 넣고 순서를 묻는다)을 적는 데 들지 않는다(불변 사실 47).
 * - **주어진 그래프 하나를 받아 순서를 구하는 일.** 알고리즘 트랙의
 *   `src/algorithms/graph/topologicalSort/topologicalSort.ts:1` 은 간선 목록 하나를 받아 순서를 내고 사이클이면
 *   `null` 을 돌려준다. 여기는 간선이 늘어나는 동안 비순환을 지키는 상태다.
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 * 물려받은 문서의 빌드 시스템 이야기는 활용 사례라 계약의 문장이 아니다(§규약1 「금지 — 내부 처방」 5번).
 *
 * **정점 번호는 구조가 매긴다 — `graph-repr/graphAdjList` 의 결정을 따른다(불변 사실 209).** `addVertex()`
 * 가 새 정점의 번호를 돌려주고 그 값은 호출 직전의 `vertexCount()` 다. 유효한 번호는 언제나
 * `[0, vertexCount())` 이고 빈틈이 없다. 물려받은 표면은 호출자가 고른 임의 정수를 정점으로 받았는데, 그
 * 모형은 번호에서 정점을 찾는 사전을 요구하고 그 사전이 자명한 구현인지가 미결이라 검증 등급이 그 미결에
 * 매달린다. 전문은 `docs/ORD-006-conventions.md` 「정점 번호는 구조가 매긴다」 절이다.
 *
 * **`graph-repr/graphAdjList` · `graph-repr/graphAdjMatrix` 와는 동시에 만족하는 구현이 없다(불변 사실 181).**
 * 반례를 계약의 문장으로 적는다. 어느 정본도 보지 않는다(불변 사실 43).
 *
 * - 정점 둘을 두고 `addEdge(0, 1)` 뒤에 `addEdge(1, 0)` 을 부르면, 방향 그래프로 연 목록 계약은 간선 둘을
 *   요구해 `edgeCount()` 가 2 이고 이 계약은 둘째를 거부해 1 이다. 방향 그래프로 연 행렬 계약도 목록
 *   계약과 같은 값을 요구한다. 같은 호출열에 다른 값을 요구하므로 한 구현이 둘을 함께 지킬 수 없다 —
 *   상한도 한정자도 쓰지 않는 논증이다.
 * - 그래서 한쪽이 다른 쪽을 담는 관계(불변 사실 43)도, 서로 담지 않는 관계(불변 사실 54)도 아니다.
 *   공통 행(`addVertex` · `vertexCount` · `edgeCount`)의 이름이 겹쳐도 판정은 같은 호출의 값에서 선다.
 *
 * **불변식.**
 * 1. `topologicalOrder()` 가 돌려준 배열의 길이가 `vertexCount()` 와 같다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 정점 수를 읽는 경로가 둘이고 — 세어 둔 수와
 * 늘어놓은 수(`linear/dynamicArray` 의 1번과 같은 모양) — 어느 계약 줄도 그 정합을 적지 않는다. 구현이 두
 * 경로를 따로 유지할 수 있고, 사이클이 한 번 들어온 구현은 그 사이클의 정점을 순서에 못 넣어 갈린다.
 *
 * 후보였다가 빠진 것이 셋이다.
 *
 * - **비순환 자체.** 이 구조의 핵심 성질이지만 그것을 상태를 바꾸지 않고 읽는 공개 연산이 없다. `addEdge`
 *   가 거부하는지로 알아볼 수는 있으나 받아들이는 순간 상태가 바뀌므로 관측 경로로 세지 않는다
 *   (`docs/ORD-006-conventions.md` 「관측이 상태를 바꾸면 관측 경로로 세지 않는다」). 비순환은 `addEdge` 행의
 *   거부와 `topologicalOrder` 행의 「모든 간선 방향을 지키는 순서」의 의미로 들어오고 축1이 본다.
 * - **순서에 같은 번호가 두 번 나오지 않는다 · 순서가 간선 방향을 지킨다.** 읽는 경로가
 *   `topologicalOrder()` 하나라 첫 물음에서 걸린다(축1).
 * - **간선 수.** 간선을 늘어놓는 연산이 없어 `edgeCount()` 하나만 그 양을 읽는다.
 *
 * **연산 계약.** n 은 `vertexCount()`, m 은 `edgeCount()` 다. 간선 u→v 를 넣는 호출의 상한에는 호출 전
 * 그래프에서 잰 **닿는 부분** k(u, v) 를 쓴다. 셋의 합이다.
 *
 * - u 에서 나가는 간선 수와 v 로 들어오는 간선 수
 * - v 에서 간선을 따라 갈 수 있는 정점(v 포함)의 수와 그 정점들에서 나가는 간선 수
 * - 간선을 거슬러 u 로 올 수 있는 정점(u 포함)의 수와 그 정점들로 들어오는 간선 수
 *
 * k(u, v) 는 2n + 4m 을 넘지 않는다. 새 간선이 그래프의 작은 부분에만 닿으면 작다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor()` | 정점도 간선도 없는 그래프를 연다 | O(1) | worst |
 * | `addVertex()` | 들어오고 나가는 간선이 없는 정점 하나를 더하고 그 번호를 돌려준다. 번호는 호출 직전의 `vertexCount()` 다 | O(1) | amortized |
 * | `addEdge(u, v)` | u→v 를 더해도 사이클이 생기지 않으면 더하고 `true`. 같은 간선이 이미 있으면 **상태가 바뀌지 않고** `true`. 더하면 사이클이 생기면 — v 에서 간선을 따라 u 에 갈 수 있으면, `u === v` 포함 — **상태가 바뀌지 않고** `false` | O(k(u, v)) | amortized |
 * | `topologicalOrder()` | 모든 정점의 번호를 한 번씩 담은 새 배열. 간선 u→v 마다 u 가 v 보다 앞에 있다. **그 밖의 순서는 정하지 않는다** — 같은 상태에서 두 번 불러도 같은 배열일 필요가 없다. 돌려준 배열을 고쳐도 그래프는 바뀌지 않는다 | O(n + m) | worst |
 * | `vertexCount()` | 정점 수 | O(1) | worst |
 * | `edgeCount()` | 간선 수. 같은 간선을 여러 번 넣어도 하나로 센다 | O(1) | worst |
 *
 * **`addEdge` 상한을 k 로 적은 것은 고른 것이다(불변 사실 48 · 51).**
 *
 * - 약하게 적으면 뜻을 잃는다. 그래프 크기 n + m 으로 적으면 넣을 때마다 그래프 전체로 순서를 지어 보는
 *   구현이 들어오고(`src/data-structures/_contract/_fixtures/fullScanDag.ts`), 그 구현은 방향 그래프 목록에
 *   위상 정렬을 매번 다시 돌리는 것과 같다 — 간선이 늘어나는 동안 비순환을 지킨다는 이 구조의 자리가 비용
 *   쪽에서 지워진다. 그리고 n + m 으로 적은 행은 그것을 어기는 구현을 축3이 받아 볼 수 없다. 그 행의
 *   시나리오가 호출마다 n 에 비례해야 하므로, 한 호출이 n² 에 비례하는 구현은 사다리 끝(n = 4,096)에서
 *   호출 4,096 번에 약 687 억 걸음이 든다(계산이고 돌리지 않았다).
 * - 강하게 적으면 나가는 계열에 이유가 없다. v 에서 갈 수 있는 부분 하나로만 적으면 u 로 올 수 있는 부분을
 *   거슬러 찾는 구현이 나가고, 두 부분 가운데 작은 쪽으로 적으면 두 방향을 번갈아 찾는 구현만 남는다 — 목적은
 *   찾는 방향을 정하지 않는다(§규약1 금지 2). 같은 간선을 찾는 차수 둘을 빼면 같은 간선을 차수와 무관하게
 *   찾아야 해서 정점마다 간선을 사전으로 드는 구현 쪽으로 좁혀지는데, 목적이 그것을 요구하지 않고 그 사전이
 *   자명한 구현인지가 미결이다. 상수나 간선 수의 제곱근 같은 값으로 적으면 순서를 들고 다니며 고치는 설계가
 *   들어야 해서 자명한 구현이 사라진다.
 * - **이 선택은 규약 절차로 닫히지 않아 사람 결정으로 올렸다**(`docs/ORD-006-conventions.md` 「A군 비순환 방향
 *   그래프」). 「간선 하나를 넣는 비용이 닿는 부분에 비례한다」가 이 구조의 목적에 드는지를 규약이 정하지
 *   않는다 — 앞선 판정은 이 구조를 의미(거부가 축1로 관측된다)로만 자료구조라 했다.
 *
 * **`topologicalOrder` 의 `O(n + m)` 은 고를 여지가 작다.** 번호 n 개를 새 배열로 내놓으므로 어느 구현도 n
 * 아래로 못 간다. 순서를 들고 다니는 구현은 m 없이 n 에 답하고, 그 구현도 이 상한 안이다.
 *
 * **한정자.** 늘리는 두 행(`addVertex` · `addEdge`)은 `amortized` 다 — 넣을 자리가 없으면 어느 구현이든
 * 어디선가 자리를 더 잡으므로 그 계열을 살려야 한다(불변 사실 194). `addEdge` 가 거부하는 호출은 늘리지
 * 않지만 같은 행이다. 읽기 셋은 `worst` 다. 셋 다 상태를 바꾸지 않고 값을 읽는 연산이고
 * (§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」 ①), `topologicalOrder` 는 자명한 구현이 호출마다
 * 상한 안에 답하므로 이따금 그보다 크게 치르는 계열을 살릴 이유가 목적에 없다(불변 사실 194).
 *
 * **주입 정책.**
 * - 주입받는 것이 없다. 정점은 번호이고 번호끼리의 동등성은 수의 비교다.
 * - 정점 번호는 `[0, vertexCount())` 안의 정수여야 한다. 벗어나면 `addEdge` 가 `RangeError` 를 던지고 상태는
 *   바뀌지 않는다. `false` 로 답하지 않는 이유는 그 값이 「사이클을 닫아 거부했다」로 읽혀 잘못된 번호가
 *   조용히 지나가기 때문이다 — 반환 타입에 「그런 정점은 없다」를 담을 자리가 없다(`graph-repr/graphAdjList`
 *   · `tree/linkCutTree` 와 같은 처분).
 * - **사이클을 닫는 간선은 전제조건이 아니라 정의된 입력이다.** 호출자에게 「사이클을 만들지 말 것」을 요구하지
 *   않고 `false` 로 답한다(`docs/ORD-006-conventions.md` 「전제조건을 두는 계약은 축1이 그 자리를 못 잰다 —
 *   연산을 전면화한다」). 물려받은 표면은 그 자리에서 예외를 던졌다.
 *
 * **검증 등급.** `invariant`.
 * 상한이 자명한 구현으로 달성된다. 정점마다 나가는 간선의 끝을 담는 배열 하나, 간선 수를 세는 정수 하나,
 * 정점마다 「이번 찾기에서 지나갔다」 표시 하나를 두면 여섯 행이 전부 상한 안이다. `addEdge(u, v)` 는 u 의
 * 배열을 훑어 같은 간선을 찾고, 없으면 v 에서 간선을 따라 가며 u 에 닿는지 본다. 지나간 정점을 목록에 적어
 * 두었다가 찾기가 끝나면 그 자리의 표시만 되돌리므로 표시를 지우는 데 정점 수가 들지 않는다. 순서는 부를
 * 때마다 정점과 간선을 한 번씩 지나며 새로 짓는다. 번호가 조밀하므로 사전이 들지 않고, 배열 늘리기는 계약이
 * 그 행에 적은 `amortized` 안이다(불변 사실 197). 재균형도 상각 설계도 확률 논증도 없으므로 `complexity` 가
 * 아니고, 불변식 절에 내용이 있으므로 `basic` 도 아니다.
 *
 * **필요충분조건.**
 * - 의미: 사이클을 닫는 간선은 넣는 그 호출이 거부하고 상태를 바꾸지 않아야 하며, 돌려준 순서는 모든 간선
 *   방향을 지켜야 한다. 거부하지 않으면 방향 그래프로 연 `graph-repr/graphAdjList` 가 되고, 순서를 하나로
 *   정하면 그 순서를 짓는 방법이 계약이 된다.
 * - 비용: `addEdge` 가 닿는 부분이 아니라 그래프 전체에 비례하면 넣을 때마다 그래프 전체를 다시 훑어 사이클을
 *   찾는 구현이다 — 작은 부분에만 닿는 간선을 넣는 데 그래프 전체를 치른다. 찾을 때마다 정점 수만큼 표시를
 *   새로 잡는 구현도 여기 든다. `topologicalOrder` 가 n + m 보다 빨리 자라면 순서의 다음 정점을 매번 정점
 *   전체에서 다시 찾는 구현이다.
 */
