/**
 * DAG — 정점을 늘리며 간선을 넣고, 사이클을 닫는 간선은 넣는 그 호출이 거부하는 방향 그래프. 모든 간선 방향을 지키는 정점 순서를 묻는다.
 *
 * **목적.** 정점 수를 미리 정하지 않는 방향 그래프 하나를 두고, 간선을 넣는 **동안** 사이클이
 * 생기지 않게 지키는 것. 사이클을 닫는 간선은 넣는 그 호출이 `false` 로 거부하고 상태를 바꾸지 않는다. 그래서 그래프는
 * 언제나 비순환이고, 모든 간선 u→v 에서 u 가 v 보다 앞에 오는 정점 순서를 언제든 물을 수 있다. **간선 하나를 넣는 비용이
 * 그래프 전체가 아니라 그 간선이 닿는 부분에 묶이는 것 — 국소 갱신 비용 — 도 이 계약의 목적이다**(2026-09-16 검토 결정). 새
 * 간선이 그래프의 작은 부분에만 닿으면 그래프 전체의 크기가 들지 않고, 그 점에서 넣을 때마다 순서를 새로 짓는 일과 갈린다.
 *
 * 이 계약에 없는 것은 일곱이다.
 *
 * - **순서를 하나로 정하는 일.** 모든 간선 방향을 지키는 순서가 여럿일 때 어느 것을 돌려줄지 적으면
 *   그 순서를 짓는 방법까지 계약이 정하게 된다(§규약1 금지 2 —
 *   `src/data-structures/trie/ternarySearchTree/ternarySearchTree.ts:79-81` 와 같은 이유). 계약은
 *   「모든 간선 방향을 지킨다」만 적고, 축1은 돌려받은 순서가 그것을 지키는지를 본다.
 * - **최장 경로와 간선 무게.** 물려받은 표면의 `longestPath` 는 순서를 따라 앞 정점의 값을 뒤로 넘기는 계산이라 `topologicalOrder`
 *   한 번과 호출자가 받아들여진 `addEdge` 로 아는 간선으로 짓는 조합이고(A2), 그렇게 지으면 누구든 정점 수 + 간선 수에 답해
 *   떨어지는 계열이 없는 **같은 비용의 편의 연산**이며(A4), 위 목적이 비순환을 지키며 넣고 순서를 묻는 일만 적고 순서 위의 값
 *   계산은 적지 않는다(`docs/ORD-006-conventions.md` 「원칙 A5′」 재판정표 ④ 의 19 행). 무게는 그 연산 말고 읽는 연산이 없어
 *   목적이 적는 사용이 아니므로 함께 뺐다(A3 · 불변 사실 69 ③). 비순환 그래프 위의 경로 계산은 알고리즘 트랙이 받는다(`src/algorithms/shortest-path/dagShortestPath/dagShortestPath.ts:1`).
 * - **사이클 유무 질의.** 물려받은 `hasCycle()` 은 늘 거짓인 상수라 호출 없이 아는 값이고(A2) 떨어지는 계열이 없으며(A4), 위 목적이 사이클 유무를 `addEdge` 의 반환값으로 관측하게 적었다(A5′ — 재판정표 ④ 의 20 행).
 * - **간선 지우기 · 정점 지우기.** 간선을 지워서는 사이클이 생기지 않으므로 목적이 요구하지 않는다(불변
 *   사실 47). 정점 지우기는 아래 정점 번호 문단의 약속과 부딪힌다(불변 사실 209).
 * - **이웃 열거 · 두 정점 사이에 간선이 있는지 묻기.** `graph-repr/graphAdjList` · `graph-repr/graphAdjMatrix`
 *   의 계약이다. 이 계약의 목적(비순환을 지키며 넣고 순서를 묻는다)을 적는 데 들지 않는다(불변 사실 47).
 * - **정점 수 · 간선 수를 읽는 일.** 물려받은 표면의 `vertexCount()` · `edgeCount()` 를 뺐다. 위 목적에서
 *   그래프 전체의 크기는 **비용의 파라미터**로만 나온다.
 * - **주어진 그래프 하나를 받아 순서를 구하는 일.** 알고리즘 트랙의
 *   `src/algorithms/graph/topologicalSort/topologicalSort.ts:1` 은 간선 목록 하나를 받아 순서를 내고 사이클이면
 *   `null` 을 돌려준다. 여기는 간선이 늘어나는 동안 비순환을 지키는 상태다.
 *
 * **뺀 두 행의 판정은 목적 항목 밖에 적는다.** `vertexCount()` · `edgeCount()` 는 원칙 A 판정표 ③ 의
 * 판정으로 뺐다 — 판정 줄과 목적 인용은 `docs/ORD-006-conventions.md` 「판정표 ③ 의 103 행을 묶어
 * 판정했다」 절에, 행 단위 대장은 `tools/_baseline/principle-a-verdicts.tsv` 에 있다. 판정의 결론을
 * 목적 문단 안에 적으면 다음 판정이 자기 메아리를 근거로 읽는다(§원칙 A A5′-2).
 *
 * **이 계약은 시간만 말한다.** 저장 공간에 대한 조건이 없다(§규약1 「공간은 어느 계약에도 없다」 — 미결).
 * 물려받은 문서의 빌드 시스템 이야기는 활용 사례라 계약의 문장이 아니다(§규약1 「금지 — 내부 처방」 5번).
 *
 * **정점 번호는 구조가 매긴다 — `graph-repr/graphAdjList` 의 결정을 따른다(불변 사실 209).** `addVertex()`
 * 가 새 정점의 번호를 돌려주고 그 값은 **그 호출 전까지 더한 정점 수** n 이다. 유효한 번호는 언제나
 * `[0, n)` 이고 빈틈이 없다. 물려받은 표면은 호출자가 고른 임의 정수를 정점으로 받았는데, 그
 * 모형은 번호에서 정점을 찾는 사전을 요구하고 그 사전이 자명한 구현인지가 미결이라 검증 등급이 그 미결에
 * 매달린다. 전문은 `docs/ORD-006-conventions.md` 「정점 번호는 구조가 매긴다」 절이다.
 *
 * **`graph-repr/graphAdjList` · `graph-repr/graphAdjMatrix` 와는 동시에 만족하는 구현이 없다(불변 사실 181).**
 * 반례를 계약의 문장으로 적는다. 어느 정본도 보지 않는다(불변 사실 43).
 *
 * - 정점 둘을 두고 `addEdge(0, 1)` 뒤에 `addEdge(1, 0)` 을 부르면, 방향 그래프로 연 목록 계약은 둘째 간선을
 *   두어 `neighbors(1)` 에 정점 0 항목을 요구한다. 방향 그래프로 연 행렬 계약도 `hasEdge(1, 0)` 이 참이기를
 *   요구한다. 이 계약은 둘째 호출을 `false` 로 거부하고 상태를 바꾸지 않으며, 그 뒤에도 `topologicalOrder()`
 *   가 **모든 간선 방향을 지키는 순서**를 내놓기를 요구한다 — 간선 둘이 다 있으면 그런 순서가 없다. 같은
 *   호출열에 다른 값을 요구하므로 한 구현이 둘을 함께 지킬 수 없다 — 상한도 한정자도 쓰지 않는 논증이다.
 * - 그래서 한쪽이 다른 쪽을 담는 관계(불변 사실 43)도, 서로 담지 않는 관계(불변 사실 54)도 아니다.
 *   공통 행(`addVertex`)의 이름이 겹쳐도 판정은 같은 호출의 값에서 선다.
 *
 * **불변식.** 없다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 **두 행을 뺀 표면에 다시 돌린 결과다.** 하나 있던 불변식
 * 「`topologicalOrder()` 가 돌려준 배열의 길이가 `vertexCount()` 와 같다」는 정점 수를 읽는 두 경로
 * (세어 둔 수 · 늘어놓은 수) 가운데 세어 둔 쪽이 표면에서 사라져 **경로가 `topologicalOrder()` 하나**
 * 로 줄었다. 첫 번째 물음에서 걸리므로 불변식이 아니고, 배열의 길이는 그 행의 의미(「모든 정점의 번호를
 * 한 번씩 담은 새 배열」)라 축1이 참조 모델과 대조한다. 남은 표면에서 관측 경로가 둘인 성질은 새로
 * 서지 않는다.
 *
 * 후보였다가 빠진 것이 셋이다.
 *
 * - **비순환 자체.** 이 구조의 핵심 성질이지만 그것을 상태를 바꾸지 않고 읽는 공개 연산이 없다. `addEdge`
 *   가 거부하는지로 알아볼 수는 있으나 받아들이는 순간 상태가 바뀌므로 관측 경로로 세지 않는다
 *   (`docs/ORD-006-conventions.md` 「관측이 상태를 바꾸면 관측 경로로 세지 않는다」). 비순환은 `addEdge` 행의
 *   거부와 `topologicalOrder` 행의 「모든 간선 방향을 지키는 순서」의 의미로 들어오고 축1이 본다.
 * - **순서에 같은 번호가 두 번 나오지 않는다 · 순서가 간선 방향을 지킨다.** 읽는 경로가
 *   `topologicalOrder()` 하나라 첫 물음에서 걸린다(축1).
 * - **간선 수.** 간선을 늘어놓는 연산도 세는 연산도 없어 읽는 경로가 아예 없다.
 *
 * **연산 계약.** n 은 정점 수, m 은 간선 수다. 간선 u→v 를 넣는 호출의 상한에는 **닿는 부분의 크기** k(u, v) 를
 * 쓴다 — 호출 전 그래프와 넣는 간선 u→v 만으로 정해지는 양이고, 구현이 무엇을 들고 어느 방향으로 찾는지와 무관하다.
 *
 * - **닿는 부분** A(u, v) = 간선을 따라 u 에 올 수 있는 정점(u 포함) ∪ v 에서 간선을 따라 갈 수 있는 정점(v 포함)
 * - k(u, v) = |A(u, v)| + 끝점 하나 이상이 A(u, v) 안에 있는 간선의 수
 * - 사이클이 되는지(v 에서 u 로 가는 길)와 새 간선이 더하는 선후 조건(u 에 오는 정점이 v 에서 가는 정점보다 앞)이 전부 A 안에서 정해진다
 *
 * k(u, v) 는 n + m 을 넘지 않는다. 새 간선이 그래프의 작은 부분에만 닿으면 작다. 고른 이유는 표 아래 문단이다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor()` | 정점도 간선도 없는 그래프를 연다 | O(1) | worst |
 * | `addVertex()` | 들어오고 나가는 간선이 없는 정점 하나를 더하고 그 번호를 돌려준다. 번호는 그 호출 전까지 더한 정점 수다 | O(1) | amortized |
 * | `addEdge(u, v)` | u→v 를 더해도 사이클이 생기지 않으면 더하고 `true`. 같은 간선이 이미 있으면 **상태가 바뀌지 않고** `true`. 더하면 사이클이 생기면 — v 에서 간선을 따라 u 에 갈 수 있으면, `u === v` 포함 — **상태가 바뀌지 않고** `false` | O(k(u, v)) | amortized |
 * | `topologicalOrder()` | 모든 정점의 번호를 한 번씩 담은 새 배열. 간선 u→v 마다 u 가 v 보다 앞에 있다. **그 밖의 순서는 정하지 않는다** — 같은 상태에서 두 번 불러도 같은 배열일 필요가 없다. 돌려준 배열을 고쳐도 그래프는 바뀌지 않는다 | O(n + m) | worst |
 *
 * **`addEdge` 상한을 k 로 적은 것은 고른 것이다(불변 사실 48 · 51) — 국소 갱신 비용이 목적이라 그렇게 골랐다.**
 *
 * - **k 는 구현의 탐색량이 아니라 그래프의 양이다.** 처음 적은 k 는 「u 의 나가는 간선 수 + v 의 들어오는 간선 수 + v 에서 가는
 *   부분과 그 나가는 간선 + u 로 오는 부분과 그 들어오는 간선」이었다. 그 항목들이 앞으로 찾는 구현과 거슬러 찾는 구현이 각자
 *   지나가는 몫이라 특정 구현의 탐색량으로 읽혔다. 지금 k 는 두 부분의 합집합과 거기 닿는 간선만 센다. 처음 것은 지금 것의 4 배를
 *   넘지 않으므로(두 부분의 크기가 각각 |A| 이하, 간선 항목 넷이 각각 닿는 간선 수 이하) 처음 계약을 지키던 구현은 전부 지금 계약을
 *   지킨다. 축3 시나리오 둘의 k 는 떨어진 쌍 2(처음 것도 2) · 사슬의 끝 2n − 1(처음 것 4n − 2)이라 두 시나리오의 계급이 그대로다.
 * - **알려진 국소 방법 넷을 대 보았다(탐침 — 저장소에 두지 않았다).** v 에서 앞으로 찾는 정본과 u 에서 거슬러 찾는 구현은 한 호출
 *   비용이 k 의 1.5 배를 넘지 않았다(두 시나리오 · 무작위 작업 · 두 사슬 잇기). 순서를 들고 다니며 어긋난 부분만 다시 매기는
 *   Pearce-Kelly 는 다시 매길 정점을 정렬하는 몫만큼 로그 인수가 붙어 두 사슬을 잇는 한 호출에서 비용/k 가 4.02 → 4.26 → 4.51
 *   (n = 256 → 4,096)로 자란다. 이 인수는 축3 해상도 아래이고(불변 사실 53), 이 계약에서는 순서를 들고 다녀도 `topologicalOrder` 가
 *   정점 n 개를 내놓아야 해서 얻는 것이 없으므로 상한에 로그를 더하지 않았다. 두 위치 사이 구간 전체를 미는 방법(MNR)은 떨어진 쌍을
 *   큰 번호에서 작은 번호로 이을 때 k = 2 인데 비용이 n 을 따라가 나간다 — 그 비용은 구현이 스스로 고른 순서의 구간 길이라 계약의
 *   양으로 적을 수 없다(§규약1 금지 2).
 * - **약하게 적으면 목적을 잃는다.** 그래프 크기 n + m 으로 적으면 넣을 때마다 그래프 전체로 순서를 지어 보는 구현이 들어오고
 *   (`src/data-structures/_contract/_fixtures/fullScanDag.ts`), 그 구현은 방향 그래프 목록에 위상 정렬을 매번 다시 돌리는 것과 같다 —
 *   국소 갱신 비용이라는 목적이 비용 쪽에서 지워진다. 그 구현은 k = 2 인 떨어진 쌍에서 한 호출 평균 5,123 → 20,483 걸음이다(정본
 *   3 → 3). 그리고 n + m 으로 적은 행은 그것을 어기는 구현을 축3이 받아 볼 수 없다. 그 행의 시나리오가 호출마다 n 에 비례해야 하므로,
 *   한 호출이 n² 에 비례하는 구현은 사다리 끝(n = 4,096)에서 호출 4,096 번에 약 687 억 걸음이 든다(계산이고 돌리지 않았다).
 * - **강하게 적으면 나가는 계열에 이유가 없다.** v 에서 갈 수 있는 부분 하나로만 적으면 u 로 올 수 있는 부분을 거슬러 찾는 구현이
 *   나가고, 두 부분 가운데 작은 쪽으로 적으면 두 방향을 번갈아 찾는 구현만 남는다 — 목적은 찾는 방향을 정하지 않는다(§규약1 금지 2).
 *   간선을 양 끝이 A 안인 것만 세면 u 에서 A 밖으로 나가는 간선이 빠져, 같은 간선을 u 의 나가는 간선에서 찾는 구현이 나가고 정점마다
 *   간선을 사전으로 드는 구현 쪽으로 좁혀진다 — 목적이 그것을 요구하지 않고 그 사전이 자명한 구현인지가 미결이다. 상수나 간선 수의
 *   제곱근 같은 값으로 적으면 순서를 들고 다니며 고치는 설계가 들어야 해서 자명한 구현이 사라진다.
 * - **넓힌 대가는 하나다.** 닿는 간선에는 A 밖에서 v 쪽 부분으로 들어오는 간선과 u 쪽 부분에서 A 밖으로 나가는 간선도 든다. 위의 어느
 *   방법도 그 간선을 지나지 않으므로 그만큼 약하다. 그 간선까지 훑는 구현이 새로 들어오지만 비용이 여전히 닿는 부분에 묶여 목적을
 *   잃지 않는다.
 *
 * **`topologicalOrder` 의 `O(n + m)` 은 고를 여지가 작다.** 번호 n 개를 새 배열로 내놓으므로 어느 구현도 n
 * 아래로 못 간다. 순서를 들고 다니는 구현은 m 없이 n 에 답하고, 그 구현도 이 상한 안이다.
 *
 * **한정자.** 늘리는 두 행(`addVertex` · `addEdge`)은 `amortized` 다 — 넣을 자리가 없으면 어느 구현이든
 * 어디선가 자리를 더 잡으므로 그 계열을 살려야 한다(불변 사실 194). `addEdge` 가 거부하는 호출은 늘리지
 * 않지만 같은 행이다. 읽기 하나(`topologicalOrder`)는 `worst` 다. 상태를 바꾸지 않고 값을 읽는 연산이고
 * (§규약1 「가장 약한 한정자는 셋을 줄 세우지 않는다」 ①), 자명한 구현이 호출마다
 * 상한 안에 답하므로 이따금 그보다 크게 치르는 계열을 살릴 이유가 목적에 없다(불변 사실 194).
 *
 * **주입 정책.**
 * - 주입받는 것이 없다. 정점은 번호이고 번호끼리의 동등성은 수의 비교다.
 * - 정점 번호는 `[0, 지금까지 더한 정점 수)` 안의 정수여야 한다. 벗어나면 `addEdge` 가 `RangeError` 를 던지고 상태는
 *   바뀌지 않는다. `false` 로 답하지 않는 이유는 그 값이 「사이클을 닫아 거부했다」로 읽혀 잘못된 번호가
 *   조용히 지나가기 때문이다 — 반환 타입에 「그런 정점은 없다」를 담을 자리가 없다(`graph-repr/graphAdjList`
 *   · `tree/linkCutTree` 와 같은 처분).
 * - **사이클을 닫는 간선은 전제조건이 아니라 정의된 입력이다.** 호출자에게 「사이클을 만들지 말 것」을 요구하지
 *   않고 `false` 로 답한다(`docs/ORD-006-conventions.md` 「전제조건을 두는 계약은 축1이 그 자리를 못 잰다 —
 *   연산을 전면화한다」). 물려받은 표면은 그 자리에서 예외를 던졌다.
 *
 * **검증 등급.** `basic`.
 * 상한이 자명한 구현으로 달성된다. 정점마다 나가는 간선의 끝을 담는 배열 하나와
 * 정점마다 「이번 찾기에서 지나갔다」 표시 하나를 두면 네 행이 전부 상한 안이다(간선 수를 세는 정수는
 * 이제 들지 않는다 — `KAN-040` `S3` 이 그 행을 뺐다). `addEdge(u, v)` 는 u 의
 * 배열을 훑어 같은 간선을 찾고(u 는 A 안이라 그 간선은 닿는 간선이다), 없으면 v 에서 간선을 따라 가며 u 에 닿는지
 * 본다(지나가는 정점과 간선이 전부 A 안이다). 지나간 정점을 목록에 적어
 * 두었다가 찾기가 끝나면 그 자리의 표시만 되돌리므로 표시를 지우는 데 정점 수가 들지 않는다. 순서는 부를
 * 때마다 정점과 간선을 한 번씩 지나며 새로 짓는다. 번호가 조밀하므로 사전이 들지 않고, 배열 늘리기는 계약이
 * 그 행에 적은 `amortized` 안이다(불변 사실 197). 재균형도 상각 설계도 확률 논증도 없으므로 `complexity` 가
 * 아니고, **불변식 절이 비어 있으므로 `invariant` 도 아니다** — `KAN-040` `S3` 이 정점 수 · 간선 수 읽기를
 * 빼면서 하나 있던 불변식의 경로가 하나로 줄어 위 판별에서 떨어졌고, `S5` 가 판정 절차를 다시 대어
 * `invariant` 에서 `basic` 으로 내렸다(불변 사실 426).
 *
 * **필요충분조건.**
 * - 의미: 사이클을 닫는 간선은 넣는 그 호출이 거부하고 상태를 바꾸지 않아야 하며, 돌려준 순서는 모든 간선
 *   방향을 지켜야 한다. 거부하지 않으면 방향 그래프로 연 `graph-repr/graphAdjList` 가 되고, 순서를 하나로
 *   정하면 그 순서를 짓는 방법이 계약이 된다.
 * - 비용: `addEdge` 가 닿는 부분이 아니라 그래프 전체에 비례하면 넣을 때마다 그래프 전체를 다시 훑어 사이클을
 *   찾는 구현이다 — 작은 부분에만 닿는 간선을 넣는 데 그래프 전체를 치러 국소 갱신 비용이라는 목적을 잃는다. 찾을 때마다 정점 수만큼 표시를
 *   새로 잡는 구현도 여기 든다. `topologicalOrder` 가 n + m 보다 빨리 자라면 순서의 다음 정점을 매번 정점
 *   전체에서 다시 찾는 구현이다.
 */
