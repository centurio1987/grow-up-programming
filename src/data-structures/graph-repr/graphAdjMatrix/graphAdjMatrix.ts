/**
 * GraphAdjMatrix — 정점 수가 생성 때 정해진 그래프. 두 정점 사이에 간선이 있는지와 그 무게를 정점 수와 차수에 기대지 않는 비용으로 답한다.
 *
 * **목적.** 정점 `0` 부터 `n-1` 까지를 생성 때 고정한 그래프 하나를 두고, 간선 넣기 · 간선 빼기와
 * **두 정점 사이에 간선이 있는가 · 그 무게는 무엇인가**를 호출 하나당 상수 비용으로 제공하는 것.
 * 쌍 하나를 다루는 데 그래프의 크기(정점 수 · 차수)가 들지 않는다는 것이 이 계약의 비용 쪽
 * 내용이다. 그 대가로 한 정점의 이웃 열거는 정점 수에 비례해도 된다. 방향 그래프인지는 생성 때
 * 정해지고 바뀌지 않는다.
 *
 * 이 계약에 없는 것은 넷이다.
 *
 * - **정점 늘리기와 차수에 비례하는 이웃 열거.** `graph-repr/graphAdjList` 의 계약이다. 두 계약의
 *   관계는 아래 반례 문단에 있다.
 * - **탐색.** 물려받은 표면의 `bfs`·`dfs` 를 뺐다. `neighbors` 를 거듭 불러 짓고(A2) 떨어지는 계열이 없는 **같은 비용의 편의
 *   연산**이다(A4). 위 목적이 적는 관찰의 단위는 **쌍 하나**라 그래프를 도는 일을 적지 않으므로 뺀다(`docs/ORD-006-conventions.md`
 *   「원칙 A5′」 재판정표 ④ 의 17 행). 방문 순서가 계약으로 정해지지 않는다는 것(불변 사실 69 ③)은 보조 근거이고, 판정 전문은
 *   `graph-repr/graphAdjList` 헤더의 같은 항목이다.
 * - **간선 수.** 물려받은 표면에 없고 더하지 않는다. 칸마다 `hasEdge` 를 불러 세면 같은 뜻이고(A2), 칸을 고칠 때마다 수 하나를
 *   고치는 상수 보강으로 어느 구현이든 상수에 답하므로 **같은 비용의 편의 연산**이며(A4), 위 목적이 그래프 전체의 요약을
 *   사용으로 적지 않는다(「원칙 A5′」 재판정표 ④ 의 18 행).
 * - **같은 두 정점 사이의 간선 여럿(다중 간선).** 같은 쌍에 다시 넣으면 무게만 바뀐다. 여럿을 두면
 *   `weight(u, v)` 가 무엇을 돌려줄지 정해지지 않는다.
 *
 * **「밀집 그래프에 유리하다」는 물려받은 존재 이유는 계약의 문장이 못 되고, 다시 적으면 비용이
 * 남는다.** 판별 절차 세 걸음(`docs/ORD-006-conventions.md:2870-2877`, 셋째 걸음의 축은
 * `docs/ORD-006-conventions.md:3037-3040`)을 이 계약에 돌렸다.
 *
 * 1. 존재 이유를 계약의 용어로 다시 적는다(불변 사실 188). 저장량(칸이 정점 수의 제곱)은 계약에
 *    들어오지 못하고(§규약1 「공간은 어느 계약에도 없다」 — 미결), 남는 문장이 「쌍 하나를 다루는
 *    비용이 그래프 크기와 무관하다」다.
 * 2. 그 문장이 되는 행은 넷이다 — `hasEdge` · `weight` · `addEdge` · `removeEdge`.
 * 3. 제약이 비용이므로 그것이 사는 축은 축3이다. **실제로 돌렸다** — 정점마다 이웃 배열을 드는
 *    구현(`_contract/_fixtures/neighborListMatrixGraph.ts`)을 이 스위트에 넣으면 차수가 n 인 정점을
 *    다루는 네 행이 전부 성장률 4 부근으로 걸리고 값은 한 자리도 틀리지 않는다
 *    (`src/data-structures/_contract/runContract.graphAdjMatrix.test.ts`).
 *
 * 그래서 **B15 처분(존치 + 성격 전환)이 아니라 계약이 갈린다**(불변 사실 204 의 판정을 실행으로
 * 확인). 공간은 이 판정 뒤에도 계약에 없다 — 칸을 정점 수의 제곱보다 훨씬 적게 쓰는 구현도 여덟
 * 행을 지키면 이 계약을 지킨다.
 *
 * **정점 번호는 `[0, n)` 이다.** n 이 생성 인자라 번호에서 정점을 찾는 사전 물음이 애초에 생기지
 * 않는다. 정점 번호를 구조가 매기는 모형은 `graph-repr/graphAdjList` 와 같다
 * (`docs/ORD-006-conventions.md` 「정점 번호는 구조가 매긴다」 절).
 *
 * **`graph-repr/graphAdjList` 와 서로 담지 않는다(불변 사실 54).** 반례는 둘이고 어느 정본도 보지
 * 않는다(불변 사실 43).
 *
 * - **이쪽을 지키고 저쪽을 못 지키는 구현** — 정점 수 곱하기 정점 수의 칸에 무게를 적는 구현. 이
 *   계약의 행을 전부 지키지만 목록 계약의 `neighbors` 가 차수 1 인 정점에서도 행 하나를 끝까지
 *   훑어 정점 수에 비례한다.
 * - **저쪽을 지키고 이쪽을 못 지키는 구현** — 정점마다 이웃 배열을 드는 구현. 목록 계약을 지키지만
 *   차수가 d 인 정점에서 이 계약의 `hasEdge` 가 그 배열을 훑어 d 에 비례한다.
 * - **둘 다 지키는 구현은 정점 수가 고정된 동안에만 보였다.** 칸에 「그 간선 항목이 이웃 배열의
 *   몇 번째에 있는가」를 적고 이웃 배열을 함께 들면 이 계약의 행 전부와 목록 계약의 `addEdge` ·
 *   `removeEdge` · `neighbors` 행을 지킨다. 목록 계약의 `addVertex` 까지 상각 상수로 함께 지키는
 *   구현은 찾지 못했다(`docs/ORD-006-conventions.md:2796` — 「없다」가 아니라 「못 찾았다」).
 *
 * **불변식.**
 * 1. `hasEdge(u, v)` 가 참인 것과 `weight(u, v)` 가 `null` 이 아닌 것이 같다.
 * 2. `neighbors(u)` 가 돌려주는 정점들이 `hasEdge(u, v)` 가 참인 v 전부와 같다.
 * 3. 무방향 그래프에서 `hasEdge(u, v)` 와 `hasEdge(v, u)` 가 같고 `weight(u, v)` 와 `weight(v, u)`
 *    가 같다.
 *
 * 판별 절차(§규약1 「불변식 판별 절차」)를 돌린 결과다. 셋 다 같은 양을 읽는 경로가 둘이고 어느 계약
 * 줄도 그 정합을 적지 않는다. 구현이 두 경로를 따로 유지할 수 있고, 따로 유지하는 순간 갈린다.
 *
 * - 1번은 **간선이 있는가를 읽는 두 경로**다. 있음 표시와 무게를 따로 적는 구현이 `removeEdge` 에서
 *   한쪽만 지우면 갈린다.
 * - 2번은 **한 쌍씩 묻는 경로와 늘어놓는 경로**다(`hash/hashSet` 의 2번과 같은 모양). 칸과 함께
 *   이웃 목록을 들고 다니는 구현이 한쪽만 고치면 갈린다.
 * - 3번은 **같은 간선을 두 방향에서 읽는 두 경로**다. 무방향 간선을 칸 둘에 적는 구현이 한 칸만
 *   고치면 갈린다.
 *
 * 「`neighbors(u)` 에 같은 정점이 두 번 나오지 않는다」는 읽는 경로가 하나라 첫 물음에서 걸리고 축1이
 * 본다. 담는 모양의 성질(칸이 대칭이다 등)은 계약의 말로 적을 수 없으므로 후보가 아니다(불변 사실 36)
 * — 3번은 칸이 아니라 두 호출의 반환값을 말한다.
 *
 * **연산 계약.** n 은 생성자가 정한 **정점 수**다. 구조가 사는 동안 바뀌지 않는다.
 *
 * | 연산 | 의미 | 상한 | 한정자 |
 * |---|---|---|---|
 * | `constructor(n, directed = false)` | 정점 `0` 부터 `n-1` 까지를 두고 간선은 하나도 없다. `directed` 가 참이면 방향 그래프, 거짓이면 무방향 그래프이고 바뀌지 않는다 | O(n^2) | worst |
 * | `addEdge(u, v, weight = 1)` | 방향 그래프면 u→v, 무방향이면 u–v 간선을 무게 `weight` 로 둔다. 같은 간선이 이미 있으면 **무게만 바뀐다.** `u === v` 인 제자리 간선도 받는다 | O(1) | amortized |
 * | `removeEdge(u, v)` | 그 간선이 있으면 지운다. 없으면 상태가 바뀌지 않는다 | O(1) | amortized |
 * | `hasEdge(u, v)` | 방향 그래프면 u→v, 무방향이면 u–v 간선이 있는가 | O(1) | worst |
 * | `weight(u, v)` | 그 간선의 무게. 없으면 `null` | O(1) | worst |
 * | `neighbors(u)` | 방향 그래프면 u 에서 나가는 간선마다, 무방향이면 u 에 닿은 간선마다 반대쪽 정점 하나. 제자리 간선이면 u 가 한 번 나온다. **순서를 정하지 않는다.** 돌려준 배열을 고쳐도 그래프는 바뀌지 않는다 | O(n) | worst |
 * | `vertexCount()` | n | O(1) | worst |
 *
 * **쌍을 다루는 네 행을 상수로 적은 것이 이 계약의 전부다.** 차수로 적으면(`O(d(u) + d(v))`)
 * 이웃 배열을 훑는 구현이 들어오고 그 순간 목록 계약보다 나은 것이 없다. `neighbors` 의 `O(n)` 은
 * 고른 값이다 — 차수로 강하게 적으면 칸을 훑는 구현이 통째로 나가는데 목적(쌍 질의)이 그 배제를
 * 요구하지 않고, 그렇게 적은 계약은 쌍 질의와 이웃 열거를 둘 다 싸게 두는 셋째 계약이다. 생성자의
 * `O(n^2)` 은 칸을 비워 두는 준비를 허용하는 값이고, 축3 사다리에 없는 계급이지만 생성자는 n 에 대해
 * 반복 호출되지 않아 시나리오 면제다(§규약2 시나리오 규칙 2).
 *
 * **한정자.** 갱신 둘은 `amortized` 다. 정점 수가 생성 때 정해져 늘릴 일이 없으므로 `worst` 로
 * 올릴 근거는 있다(`linear/circularBuffer` 가 같은 근거로 `worst` 를 적었다). 그러나 `worst` 가
 * **추가로** 배제하는 계열(쌍을 사전으로 찾고 이따금 표를 다시 짓는 구현)이 약한 쪽을 통과함을 재서
 * 보여야 적을 수 있고(불변 사실 183) 그 계열을 짓지 않았으므로 약한 쪽을 적는다. 읽기 넷은 `worst`
 * 다 — 넷 다 상태를 바꾸지 않고 값을 읽는 연산이라, `worst` 가 추가로 배제하는 계열(첫 호출에 값을
 * 지어 두는 구현)을 배제해도 그 값을 처음부터 들고 있는 대가가 계약에 없다(§규약1 「가장 약한
 * 한정자는 셋을 줄 세우지 않는다」).
 *
 * **주입 정책.**
 * - 주입받는 것이 없다. 정점은 번호이고 번호끼리의 동등성은 수의 비교다. 무게는 아무 `number` 나
 *   받아 그대로 돌려주고 검사하지 않는다 — 이 계약 안에서 무게로 계산하는 연산이 없다.
 * - `n` 은 0 이상의 정수여야 하고, 아니면 생성자가 `RangeError` 를 던진다. `n === 0` 은 정당하다 —
 *   정점이 없는 그래프이고 `vertexCount()` 말고는 부를 수 있는 연산이 없다.
 * - 정점 번호는 `[0, n)` 안의 정수여야 한다. 벗어나면 `addEdge` · `removeEdge` · `hasEdge` ·
 *   `weight` · `neighbors` 가 `RangeError` 를 던지고 상태는 바뀌지 않는다. `hasEdge` 가 `false` 로,
 *   `weight` 가 `null` 로 답하지 않는 이유는 그 값이 「간선이 없다」로 읽혀 잘못된 번호가 조용히
 *   지나가기 때문이다. `weight` 의 `null` 은 「간선이 없다」 하나만 뜻한다.
 * - `weight` 를 생략하면 1 이다.
 *
 * **검증 등급.** `invariant`.
 * 상한이 자명한 구현으로 달성된다 — 정점 수 곱하기 정점 수의 칸 배열 하나에 있음 표시와 무게를 적으면
 * 여덟 행이 전부 상한 안이다. 재균형도 상각 설계도 확률 논증도 없으므로 `complexity` 가 아니고,
 * 불변식 절에 내용이 있으므로 `basic` 도 아니다.
 *
 * **필요충분조건.**
 * - 의미: 정점 수가 **생성 때 고정되고**, 한 쌍에 간선이 하나여야 한다. 정점을 나중에 늘릴 수 있으면
 *   `graph-repr/graphAdjList` 가 서는 자리이고(그때 이 비용을 함께 지키는 구현은 찾지 못했다), 한 쌍에
 *   간선 여럿을 두면 `weight(u, v)` 가 무엇을 돌려주는지가 정해지지 않는다.
 * - 비용: `hasEdge` · `weight` · `addEdge` · `removeEdge` 가 차수에 비례하면 정점마다 이웃 배열을 든
 *   구현이다. 그러면 쌍 하나를 그래프 크기와 무관하게 다루는 이 계약의 유일한 값이 사라지고, 남는
 *   계약은 목록 계약보다 이웃 열거가 느린 그래프다.
 */
